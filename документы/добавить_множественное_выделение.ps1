function Проверить-Совпадение([string]$Текст, [string]$Маркер, [string]$Имя) {
    $количество = ([regex]::Matches($Текст, [regex]::Escape($Маркер))).Count

    if ($количество -ne 1) {
        throw "Изменение «$Имя» отменено: найдено совпадений — $количество. Файл не записан."
    }
}

function Заменить-Участок(
    [string]$Текст,
    [string]$Маркер,
    [string]$Замена,
    [string]$Имя
) {
    Проверить-Совпадение $Текст $Маркер $Имя
    return $Текст.Replace($Маркер, $Замена)
}

