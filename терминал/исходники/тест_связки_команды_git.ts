import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьБезопаснуюGitКоманду,
} from "./связка_команды_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ СВЯЗКИ РУССКИХ КОМАНД С GIT");
console.log("===================================");
console.log("");

const состояние = разобратьКоманду(
    "состояние",
);

проверить(
    состояние !== undefined,
    "Команда «состояние» разобрана",
);

if (состояние !== undefined) {
    const результат = выполнитьБезопаснуюGitКоманду(
        состояние,
    );

    проверить(
        результат.выполнено,
        "«состояние» реально выполнено через Git",
    );

    проверить(
        результат.вывод.includes("##"),
        "«состояние» вернула состояние ветки",
    );
}

const изменения = разобратьКоманду(
    "изменения",
);

проверить(
    изменения !== undefined,
    "Команда «изменения» разобрана",
);

if (изменения !== undefined) {
    const результат = выполнитьБезопаснуюGitКоманду(
        изменения,
    );

    проверить(
        результат.выполнено,
        "«изменения» реально выполнена через Git",
    );
}

const история = разобратьКоманду(
    "история",
);

проверить(
    история !== undefined,
    "Команда «история» разобрана",
);

if (история !== undefined) {
    const результат = выполнитьБезопаснуюGitКоманду(
        история,
    );

    проверить(
        результат.выполнено,
        "«история» реально выполнена через Git",
    );

    проверить(
        результат.вывод.trim().length > 0,
        "«история» вернула записи",
    );
}

const сохранить = разобратьКоманду(
    "сохранить",
);

проверить(
    сохранить !== undefined,
    "Команда «сохранить» разобрана",
);

if (сохранить !== undefined) {
    const результат = выполнитьБезопаснуюGitКоманду(
        сохранить,
    );

    проверить(
        результат.выполнено === false,
        "«сохранить» пока защищена от выполнения",
    );

    проверить(
        результат.сообщение.includes("защищена"),
        "Причина блокировки «сохранить» сообщается",
    );
}

console.log("");
console.log("🐌 ТЕСТ СВЯЗКИ РУССКИХ КОМАНД С GIT ЗАВЕРШЁН");
console.log("");
