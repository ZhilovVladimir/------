import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьКоманду,
} from "./исполнитель_команд.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ ИСПОЛНИТЕЛЯ РУССКИХ КОМАНД");
console.log("=================================");
console.log("");

const состояние = разобратьКоманду(
    "состояние",
);

проверить(
    состояние !== undefined,
    "Команда «состояние» разобрана",
);

if (состояние !== undefined) {
    const результат = выполнитьКоманду(
        состояние,
    );

    проверить(
        результат.успешно,
        "Команда «состояние» принята исполнителем",
    );

    проверить(
        результат.действие === "состояние",
        "Исполнитель определил действие «состояние»",
    );

    проверить(
        результат.сообщение ===
            "Команда «состояние» принята к выполнению",
        "Исполнитель сформировал правильное сообщение",
    );
}

const сохранить = разобратьКоманду(
    "сохранить Улитка",
);

проверить(
    сохранить !== undefined,
    "Команда «сохранить Улитка» разобрана",
);

if (сохранить !== undefined) {
    const результат = выполнитьКоманду(
        сохранить,
    );

    проверить(
        результат.успешно,
        "Команда «сохранить» принята исполнителем",
    );

    проверить(
        результат.действие === "сохранить",
        "Исполнитель определил действие «сохранить»",
    );
}

const запустить = разобратьКоманду(
    "запустить",
);

проверить(
    запустить !== undefined,
    "Команда «запустить» разобрана",
);

if (запустить !== undefined) {
    const результат = выполнитьКоманду(
        запустить,
    );

    проверить(
        результат.успешно,
        "Команда «запустить» принята исполнителем",
    );

    проверить(
        результат.действие === "запустить",
        "Исполнитель определил действие «запустить»",
    );
}

