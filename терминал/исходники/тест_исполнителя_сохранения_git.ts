import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьСохранение,
} from "./исполнитель_сохранения_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 БЕЗОПАСНЫЙ ТЕСТ ИСПОЛНИТЕЛЯ «СОХРАНИТЬ»");
console.log("============================================");
console.log("");

const пустаяКоманда = разобратьКоманду(
    "сохранить",
);

проверить(
    пустаяКоманда !== undefined,
    "Команда «сохранить» разобрана",
);

if (пустаяКоманда === undefined) {
    throw new Error(
        "Команда сохранения не была разобрана.",
    );
}

проверить(
    пустаяКоманда.команда.действие === "сохранить",
    "Определено действие «сохранить»",
);

проверить(
    пустаяКоманда.аргументы.length === 0,
    "Для пустой команды аргументы отсутствуют",
);

const пустойРезультат =
    выполнитьСохранение(пустаяКоманда);

проверить(
    !пустойРезультат.выполнено,
    "Сохранение без сообщения заблокировано",
);

проверить(
    пустойРезультат.ошибка.includes(
        "Необходимо указать сообщение",
    ),
    "Для пустого сообщения возвращена ошибка",
);

console.log("");

const командаССообщением = разобратьКоманду(
    "сохранить Проверка безопасного исполнителя",
);

проверить(
    командаССообщением !== undefined,
    "Команда с сообщением разобрана",
);

if (командаССообщением === undefined) {
    throw new Error(
        "Команда сохранения с сообщением не была разобрана.",
    );
}

проверить(
    командаССообщением.команда.действие === "сохранить",
    "Команда с сообщением определена как «сохранить»",
);

проверить(
    командаССообщением.аргументы.length > 0,
    "Сообщение сохранения передано как аргументы",
);

проверить(
    командаССообщением.аргументы.join(" ") ===
        "Проверка безопасного исполнителя",
    "Сообщение сохранения разобрано без потери текста",
);

console.log("");
console.log(
    "⚠️ Настоящий git commit этим тестом НЕ выполняется.",
);
console.log(
    "⚠️ История Git этим тестом НЕ изменяется.",
);
console.log("");

console.log(
    "🐌 БЕЗОПАСНЫЙ ТЕСТ ИСПОЛНИТЕЛЯ «СОХРАНИТЬ» ЗАВЕРШЁН",
);
console.log("");
