import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьСохранение,
} from "./исполнитель_сохранения_git.js";

import {
    выполнитьGit,
} from "./исполнитель_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ НАСТОЯЩЕЙ КОМАНДЫ «СОХРАНИТЬ»");
console.log("=======================================");
console.log("");

const пустаяКоманда = разобратьКоманду(
    "сохранить",
);

проверить(
    пустаяКоманда !== undefined,
    "Команда «сохранить» разобрана",
);

if (пустаяКоманда === undefined) {
    throw new Error(
        "Команда сохранения не была разобрана.",
    );
}

const пустойРезультат =
    выполнитьСохранение(пустаяКоманда);

проверить(
    !пустойРезультат.выполнено,
    "Сохранение без сообщения заблокировано",
);

проверить(
    пустойРезультат.ошибка.includes(
        "Необходимо указать сообщение",
    ),
    "Для пустого сообщения возвращена ошибка",
);

console.log("");

const сообщение =
    "Проверена настоящая команда сохранения Git";

const команда = разобратьКоманду(
    `сохранить ${сообщение}`,
);

проверить(
    команда !== undefined,
    "Команда настоящего сохранения разобрана",
);

if (команда === undefined) {
    throw new Error(
        "Команда настоящего сохранения не была разобрана.",
    );
}

проверить(
    команда.команда.действие === "сохранить",
    "Определено действие «сохранить»",
);

проверить(
    команда.аргументы.length > 0,
    "Передано сообщение сохранения",
);

const результат =
    выполнитьСохранение(команда);

проверить(
    результат.выполнено,
    "Настоящий git commit выполнен",
);

проверить(
    результат.ошибка.length === 0,
    "Git не сообщил об ошибке",
);

console.log("");
console.log("Сообщение:");
console.log(результат.сообщение);
console.log("");

console.log("Вывод Git:");
console.log(
    результат.вывод || "Git не вернул дополнительный вывод.",
);
console.log("");

const история = выполнитьGit({
    команда: "log",
    аргументы: [
        "-1",
        "--oneline",
    ],
});

проверить(
    история.успешно,
    "История Git получена",
);

проверить(
    история.вывод.includes(
        "Проверена настоящая команда сохранения Git",
    ),
    "Последнее сохранение содержит указанное сообщение",
);

console.log("");
console.log("Последнее сохранение:");
console.log(
    история.вывод.trim(),
);
console.log("");

console.log(
    "🐌 ТЕСТ НАСТОЯЩЕЙ КОМАНДЫ «СОХРАНИТЬ» ЗАВЕРШЁН",
);
console.log("");