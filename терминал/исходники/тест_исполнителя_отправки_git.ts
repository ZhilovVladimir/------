import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьОтправку,
} from "./исполнитель_отправки_git.js";

import {
    выполнитьGit,
} from "./исполнитель_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ НАСТОЯЩЕЙ КОМАНДЫ «ОТПРАВИТЬ»");
console.log("=======================================");
console.log("");

const команда = разобратьКоманду(
    "отправить",
);

проверить(
    команда !== undefined,
    "Команда «отправить» разобрана",
);

if (команда === undefined) {
    throw new Error(
        "Команда отправки не была разобрана.",
    );
}

проверить(
    команда.команда.действие === "отправить",
    "Определено действие «отправить»",
);

проверить(
    команда.аргументы.length === 0,
    "Для отправки не требуются аргументы",
);

console.log("");
console.log(
    "⚠️ Настоящий git push уже будет выполнен.",
);
console.log(
    "⚠️ Изменения будут отправлены в удалённый репозиторий.",
);
console.log("");

const результат =
    выполнитьОтправку(команда);

проверить(
    результат.выполнено,
    "Настоящий git push выполнен",
);

console.log("");
console.log("Сообщение:");
console.log(результат.сообщение);
console.log("");

console.log("Вывод Git:");
console.log(
    результат.вывод ||
    "Git не вернул дополнительный вывод.",
);
console.log("");

if (результат.ошибка.length > 0) {
    console.log("Дополнительный вывод Git:");
    console.log(результат.ошибка);
    console.log("");
}

const состояние = выполнитьGit({
    команда: "status",
    аргументы: [
        "--short",
        "--branch",
    ],
});

проверить(
    состояние.успешно,
    "Состояние Git получено после отправки",
);

проверить(
    состояние.вывод.includes(
        "master...origin/master",
    ),
    "Локальная и удалённая ветви связаны",
);

console.log("");
console.log("Состояние после отправки:");
console.log(состояние.вывод.trim());
console.log("");

console.log(
    "🐌 ТЕСТ НАСТОЯЩЕЙ КОМАНДЫ «ОТПРАВИТЬ» ЗАВЕРШЁН",
);
console.log("");