import {
    spawnSync,
} from "node:child_process";

export interface РезультатGit {
    успешно: boolean;
    кодЗавершения: number | null;
    вывод: string;
    ошибка: string;
}

export interface ПараметрыGit {
    /**
     * Параметры Git, которые должны находиться
     * перед названием команды.
     *
     * Например:
     *
     * git -c core.quotePath=false status
     *
     * Здесь:
     * параметрыПередКомандой:
     * ["-c", "core.quotePath=false"]
     *
     * команда:
     * "status"
     */
    параметрыПередКомандой?: string[];

    /**
     * Название команды Git.
     */
    команда: string;

    /**
     * Аргументы конкретной команды Git.
     */
    аргументы?: string[];
}

export function выполнитьGit(
    параметры: ПараметрыGit,
): РезультатGit {
    const аргументыGit = [
        ...(параметры.параметрыПередКомандой ?? []),
        параметры.команда,
        ...(параметры.аргументы ?? []),
    ];

    const результат = spawnSync(
        "git",
        аргументыGit,
        {
            cwd: process.cwd(),
            encoding: "utf8",
            windowsHide: true,
        },
    );

    const вывод = результат.stdout ?? "";
    const ошибка = результат.stderr ?? "";

    return {
        успешно: результат.status === 0,
        кодЗавершения: результат.status,
        вывод,
        ошибка,
    };
}
