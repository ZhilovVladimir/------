import {
    получитьКоманду,
    type КомандаТерминала,
} from "./словарь_команд.js";

export interface РазобраннаяКоманда {
    исходнаяСтрока: string;
    команда: КомандаТерминала;
    аргументы: string[];
}

export function разобратьКоманду(
    строка: string,
): РазобраннаяКоманда | undefined {
    const исходнаяСтрока = строка.trim();

    if (исходнаяСтрока.length === 0) {
        return undefined;
    }

    const части = исходнаяСтрока.split(/\s+/);
    const имяКоманды = части[0];

    if (имяКоманды === undefined) {
        return undefined;
    }

    const команда = получитьКоманду(имяКоманды);

    if (команда === undefined) {
        return undefined;
    }

    return {
        исходнаяСтрока,
        команда,
        аргументы: части.slice(1),
    };
}
