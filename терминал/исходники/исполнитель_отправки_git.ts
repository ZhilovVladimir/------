import type {
    РазобраннаяКоманда,
} from "./разборщик_команд.js";

import {
    выполнитьGit,
} from "./исполнитель_git.js";

export interface РезультатОтправки {
    выполнено: boolean;
    сообщение: string;
    вывод: string;
    ошибка: string;
}

export function выполнитьОтправку(
    команда: РазобраннаяКоманда,
): РезультатОтправки {
    if (команда.команда.действие !== "отправить") {
        return {
            выполнено: false,
            сообщение:
                `Команда «${команда.команда.имя}» ` +
                `не является командой отправки.`,
            вывод: "",
            ошибка: "",
        };
    }

    const результат = выполнитьGit({
        команда: "push",
        аргументы: [],
    });

    if (!результат.успешно) {
        return {
            выполнено: false,
            сообщение:
                "Не удалось отправить изменения в удалённый репозиторий.",
            вывод: результат.вывод.trim(),
            ошибка: результат.ошибка.trim(),
        };
    }

    return {
        выполнено: true,
        сообщение:
            "Изменения успешно отправлены в удалённый репозиторий.",
        вывод: результат.вывод.trim(),
        ошибка: результат.ошибка.trim(),
    };
}