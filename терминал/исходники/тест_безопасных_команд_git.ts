import {
    получитьСостояниеGit,
    получитьИзмененияGit,
    получитьИсториюGit,
} from "./безопасные_команды_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ БЕЗОПАСНЫХ КОМАНД GIT");
console.log("============================");
console.log("");

const состояние = получитьСостояниеGit();

проверить(
    состояние.успешно,
    "Команда «состояние» выполнена",
);

проверить(
    состояние.кодЗавершения === 0,
    "«состояние» завершилась с кодом 0",
);

проверить(
    состояние.вывод.includes("##"),
    "«состояние» вернула информацию о ветке",
);

console.log("");
console.log("Состояние проекта:");
console.log(состояние.вывод.trim());
console.log("");

const изменения = получитьИзмененияGit();

проверить(
    изменения.успешно,
    "Команда «изменения» выполнена",
);

проверить(
    изменения.кодЗавершения === 0,
    "«изменения» завершилась с кодом 0",
);

console.log("");
console.log("Изменения проекта:");
console.log(
    изменения.вывод.trim().length > 0
        ? изменения.вывод.trim()
        : "Изменений нет.",
);
console.log("");

const история = получитьИсториюGit();

проверить(
    история.успешно,
    "Команда «история» выполнена",
);

проверить(
    история.кодЗавершения === 0,
    "«история» завершилась с кодом 0",
);

проверить(
    история.вывод.trim().length > 0,
    "«история» вернула записи",
);

console.log("");
console.log("Последние сохранения:");
console.log(история.вывод.trim());
console.log("");

console.log("🐌 ТЕСТ БЕЗОПАСНЫХ КОМАНД GIT ЗАВЕРШЁН");
console.log("");
