import type {
    ДействиеКоманды,
} from "./словарь_команд.js";

export interface КомандаGit {
    действие: ДействиеКоманды;
    команда: string;
    описание: string;
    изменяетПроект: boolean;
}

export function получитьКомандуGit(
    действие: ДействиеКоманды,
): КомандаGit | undefined {
    switch (действие) {
        case "состояние":
            return {
                действие,
                команда: "git status",
                описание: "показать состояние проекта",
                изменяетПроект: false,
            };

        case "изменения":
            return {
                действие,
                команда: "git diff",
                описание: "показать изменения проекта",
                изменяетПроект: false,
            };

        case "история":
            return {
                действие,
                команда: "git log",
                описание: "показать историю сохранений",
                изменяетПроект: false,
            };

        case "подготовить":
            return {
                действие,
                команда: "git add",
                описание: "подготовить изменения к сохранению",
                изменяетПроект: true,
            };

        case "сохранить":
            return {
                действие,
                команда: "git commit",
                описание: "создать сохранение проекта",
                изменяетПроект: true,
            };

        case "отправить":
            return {
                действие,
                команда: "git push",
                описание: "отправить сохранения на GitHub",
                изменяетПроект: true,
            };

        case "получить":
            return {
                действие,
                команда: "git pull",
                описание: "получить изменения с GitHub",
                изменяетПроект: true,
            };

        default:
            return undefined;
    }
}
