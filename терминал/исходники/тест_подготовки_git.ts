import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьКоманду,
} from "./исполнитель_команд.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 БЕЗОПАСНЫЙ ТЕСТ ПОДГОТОВКИ GIT");
console.log("==================================");
console.log("");

const путь =
    "терминал/исходники/подготовка_git.ts";

const команда = разобратьКоманду(
    `подготовить ${путь}`,
);

проверить(
    команда !== undefined,
    "Команда «подготовить» разобрана",
);

if (команда === undefined) {
    throw new Error(
        "Команда «подготовить» не была разобрана.",
    );
}

проверить(
    команда.команда.действие === "подготовить",
    "Определено действие «подготовить»",
);

проверить(
    команда.аргументы.length === 1,
    "Передан ровно один путь",
);

проверить(
    команда.аргументы[0] === путь,
    "Передан именно указанный путь",
);

const результат = выполнитьКоманду(
    команда,
);

проверить(
    результат.успешно,
    "Команда принята исполнителем без изменения проекта",
);

проверить(
    результат.действие === "подготовить",
    "Исполнитель сохранил действие «подготовить»",
);

проверить(
    результат.сообщение.includes("подготовить"),
    "Исполнитель сформировал сообщение о команде «подготовить»",
);

const безПути = разобратьКоманду(
    "подготовить",
);

проверить(
    безПути !== undefined,
    "Команда «подготовить» без пути разбирается",
);

if (безПути !== undefined) {
    проверить(
        безПути.аргументы.length === 0,
        "Для команды без пути аргументы отсутствуют",
    );
}

console.log("");
console.log(
    "⚠ Настоящий git add НЕ выполнялся.",
);
console.log(
    "⚠ Индекс Git НЕ изменялся.",
);
console.log(
    "⚠ git commit, git push и git pull НЕ выполнялись.",
);
console.log("");

console.log(
    "🐌 БЕЗОПАСНЫЙ ТЕСТ ПОДГОТОВКИ GIT ЗАВЕРШЁН",
);
console.log("");
