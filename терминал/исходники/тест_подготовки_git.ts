import {
    подготовитьИзмененияGit,
} from "./подготовка_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ БЕЗОПАСНОЙ ПОДГОТОВКИ GIT");
console.log("================================");
console.log("");

const безПути = подготовитьИзмененияGit([]);

проверить(
    безПути.успешно === false,
    "Пустой список путей отклоняется",
);

проверить(
    безПути.пути.length === 0,
    "При пустом списке пути не передаются",
);

проверить(
    безПути.ошибка.includes("Не указаны"),
    "Для пустого списка возвращается понятная ошибка",
);

const сПутём = подготовитьИзмененияGit([
    "терминал/исходники/подготовка_git.ts",
]);

проверить(
    сПутём.пути.length === 1,
    "Передан ровно один путь",
);

проверить(
    сПутём.пути[0] ===
        "терминал/исходники/подготовка_git.ts",
    "Передан именно указанный путь",
);

console.log("");
console.log("⚠️ Сейчас реальный git add НЕ выполняется.");
console.log("Проверяется только формирование безопасного списка путей.");
