import {
    создатьМодельКоманды,
    нужныАргументы,
    получитьОбязательныеАргументы,
    командаИзменяетПроект,
    командаОпасная,
    type МодельКоманды,
} from "./модель_команды.js";

let проверок = 0;
let успешныхПроверок = 0;

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    проверок++;

    if (условие) {
        успешныхПроверок++;
        console.log(`✓ ${сообщение}`);
    } else {
        console.error(`✗ ${сообщение}`);
    }
}

console.log("");
console.log("🐌 ТЕСТ МОДЕЛИ РАСШИРЯЕМОЙ КОМАНДЫ");
console.log("===================================");
console.log("");

const командаПроверить: МодельКоманды =
    создатьМодельКоманды({
        имя: "проверить",
        группа: "разработка",
        действие: "проверить",
        описание: "проверить проект",
        безопасность: "проверка",
        аргументы: [],
        изменяетПроект: false,
    });

const командаУдалить: МодельКоманды =
    создатьМодельКоманды({
        имя: "удалить",
        группа: "файлы",
        действие: "удалить",
        описание: "удалить файл или папку",
        безопасность: "опасное_изменение",
        аргументы: [
            {
                имя: "путь",
                описание: "путь удаляемого объекта",
                обязательный: true,
                тип: "путь",
            },
        ],
        изменяетПроект: true,
    });

проверить(
    командаПроверить.имя === "проверить",
    "Имя команды определяется правильно",
);

проверить(
    командаПроверить.группа === "разработка",
    "Группа команды определяется правильно",
);

проверить(
    командаПроверить.действие === "проверить",
    "Действие команды определяется правильно",
);

проверить(
    командаПроверить.безопасность === "проверка",
    "Уровень безопасности определяется правильно",
);

проверить(
    командаПроверить.изменяетПроект === false,
    "Команда проверки не изменяет проект",
);

проверить(
    нужныАргументы(командаПроверить) === false,
    "Для команды проверки аргументы не требуются",
);

проверить(
    командаУдалить.аргументы.length === 1,
    "Команда удаления содержит один аргумент",
);

проверить(
    нужныАргументы(командаУдалить) === true,
    "Для команды удаления требуются аргументы",
);

проверить(
    получитьОбязательныеАргументы(командаУдалить).length === 1,
    "Обязательные аргументы определяются правильно",
);

проверить(
    получитьОбязательныеАргументы(командаУдалить)[0]?.имя === "путь",
    "Обязательный аргумент называется «путь»",
);

проверить(
    командаИзменяетПроект(командаУдалить) === true,
    "Команда удаления помечена как изменяющая проект",
);

проверить(
    командаОпасная(командаУдалить) === true,
    "Команда удаления правильно определена как опасная",
);

проверить(
    командаОпасная(командаПроверить) === false,
    "Команда проверки не считается опасной",
);

console.log("");
console.log("===================================");

const ошибок = проверок - успешныхПроверок;

if (ошибок === 0) {
    console.log(
        `🐌 ТЕСТ УСПЕШЕН: ${проверок} проверок пройдено.`,
    );
} else {
    console.error(
        `🐌 ТЕСТ НЕ ПРОЙДЕН: ошибок — ${ошибок}, проверок — ${проверок}.`,
    );
    process.exitCode = 1;
}

console.log("");
