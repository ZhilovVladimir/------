import type {
    РазобраннаяКоманда,
} from "./разборщик_команд.js";

export interface РезультатИсполнения {
    успешно: boolean;
    действие: РазобраннаяКоманда["команда"]["действие"];
    сообщение: string;
}

export function выполнитьКоманду(
    команда: РазобраннаяКоманда,
): РезультатИсполнения {
    return {
        успешно: true,
        действие: команда.команда.действие,
        сообщение: `Команда «${команда.команда.имя}» принята к выполнению`,
    };
}
