import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьКоманду,
} from "./исполнитель_команд.js";

import {
    получитьСообщениеИсполнения,
} from "./сообщения_терминала.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ РУССКИХ СООБЩЕНИЙ ТЕРМИНАЛА");
console.log("===================================");
