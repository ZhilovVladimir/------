const состояние = разобратьКоманду(
    "состояние",
);

проверить(
    состояние !== undefined,
    "Команда «состояние» разобрана",
);

if (состояние !== undefined) {
    const результат = выполнитьКоманду(
        состояние,
    );

    const сообщение = получитьСообщениеИсполнения(
        результат,
    );

    проверить(
        сообщение ===
            "Состояние проекта будет проверено.",
        "Для «состояние» сформировано русское сообщение",
    );
}

