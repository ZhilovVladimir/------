import {
    разобратьКоманду,
} from "./разборщик_команд.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ РАЗБОРЩИКА РУССКИХ КОМАНД");
console.log("=================================");
console.log("");

const состояние = разобратьКоманду("состояние");

проверить(
    состояние !== undefined,
    "Команда «состояние» распознаётся",
);

проверить(
    состояние?.команда.имя === "состояние",
    "Имя команды «состояние» распознаётся правильно",
);

проверить(
    состояние?.команда.действие === "состояние",
    "Действие команды «состояние» определяется правильно",
);

проверить(
    состояние?.аргументы.length === 0,
    "У команды «состояние» нет аргументов",
);

const сохранить = разобратьКоманду(
    "сохранить Улитка",
);

проверить(
    сохранить !== undefined,
    "Команда «сохранить Улитка» распознаётся",
);

проверить(
    сохранить?.команда.имя === "сохранить",
    "Имя команды «сохранить» определяется правильно",
);

проверить(
    сохранить?.команда.действие === "сохранить",
    "Действие команды «сохранить» определяется правильно",
);

проверить(
    сохранить?.аргументы.length === 1,
    "У команды «сохранить» найден один аргумент",
);

проверить(
    сохранить?.аргументы[0] === "Улитка",
    "Аргумент «Улитка» распознаётся правильно",
);

const несколькоАргументов = разобратьКоманду(
    "проверить исходники полный",
);

проверить(
    несколькоАргументов !== undefined,
    "Команда с несколькими аргументами распознаётся",
);

проверить(
    несколькоАргументов?.аргументы.length === 2,
    "Найдено два аргумента",
);

проверить(
    несколькоАргументов?.аргументы[0] === "исходники",
    "Первый аргумент распознаётся правильно",
);

проверить(
    несколькоАргументов?.аргументы[1] === "полный",
    "Второй аргумент распознаётся правильно",
);

const сПробелами = разобратьКоманду(
    "   состояние   ",
);

проверить(
    сПробелами?.команда.имя === "состояние",
    "Лишние пробелы в начале и конце обрабатываются",
);

const неизвестная = разобратьКоманду(
    "неизвестная команда",
);

проверить(
    неизвестная === undefined,
    "Неизвестная команда отклоняется",
);

const пустая = разобратьКоманду("   ");

проверить(
    пустая === undefined,
    "Пустая строка отклоняется",
);

