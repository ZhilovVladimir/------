export function получитьКомандуИзКаталога(
    имя: string,
): МодельКоманды | undefined {
    const нормализованноеИмя = имя.trim().toLowerCase();

    return создатьКаталогКоманд().find(
        (команда) => команда.имя === нормализованноеИмя,
    );
}

export function командаЕстьВКаталоге(
    имя: string,
): boolean {
    return получитьКомандуИзКаталога(имя) !== undefined;
}

export function получитьКомандыГруппы(
    группа: МодельКоманды["группа"],
): МодельКоманды[] {
    return создатьКаталогКоманд().filter(
        (команда) => команда.группа === группа,
    );
}

export function количествоКомандКаталога(): number {
    return создатьКаталогКоманд().length;
}