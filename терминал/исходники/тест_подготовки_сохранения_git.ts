import {
    подготовитьСохранениеGit,
} from "./подготовка_сохранения_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ ПОДГОТОВКИ КОМАНДЫ «СОХРАНИТЬ»");
console.log("=======================================");
console.log("");

const сообщение =
    "Проверена команда сохранения Git";

const результат =
    подготовитьСохранениеGit(сообщение);

проверить(
    результат.успешно,
    "Сообщение сохранения принято",
);

проверить(
    результат.вывод.includes("git commit"),
    "Подготовлена команда git commit",
);

проверить(
    результат.вывод.includes(
        "Проверена команда сохранения Git",
    ),
    "Сообщение передано в git commit",
);

console.log("");
console.log("Подготовленная команда:");
console.log(результат.вывод);
console.log("");

const пустое =
    подготовитьСохранениеGit("");

проверить(
    !пустое.успешно,
    "Пустое сообщение отклонено",
);

проверить(
    пустое.ошибка.includes(
        "необходимо указать сообщение",
    ),
    "Для пустого сообщения возвращена ошибка",
);

console.log("");
console.log(
    "⚠️ Настоящий git commit этим тестом не выполнялся.",
);
console.log("");

console.log(
    "🐌 ТЕСТ ПОДГОТОВКИ КОМАНДЫ «СОХРАНИТЬ» ЗАВЕРШЁН",
);
console.log("");