import {
    выполнитьGit,
    type РезультатGit,
} from "./исполнитель_git.js";

const НАСТРОЙКИ_РУССКИХ_ПУТЕЙ_GIT = [
    "-c",
    "core.quotePath=false",
];

export function получитьСостояниеGit(): РезультатGit {
    return выполнитьGit({
        параметрыПередКомандой:
            НАСТРОЙКИ_РУССКИХ_ПУТЕЙ_GIT,
        команда: "status",
        аргументы: [
            "--short",
            "--branch",
        ],
    });
}

export function получитьИзмененияGit(): РезультатGit {
    return выполнитьGit({
        параметрыПередКомандой:
            НАСТРОЙКИ_РУССКИХ_ПУТЕЙ_GIT,
        команда: "diff",
        аргументы: [
            "--stat",
        ],
    });
}

export function получитьИсториюGit(): РезультатGit {
    return выполнитьGit({
        параметрыПередКомандой:
            НАСТРОЙКИ_РУССКИХ_ПУТЕЙ_GIT,
        команда: "log",
        аргументы: [
            "-5",
            "--oneline",
        ],
    });
}