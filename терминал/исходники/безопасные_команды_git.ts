import {
    выполнитьGit,
    type РезультатGit,
} from "./исполнитель_git.js";

export function получитьСостояниеGit(): РезультатGit {
    return выполнитьGit({
        команда: "status",
        аргументы: ["--short", "--branch"],
    });
}

export function получитьИзмененияGit(): РезультатGit {
    return выполнитьGit({
        команда: "diff",
    });
}

export function получитьИсториюGit(): РезультатGit {
    return выполнитьGit({
        команда: "log",
        аргументы: ["-5", "--oneline"],
    });
}
