import type {
    АргументКоманды,
    МодельКоманды,
} from "./модель_команды.js";

export interface РезультатПроверкиАргументов {
    корректно: boolean;
    ошибки: string[];
    значения: string[];
}

export function проверитьАргументыКоманды(
    команда: МодельКоманды,
    аргументы: string[],
): РезультатПроверкиАргументов {
    const ошибки: string[] = [];
    const значения = аргументы
        .map((аргумент) => аргумент.trim())
        .filter((аргумент) => аргумент.length > 0);

    const обязательныеАргументы = команда.аргументы.filter(
        (аргумент) => аргумент.обязательный,
    );

    if (значения.length < обязательныеАргументы.length) {
        for (
            let индекс = значения.length;
            индекс < обязательныеАргументы.length;
            индекс++
        ) {
            const аргумент = обязательныеАргументы[индекс];

            if (аргумент !== undefined) {
                ошибки.push(
                    `Для команды «${команда.имя}» требуется аргумент «${аргумент.имя}».`,
                );
            }
        }
    }

    if (значения.length > команда.аргументы.length) {
        ошибки.push(
            `Команда «${команда.имя}» получила слишком много аргументов.`,
        );
    }

    for (
        let индекс = 0;
        индекс < значения.length;
        индекс++
    ) {
        const значение = значения[индекс];
        const описаниеАргумента = команда.аргументы[индекс];

        if (
            значение === undefined ||
            описаниеАргумента === undefined
        ) {
            continue;
        }

        const ошибкаТипа = проверитьТипАргумента(
            описаниеАргумента,
            значение,
        );

        if (ошибкаТипа !== null) {
            ошибки.push(ошибкаТипа);
        }
    }

    return {
        корректно: ошибки.length === 0,
        ошибки,
        значения,
    };
}

function проверитьТипАргумента(
    аргумент: АргументКоманды,
    значение: string,
): string | null {
    if (значение.length === 0) {
        return `Аргумент «${аргумент.имя}» не может быть пустым.`;
    }

    if (аргумент.тип === "нет") {
        return null;
    }

    if (аргумент.тип === "текст") {
        return null;
    }

    if (аргумент.тип === "имя") {
        if (!/^[А-Яа-яЁёA-Za-z_][А-Яа-яЁёA-Za-z0-9_]*$/.test(значение)) {
            return `Аргумент «${аргумент.имя}» должен быть именем.`;
        }

        return null;
    }

    if (аргумент.тип === "путь") {
        if (/[<>:"|?*]/.test(значение)) {
            return `Аргумент «${аргумент.имя}» содержит недопустимые символы пути.`;
        }

        return null;
    }

    return null;
}