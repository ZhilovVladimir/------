/**

* ============================================================
* 🐌 УЛИТКА
* Модель расширяемой команды терминала
* Этап 3.4.1
* ============================================================
*
* Этот файл НЕ выполняет команды.
*
* Он описывает:
* * название команды;
* * группу;
* * действие;
* * описание;
* * аргументы;
* * уровень безопасности;
* * изменение проекта.
*
* Исполнение будет находиться в других слоях.
* ============================================================
  */

/**

* Группы команд среды «Улитки».
  */
  export type ГруппаКоманды =
  | "справка"
  | "проект"
  | "файлы"
  | "разработка"
  | "тестирование"
  | "git"
  | "терминал";

/**

* Уровень безопасности команды.
*
* наблюдение
* Только получение информации.
*
* проверка
* Проверка проекта без изменения его состояния.
*
* изменение
* Команда может изменить проект.
*
* опасное_изменение
* Команда может существенно изменить состояние проекта
* или его историю.
  */
  export type УровеньБезопасности =
  | "наблюдение"
  | "проверка"
  | "изменение"
  | "опасное_изменение";

/**

* Тип аргумента команды.
  */
  export type ТипАргумента =
  | "нет"
  | "текст"
  | "имя"
  | "путь";

/**

* Описание одного аргумента команды.
  */
  export interface АргументКоманды {
  имя: string;
  описание: string;
  обязательный: boolean;
  тип: ТипАргумента;
  }

/**

* Полное описание команды.
  */
  export interface МодельКоманды {
  имя: string;
  группа: ГруппаКоманды;
  действие: string;
  описание: string;
  безопасность: УровеньБезопасности;
  аргументы: АргументКоманды[];
  изменяетПроект: boolean;
  }

/**

* Создаёт описание команды.
*
* Функция ничего не выполняет.
* Она только создаёт единое описание,
* которое смогут использовать разборщик,
* проверка аргументов и исполнитель.
  */
  export function создатьМодельКоманды(
  параметры: МодельКоманды,
  ): МодельКоманды {
  return {
  ...параметры,
  аргументы: [...параметры.аргументы],
  };
  }

/**

* Проверяет, требуется ли команде аргумент.
  */
  export function нужныАргументы(
  команда: МодельКоманды,
  ): boolean {
  return команда.аргументы.length > 0;
  }

/**

* Возвращает обязательные аргументы команды.
  */
  export function получитьОбязательныеАргументы(
  команда: МодельКоманды,
  ): АргументКоманды[] {
  return команда.аргументы.filter(
  (аргумент) => аргумент.обязательный,
  );
  }

/**

* Проверяет, изменяет ли команда проект.
  */
  export function командаИзменяетПроект(
  команда: МодельКоманды,
  ): boolean {
  return команда.изменяетПроект;
  }

/**

* Проверяет, относится ли команда
* к потенциально опасным операциям.
  */
  export function командаОпасная(
  команда: МодельКоманды,
  ): boolean {
  return команда.безопасность === "опасное_изменение";
  }
