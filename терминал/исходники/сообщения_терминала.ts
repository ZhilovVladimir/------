import type {
    РезультатИсполнения,
} from "./исполнитель_команд.js";

export function получитьСообщениеИсполнения(
    результат: РезультатИсполнения,
): string {
    switch (результат.действие) {
        case "помощь":
            return "Показаны доступные команды.";

        case "состояние":
            return "Состояние проекта будет проверено.";

        case "изменения":
            return "Изменения проекта будут проверены.";

        case "история":
            return "История сохранений будет показана.";

        case "подготовить":
            return "Изменения будут подготовлены к сохранению.";

        case "сохранить":
            return "Изменения будут сохранены.";

        case "отправить":
            return "Сохранения будут отправлены на GitHub.";

        case "получить":
            return "Изменения будут получены с GitHub.";

        case "проверить":
            return "Проверка проекта будет выполнена.";

        case "собрать":
            return "Сборка проекта будет выполнена.";

        case "запустить":
            return "Проект будет запущен.";

        case "очистить":
            return "Вывод терминала будет очищен.";

        default:
            return "Команда принята к выполнению.";
    }
}
