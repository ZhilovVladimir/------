import {
    разобратьКоманду,
} from "./разборщик_команд.js";

import {
    выполнитьПодготовку,
} from "./исполнитель_подготовки_git.js";

import {
    выполнитьGit,
} from "./исполнитель_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ НАСТОЯЩЕЙ КОМАНДЫ «ПОДГОТОВИТЬ»");
console.log("========================================");
console.log("");

const путь =
    "терминал/исходники/подготовка_git.ts";

const команда = разобратьКоманду(
    `подготовить ${путь}`,
);

проверить(
    команда !== undefined,
    "Команда «подготовить» разобрана",
);

if (команда === undefined) {
    throw new Error(
        "Команда подготовки не была разобрана.",
    );
}

проверить(
    команда.команда.действие === "подготовить",
    "Определено действие «подготовить»",
);

проверить(
    команда.аргументы.length === 1,
    "Передан ровно один путь",
);

проверить(
    команда.аргументы[0] === путь,
    "Передан правильный путь",
);

const результат = выполнитьПодготовку(
    команда,
);

проверить(
    результат.выполнено,
    "Файл реально подготовлен через Git",
);

проверить(
    результат.пути.length === 1,
    "Git получил только один путь",
);

console.log("");
console.log("Сообщение:");
console.log(результат.сообщение);
console.log("");

const индекс = выполнитьGit({
    команда: "diff",
    аргументы: [
        "--cached",
        "--name-only",
        "-z",
        "--",
        путь,
    ],
});

проверить(
    индекс.успешно,
    "Состояние подготовленной области получено",
);

const подготовленныеПути = индекс.вывод
    .split("\0")
    .map((строка) => строка.trim())
    .filter((строка) => строка.length > 0);

проверить(
    подготовленныеПути.length === 1,
    "В подготовленной области найден ровно один файл",
);

проверить(
    подготовленныеПути[0] === путь,
    "В подготовленной области находится именно указанный файл",
);

console.log("");
console.log("Подготовленный файл:");
console.log(
    подготовленныеПути[0] ?? "Не найден",
);
console.log("");

console.log(
    "⚠️ Подготовлен только один указанный файл.",
);
console.log(
    "⚠️ git commit, git push и git pull не выполнялись.",
);
console.log("");

console.log(
    "🐌 ТЕСТ НАСТОЯЩЕЙ КОМАНДЫ «ПОДГОТОВИТЬ» ЗАВЕРШЁН",
);
console.log("");