import type {
    РезультатGit,
} from "./исполнитель_git.js";

export interface ПараметрыСохраненияGit {
    сообщение: string;
}

export function подготовитьСохранениеGit(
    сообщение: string,
): РезультатGit {
    const очищенноеСообщение = сообщение.trim();

    if (очищенноеСообщение.length === 0) {
        return {
            успешно: false,
            кодЗавершения: null,
            вывод: "",
            ошибка:
                "Для сохранения необходимо указать сообщение.",
        };
    }

    return {
        успешно: true,
        кодЗавершения: null,
        вывод:
            `git commit -m "${очищенноеСообщение}"`,
        ошибка: "",
    };
}