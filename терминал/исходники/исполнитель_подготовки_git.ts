import type {
    РазобраннаяКоманда,
} from "./разборщик_команд.js";

import {
    подготовитьИзмененияGit,
} from "./подготовка_git.js";

export interface РезультатПодготовки {
    выполнено: boolean;
    сообщение: string;
    вывод: string;
    пути: string[];
}

export function выполнитьПодготовку(
    команда: РазобраннаяКоманда,
): РезультатПодготовки {
    if (команда.команда.действие !== "подготовить") {
        return {
            выполнено: false,
            сообщение:
                `Команда «${команда.команда.имя}» ` +
                `не является командой подготовки.`,
            вывод: "",
            пути: [],
        };
    }

    if (команда.аргументы.length === 0) {
        return {
            выполнено: false,
            сообщение:
                "Для команды «подготовить» " +
                "не указаны файлы или папки.",
            вывод: "",
            пути: [],
        };
    }

    const результат = подготовитьИзмененияGit(
        команда.аргументы,
    );

    if (!результат.успешно) {
        return {
            выполнено: false,
            сообщение:
                "Не удалось подготовить указанные изменения.",
            вывод: результат.ошибка.trim(),
            пути: результат.пути,
        };
    }

    return {
        выполнено: true,
        сообщение:
            "Указанные изменения подготовлены к сохранению.",
        вывод: результат.вывод,
        пути: результат.пути,
    };
}