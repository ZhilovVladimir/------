import type {
    РазобраннаяКоманда,
} from "./разборщик_команд.js";

import {
    выполнитьGit,
} from "./исполнитель_git.js";

export interface РезультатСохранения {
    выполнено: boolean;
    сообщение: string;
    вывод: string;
    ошибка: string;
}

export function выполнитьСохранение(
    команда: РазобраннаяКоманда,
): РезультатСохранения {
    if (команда.команда.действие !== "сохранить") {
        return {
            выполнено: false,
            сообщение:
                `Команда «${команда.команда.имя}» ` +
                `не является командой сохранения.`,
            вывод: "",
            ошибка: "",
        };
    }

    if (команда.аргументы.length === 0) {
        return {
            выполнено: false,
            сообщение:
                "Для команды «сохранить» " +
                "не указано сообщение.",
            вывод: "",
            ошибка:
                "Необходимо указать сообщение сохранения.",
        };
    }

    const сообщение =
        команда.аргументы.join(" ").trim();

    if (сообщение.length === 0) {
        return {
            выполнено: false,
            сообщение:
                "Сообщение сохранения не может быть пустым.",
            вывод: "",
            ошибка:
                "Пустое сообщение сохранения.",
        };
    }

    const результат = выполнитьGit({
        команда: "commit",
        аргументы: [
            "-m",
            сообщение,
        ],
    });

    if (!результат.успешно) {
        return {
            выполнено: false,
            сообщение:
                "Не удалось сохранить изменения.",
            вывод: результат.вывод.trim(),
            ошибка: результат.ошибка.trim(),
        };
    }

    return {
        выполнено: true,
        сообщение:
            "Изменения успешно сохранены в Git.",
        вывод: результат.вывод.trim(),
        ошибка: результат.ошибка.trim(),
    };
}