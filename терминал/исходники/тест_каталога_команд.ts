import {
    создатьКаталогКоманд,
    получитьКомандуИзКаталога,
    командаЕстьВКаталоге,
    получитьКомандыГруппы,
    количествоКомандКаталога,
} from "./каталог_команд.js";

let проверок = 0;
let успешныхПроверок = 0;

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    проверок++;

    if (условие) {
        успешныхПроверок++;
        console.log(`✓ ${сообщение}`);
    } else {
        console.error(`✗ ${сообщение}`);
    }
}

console.log("");
console.log("🐌 ТЕСТ КАТАЛОГА РАСШИРЯЕМЫХ КОМАНД");
console.log("====================================");
console.log("");

const команды = создатьКаталогКоманд();

проверить(
    команды.length === количествоКомандКаталога(),
    "Количество команд каталога определяется правильно",
);

проверить(
    команды.length >= 10,
    "Каталог содержит не менее десяти команд",
);

проверить(
    командаЕстьВКаталоге("помощь"),
    "Команда «помощь» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("показать"),
    "Команда «показать» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("создать"),
    "Команда «создать» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("удалить"),
    "Команда «удалить» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("проверить"),
    "Команда «проверить» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("собрать"),
    "Команда «собрать» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("запустить"),
    "Команда «запустить» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("сохранить"),
    "Команда «сохранить» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("отправить"),
    "Команда «отправить» есть в каталоге",
);

проверить(
    командаЕстьВКаталоге("НЕСУЩЕСТВУЮЩАЯ") === false,
    "Несуществующая команда правильно отклоняется",
);

const командаУдалить =
    получитьКомандуИзКаталога("удалить");

проверить(
    командаУдалить !== undefined,
    "Команда удаления получается из каталога",
);

проверить(
    командаУдалить?.группа === "файлы",
    "Команда удаления относится к группе «файлы»",
);

проверить(
    командаУдалить?.изменяетПроект === true,
    "Команда удаления помечена как изменяющая проект",
);

проверить(
    командаУдалить?.безопасность === "опасное_изменение",
    "Команда удаления имеет опасный уровень безопасности",
);

const командаСохранить =
    получитьКомандуИзКаталога("СОХРАНИТЬ");

проверить(
    командаСохранить !== undefined,
    "Поиск команды не зависит от регистра букв",
);

проверить(
    командаСохранить?.группа === "git",
    "Команда сохранения относится к группе Git",
);

проверить(
    командаСохранить?.аргументы[0]?.имя === "сообщение",
    "Команда сохранения требует сообщение",
);

const командыФайлов =
    получитьКомандыГруппы("файлы");

проверить(
    командыФайлов.length === 3,
    "В группе «файлы» зарегистрированы три команды",
);

проверить(
    командыФайлов.some(
        (команда) => команда.имя === "показать",
    ),
    "Группа «файлы» содержит команду «показать»",
);

проверить(
    командыФайлов.some(
        (команда) => команда.имя === "создать",
    ),
    "Группа «файлы» содержит команду «создать»",
);

проверить(
    командыФайлов.some(
        (команда) => команда.имя === "удалить",
    ),
    "Группа «файлы» содержит команду «удалить»",
);

console.log("");
console.log("====================================");

const ошибок = проверок - успешныхПроверок;

if (ошибок === 0) {
    console.log(
        `🐌 ТЕСТ УСПЕШЕН: ${проверок} проверок пройдено.`,
    );
} else {
    console.error(
        `🐌 ТЕСТ НЕ ПРОЙДЕН: ошибок — ${ошибок}, проверок — ${проверок}.`,
    );

    process.exitCode = 1;
}

