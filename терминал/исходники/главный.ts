function безопасноеЗначение(
    значение: unknown,
): string {
    if (typeof значение === "string") {
        return значение;
    }

    if (
        typeof значение === "number" ||
        typeof значение === "boolean" ||
        typeof значение === "bigint"
    ) {
        return String(значение);
    }

    if (значение === null) {
        return "пусто";
    }

    if (значение === undefined) {
        return "не определено";
    }

    try {
        return JSON.stringify(
            значение,
            null,
            2,
        );
    } catch {
        return String(значение);
    }
}

function показатьПеременные(
    переменные:
        | Record<string, unknown>
        | undefined,
): void {
    очиститьНаблюдение(
        элементы.переменные,
    );

    if (!переменные) {
        показатьСообщениеНаблюдения(
            элементы.переменные,
            "ядро не передало переменные",
        );
        return;
    }

    const имена =
        Object.keys(переменные);

    if (имена.length === 0) {
        показатьСообщениеНаблюдения(
            элементы.переменные,
            "переменных пока нет",
        );
        return;
    }

    for (const имя of имена) {
        const элемент =
            document.createElement("div");

        элемент.className =
            "элемент-наблюдения";

        const название =
            document.createElement("strong");

        название.textContent =
            имя;

        const значение =
            document.createElement("span");

        значение.textContent =
            ` = ${безопасноеЗначение(
                переменные[имя],
            )}`;

        элемент.appendChild(
            название,
        );

        элемент.appendChild(
            значение,
        );

        элементы.переменные?.appendChild(
            элемент,
        );
    }
}

/**
 * ============================================================
 * ФУНКЦИИ
 *
 * Объявленные функции берутся из семантического анализа.
 * Вызовы функций берутся только из событий выполнения.
 *
 * Объявлена функция ≠ функция вызвана.
 *
 * Терминал не делает предположений.
 * ============================================================
 */

function получитьЗаписьСобытия(
    событие: unknown,
): Record<string, unknown> | null {
    if (
        typeof событие !== "object" ||
        событие === null
    ) {
        return null;
    }

    return событие as Record<
        string,
        unknown
    >;
}

function получитьДанныеСобытия(
    событие: unknown,
): Record<string, unknown> | null {
    const запись =
        получитьЗаписьСобытия(
            событие,
        );

    if (!запись) {
        return null;
    }

    const данные =
        запись["данные"];

    if (
        typeof данные !== "object" ||
        данные === null
    ) {
        return null;
    }

    return данные as Record<
        string,
        unknown
    >;
}

function получитьИмяСобытия(
    событие: unknown,
): string | null {
    const запись =
        получитьЗаписьСобытия(
            событие,
        );

    if (!запись) {
        return null;
    }

    const возможныеИмена = [
        "имя",
        "функция",
        "название",
        "тип",
        "событие",
    ];

    for (const ключ of возможныеИмена) {
        const значение =
            запись[ключ];

        if (
            typeof значение === "string"
        ) {
            return значение;
        }
    }

    return null;
}

function являетсяСобытиемВызоваФункции(
    событие: unknown,
): boolean {
    const запись =
        получитьЗаписьСобытия(
            событие,
        );

    if (!запись) {
        return false;
    }

    const значения: string[] = [];

    for (const ключ of [
        "тип",
        "событие",
        "название",
        "имя",
        "функция",
    ]) {
        const значение =
            запись[ключ];

        if (
            typeof значение === "string"
        ) {
            значения.push(
                значение.toLowerCase(),
            );
        }
    }

    const источник =
        запись["источник"];

    if (
        typeof источник === "string"
    ) {
        значения.push(
            источник.toLowerCase(),
        );
    }

    const данные =
        получитьДанныеСобытия(
            событие,
        );

    if (данные) {
        for (const ключ of [
            "тип",
            "событие",
            "название",
            "имя",
            "функция",
        ]) {
            const значение =
                данные[ключ];

            if (
                typeof значение === "string"
            ) {
                значения.push(
                    значение.toLowerCase(),
                );
            }
        }
    }

    return значения.some(
        (значение) =>
            значение.includes(
                "вызов_функции",
            ) ||
            значение.includes(
                "вызов функции",
            ) ||
            значение === "вызов" ||
            значение.startsWith(
                "вызов:",
            ),
    );
}

function получитьИмяВызваннойФункции(
    событие: unknown,
): string | null {
    const запись =
        получитьЗаписьСобытия(
            событие,
        );

    if (!запись) {
        return null;
    }

    const данные =
        получитьДанныеСобытия(
            событие,
        );

    if (данные) {
        for (const ключ of [
            "имя",
            "имяФункции",
            "функция",
            "название",
        ]) {
            const значение =
                данные[ключ];

            if (
                typeof значение === "string" &&
                значение.trim().length > 0
            ) {
                return значение.trim();
            }
        }
    }

    for (const ключ of [
        "имяФункции",
        "функция",
        "имя",
        "название",
    ]) {
        const значение =
            запись[ключ];

        if (
            typeof значение === "string" &&
            значение.trim().length > 0
        ) {
            return значение.trim();
        }
    }

    const источник =
        запись["источник"];

    if (
        typeof источник === "string"
    ) {
        const начало =
            "функция:";

        if (
            источник.startsWith(
                начало,
            )
        ) {
            const имя =
                источник
                    .slice(
                        начало.length,
                    )
                    .trim();

            if (имя.length > 0) {
                return имя;
            }
        }
    }

    return null;
}

function показатьФункции(
    функции:
        | ОбъявленнаяФункция[]
        | undefined,
    события:
        | unknown[]
        | undefined,
): void {
    очиститьНаблюдение(
        элементы.функции,
    );

    if (!функции) {
        показатьСообщениеНаблюдения(
            элементы.функции,
            "сведения о функциях не переданы",
        );
        return;
    }

    const заголовокОбъявленных =
        document.createElement("div");

    заголовокОбъявленных.className =
        "элемент-наблюдения";

    const сильныйЗаголовок =
        document.createElement("strong");

    сильныйЗаголовок.textContent =
        "Объявленные функции";

    заголовокОбъявленных.appendChild(
        сильныйЗаголовок,
    );

    элементы.функции?.appendChild(
        заголовокОбъявленных,
    );

    if (функции.length === 0) {
        показатьСообщениеНаблюдения(
            элементы.функции,
            "  • функций не объявлено",
        );
    } else {
        for (const функция of функции) {
            const параметры =
                функция.параметры.join(
                    ", ",
                );

            const строка =
                document.createElement("div");

            строка.className =
                "элемент-наблюдения";

            строка.textContent =
                `  • ${функция.имя}(${параметры})`;

            элементы.функции?.appendChild(
                строка,
            );
        }
    }

    const заголовокВызовов =
        document.createElement("div");

    заголовокВызовов.className =
        "элемент-наблюдения";

    const сильныйЗаголовокВызовов =
        document.createElement("strong");

    сильныйЗаголовокВызовов.textContent =
        "Вызовы функций";

    заголовокВызовов.appendChild(
        сильныйЗаголовокВызовов,
    );

    элементы.функции?.appendChild(
        заголовокВызовов,
    );

    const вызванныеФункции =
        new Set<string>();

    if (события) {
        for (const событие of события) {
            if (
                !являетсяСобытиемВызоваФункции(
                    событие,
                )
            ) {
                continue;
            }

            const имя =
                получитьИмяВызваннойФункции(
                    событие,
                );

            if (имя) {
                вызванныеФункции.add(
                    имя,
                );
            }
        }
    }

    if (
        вызванныеФункции.size === 0
    ) {
        показатьСообщениеНаблюдения(
            элементы.функции,
            "  • вызовы не зафиксированы",
        );
        return;
    }

    for (
        const имя of вызванныеФункции
    ) {
        показатьСообщениеНаблюдения(
            элементы.функции,
            `  • ${имя}()`,
        );
    }
}

