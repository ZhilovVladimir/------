// ============================================================
// 🐌 УЛИТКА — ТЕРМИНАЛ
// Управляющее ядро интерфейса
// Этап 1 — состояние и управление терминалом
// ============================================================

type СостояниеТерминала =
    | "готов"
    | "выполнение"
    | "остановлено"
    | "завершено";

interface ЭлементыТерминала {
    кнопкаЗапуск: HTMLButtonElement | null;
    кнопкаОстановка: HTMLButtonElement | null;
    вывод: HTMLElement | null;
    состояние: HTMLElement | null;
    состояниеСистемы: HTMLElement | null;
    состояниеРедактора: HTMLElement | null;
    код: HTMLElement | null;
    переменные: HTMLElement | null;
    функции: HTMLElement | null;
}

// ============================================================
// ПОЛУЧЕНИЕ ЭЛЕМЕНТОВ
// ============================================================

const элементы: ЭлементыТерминала = {
    кнопкаЗапуск:
        document.getElementById(
            "кнопка-запуск"
        ) as HTMLButtonElement | null,

    кнопкаОстановка:
        document.getElementById(
            "кнопка-остановка"
        ) as HTMLButtonElement | null,

    вывод:
        document.getElementById("вывод"),

    состояние:
        document.getElementById("состояние"),

    состояниеСистемы:
        document.getElementById(
            "состояние-системы"
        ),

    состояниеРедактора:
        document.getElementById(
            "состояние-редактора"
        ),

    код:
        document.getElementById("код"),

    переменные:
        document.getElementById("переменные"),

    функции:
        document.getElementById("функции"),
};

// ============================================================
// СОСТОЯНИЕ ТЕРМИНАЛА
// ============================================================

let состояниеТерминала:
    СостояниеТерминала = "готов";

let таймерЗавершения:
    ReturnType<typeof setTimeout> | null = null;

// ============================================================
// ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================

function добавитьВывод(
    сообщение: string
): void {

    if (!элементы.вывод) {
        return;
    }

    const строка =
        document.createElement("div");

    строка.textContent = сообщение;

    элементы.вывод.appendChild(строка);

    элементы.вывод.scrollTop =
        элементы.вывод.scrollHeight;
}

function установитьСостояние(
    новоеСостояние: СостояниеТерминала
): void {

    состояниеТерминала =
        новоеСостояние;

    if (элементы.состояние) {

        switch (новоеСостояние) {

            case "готов":
                элементы.состояние.textContent =
                    "● Готово";
                break;

            case "выполнение":
                элементы.состояние.textContent =
                    "● Выполнение";
                break;

            case "остановлено":
                элементы.состояние.textContent =
                    "● Остановлено";
                break;

            case "завершено":
                элементы.состояние.textContent =
                    "● Завершено";
                break;
        }
    }

    if (элементы.состояниеСистемы) {

        switch (новоеСостояние) {

            case "готов":
                элементы.состояниеСистемы.textContent =
                    "● Система готова";
                break;

            case "выполнение":
                элементы.состояниеСистемы.textContent =
                    "● Программа выполняется";
                break;

            case "остановлено":
                элементы.состояниеСистемы.textContent =
                    "● Выполнение остановлено";
                break;

            case "завершено":
                элементы.состояниеСистемы.textContent =
                    "● Программа завершена";
                break;
        }
    }

    if (элементы.состояниеРедактора) {

        switch (новоеСостояние) {

            case "готов":
                элементы.состояниеРедактора.textContent =
                    "готов";
                break;

            case "выполнение":
                элементы.состояниеРедактора.textContent =
                    "выполнение";
                break;

            case "остановлено":
                элементы.состояниеРедактора.textContent =
                    "остановлено";
                break;

            case "завершено":
                элементы.состояниеРедактора.textContent =
                    "завершено";
                break;
        }
    }
}

// ============================================================
// ОЧИСТКА ПРЕДЫДУЩЕГО ВЫПОЛНЕНИЯ
// ============================================================

function очиститьТаймер(): void {

    if (таймерЗавершения !== null) {

        clearTimeout(
            таймерЗавершения
        );

        таймерЗавершения = null;
    }
}

// ============================================================
// ЗАПУСК ПРОГРАММЫ
// ============================================================

function запуститьПрограмму(): void {

    if (
        состояниеТерминала ===
        "выполнение"
    ) {
        добавитьВывод(
            "⚠ Программа уже выполняется."
        );

        return;
    }

    очиститьТаймер();

    установитьСостояние(
        "выполнение"
    );

    добавитьВывод(
        "▶ Запуск программы..."
    );

    добавитьВывод(
        "🐌 Терминал передал управление системе выполнения."
    );

    таймерЗавершения =
        setTimeout(() => {

            таймерЗавершения = null;

            if (
                состояниеТерминала !==
                "выполнение"
            ) {
                return;
            }

            установитьСостояние(
                "завершено"
            );

            добавитьВывод(
                "✓ Выполнение завершено."
            );

            добавитьВывод(
                "● Ошибок интерфейса не обнаружено."
            );

        }, 700);
}

// ============================================================
// ОСТАНОВКА ПРОГРАММЫ
// ============================================================

function остановитьПрограмму(): void {

    if (
        состояниеТерминала !==
        "выполнение"
    ) {
        добавитьВывод(
            "⚠ Сейчас нет выполняемой программы."
        );

        установитьСостояние(
            "остановлено"
        );

        return;
    }

    очиститьТаймер();

    установитьСостояние(
        "остановлено"
    );

    добавитьВывод(
        "■ Выполнение остановлено пользователем."
    );
}

// ============================================================
// НАЧАЛЬНАЯ ПРОВЕРКА ИНТЕРФЕЙСА
// ============================================================

function проверитьИнтерфейс(): void {

    const отсутствующие: string[] = [];

    if (!элементы.кнопкаЗапуск) {
        отсутствующие.push(
            "кнопка-запуск"
        );
    }

    if (!элементы.кнопкаОстановка) {
        отсутствующие.push(
            "кнопка-остановка"
        );
    }

    if (!элементы.вывод) {
        отсутствующие.push(
            "вывод"
        );
    }

    if (!элементы.состояние) {
        отсутствующие.push(
            "состояние"
        );
    }

    if (!элементы.состояниеСистемы) {
        отсутствующие.push(
            "состояние-системы"
        );
    }

    if (!элементы.состояниеРедактора) {
        отсутствующие.push(
            "состояние-редактора"
        );
    }

    if (отсутствующие.length > 0) {

        console.error(
            "🐌 Ошибка интерфейса. Отсутствуют элементы:",
            отсутствующие
        );

        return;
    }

    console.log(
        "🐌 Интерфейс терминала «Улитки» проверен."
    );
}

// ============================================================
// ПОДКЛЮЧЕНИЕ СОБЫТИЙ
// ============================================================

элементы.кнопкаЗапуск?.addEventListener(
    "click",
    запуститьПрограмму
);

элементы.кнопкаОстановка?.addEventListener(
    "click",
    остановитьПрограмму
);

// ============================================================
// ЗАПУСК ТЕРМИНАЛА
// ============================================================

проверитьИнтерфейс();

установитьСостояние(
    "готов"
);

console.log(
    "🐌 Терминал «Улитки» загружен."
);

console.log(
    "Состояние:",
    состояниеТерминала
);