function установитьСтиль(
    имя: string,
    значение: string,
): void {
    if (!элементы.приложение) {
        return;
    }

    элементы.приложение.style.setProperty(
        имя,
        значение,
    );
}

function начатьИзменениеРазмера(
    разделитель: HTMLElement,
    тип: ТипРазделителя,
    событие: PointerEvent,
): void {
    событие.preventDefault();

    разделитель.setPointerCapture(
        событие.pointerId,
    );

    document.body.classList.add(
        "изменение-размера",
    );

    if (
        тип === "проект" ||
        тип === "наблюдение"
    ) {
        document.body.classList.add(
            "изменение-размера-вертикальное",
        );
    } else {
        document.body.classList.add(
            "изменение-размера-горизонтальное",
        );
    }

    const обработатьПеремещение =
        (перемещение: PointerEvent): void => {
            if (!элементы.приложение) {
                return;
            }

            const прямоугольник =
                элементы.приложение.getBoundingClientRect();

            if (тип === "проект") {
                const ширина =
                    перемещение.clientX -
                    прямоугольник.left;

                const ограниченнаяШирина =
                    Math.max(
                        170,
                        Math.min(
                            ширина,
                            360,
                        ),
                    );

                установитьСтиль(
                    "--ширина-проекта",
                    `${Math.round(ограниченнаяШирина)}px`,
                );

                return;
            }

            if (тип === "наблюдение") {
                const ширина =
                    прямоугольник.right -
                    перемещение.clientX;

                const ограниченнаяШирина =
                    Math.max(
                        210,
                        Math.min(
                            ширина,
                            420,
                        ),
                    );

                установитьСтиль(
                    "--ширина-наблюдения",
                    `${Math.round(ограниченнаяШирина)}px`,
                );

                return;
            }

            const высота =
                прямоугольник.bottom -
                перемещение.clientY;

            const максимальнаяВысота =
                Math.max(
                    140,
                    Math.round(
                        window.innerHeight *
                        0.60,
                    ),
                );

            const ограниченнаяВысота =
                Math.max(
                    140,
                    Math.min(
                        высота,
                        максимальнаяВысота,
                    ),
                );

            установитьСтиль(
                "--высота-консоли",
                `${Math.round(ограниченнаяВысота)}px`,
            );
        };

    const завершитьИзменение =
        (): void => {
            разделитель.removeEventListener(
                "pointermove",
                обработатьПеремещение,
            );

            разделитель.removeEventListener(
                "pointerup",
                завершитьИзменение,
            );

            разделитель.removeEventListener(
                "pointercancel",
                завершитьИзменение,
            );

            document.body.classList.remove(
                "изменение-размера",
                "изменение-размера-вертикальное",
                "изменение-размера-горизонтальное",
            );

            if (
                разделитель.hasPointerCapture(
                    событие.pointerId,
                )
            ) {
                разделитель.releasePointerCapture(
                    событие.pointerId,
                );
            }
        };

    разделитель.addEventListener(
        "pointermove",
        обработатьПеремещение,
    );

    разделитель.addEventListener(
        "pointerup",
        завершитьИзменение,
        {
            once: true,
        },
    );

    разделитель.addEventListener(
        "pointercancel",
        завершитьИзменение,
        {
            once: true,
        },
    );
}

function настроитьИзменениеРазмеров(): void {
    if (элементы.разделительПроекта) {
        элементы.разделительПроекта.addEventListener(
            "pointerdown",
            событие => {
                начатьИзменениеРазмера(
                    элементы.разделительПроекта!,
                    "проект",
                    событие,
                );
            },
        );
    }

    if (элементы.разделительНаблюдения) {
        элементы.разделительНаблюдения.addEventListener(
            "pointerdown",
            событие => {
                начатьИзменениеРазмера(
                    элементы.разделительНаблюдения!,
                    "наблюдение",
                    событие,
                );
            },
        );
    }

    if (элементы.разделительКонсоли) {
        элементы.разделительКонсоли.addEventListener(
            "pointerdown",
            событие => {
                начатьИзменениеРазмера(
                    элементы.разделительКонсоли!,
                    "консоль",
                    событие,
                );
            },
        );
    }
}

