/**
 * ============================================================
 * ЗАПУСК ПРОГРАММЫ
 * ============================================================
 */

async function запуститьПрограмму(): Promise<void> {
    if (
        состояниеТерминала ===
        "выполнение"
    ) {
        добавитьВывод(
            "⚠ Программа уже выполняется.",
        );

        return;
    }

    if (
        !элементы.редакторИсходногоКода
    ) {
        добавитьВывод(
            "❌ Не найден редактор исходного кода.",
        );

        return;
    }

    const исходныйКод =
        элементы.редакторИсходногоКода.value;

    if (
        исходныйКод.trim().length === 0
    ) {
        добавитьВывод(
            "❌ Исходный код программы пуст.",
        );

        return;
    }

    if (запросВыполнения) {
        запросВыполнения.abort();
        запросВыполнения = null;
    }

    запросВыполнения =
        new AbortController();

    установитьСостояние(
        "выполнение",
    );

    добавитьВывод("");

    добавитьВывод(
        "▶ Запуск программы...",
    );

    добавитьВывод(
        "🐌 Терминал передал управление системе выполнения.",
    );

    try {
        const ответ =
            await fetch(
                "/api/выполнение",
                {
                    method: "POST",
                    headers: {
                        "Content-Type":
                            "application/json; charset=utf-8",
                    },
                    body: JSON.stringify({
                        код: исходныйКод,
                    }),
                    signal:
                        запросВыполнения.signal,
                },
            );

        if (!ответ.ok) {
            let детали:
                string | null = null;

            try {
                const тело =
                    await ответ.text();

                if (
                    тело.trim().length > 0
                ) {
                    const данные =
                        JSON.parse(
                            тело,
                        ) as {
                            сообщение?: unknown;
                        };

                    if (
                        typeof данные.сообщение ===
                        "string"
                    ) {
                        детали =
                            данные.сообщение;
                    } else {
                        детали =
                            тело;
                    }
                }
            } catch {
                детали = null;
            }

            установитьСостояние(
                "готов",
            );

            добавитьВывод(
                `❌ Сервер завершил запрос с ошибкой HTTP ${ответ.status}.`,
            );

            if (детали) {
                добавитьВывод(
                    `Причина: ${детали}`,
                );
            }

            return;
        }

        let результат:
            РезультатВыполнения;

        try {
            результат =
                (await ответ.json()) as
                    РезультатВыполнения;
        } catch {
            установитьСостояние(
                "готов",
            );

            добавитьВывод(
                `❌ Сервер вернул ответ, который «Улитка» не смогла прочитать. Код ответа: ${ответ.status}.`,
            );

            return;
        }

        показатьРезультатВыполнения(
            результат,
        );
    } catch (ошибка) {
        if (
            ошибка instanceof DOMException &&
            ошибка.name === "AbortError"
        ) {
            return;
        }

        const сообщение =
            ошибка instanceof Error
                ? ошибка.message
                : String(ошибка);

        установитьСостояние(
            "готов",
        );

        добавитьВывод(
            "❌ Не удалось связаться с системой выполнения «Улитки».",
        );

        добавитьВывод(
            `Причина: ${сообщение}`,
        );
    } finally {
        запросВыполнения = null;
    }
}

