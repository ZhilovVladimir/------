/**
 * ============================================================
 * ТАЙМЕР
 * ============================================================
 */

function очиститьТаймер(): void {
    if (таймерЗавершения !== null) {
        clearTimeout(
            таймерЗавершения,
        );

        таймерЗавершения = null;
    }
}

/**
 * ============================================================
 * GIT
 * ============================================================
 */

async function выполнитьКомандуGit(
    команда: string,
): Promise<void> {
    добавитьВывод("");

    добавитьВывод(
        `🐌 Выполняется команда «${команда}»...`,
    );

    try {
        const ответ =
            await fetch(
                "/api/git",
                {
                    method: "POST",

                    headers: {
                        "Content-Type":
                            "application/json; charset=utf-8",
                    },

                    body: JSON.stringify({
                        команда,
                    }),
                },
            );

        const результат =
            (await ответ.json()) as ОтветGit;

        if (!результат.успешно) {
            добавитьВывод(
                `❌ ${результат.сообщение}`,
            );

            if (результат.вывод) {
                добавитьВывод(
                    результат.вывод,
                );
            }

            установитьСостояние(
                "готов",
            );

            return;
        }

        добавитьВывод(
            `✓ ${результат.сообщение}`,
        );

        if (
            результат.вывод &&
            результат.вывод.trim().length > 0
        ) {
            добавитьВывод(
                результат.вывод,
            );
        } else if (команда === "состояние") {
            добавитьВывод(
                "✓ Git не сообщил об изменениях.",
            );
        } else if (команда === "изменения") {
            добавитьВывод(
                "✓ Изменений в рабочем дереве нет.",
            );
        } else if (команда === "история") {
            добавитьВывод(
                "✓ История Git пуста.",
            );
        }

        установитьСостояние(
            "готов",
        );
    } catch (ошибка) {
        const сообщение =
            ошибка instanceof Error
                ? ошибка.message
                : String(ошибка);

        добавитьВывод(
            "❌ Не удалось связаться с серверной частью «Улитки».",
        );

        добавитьВывод(
            `Причина: ${сообщение}`,
        );

        установитьСостояние(
            "готов",
        );
    }
}

async function получитьСостояниеGit(): Promise<void> {
    установитьСостояние(
        "выполнение",
    );

    await выполнитьКомандуGit(
        "состояние",
    );
}

async function получитьИзмененияGit(): Promise<void> {
    установитьСостояние(
        "выполнение",
    );

    await выполнитьКомандуGit(
        "изменения",
    );
}

async function получитьИсториюGit(): Promise<void> {
    установитьСостояние(
        "выполнение",
    );

    добавитьВывод(
        "📜 Последние пять сохранений Git:",
    );

    await выполнитьКомандуGit(
        "история",
    );
}

/**
 * ============================================================
 * ЗАПУСК ПРОГРАММЫ
 * ============================================================
 */

function запуститьПрограмму(): void {
    if (
        состояниеТерминала ===
        "выполнение"
    ) {
        добавитьВывод(
            "⚠ Программа уже выполняется.",
        );

        return;
    }

    очиститьТаймер();

    установитьСостояние(
        "выполнение",
    );

    добавитьВывод(
        "▶ Запуск программы...",
    );

    добавитьВывод(
        "🐌 Терминал передал управление системе выполнения.",
    );

    таймерЗавершения =
        setTimeout(
            () => {
                таймерЗавершения = null;

                if (
                    состояниеТерминала !==
                    "выполнение"
                ) {
                    return;
                }

                установитьСостояние(
                    "завершено",
                );

                добавитьВывод(
                    "✓ Выполнение завершено.",
                );

                добавитьВывод(
                    "👍 Интерфейс проверен. Ошибок не обнаружено.",
                );
            },
            700,
        );
}

/**
 * ============================================================
 * ОСТАНОВКА
 * ============================================================
 */

function остановитьПрограмму(): void {
    if (
        состояниеТерминала !==
        "выполнение"
    ) {
        добавитьВывод(
            "⚠ Сейчас нет выполняемой программы.",
        );

        установитьСостояние(
            "остановлено",
        );

        return;
    }

    очиститьТаймер();

    установитьСостояние(
        "остановлено",
    );

    добавитьВывод(
        "■ Выполнение остановлено пользователем.",
    );
}

