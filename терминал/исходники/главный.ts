function экранироватьHTML(
    текст: string,
): string {
    return текст
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")
        .replace(/'/g, "&#039;");
}

function подсветитьСтроку(
    строка: string,
): string {
    if (строка.length === 0) {
        return "";
    }

    let результат = "";
    let позиция = 0;

    const добавитьТекст =
        (
            начало: number,
            конец: number,
        ): void => {
            if (конец <= начало) {
                return;
            }

            const фрагмент =
                строка.slice(
                    начало,
                    конец,
                );

            let экранированный =
                экранироватьHTML(
                    фрагмент,
                );

            экранированный =
                экранированный.replace(
                    /(\b\d+(?:\.\d+)?\b)/g,
                    '<span class="число">$1</span>',
                );

            экранированный =
                экранированный.replace(
                    /\b(истина|ложь)\b/g,
                    '<span class="логическое">$1</span>',
                );

            экранированный =
                экранированный.replace(
                    /\b(программа|начало|конец|пусть|показать|если|тогда|иначе|повторить|раз|функция|вернуть)\b/g,
                    '<span class="ключевое">$1</span>',
                );

            экранированный =
                экранированный.replace(
                    /(==|!=|>=|<=|>|<|\+|-|\*|\/|%|=|\bи\b|\bили\b|\bне\b)/g,
                    '<span class="оператор">$1</span>',
                );

            результат +=
                экранированный;
        };

    while (позиция < строка.length) {
        const символ =
            строка[позиция];

        if (символ === "#") {
            добавитьТекст(
                0,
                позиция,
            );

            результат +=
                `<span class="комментарий">${экранироватьHTML(
                    строка.slice(позиция),
                )}</span>`;

            return результат;
        }

        if (символ === '"') {
            добавитьТекст(
                0,
                позиция,
            );

            let конец =
                позиция + 1;

            while (
                конец < строка.length
            ) {
                if (
                    строка[конец] === "\\" &&
                    конец + 1 < строка.length
                ) {
                    конец += 2;
                    continue;
                }

                if (
                    строка[конец] === '"'
                ) {
                    конец++;
                    break;
                }

                конец++;
            }

            результат +=
                `<span class="текст">${экранироватьHTML(
                    строка.slice(
                        позиция,
                        конец,
                    ),
                )}</span>`;

            строка =
                строка.slice(
                    конец,
                );

            позиция = 0;
            continue;
        }

        позиция++;
    }

    if (позиция > 0) {
        добавитьТекст(
            0,
            позиция,
        );

        if (
            позиция < строка.length
        ) {
            результат +=
                экранироватьHTML(
                    строка.slice(
                        позиция,
                    ),
                );
        }

        return результат;
    }

    добавитьТекст(
        0,
        строка.length,
    );

    return результат;
}

function подсветитьКод(
    исходныйКод: string,
): string {
    const строки =
        исходныйКод.split("\n");

    return строки
        .map(
            (строка) =>
                подсветитьСтроку(
                    строка,
                ) || " ",
        )
        .join("\n");
}

function обновитьНомераСтрок(
    исходныйКод: string,
): void {
    if (!элементы.номераСтрок) {
        return;
    }

    const количествоСтрок =
        Math.max(
            1,
            исходныйКод.split("\n").length,
        );

    const фрагмент =
        document.createDocumentFragment();

    for (
        let номер = 1;
        номер <= количествоСтрок;
        номер++
    ) {
        const строка =
            document.createElement("div");

        строка.textContent =
            String(номер);

        фрагмент.appendChild(
            строка,
        );
    }

    элементы.номераСтрок.innerHTML =
        "";

    элементы.номераСтрок.appendChild(
        фрагмент,
    );
}

function обновитьПодсветкуКода(): void {
    if (
        !элементы.редакторИсходногоКода ||
        !элементы.подсветкаКода
    ) {
        return;
    }

    const исходныйКод =
        элементы.редакторИсходногоКода.value;

    элементы.подсветкаКода.innerHTML =
        подсветитьКод(
            исходныйКод,
        );

    обновитьНомераСтрок(
        исходныйКод,
    );

    синхронизироватьПрокруткуРедактора();
}

function синхронизироватьПрокруткуРедактора(): void {
    if (
        !элементы.редакторИсходногоКода
    ) {
        return;
    }

    const редактор =
        элементы.редакторИсходногоКода;

    if (элементы.подсветкаКода) {
        элементы.подсветкаКода.scrollTop =
            редактор.scrollTop;

        элементы.подсветкаКода.scrollLeft =
            редактор.scrollLeft;
    }

    if (элементы.номераСтрок) {
        элементы.номераСтрок.scrollTop =
            редактор.scrollTop;
    }
}

function вставитьТекстВРедактор(
    текст: string,
): void {
    if (!элементы.редакторИсходногоКода) {
        return;
    }

    const редактор =
        элементы.редакторИсходногоКода;

    const начало =
        редактор.selectionStart;

    const конец =
        редактор.selectionEnd;

    const исходныйКод =
        редактор.value;

    редактор.value =
        исходныйКод.slice(
            0,
            начало,
        ) +
        текст +
        исходныйКод.slice(
            конец,
        );

    const новаяПозиция =
        начало + текст.length;

    редактор.selectionStart =
        новаяПозиция;

    редактор.selectionEnd =
        новаяПозиция;

    обновитьПодсветкуКода();

    редактор.dispatchEvent(
        new Event(
            "input",
            {
                bubbles: true,
            },
        ),
    );
}

function обработатьВводРедактора(): void {
    обновитьПодсветкуКода();

    if (
        состояниеТерминала !==
        "выполнение"
    ) {
        if (элементы.состояниеРедактора) {
            элементы.состояниеРедактора.textContent =
                "изменён";
        }
    }
}

function обработатьНажатиеКлавишиРедактора(
    событие: KeyboardEvent,
): void {
    if (
        событие.key !== "Tab" ||
        !элементы.редакторИсходногоКода
    ) {
        return;
    }

    событие.preventDefault();

    вставитьТекстВРедактор(
        "    ",
    );
}

function настроитьРедактор(): void {
    const редактор =
        элементы.редакторИсходногоКода;

    if (!редактор) {
        return;
    }

    редактор.addEventListener(
        "input",
        обработатьВводРедактора,
    );

    редактор.addEventListener(
        "scroll",
        синхронизироватьПрокруткуРедактора,
    );

    редактор.addEventListener(
        "keydown",
        обработатьНажатиеКлавишиРедактора,
    );

    обновитьПодсветкуКода();
}

