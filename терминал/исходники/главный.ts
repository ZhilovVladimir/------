function добавитьВывод(
    сообщение: string,
): void {
    if (!элементы.вывод) {
        return;
    }

    const строки =
        сообщение.split(/\r?\n/);

    for (const строкаТекста of строки) {
        const строка =
            document.createElement("div");

        строка.textContent =
            строкаТекста;

        элементы.вывод.appendChild(
            строка,
        );
    }

    элементы.вывод.scrollTop =
        элементы.вывод.scrollHeight;
}

