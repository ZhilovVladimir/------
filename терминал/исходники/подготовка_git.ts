import {
    выполнитьGit,
    type РезультатGit,
} from "./исполнитель_git.js";

export interface РезультатПодготовкиGit
    extends РезультатGit {
    пути: string[];
}

export function подготовитьИзмененияGit(
    пути: string[],
): РезультатПодготовкиGit {
    const очищенныеПути = пути
        .map((путь) => путь.trim())
        .filter((путь) => путь.length > 0);

    if (очищенныеПути.length === 0) {
        return {
            успешно: false,
            кодЗавершения: null,
            вывод: "",
            ошибка:
                "Не указаны файлы или папки для подготовки.",
            пути: [],
        };
    }

    const результат = выполнитьGit({
        команда: "add",
        аргументы: очищенныеПути,
    });

    return {
        ...результат,
        пути: очищенныеПути,
    };
}