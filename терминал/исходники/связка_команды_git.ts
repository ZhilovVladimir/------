import type {
    РазобраннаяКоманда,
} from "./разборщик_команд.js";

import {
    получитьКомандуGit,
} from "./команды_git.js";

import {
    получитьСостояниеGit,
    получитьИзмененияGit,
    получитьИсториюGit,
} from "./безопасные_команды_git.js";

export interface РезультатСвязкиGit {
    выполнено: boolean;
    сообщение: string;
    вывод: string;
}

export function выполнитьБезопаснуюGitКоманду(
    команда: РазобраннаяКоманда,
): РезультатСвязкиGit {
    const действие = команда.команда.действие;

    const командаGit = получитьКомандуGit(
        действие,
    );

    if (командаGit === undefined) {
        return {
            выполнено: false,
            сообщение: `Команда «${команда.команда.имя}» не относится к Git.`,
            вывод: "",
        };
    }

    if (командаGit.изменяетПроект) {
        return {
            выполнено: false,
            сообщение:
                `Команда «${команда.команда.имя}» изменяет проект ` +
                `и пока защищена.`,
            вывод: "",
        };
    }

    let результат;

    switch (действие) {
        case "состояние":
            результат = получитьСостояниеGit();
            break;

        case "изменения":
            результат = получитьИзмененияGit();
            break;

        case "история":
            результат = получитьИсториюGit();
            break;

        default:
            return {
                выполнено: false,
                сообщение:
                    `Для команды «${команда.команда.имя}» ` +
                    `нет безопасного исполнителя.`,
                вывод: "",
            };
    }

    if (!результат.успешно) {
        return {
            выполнено: false,
            сообщение:
                `Git завершился с ошибкой при выполнении ` +
                `«${команда.команда.имя}».`,
            вывод: результат.ошибка,
        };
    }

    return {
        выполнено: true,
        сообщение:
            `Команда «${команда.команда.имя}» успешно выполнена через Git.`,
        вывод: результат.вывод,
    };
}
