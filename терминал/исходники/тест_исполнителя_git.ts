import {
    выполнитьGit,
} from "./исполнитель_git.js";

function проверить(
    условие: boolean,
    сообщение: string,
): void {
    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }

    console.log(`✓ ${сообщение}`);
}

console.log("");
console.log("🐌 ТЕСТ БЕЗОПАСНОГО ИСПОЛНИТЕЛЯ GIT");
console.log("=================================");
console.log("");

const версия = выполнитьGit({
    команда: "--version",
});

проверить(
    версия.успешно,
    "Git успешно запущен",
);

проверить(
    версия.кодЗавершения === 0,
    "Git завершился с кодом 0",
);

проверить(
    версия.вывод.toLowerCase().includes("git"),
    "Получен вывод версии Git",
);

проверить(
    версия.ошибка === "",
    "При успешном запуске нет ошибки",
);

console.log("");
console.log("Полученный результат:");
console.log(версия.вывод.trim());
console.log("");

const неизвестная = выполнитьGit({
    команда: "команда_которой_не_существует",
});

проверить(
    неизвестная.успешно === false,
    "Ошибка Git правильно определяется",
);

проверить(
    неизвестная.кодЗавершения !== 0,
    "Ошибка имеет ненулевой код завершения",
);

проверить(
    неизвестная.ошибка.length > 0,
    "Ошибка Git возвращается отдельно",
);

console.log("");
console.log("🐌 ТЕСТ БЕЗОПАСНОГО ИСПОЛНИТЕЛЯ GIT ЗАВЕРШЁН");
console.log("");
