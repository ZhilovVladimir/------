function проверить(условие: boolean, сообщение: string): void {
    if (условие) {
        успешно++;
        console.log(`✓ ${сообщение}`);
    } else {
        ошибки++;
        console.error(`✗ ${сообщение}`);
    }
}

function близко(а: number, б: number, точность = 0.000001): boolean {
    return Math.abs(а - б) <= точность;
}

function позицииРавны(
    а: { x: number; y: number; z: number },
    б: { x: number; y: number; z: number }
): boolean {
    return (
        близко(а.x, б.x) &&
        близко(а.y, б.y) &&
        близко(а.z, б.z)
    );
}

function создатьТестовыйОбъект(
    идентификатор: string,
    имя: string,
    трансформация: ReturnType<typeof создатьТрансформацию3D>
) {
    const объект = создатьОбъект3D(
        идентификатор,
        имя,
        "группа"
    );

    объект.трансформация = трансформация;

    return объект;
}

