// ============================================================
// 🐌 УЛИТКА
// Синхронизация подтверждённой внутренней модели с 3D-ядром
// Этап 3.5.1
// ============================================================

import type {
    ЕдинаяВнутренняяМодельПрограммы
} from "./модель/единая_внутренняя_модель.js";

import {
    Ядро3D
} from "./ядро_3d.js";

// ============================================================
// РЕЗУЛЬТАТ СИНХРОНИЗАЦИИ
// ============================================================

export interface РезультатСинхронизацииМодели3D {

    успешно: boolean;

    идентификаторПрограммы: string | null;

    идентификаторыПеременных: Map<
        string,
        string
    >;

    идентификаторыФункций: Map<
        string,
        string
    >;

    идентификаторыОшибок: string[];

    созданоУзлов: number;
}

// ============================================================
// 🐌 СИНХРОНИЗАТОР МОДЕЛИ С 3D
// ============================================================

export class СинхронизаторМодели3D {

    private readonly ядро: Ядро3D;

    private идентификаторПрограммы:
        string | null = null;

    private readonly идентификаторыПеременных:
        Map<string, string> = new Map();

    private readonly идентификаторыФункций:
        Map<string, string> = new Map();

    private идентификаторыОшибок:
        string[] = [];

    // ========================================================
    // КОНСТРУКТОР
    // ========================================================

    public constructor(
        ядро: Ядро3D
    ) {

        this.ядро = ядро;
    }

    // ========================================================
    // ПОЛУЧИТЬ ЯДРО
    // ========================================================

    public получитьЯдро():
        Ядро3D {

        return this.ядро;
    }

    // ========================================================
    // СИНХРОНИЗИРОВАТЬ МОДЕЛЬ
    // ========================================================

    public синхронизировать(
        модель:
            ЕдинаяВнутренняяМодельПрограммы
    ):
        РезультатСинхронизацииМодели3D {

        this.очиститьПривязки();

        let созданоУзлов = 0;

        // ----------------------------------------------------
        // ПРОГРАММА
        //
        // Имя программы подтверждено внутренней моделью.
        // ----------------------------------------------------

        this.идентификаторПрограммы =
            this.ядро.добавитьУзел(
                "программа",
                модель.получитьИмяПрограммы(),
                {
                    источник:
                        "единая_внутренняя_модель",

                    тип:
                        "программа"
                }
            );

        созданоУзлов++;

        // ----------------------------------------------------
        // ГЛОБАЛЬНЫЕ СИМВОЛЫ
        // ----------------------------------------------------

        const символы =
            модель.получитьГлобальныеСимволы();

        for (const символ of символы) {

            // ------------------------------------------------
            // ПЕРЕМЕННАЯ
            // ------------------------------------------------

            if (
                символ.вид ===
                "переменная"
            ) {

                const идентификатор =
                    this.ядро.добавитьУзел(
                        "переменная",
                        символ.имя,
                        {
                            источник:
                                "единая_внутренняя_модель",

                            вид:
                                символ.вид,

                            тип:
                                символ.тип,

                            инициализирована:
                                символ.инициализирован
                        }
                    );

                this.идентификаторыПеременных.set(
                    символ.имя,
                    идентификатор
                );

                созданоУзлов++;

                continue;
            }

            // ------------------------------------------------
            // ФУНКЦИЯ
            // ------------------------------------------------

            if (
                символ.вид ===
                "функция"
            ) {

                const идентификатор =
                    this.ядро.добавитьУзел(
                        "функция",
                        символ.имя,
                        {
                            источник:
                                "единая_внутренняя_модель",

                            вид:
                                символ.вид,

                            тип:
                                символ.тип,

                            параметры:
                                символ.параметры ??
                                [],

                            типВозврата:
                                символ.типВозврата ??
                                "неизвестно"
                        }
                    );

                this.идентификаторыФункций.set(
                    символ.имя,
                    идентификатор
                );

                созданоУзлов++;
            }

            // ------------------------------------------------
            // ПАРАМЕТР
            //
            // Параметры находятся внутри функций.
            // На этом этапе они не являются глобальными узлами.
            // ------------------------------------------------

        }

        // ----------------------------------------------------
        // СЕМАНТИЧЕСКИЕ ОШИБКИ
        //
        // Ошибки уже подтверждены семантическим анализатором.
        // ----------------------------------------------------

        const ошибки =
            модель.получитьОшибки();

        for (const ошибка of ошибки) {

            const идентификатор =
                this.ядро.добавитьУзел(
                    "ошибка",
                    `ошибка_${ошибка.код}`,
                    {
                        источник:
                            "единая_внутренняя_модель",

                        код:
                            ошибка.код,

                        сообщение:
                            ошибка.сообщение,

                        имя:
                            ошибка.имя,

                        ожидаемыйТип:
                            ошибка.ожидаемыйТип,

                        полученныйТип:
                            ошибка.полученныйТип
                    }
                );

            this.идентификаторыОшибок.push(
                идентификатор
            );

            созданоУзлов++;
        }

        return {

            успешно:
                модель.успешна(),

            идентификаторПрограммы:
                this.идентификаторПрограммы,

            идентификаторыПеременных:
                new Map(
                    this.идентификаторыПеременных
                ),

            идентификаторыФункций:
                new Map(
                    this.идентификаторыФункций
                ),

            идентификаторыОшибок:
                [
                    ...this.идентификаторыОшибок
                ],

            созданоУзлов
        };
    }

    // ========================================================
    // ОЧИСТИТЬ ПРИВЯЗКИ
    // ========================================================

    public очиститьПривязки():
        void {

        this.идентификаторПрограммы =
            null;

        this.идентификаторыПеременных.clear();

        this.идентификаторыФункций.clear();

        this.идентификаторыОшибок = [];
    }

    // ========================================================
    // ПОЛУЧИТЬ УЗЕЛ ПРОГРАММЫ
    // ========================================================

    public получитьИдентификаторПрограммы():
        string | null {

        return this.идентификаторПрограммы;
    }

    // ========================================================
    // ПОЛУЧИТЬ УЗЕЛ ПЕРЕМЕННОЙ
    // ========================================================

    public получитьИдентификаторПеременной(
        имя: string
    ):
        string | null {

        return (
            this.идентификаторыПеременных
                .get(имя)
            ?? null
        );
    }

    // ========================================================
    // ПОЛУЧИТЬ УЗЕЛ ФУНКЦИИ
    // ========================================================

    public получитьИдентификаторФункции(
        имя: string
    ):
        string | null {

        return (
            this.идентификаторыФункций
                .get(имя)
            ?? null
        );
    }

    // ========================================================
    // ПОЛУЧИТЬ УЗЛЫ ОШИБОК
    // ========================================================

    public получитьИдентификаторыОшибок():
        string[] {

        return [
            ...this.идентификаторыОшибок
        ];
    }
}

// ============================================================
// ФАБРИКА
// ============================================================

export function создатьСинхронизаторМодели3D(
    ядро: Ядро3D
):
    СинхронизаторМодели3D {

    return new СинхронизаторМодели3D(
        ядро
    );
}
