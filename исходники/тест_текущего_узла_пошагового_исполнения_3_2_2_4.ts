// ============================================================
// 🐌 УЛИТКА
// Тест текущего узла пошагового выполнения
// Этап 3.2.2.4
// ============================================================

import {
    Исполнитель,
    type СобытиеИсполнения
} from "./исполнитель.js";

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `  ✅ ${сообщение}`
        );

    } else {

        ошибок++;

        console.error(
            `  ❌ ${сообщение}`
        );
    }
}

function проверитьРавно<T>(
    фактическое: T,
    ожидаемое: T,
    сообщение: string
): void {

    проверить(
        фактическое === ожидаемое,
        `${сообщение} | получено: ${String(фактическое)}, ожидалось: ${String(ожидаемое)}`
    );
}

console.log("");
console.log("============================================================");
console.log("🐌 ТЕСТ 3.2.2.4 — ТЕКУЩИЙ УЗЕЛ ПОШАГОВОГО ВЫПОЛНЕНИЯ");
console.log("============================================================");
console.log("");

const дерево = [
    {
        вид: "ПРОГРАММА" as const,
        имя: "текущий_узел",
        тело: {
            вид: "БЛОК" as const,
            команды: [
                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ" as const,
                    имя: "имя",
                    значение: {
                        вид: "ТЕКСТ" as const,
                        значение: "Владимир"
                    }
                },
                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ" as const,
                    имя: "возраст",
                    значение: {
                        вид: "ЧИСЛО" as const,
                        значение: 40
                    }
                },
                {
                    вид: "ПОКАЗАТЬ" as const,
                    значения: [
                        {
                            вид: "ИМЯ" as const,
                            значение: "имя"
                        }
                    ]
                }
            ]
        }
    }
];

const исполнитель =
    new Исполнитель();

console.log(
    "Проверка подготовки пошагового выполнения:"
);

исполнитель.начатьПошаговоеВыполнение(
    дерево
);

проверитьРавно(
    исполнитель.получитьКоличествоШагов(),
    3,
    "Количество шагов равно количеству исполняемых команд"
);

проверитьРавно(
    исполнитель.получитьТекущийШаг(),
    0,
    "Начальный номер шага равен 0"
);

console.log("");
console.log(
    "Проверка текущего узла:"
);

const текущийУзелДоВыполнения =
    исполнитель.получитьТекущийУзел();

проверитьРавно(
    текущийУзелДоВыполнения,
    null,
    "До выполнения текущий узел отсутствует"
);

исполнитель.выполнитьШаг();

const первыйУзел =
    исполнитель.получитьТекущийУзел();

проверить(
    первыйУзел !== null,
    "После первого шага текущий узел существует"
);

проверитьРавно(
    первыйУзел?.вид,
    "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
    "Первый текущий узел — объявление переменной"
);

проверитьРавно(
    (первыйУзел as any)?.имя,
    "имя",
    "Первый текущий узел содержит имя переменной"
);

исполнитель.выполнитьШаг();

const второйУзел =
    исполнитель.получитьТекущийУзел();

проверить(
    второйУзел !== null,
    "После второго шага текущий узел существует"
);

проверитьРавно(
    второйУзел?.вид,
    "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
    "Второй текущий узел — объявление переменной"
);

проверитьРавно(
    (второйУзел as any)?.имя,
    "возраст",
    "Второй текущий узел содержит имя переменной"
);

проверить(
    первыйУзел !== второйУзел,
    "При переходе к следующему шагу текущий узел изменяется"
);

console.log("");
console.log(
    "Проверка последнего шага через событие:"
);

исполнитель.выполнитьШаг();

const события =
    исполнитель.получитьСобытия();

проверить(
    события.length > 0,
    "Исполнитель сохранил события выполнения"
);

const событиеПоказа =
    события.find(
        (событие: СобытиеИсполнения) =>
            событие.тип === "показ"
    );

проверить(
    событиеПоказа !== undefined,
    "Для последнего шага создано событие показа"
);

const текущийУзелИзСобытия =
    событиеПоказа !== undefined &&
    событиеПоказа.данные !== null &&
    typeof событиеПоказа.данные === "object" &&
    "текущийУзел" in событиеПоказа.данные
        ? (
            событиеПоказа.данные as {
                текущийУзел: unknown
            }
        ).текущийУзел
        : null;

проверить(
    текущийУзелИзСобытия !== null,
    "Событие последнего шага содержит текущий узел"
);

проверитьРавно(
    (
        текущийУзелИзСобытия as {
            вид?: string
        } | null
    )?.вид,
    "ПОКАЗАТЬ",
    "Текущий узел последнего шага — показать"
);

проверить(
    текущийУзелИзСобытия !== первыйУзел &&
    текущийУзелИзСобытия !== второйУзел,
    "Текущий узел последнего шага отличается от предыдущих"
);

console.log("");
console.log(
    "Проверка завершения:"
);

проверитьРавно(
    исполнитель.получитьСостояниеПошаговогоВыполнения(),
    "завершено",
    "После последнего шага состояние — завершено"
);

const текущийУзелПослеЗавершения =
    исполнитель.получитьТекущийУзел();

проверитьРавно(
    текущийУзелПослеЗавершения,
    null,
    "После завершения текущий узел очищается"
);

console.log("");
console.log(
    "Проверка связи текущего узла с событиями:"
);

const событияСУзлами =
    события.filter(
        (событие: СобытиеИсполнения) => {

            if (
                событие.данные === null ||
                typeof событие.данные !== "object"
            ) {
                return false;
            }

            return (
                "текущийУзел" in
                событие.данные
            );
        }
    );

проверить(
    событияСУзлами.length > 0,
    "События содержат информацию о текущем узле"
);

console.log("");
console.log("============================================================");
console.log("🐌 РЕЗУЛЬТАТ 3.2.2.4");
console.log("============================================================");
console.log(
    `Всего проверок: ${всегоПроверок}`
);
console.log(
    `Успешных:       ${успешныхПроверок}`
);
console.log(
    `Ошибок:         ${ошибок}`
);
console.log("============================================================");

if (ошибок === 0) {

    console.log("");
    console.log(
        "🐌 ✅ 3.2.2.4 ПРОШЁЛ ВСЕ ПРОВЕРКИ"
    );
    console.log("");

} else {

    console.error("");
    console.error(
        "🐌 ❌ 3.2.2.4 ОБНАРУЖЕНЫ ОШИБКИ"
    );
    console.error("");
    process.exitCode = 1;
}
