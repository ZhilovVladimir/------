// ============================================================
// 🐌 УЛИТКА
// Регрессионный тест неизвестной конструкции парсера
// ============================================================

import { разобрать } from "./лексический_анализатор.js";
import { Парсер } from "./ядро/парсер.js";

// ============================================================
// СЧЁТЧИКИ
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;

// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {
    всегоПроверок++;

    if (условие) {
        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибок++;

    console.log(
        `❌ ${сообщение}`
    );
}

// ============================================================
// ПОЛУЧЕНИЕ ОШИБКИ ПАРСЕРА
// ============================================================

function получитьОшибка(
    код: string
): string {
    try {
        const лексемы =
            разобрать(код);

        const парсер =
            new Парсер(лексемы);

        парсер.разобрать();

        return "";
    } catch (ошибка: unknown) {
        if (ошибка instanceof Error) {
            return ошибка.message;
        }

        return String(ошибка);
    }
}

// ============================================================
// [1] НЕИЗВЕСТНАЯ КОНСТРУКЦИЯ
// ============================================================

console.log("");
console.log("================================");
console.log(
    "🐌 ТЕСТ НЕИЗВЕСТНОЙ КОНСТРУКЦИИ ПАРСЕРА"
);
console.log("================================");
console.log("");

const ошибка =
    получитьОшибка(`
        прыгнуть куда-нибудь
    `);

проверить(
    ошибка.length > 0,
    "Неизвестная конструкция должна вызывать ошибку"
);

проверить(
    ошибка.includes("прыгнуть"),
    "Сообщение об ошибке должно содержать неизвестную конструкцию"
);

console.log("");
console.log(
    `Полученное сообщение: ${ошибка || "ОШИБКИ НЕТ"}`
);

// ============================================================
// ИТОГ
// ============================================================

console.log("");
console.log("================================");
console.log("🐌 ИТОГ");
console.log("================================");

console.log(
    `Всего проверок: ${всегоПроверок}`
);

console.log(
    `Успешных: ${успешныхПроверок}`
);

console.log(
    `Ошибок: ${ошибок}`
);

console.log("");

if (ошибок === 0) {
    console.log(
        "🐌 ✅ РЕГРЕССИОННЫЙ ТЕСТ ПРОЙДЕН"
    );
} else {
    console.log(
        "🐌 ❌ РЕГРЕССИОННЫЙ ТЕСТ НЕ ПРОЙДЕН"
    );
}

console.log("");
console.log(
    "🐌 ТЕСТ ЗАВЕРШЁН"
);
