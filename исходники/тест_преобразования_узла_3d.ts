console.log("1. Проверка преобразования типов");

if (
    преобразоватьТипУзлаВТипОбъекта3D(
        "программа"
    ) !== "программа"
) {
    throw new Error(
        "❌ Тип «программа» преобразуется неправильно."
    );
}

if (
    преобразоватьТипУзлаВТипОбъекта3D(
        "переменная"
    ) !== "переменная"
) {
    throw new Error(
        "❌ Тип «переменная» преобразуется неправильно."
    );
}

if (
    преобразоватьТипУзлаВТипОбъекта3D(
        "функция"
    ) !== "функция"
) {
    throw new Error(
        "❌ Тип «функция» преобразуется неправильно."
    );
}

if (
    преобразоватьТипУзлаВТипОбъекта3D(
        "выполнение"
    ) !== "выполнение"
) {
    throw new Error(
        "❌ Тип «выполнение» преобразуется неправильно."
    );
}

if (
    преобразоватьТипУзлаВТипОбъекта3D(
        "ошибка"
    ) !== "ошибка"
) {
    throw new Error(
        "❌ Тип «ошибка» преобразуется неправильно."
    );
}

console.log(
    "✅ Все типы преобразуются правильно."
);

console.log("");
console.log("2. Создание узла системы");

const узел: УзелСистемы = {
    идентификатор: "узел_1",
    тип: "переменная",
    имя: "имя",
    позиция: {
        x: 10,
        y: 20,
        z: 30
    },
    активен: true,
    интенсивность: 0.75
};

console.log(
    "Узел:",
    узел
);

console.log(
    "✅ Узел системы создан."
);

console.log("");
console.log("3. Преобразование узла в объект 3D");

const объект =
    преобразоватьУзелВОбъект3D(
        узел
    );

console.log(
    "Объект 3D:",
    объект
);

if (
    объект.идентификатор !==
    узел.идентификатор
) {
    throw new Error(
        "❌ Идентификатор не перенесён."
    );
}

if (
    объект.имя !==
    узел.имя
) {
    throw new Error(
        "❌ Имя не перенесено."
    );
}

if (
    объект.тип !==
    "переменная"
) {
    throw new Error(
        "❌ Тип объекта преобразован неправильно."
    );
}

console.log(
    "✅ Основные данные узла перенесены."
);

console.log("");
console.log("4. Проверка позиции");

if (
    объект.трансформация.позиция.x !==
    узел.позиция.x
) {
    throw new Error(
        "❌ Координата X перенесена неправильно."
    );
}

if (
    объект.трансформация.позиция.y !==
    узел.позиция.y
) {
    throw new Error(
        "❌ Координата Y перенесена неправильно."
    );
}

if (
    объект.трансформация.позиция.z !==
    узел.позиция.z
) {
    throw new Error(
        "❌ Координата Z перенесена неправильно."
    );
}

console.log(
    "Позиция:",
    объект.трансформация.позиция
);

console.log(
    "✅ Позиция перенесена правильно."
);

console.log("");
console.log("5. Проверка активности");

if (
    объект.активен !==
    узел.активен
) {
    throw new Error(
        "❌ Активность узла не перенесена."
    );
}

if (
    объект.интенсивность !==
    узел.интенсивность
) {
    throw new Error(
        "❌ Интенсивность узла не перенесена."
    );
}

console.log(
    "Активен:",
    объект.активен
);

console.log(
    "Интенсивность:",
    объект.интенсивность
);

console.log(
    "Состояние:",
    объект.состояние
);

console.log(
    "✅ Активность и интенсивность перенесены."
);

console.log("");
console.log("6. Проверка метаданных");

const источник =
    объект.метаданные[
        "источник"
    ];

const идентификаторУзла =
    объект.метаданные[
        "идентификаторУзла"
    ];

const типУзла =
    объект.метаданные[
        "типУзла"
    ];

const имяУзла =
    объект.метаданные[
        "имяУзла"
    ];

if (
    источник !==
    "узел_системы"
) {
    throw new Error(
        "❌ Источник не записан в метаданные."
    );
}

if (
    идентификаторУзла !==
    узел.идентификатор
) {
    throw new Error(
        "❌ Идентификатор узла не записан в метаданные."
    );
}

if (
    типУзла !==
    узел.тип
) {
    throw new Error(
        "❌ Тип узла не записан в метаданные."
    );
}

if (
    имяУзла !==
    узел.имя
) {
    throw new Error(
        "❌ Имя узла не записано в метаданные."
    );
}

console.log(
    "Метаданные:",
    объект.метаданные
);

console.log(
    "✅ Связь с исходным узлом сохранена."
);

console.log("");
console.log("7. Проверка соответствия");

if (
    !проверитьСоответствиеОбъектаУзлу(
        объект,
        узел
    )
) {
    throw new Error(
        "❌ Объект 3D не соответствует исходному узлу."
    );
}

console.log(
    "✅ Объект 3D полностью соответствует узлу."
);

console.log("");
console.log("8. Создание объекта через отдельную функцию");

const второйОбъект =
    создатьОбъект3DИзУзла(
        узел
    );

if (
    !проверитьСоответствиеОбъектаУзлу(
        второйОбъект,
        узел
    )
) {
    throw new Error(
        "❌ Создание через отдельную функцию работает неправильно."
    );
}

console.log(
    "Второй объект:",
    второйОбъект
);

console.log(
    "✅ Отдельная функция создания работает."
);

console.log("");
console.log("9. Преобразование массива узлов");

const узлы: УзелСистемы[] = [
    {
        идентификатор: "узел_1",
        тип: "программа",
        имя: "Главная программа",
        позиция: {
            x: 0,
            y: 0,
            z: 0
        },
        активен: false,
        интенсивность: 0
    },

    {
        идентификатор: "узел_2",
        тип: "переменная",
        имя: "имя",
        позиция: {
            x: 10,
            y: 5,
            z: 2
        },
        активен: true,
        интенсивность: 0.5
    },

    {
        идентификатор: "узел_3",
        тип: "функция",
        имя: "сложить",
        позиция: {
            x: 20,
            y: 10,
            z: 5
        },
        активен: true,
        интенсивность: 1
    }
];

const объекты =
    преобразоватьУзлыВОбъекты3D(
        узлы
    );

console.log(
    "Количество узлов:",
    узлы.length
);

console.log(
    "Количество 3D-объектов:",
    объекты.length
);

if (
    объекты.length !==
    узлы.length
) {
    throw new Error(
        "❌ Количество объектов не соответствует количеству узлов."
    );
}

for (
    let индекс = 0;
    индекс < узлы.length;
    индекс++
) {
    if (
        !проверитьСоответствиеОбъектаУзлу(
            объекты[индекс],
            узлы[индекс]
        )
    ) {
        throw new Error(
            `❌ Объект ${индекс + 1} не соответствует своему узлу.`
        );
    }
}

console.log(
    "✅ Массив узлов успешно преобразован."
);

