// ============================================================
// 🐌 УЛИТКА — ЦЕНТРАЛЬНАЯ 3D-СИСТЕМА
//
// Единая система компиляции, выполнения и 3D-визуализации.
//
// Архитектура:
//
// Код программы
//     ↓
// Компилятор
//     ↓
// Единая внутренняя модель
//     ↓
// Синхронизатор модели 3D
//     ↓
// Ядро3D
//
// И одновременно:
//
// Исполнитель
//     ↓ события
// ИнтеграторИсполнения3D
//     ↓
// Ядро3D
//
// ВАЖНО:
// Исполнитель существует только внутри Компилятора.
// Центральная система не создаёт второго исполнителя.
// ============================================================

import {
    Компилятор
} from "./компилятор.js";

import type {
    РезультатКомпиляции
} from "./компилятор.js";

import {
    ИнтеграторИсполнения3D
} from "./интегратор_исполнения_3d.js";

import {
    Ядро3D
} from "./ядро_3d.js";

import {
    СинхронизаторМодели3D
} from "./синхронизация_модели_3d.js";

import type {
    РезультатСинхронизацииМодели3D
} from "./синхронизация_модели_3d.js";

import type {
    Исполнитель
} from "./исполнитель.js";

// ============================================================
// ЦЕНТРАЛЬНАЯ СИСТЕМА
// ============================================================

export class СистемаУлитки3D {

    // ========================================================
    // ОСНОВНЫЕ КОМПОНЕНТЫ
    // ========================================================

    private readonly ядро:
        Ядро3D;

    private readonly интегратор:
        ИнтеграторИсполнения3D;

    private readonly синхронизаторМодели:
        СинхронизаторМодели3D;

    private readonly компилятор:
        Компилятор;

    // ========================================================
    // СОЗДАНИЕ СИСТЕМЫ
    // ========================================================

    public constructor() {

        // ----------------------------------------------------
        // 1. Создаём единое 3D-ядро.
        // ----------------------------------------------------

        this.ядро =
            new Ядро3D();

        // ----------------------------------------------------
        // 2. Создаём интегратор исполнения,
        //    подключённый непосредственно к этому ядру.
        // ----------------------------------------------------

        this.интегратор =
            new ИнтеграторИсполнения3D(
                this.ядро
            );

        // ----------------------------------------------------
        // 3. Создаём синхронизатор внутренней модели.
        //
        // Он будет передавать в 3D-ядро только те сущности,
        // которые уже подтверждены анализом программы.
        // ----------------------------------------------------

        this.синхронизаторМодели =
            new СинхронизаторМодели3D(
                this.ядро
            );

        // ----------------------------------------------------
        // 4. Создаём единый компилятор.
        //
        // Внутри компилятора уже существует Исполнитель.
        // Второй Исполнитель здесь НЕ создаём.
        // ----------------------------------------------------

        this.компилятор =
            new Компилятор();

        // ----------------------------------------------------
        // 5. Подключаем поток событий компилятора
        //    к 3D-интегратору.
        //
        // Теперь:
        //
        // Исполнитель
        //     ↓
        // Компилятор
        //     ↓
        // Интегратор3D
        //     ↓
        // Ядро3D
        // ----------------------------------------------------

        this.компилятор
            .установитьОбработчикСобытий(
                this.интегратор
                    .создатьОбработчик()
            );
    }

    // ========================================================
    // ПРОВЕРИТЬ ПРОГРАММУ И СИНХРОНИЗИРОВАТЬ МОДЕЛЬ С 3D
    // ========================================================

    /**
     * Проверяет программу единым компилятором.
     *
     * Если семантический анализ подтверждает программу,
     * её единая внутренняя модель передаётся
     * в синхронизатор 3D.
     *
     * При наличии ошибок неподтверждённая модель
     * не передаётся в 3D-ядро как успешная структура.
     */
    public проверитьПрограмму(
        код: string
    ):
        РезультатКомпиляции {

        const результат =
            this.компилятор
                .проверить(код);

        if (
            результат.успешно &&
            результат.модель !== null
        ) {

            this.синхронизаторМодели
                .синхронизировать(
                    результат.модель
                );
        }

        return результат;
    }

    // ========================================================
    // СИНХРОНИЗИРОВАТЬ ТЕКУЩУЮ МОДЕЛЬ
    // ========================================================

    /**
     * Передаёт текущую подтверждённую внутреннюю модель
     * в 3D-ядро.
     *
     * Если модель ещё не создана, возвращается null.
     */
    public синхронизироватьТекущуюМодель():
        РезультатСинхронизацииМодели3D | null {

        const модель =
            this.компилятор
                .получитьМодель();

        if (модель === null) {
            return null;
        }

        return this.синхронизаторМодели
            .синхронизировать(
                модель
            );
    }

    // ========================================================
    // ПОЛУЧИТЬ КОМПИЛЯТОР
    // ========================================================

    /**
     * Возвращает единый компилятор системы.
     *
     * Через него программа проходит полный конвейер:
     *
     * лексический анализ
     * → синтаксический анализ
     * → семантический анализ
     * → создание внутренней модели
     * → выполнение.
     */
    public получитьКомпилятор():
        Компилятор {

        return this.компилятор;
    }

    // ========================================================
    // ПОЛУЧИТЬ 3D-ЯДРО
    // ========================================================

    /**
     * Возвращает 3D-ядро системы.
     */
    public получитьЯдро():
        Ядро3D {

        return this.ядро;
    }

    // ========================================================
    // ПОЛУЧИТЬ ИНТЕГРАТОР ИСПОЛНЕНИЯ
    // ========================================================

    /**
     * Возвращает интегратор исполнения.
     */
    public получитьИнтегратор():
        ИнтеграторИсполнения3D {

        return this.интегратор;
    }

    // ========================================================
    // ПОЛУЧИТЬ СИНХРОНИЗАТОР МОДЕЛИ
    // ========================================================

    /**
     * Возвращает синхронизатор внутренней модели
     * с 3D-ядром.
     */
    public получитьСинхронизаторМодели():
        СинхронизаторМодели3D {

        return this.синхронизаторМодели;
    }

    // ========================================================
    // ПОЛУЧИТЬ ЕДИНЫЙ ИСПОЛНИТЕЛЬ
    // ========================================================

    /**
     * Возвращает Исполнитель, принадлежащий Компилятору.
     *
     * Второго исполнителя в системе нет.
     */
    public получитьИсполнитель():
        Исполнитель {

        return this.компилятор
            .получитьИсполнитель();
    }

    // ========================================================
    // СОЗДАТЬ НОВУЮ СИСТЕМУ
    // ========================================================

    /**
     * Создаёт полностью новую связанную систему.
     *
     * Все компоненты новой системы независимы
     * от предыдущей системы.
     */
    public static создать():
        СистемаУлитки3D {

        return new СистемаУлитки3D();
    }
}
