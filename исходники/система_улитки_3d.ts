// 🐌 УЛИТКА — ЦЕНТРАЛЬНАЯ 3D-СИСТЕМА
//
// Назначение:
// Единая сборка исполнителя программы,
// 3D-ядра и интегратора событий.
//
// Архитектура:
//
// Исполнитель
//     ↓ события
// ИнтеграторИсполнения3D
//     ↓
// Ядро3D
//
// Этот класс не дублирует логику существующих компонентов.
// Он только создаёт их и связывает между собой.

import { Исполнитель } from "./исполнитель.js";
import { ИнтеграторИсполнения3D } from "./интегратор_исполнения_3d.js";
import { Ядро3D } from "./ядро_3d.js";

/**
 * Центральная система выполнения «Улитки».
 *
 * Отвечает за создание и связь основных компонентов:
 *
 * - Исполнитель — выполняет дерево программы;
 * - ИнтеграторИсполнения3D — преобразует события выполнения
 *   в изменения 3D-системы;
 * - Ядро3D — хранит состояние, узлы, связи и историю.
 */
export class СистемаУлитки3D {
    private readonly ядро: Ядро3D;
    private readonly интегратор: ИнтеграторИсполнения3D;
    private readonly исполнитель: Исполнитель;

    /**
     * Создаёт полностью связанную систему «Улитки».
     */
    public constructor() {
        this.ядро = new Ядро3D();

        this.интегратор = new ИнтеграторИсполнения3D(
            this.ядро
        );

        this.исполнитель = new Исполнитель();

        this.исполнитель.установитьОбработчикСобытий(
            this.интегратор.создатьОбработчик()
        );
    }

    /**
     * Возвращает 3D-ядро системы.
     */
    public получитьЯдро(): Ядро3D {
        return this.ядро;
    }

    /**
     * Возвращает интегратор исполнения.
     */
    public получитьИнтегратор(): ИнтеграторИсполнения3D {
        return this.интегратор;
    }

    /**
     * Возвращает исполнителя программы.
     */
    public получитьИсполнитель(): Исполнитель {
        return this.исполнитель;
    }

    /**
     * Полностью пересоздаёт систему.
     *
     * Старые компоненты остаются неизменными.
     * Метод возвращает новую связанную систему.
     */
    public static создать(): СистемаУлитки3D {
        return new СистемаУлитки3D();
    }
}
