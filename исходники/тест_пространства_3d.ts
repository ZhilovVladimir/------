function проверить(
    название: string,
    условие: boolean
): void {
    if (условие) {
        успешно++;
        console.log(`✅ ${название}`);
    } else {
        ошибок++;
        console.error(`❌ ${название}`);
    }
}

function почтиРавно(
    a: number,
    b: number,
    точность = 0.000001
): boolean {
    return Math.abs(a - b) <= точность;
}

function точкиПочтиРавны(
    a: { x: number; y: number; z: number },
    b: { x: number; y: number; z: number },
    точность = 0.000001
): boolean {
    return (
        почтиРавно(a.x, b.x, точность) &&
        почтиРавно(a.y, b.y, точность) &&
        почтиРавно(a.z, b.z, точность)
    );
}

