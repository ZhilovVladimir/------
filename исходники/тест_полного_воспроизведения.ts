// ============================================================
// 🐌 УЛИТКА — ТЕСТ ПОЛНОГО ВОСПРОИЗВЕДЕНИЯ ИСТОРИИ 3D-ЯДРА
// ============================================================

import { Ядро3D } from "./ядро_3d";

console.log("🐌 ТЕСТ ПОЛНОГО ВОСПРОИЗВЕДЕНИЯ ИСТОРИИ");
console.log("==========================================");

// ============================================================
// СОЗДАЁМ ЯДРО
// ============================================================

const ядро = new Ядро3D();

console.log("\n[1] Создание истории");
console.log("--------------------------------");

// ============================================================
// СОБЫТИЕ 1 — ПЕРЕМЕННАЯ
// ============================================================

ядро.добавитьПеременную({
    имя: "имя",
    значение: "Владимир",
    тип: "текст"
});

// ============================================================
// СОБЫТИЕ 2 — ФУНКЦИЯ
// ============================================================

ядро.добавитьФункцию({
    имя: "сложить",
    параметры: [
        "первое",
        "второе"
    ]
});

// ============================================================
// СОБЫТИЕ 3 — СВЯЗЬ
// ============================================================

const идентификаторСвязи =
    ядро.добавитьСвязь(
        "узел_1",
        "узел_2",
        "передача"
    );

// ============================================================
// СОБЫТИЕ 4 — НАЧАЛО ВЫПОЛНЕНИЯ
// ============================================================

ядро.установитьСостояние(
    "выполнение"
);

// ============================================================
// СОБЫТИЕ 5 — ИЗМЕНЕНИЕ СТРОКИ
// ============================================================

ядро.установитьТекущуюСтроку(10);

// ============================================================
// СОБЫТИЕ 6 — АКТИВАЦИЯ ПЕРВОГО УЗЛА
// ============================================================

ядро.активироватьУзел(
    "узел_1",
    1
);

// ============================================================
// СОБЫТИЕ 7 — АКТИВАЦИЯ ВТОРОГО УЗЛА
// ============================================================

ядро.активироватьУзел(
    "узел_2",
    0.8
);

// ============================================================
// СОБЫТИЕ 8 — АКТИВАЦИЯ СВЯЗИ
// ============================================================

ядро.активироватьСвязь(
    идентификаторСвязи,
    0.6
);

// ============================================================
// ИСХОДНАЯ ИНФОРМАЦИЯ
// ============================================================

const количествоСобытий =
    ядро.получитьКоличествоСобытий();

console.log(
    "Количество событий:",
    количествоСобытий
);

console.log(
    "Исходная позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

console.log(
    "Исходный режим:",
    ядро.получитьРежимВоспроизведения()
);

// ============================================================
// ЗАПУСК ВОСПРОИЗВЕДЕНИЯ
// ============================================================

console.log("\n[2] Запуск воспроизведения");
console.log("--------------------------------");

ядро.начатьВоспроизведение();

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

if (
    ядро.получитьРежимВоспроизведения() !==
    "воспроизведение"
) {
    console.log(
        "❌ ОШИБКА: воспроизведение не запущено"
    );
}

if (
    ядро.получитьТекущуюПозициюИстории() !==
    -1
) {
    console.log(
        "❌ ОШИБКА: воспроизведение должно начинаться с -1"
    );
}

// ============================================================
// ПОШАГОВОЕ ВОСПРОИЗВЕДЕНИЕ
// ============================================================

console.log("\n[3] Пошаговое воспроизведение");
console.log("--------------------------------");

let количествоВоспроизведённых = 0;

while (true) {

    const событие =
        ядро.следующееСобытие();

    if (событие === null) {
        break;
    }

    количествоВоспроизведённых++;

    console.log(
        `\n▶ Событие ${количествоВоспроизведённых}`
    );

    console.log(
        "Позиция:",
        ядро.получитьТекущуюПозициюИстории()
    );

    console.log(
        "Тип:",
        событие.тип
    );

    console.log(
        "Идентификатор:",
        событие.идентификатор
    );

    console.log(
        "Состояние:",
        ядро.получитьСостояние()
    );

    console.log(
        "Узлов:",
        ядро.получитьУзлы().length
    );

    console.log(
        "Связей:",
        ядро.получитьСвязи().length
    );
}

// ============================================================
// ПРОВЕРКА ОКОНЧАНИЯ
// ============================================================

console.log("\n[4] Проверка окончания");
console.log("--------------------------------");

console.log(
    "Воспроизведено событий:",
    количествоВоспроизведённых
);

console.log(
    "Всего событий:",
    количествоСобытий
);

console.log(
    "Последняя позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

if (
    количествоВоспроизведённых !==
    количествоСобытий
) {
    console.log(
        "❌ ОШИБКА: воспроизведены не все события"
    );
} else {
    console.log(
        "✅ Все события воспроизведены"
    );
}

if (
    ядро.получитьТекущуюПозициюИстории() !==
    количествоСобытий - 1
) {
    console.log(
        "❌ ОШИБКА: неверная последняя позиция"
    );
} else {
    console.log(
        "✅ Последняя позиция правильная"
    );
}

// ============================================================
// ПОПЫТКА ПОЛУЧИТЬ СОБЫТИЕ ПОСЛЕ КОНЦА
// ============================================================

console.log("\n[5] Проверка границы истории");
console.log("--------------------------------");

const послеКонца =
    ядро.следующееСобытие();

console.log(
    "Результат следующего события:",
    послеКонца
);

if (послеКонца !== null) {
    console.log(
        "❌ ОШИБКА: после последнего события получено новое событие"
    );
} else {
    console.log(
        "✅ За пределами истории событие не получено"
    );
}

// ============================================================
// ПРОВЕРКА ФИНАЛЬНОГО СОСТОЯНИЯ
// ============================================================

console.log("\n[6] Проверка финального состояния");
console.log("--------------------------------");

const финальноеСостояние =
    ядро.получитьСостояние();

console.log(
    "Состояние:",
    финальноеСостояние
);

console.log(
    "Узлы:",
    ядро.получитьУзлы()
);

console.log(
    "Связи:",
    ядро.получитьСвязи()
);

if (
    финальноеСостояние.состояние !==
    "выполнение"
) {
    console.log(
        "❌ ОШИБКА: финальное состояние должно быть 'выполнение'"
    );
} else {
    console.log(
        "✅ Финальное состояние правильное"
    );
}

if (
    финальноеСостояние.текущаяСтрока !==
    10
) {
    console.log(
        "❌ ОШИБКА: финальная строка должна быть 10"
    );
} else {
    console.log(
        "✅ Финальная строка правильная"
    );
}

if (
    ядро.получитьУзлы().length !==
    2
) {
    console.log(
        "❌ ОШИБКА: должно быть 2 узла"
    );
} else {
    console.log(
        "✅ Восстановлены 2 узла"
    );
}

if (
    ядро.получитьСвязи().length !==
    1
) {
    console.log(
        "❌ ОШИБКА: должна быть 1 связь"
    );
} else {
    console.log(
        "✅ Восстановлена 1 связь"
    );
}

// ============================================================
// ОСТАНОВКА ВОСПРОИЗВЕДЕНИЯ
// ============================================================

console.log("\n[7] Остановка воспроизведения");
console.log("--------------------------------");

ядро.остановитьВоспроизведение();

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

if (
    ядро.получитьРежимВоспроизведения() !==
    "остановлено"
) {
    console.log(
        "❌ ОШИБКА: воспроизведение не остановлено"
    );
} else {
    console.log(
        "✅ Воспроизведение остановлено"
    );
}

// ============================================================
// ФИНАЛ
// ============================================================

console.log("\n==========================================");
console.log("🐌 ТЕСТ ПОЛНОГО ВОСПРОИЗВЕДЕНИЯ ЗАВЕРШЁН");
console.log("==========================================");
