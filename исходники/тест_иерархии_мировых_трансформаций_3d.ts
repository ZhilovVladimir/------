function создатьТестовыйОбъект(
    идентификатор: string,
    x: number,
    y: number,
    z: number
): Объект3D {

    const объект =
        создатьОбъект3D(
            идентификатор,
            идентификатор,
            "переменная"
        );

    объект.трансформация.позиция = {
        x,
        y,
        z
    };

    return объект;
}

function почтиРавно(
    первое: number,
    второе: number,
    точность = 0.000001
): boolean {

    return Math.abs(
        первое - второе
    ) < точность;
}

function проверитьПозицию(
    позиция:
        | {
            x: number;
            y: number;
            z: number;
        }
        | undefined,
    x: number,
    y: number,
    z: number
): boolean {

    if (позиция === undefined) {
        return false;
    }

    return (
        почтиРавно(позиция.x, x) &&
        почтиРавно(позиция.y, y) &&
        почтиРавно(позиция.z, z)
    );
}

let успешно = 0;
