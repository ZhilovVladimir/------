import {
    Объект3D,
    СостояниеОбъекта3D,
    установитьСостояниеОбъекта3D
} from "./объект_3d";

// ============================================================
// РЕЗУЛЬТАТ ПЕРЕХОДА
// ============================================================

export interface РезультатПереходаСостояния3D {
    успешно: boolean;
    предыдущееСостояние: СостояниеОбъекта3D;
    новоеСостояние: СостояниеОбъекта3D;
    сообщение: string;
}

// ============================================================
// СОБЫТИЕ ИЗМЕНЕНИЯ СОСТОЯНИЯ
// ============================================================

export interface СобытиеСостоянияОбъекта3D {
    идентификаторОбъекта: string;
    предыдущееСостояние: СостояниеОбъекта3D;
    новоеСостояние: СостояниеОбъекта3D;
    время: number;
}

// ============================================================
// РАЗРЕШЁННЫЕ ПЕРЕХОДЫ
// ============================================================

const ПЕРЕХОДЫ: Record<
    СостояниеОбъекта3D,
    СостояниеОбъекта3D[]
> = {
    создан: [
        "ожидание",
        "ошибка"
    ],

    ожидание: [
        "активен",
        "выполняется",
        "ошибка"
    ],

    активен: [
        "ожидание",
        "изменяется",
        "выполняется",
        "ошибка"
    ],

    изменяется: [
        "активен",
        "ожидание",
        "выполняется",
        "ошибка"
    ],

    выполняется: [
        "активен",
        "завершён",
        "ошибка"
    ],

    завершён: [
        "ожидание",
        "активен",
        "восстанавливается"
    ],

    ошибка: [
        "восстанавливается"
    ],

    восстанавливается: [
        "ожидание",
        "активен",
        "ошибка"
    ]
};

// ============================================================
// ПРОВЕРКА РАЗРЕШЁННОСТИ ПЕРЕХОДА
// ============================================================

export function разрешёнПереходСостояния3D(
    текущееСостояние: СостояниеОбъекта3D,
    новоеСостояние: СостояниеОбъекта3D
): boolean {

    if (текущееСостояние === новоеСостояние) {
        return true;
    }

    return ПЕРЕХОДЫ[
        текущееСостояние
    ].includes(
        новоеСостояние
    );
}

// ============================================================
// ПОЛУЧЕНИЕ ДОСТУПНЫХ ПЕРЕХОДОВ
// ============================================================

export function получитьДоступныеПереходыСостояния3D(
    состояние: СостояниеОбъекта3D
): СостояниеОбъекта3D[] {

    return [
        ...ПЕРЕХОДЫ[состояние]
    ];
}

// ============================================================
// ПОПЫТКА ИЗМЕНИТЬ СОСТОЯНИЕ
// ============================================================

export function изменитьСостояниеОбъекта3D(
    объект: Объект3D,
    новоеСостояние: СостояниеОбъекта3D
): РезультатПереходаСостояния3D {

    const предыдущееСостояние =
        объект.состояние;

    if (
        предыдущееСостояние ===
        новоеСостояние
    ) {

        return {
            успешно: true,
            предыдущееСостояние,
            новоеСостояние,
            сообщение:
                "Объект уже находится в указанном состоянии."
        };
    }

    if (
        !разрешёнПереходСостояния3D(
            предыдущееСостояние,
            новоеСостояние
        )
    ) {

        return {
            успешно: false,
            предыдущееСостояние,
            новоеСостояние,
            сообщение:
                `Переход из состояния «${предыдущееСостояние}» ` +
                `в состояние «${новоеСостояние}» запрещён.`
        };
    }

    установитьСостояниеОбъекта3D(
        объект,
        новоеСостояние
    );

    return {
        успешно: true,
        предыдущееСостояние,
        новоеСостояние,
        сообщение:
            `Состояние изменено: ` +
            `«${предыдущееСостояние}» → ` +
            `«${новоеСостояние}».`
    };
}

// ============================================================
// ПОДПИСКА НА ИЗМЕНЕНИЕ СОСТОЯНИЯ
// ============================================================

export type ОбработчикСостояния3D =
    (
        событие: СобытиеСостоянияОбъекта3D
    ) => void;

// ============================================================
// МЕНЕДЖЕР СОСТОЯНИЙ
// ============================================================

export class МенеджерСостоянийОбъектов3D {

    private обработчики:
        ОбработчикСостояния3D[] = [];

    // --------------------------------------------------------
    // ДОБАВЛЕНИЕ ОБРАБОТЧИКА
    // --------------------------------------------------------

    добавитьОбработчик(
        обработчик: ОбработчикСостояния3D
    ): void {

        if (
            this.обработчики.includes(
                обработчик
            )
        ) {
            return;
        }

        this.обработчики.push(
            обработчик
        );
    }

    // --------------------------------------------------------
    // УДАЛЕНИЕ ОБРАБОТЧИКА
    // --------------------------------------------------------

    удалитьОбработчик(
        обработчик: ОбработчикСостояния3D
    ): void {

        this.обработчики =
            this.обработчики.filter(
                текущий =>
                    текущий !== обработчик
            );
    }

    // --------------------------------------------------------
    // ОЧИСТКА ОБРАБОТЧИКОВ
    // --------------------------------------------------------

    очиститьОбработчики(): void {

        this.обработчики = [];
    }

    // --------------------------------------------------------
    // ПЕРЕВОД ОБЪЕКТА В НОВОЕ СОСТОЯНИЕ
    // --------------------------------------------------------

    изменитьСостояние(
        объект: Объект3D,
        новоеСостояние: СостояниеОбъекта3D
    ): РезультатПереходаСостояния3D {

        const результат =
            изменитьСостояниеОбъекта3D(
                объект,
                новоеСостояние
            );

        if (
            !результат.успешно ||
            результат.предыдущееСостояние ===
                результат.новоеСостояние
        ) {

            return результат;
        }

        const событие:
            СобытиеСостоянияОбъекта3D = {
                идентификаторОбъекта:
                    объект.идентификатор,

                предыдущееСостояние:
                    результат.предыдущееСостояние,

                новоеСостояние:
                    результат.новоеСостояние,

                время: Date.now()
            };

        for (
            const обработчик
            of this.обработчики
        ) {

            обработчик(
                событие
            );
        }

        return результат;
    }

    // --------------------------------------------------------
    // ПРОВЕРКА ПЕРЕХОДА
    // --------------------------------------------------------

    можноИзменитьСостояние(
        объект: Объект3D,
        новоеСостояние: СостояниеОбъекта3D
    ): boolean {

        return разрешёнПереходСостояния3D(
            объект.состояние,
            новоеСостояние
        );
    }

    // --------------------------------------------------------
    // ПОЛУЧЕНИЕ ДОСТУПНЫХ ПЕРЕХОДОВ
    // --------------------------------------------------------

    получитьДоступныеПереходы(
        объект: Объект3D
    ): СостояниеОбъекта3D[] {

        return получитьДоступныеПереходыСостояния3D(
            объект.состояние
        );
    }
}
