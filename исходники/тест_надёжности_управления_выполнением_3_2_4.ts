// ============================================================
// 🐌 УЛИТКА
// Тест надёжности управления выполнением
// ============================================================

// ЭТАП:
//
// 3.2.4 — Проверка надёжности управления выполнением
//
// ============================================================

import {
    Исполнитель
} from "./исполнитель";

import {
    КонтекстВыполнения
} from "./контекст_выполнения";

import {
    УправлениеВыполнением
} from "./управление_выполнением";


// ============================================================
// ПРОВЕРКА
// ============================================================

let всегоПроверок = 0;

let успешныхПроверок = 0;


function проверить(
    условие: boolean,
    название: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✓ ${название}`
        );

    } else {

        console.error(
            `✗ ${название}`
        );
    }
}


// ============================================================
// ТЕСТОВАЯ ПРОГРАММА
// ============================================================

const дерево = [
    {
        вид: "ПРОГРАММА" as const,
        имя: "тест_надёжности",
        тело: {
            вид: "БЛОК" as const,
            команды: [
                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ" as const,
                    имя: "число",
                    значение: {
                        вид: "ЧИСЛО" as const,
                        значение: 10
                    }
                },
                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ" as const,
                    имя: "результат",
                    значение: {
                        вид: "ОПЕРАЦИЯ" as const,
                        оператор: "+",
                        левое: {
                            вид: "ИМЯ" as const,
                            значение: "число"
                        },
                        правое: {
                            вид: "ЧИСЛО" as const,
                            значение: 20
                        }
                    }
                },
                {
                    вид: "ПОКАЗАТЬ" as const,
                    значения: [
                        {
                            вид: "ИМЯ" as const,
                            значение: "результат"
                        }
                    ]
                }
            ]
        }
    }
];


// ============================================================
// СОЗДАНИЕ ОБЪЕКТОВ
// ============================================================

const исполнитель =
    new Исполнитель();

const контекст =
    new КонтекстВыполнения(
        "программа тест_надёжности"
    );

контекст.установитьДерево(
    дерево
);

const управление =
    new УправлениеВыполнением(
        исполнитель,
        контекст
    );


// ============================================================
// 1. ПЕРВЫЙ ЗАПУСК
// ============================================================

console.log(
    "\n🐌 1. Первый запуск"
);

let результат =
    управление.начать();

проверить(
    результат.успешно,
    "первый запуск принят"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "после запуска состояние — выполнение"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "выполнение",
    "исполнитель находится в состоянии выполнения"
);


// ============================================================
// 2. ПЕРВЫЙ ШАГ И ПОЛНОЕ ПРОДОЛЖЕНИЕ
// ============================================================

console.log(
    "\n🐌 2. Первый шаг и полное продолжение"
);

результат =
    управление.выполнитьШаг();

проверить(
    результат !== null,
    "первый шаг выполнен"
);

проверить(
    управление.получитьСостояние() ===
        "приостановлено",
    "после первого шага выполнение приостановлено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "приостановлено",
    "исполнитель после первого шага приостановлен"
);

проверить(
    управление.получитьПеременные().число ===
        10,
    "после первого шага переменная «число» равна 10"
);

проверить(
    управление.продолжить(),
    "продолжение после паузы выполнено"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "после продолжения управление завершено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "завершено",
    "после продолжения исполнитель завершён"
);

проверить(
    управление.получитьТекущийШаг() ===
        3,
    "после полного продолжения выполнены 3 шага"
);

проверить(
    управление.получитьПеременные().результат ===
        30,
    "результат вычисления равен 30"
);

проверить(
    управление.получитьВывод().length ===
        1,
    "получен один элемент вывода"
);

проверить(
    управление.получитьВывод()[0] ===
        "30",
    "вывод содержит 30"
);


// ============================================================
// 3. ПОВТОРНЫЙ ЗАПУСК ПОСЛЕ ЗАВЕРШЕНИЯ
// ============================================================

console.log(
    "\n🐌 3. Повторный запуск после завершения"
);

результат =
    управление.начать();

проверить(
    результат.успешно,
    "повторный запуск принят"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "после повторного запуска состояние — выполнение"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "выполнение",
    "исполнитель после повторного запуска — выполнение"
);

проверить(
    управление.получитьТекущийШаг() ===
        0,
    "счётчик шагов сброшен"
);

проверить(
    управление.получитьВывод().length ===
        0,
    "старый вывод очищен"
);

проверить(
    Object.keys(
        управление.получитьПеременные()
    ).length === 0,
    "старые переменные очищены"
);


// ============================================================
// 4. ОСТАНОВКА ВЫПОЛНЕНИЯ
// ============================================================

console.log(
    "\n🐌 4. Остановка выполнения"
);

результат =
    управление.выполнитьШаг();

проверить(
    результат !== null,
    "первый шаг после повторного запуска выполнен"
);

проверить(
    управление.получитьСостояние() ===
        "приостановлено",
    "после первого шага состояние — приостановлено"
);

проверить(
    управление.приостановить(),
    "повторная пауза принята"
);

проверить(
    управление.получитьСостояние() ===
        "приостановлено",
    "повторная пауза сохраняет состояние"
);

проверить(
    управление.остановить(),
    "остановка успешно выполнена"
);

проверить(
    управление.получитьСостояние() ===
        "остановлено",
    "состояние после остановки — остановлено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "остановлено",
    "исполнитель также остановлен"
);


// ============================================================
// 5. ПОВТОРНЫЙ ЗАПУСК ПОСЛЕ ОСТАНОВКИ
// ============================================================

console.log(
    "\n🐌 5. Повторный запуск после остановки"
);

результат =
    управление.начать();

проверить(
    результат.успешно,
    "запуск после остановки принят"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "после нового запуска состояние — выполнение"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "выполнение",
    "после нового запуска исполнитель — выполнение"
);

проверить(
    управление.получитьТекущийШаг() ===
        0,
    "после нового запуска шаг снова равен 0"
);


// ============================================================
// 6. ПРЯМАЯ ОСТАНОВКА
// ============================================================

console.log(
    "\n🐌 6. Прямая остановка"
);

проверить(
    управление.остановить(),
    "прямая остановка выполнена"
);

проверить(
    управление.получитьСостояние() ===
        "остановлено",
    "состояние после прямой остановки — остановлено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "остановлено",
    "исполнитель после прямой остановки — остановлен"
);


// ============================================================
// 7. ОШИБКА БЕЗ AST
// ============================================================

console.log(
    "\n🐌 7. Ошибка при отсутствии AST"
);

const исполнительОшибки =
    new Исполнитель();

const контекстОшибки =
    new КонтекстВыполнения(
        "программа без дерева"
    );

const управлениеОшибки =
    new УправлениеВыполнением(
        исполнительОшибки,
        контекстОшибки
    );

результат =
    управлениеОшибки.начать();

проверить(
    !результат.успешно,
    "запуск без AST отклонён"
);

проверить(
    управлениеОшибки.получитьСостояние() ===
        "ошибка",
    "состояние управления — ошибка"
);

проверить(
    управлениеОшибки.получитьСообщениеОшибки() !==
        null,
    "сообщение об ошибке сохранено"
);

проверить(
    контекстОшибки.получитьФазу() ===
        "ошибка",
    "контекст перешёл в фазу ошибки"
);


// ============================================================
// ИТОГ
// ============================================================

console.log(
    "\n============================================================"
);

console.log(
    `🐌 Тест 3.2.4 завершён: ${успешныхПроверок}/${всегоПроверок} проверок пройдено.`
);

if (
    успешныхПроверок !==
    всегоПроверок
) {

    throw new Error(
        "Тест 3.2.4 завершён с ошибками."
    );
}

console.log(
    "✓ Надёжность управления подтверждена."
);