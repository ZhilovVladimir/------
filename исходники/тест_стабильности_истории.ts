// ============================================================
// 🐌 УЛИТКА — ТЕСТ СТАБИЛЬНОСТИ ИСТОРИИ
// Проверка возврата из истории в обычный режим работы
// ============================================================

import { Ядро3D } from "./ядро_3d";

console.log("🐌 ТЕСТ СТАБИЛЬНОСТИ ИСТОРИИ");
console.log("==========================================");

const ядро = new Ядро3D();

console.log("\n[1] Создание исходной истории");
console.log("--------------------------------");

ядро.добавитьПеременную({
    имя: "первая",
    значение: 100,
    тип: "число"
});

ядро.добавитьФункцию({
    имя: "вторая",
    параметры: []
});

ядро.установитьСостояние("выполнение");

ядро.установитьТекущуюСтроку(5);

console.log(
    "Событий:",
    ядро.получитьКоличествоСобытий()
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

if (
    ядро.получитьКоличествоСобытий() !== 4
) {
    throw new Error(
        "❌ Исходная история должна содержать 4 события."
    );
}

console.log(
    "✅ Исходная история создана"
);

console.log("\n[2] Переход к событию");
console.log("--------------------------------");

const результатПерехода =
    ядро.перейтиКСобытию(2);

console.log(
    "Переход выполнен:",
    результатПерехода
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

if (
    ядро.получитьТекущуюПозициюИстории() !== 2
) {
    throw new Error(
        "❌ Позиция после перехода неправильная."
    );
}

if (
    ядро.получитьРежимВоспроизведения() !==
    "остановлено"
) {
    throw new Error(
        "❌ После обычного перехода режим должен быть остановлен."
    );
}

console.log(
    "✅ После перехода режим восстановлен"
);

console.log("\n[3] Создание нового события после перехода");
console.log("--------------------------------");

const количествоДо =
    ядро.получитьКоличествоСобытий();

const узлыДо =
    ядро.получитьУзлы().length;

const узел =
    ядро.получитьУзлы()[0];

if (!узел) {
    throw new Error(
        "❌ После восстановления не найден узел."
    );
}

const результатИзменения =
    ядро.активироватьУзел(
        узел.идентификатор,
        0.7
    );

const количествоПосле =
    ядро.получитьКоличествоСобытий();

console.log(
    "Узлов до изменения:",
    узлыДо
);

console.log(
    "Идентификатор узла:",
    узел.идентификатор
);

console.log(
    "Активация:",
    результатИзменения
);

console.log(
    "Событий до:",
    количествоДо
);

console.log(
    "Событий после:",
    количествоПосле
);

if (!результатИзменения) {
    throw new Error(
        "❌ Узел после восстановления не найден или не активирован."
    );
}

if (
    количествоПосле !==
    количествоДо + 1
) {
    throw new Error(
        "❌ После перехода по истории новое событие не записалось."
    );
}

console.log(
    "✅ Новое событие успешно записано"
);

console.log("\n[4] Возврат назад по истории");
console.log("--------------------------------");

const предыдущий =
    ядро.предыдущееСобытие();

console.log(
    "Получено событие:",
    предыдущий
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

if (
    ядро.получитьРежимВоспроизведения() !==
    "остановлено"
) {
    throw new Error(
        "❌ После возврата назад режим должен быть остановлен."
    );
}

console.log(
    "✅ После возврата назад режим нормальный"
);

console.log("\n[5] Проверка записи события после возврата");
console.log("--------------------------------");

const узелПослеВозврата =
    ядро.получитьУзлы()[0];

if (!узелПослеВозврата) {
    throw new Error(
        "❌ После возврата узел не восстановлен."
    );
}

const количествоПередВторым =
    ядро.получитьКоличествоСобытий();

const результатИнтенсивности =
    ядро.изменитьИнтенсивностьУзла(
        узелПослеВозврата.идентификатор,
        0.5
    );

const количествоПослеВторого =
    ядро.получитьКоличествоСобытий();

console.log(
    "Изменение интенсивности:",
    результатИнтенсивности
);

console.log(
    "Событий до:",
    количествоПередВторым
);

console.log(
    "Событий после:",
    количествоПослеВторого
);

if (!результатИнтенсивности) {
    throw new Error(
        "❌ Не удалось изменить интенсивность восстановленного узла."
    );
}

if (
    количествоПослеВторого !==
    количествоПередВторым + 1
) {
    throw new Error(
        "❌ После возврата назад новое событие не записалось."
    );
}

console.log(
    "✅ После возврата назад события снова записываются"
);

console.log("\n[6] Настоящее воспроизведение");
console.log("--------------------------------");

ядро.начатьВоспроизведение();

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

if (
    ядро.получитьРежимВоспроизведения() !==
    "воспроизведение"
) {
    throw new Error(
        "❌ Воспроизведение не запустилось."
    );
}

if (
    ядро.получитьТекущуюПозициюИстории() !==
    -1
) {
    throw new Error(
        "❌ После запуска воспроизведения позиция должна быть -1."
    );
}

console.log(
    "✅ Воспроизведение запущено"
);

const следующее =
    ядро.следующееСобытие();

console.log(
    "Следующее событие:",
    следующее
);

console.log(
    "Позиция:",
    ядро.получитьТекущуюПозициюИстории()
);

console.log(
    "Режим после шага:",
    ядро.получитьРежимВоспроизведения()
);

if (!следующее) {
    throw new Error(
        "❌ Следующее событие не получено."
    );
}

if (
    ядро.получитьРежимВоспроизведения() !==
    "воспроизведение"
) {
    throw new Error(
        "❌ После шага режим воспроизведения должен сохраниться."
    );
}

console.log(
    "✅ Пошаговое воспроизведение работает"
);

console.log("\n[7] Остановка и возврат к обычной работе");
console.log("--------------------------------");

ядро.остановитьВоспроизведение();

console.log(
    "Режим:",
    ядро.получитьРежимВоспроизведения()
);

if (
    ядро.получитьРежимВоспроизведения() !==
    "остановлено"
) {
    throw new Error(
        "❌ Воспроизведение не остановилось."
    );
}

const узелПослеОстановки =
    ядро.получитьУзлы()[0];

if (!узелПослеОстановки) {
    throw new Error(
        "❌ После остановки узел не найден."
    );
}

const количествоПередТретьим =
    ядро.получитьКоличествоСобытий();

const результатТретьегоИзменения =
    ядро.изменитьИнтенсивностьУзла(
        узелПослеОстановки.идентификатор,
        0.9
    );

const количествоПослеТретьего =
    ядро.получитьКоличествоСобытий();

console.log(
    "Изменение после остановки:",
    результатТретьегоИзменения
);

console.log(
    "Событий до:",
    количествоПередТретьим
);

console.log(
    "Событий после:",
    количествоПослеТретьего
);

if (!результатТретьегоИзменения) {
    throw new Error(
        "❌ После остановки узел не удалось изменить."
    );
}

if (
    количествоПослеТретьего !==
    количествоПередТретьим + 1
) {
    throw new Error(
        "❌ После остановки новое событие не записалось."
    );
}

console.log(
    "✅ После остановки ядро снова записывает события"
);

console.log("\n==========================================");
console.log("🐌 ТЕСТ СТАБИЛЬНОСТИ ИСТОРИИ ЗАВЕРШЁН");
console.log("==========================================");