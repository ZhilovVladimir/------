// ============================================================
// 🐌 УЛИТКА
// Тест синхронизации подтверждённой внутренней модели с 3D
// Этап 3.5.1
// ============================================================

import {
    создатьМодельИзРезультатаСемантики
} from "./модель/создатель_внутренней_модели.js";

import type {
    Узел,
    Программа
} from "./дерево/узлы.js";

import type {
    ТипЗначения,
    РезультатСемантическогоАнализа
} from "./семантика/типы.js";

import {
    Ядро3D
} from "./ядро_3d.js";

import {
    создатьСинхронизаторМодели3D
} from "./синхронизация_модели_3d.js";

// ============================================================
// СЧЁТЧИК ПРОВЕРОК
// ============================================================

let количествоПроверок = 0;

// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {

    количествоПроверок++;

    if (!условие) {

        throw new Error(
            `❌ ПРОВЕРКА НЕ ПРОЙДЕНА: ${сообщение}`
        );
    }

    console.log(
        `✅ ${сообщение}`
    );
}

// ============================================================
// ТЕСТОВАЯ ПРОГРАММА
// ============================================================

const программа: Программа = {

    вид: "ПРОГРАММА",

    имя:
        "тест_синхронизации_модели_3d",

    тело: {

        вид: "БЛОК",

        команды: []
    }
};

// ============================================================
// ДЕРЕВО ПРОГРАММЫ
// ============================================================

const дерево: Узел[] = [

    программа
];

// ============================================================
// ТЕСТОВЫЕ ГЛОБАЛЬНЫЕ СИМВОЛЫ
// ============================================================

const глобальныеСимволы = [

    {

        имя:
            "число",

        вид:
            "переменная" as const,

        тип:
            "число" as ТипЗначения,

        инициализирован:
            true
    },

    {

        имя:
            "текст",

        вид:
            "переменная" as const,

        тип:
            "текст" as ТипЗначения,

        инициализирован:
            false
    },

    {

        имя:
            "сложить",

        вид:
            "функция" as const,

        тип:
            "функция" as ТипЗначения,

        параметры: [
            "первое",
            "второе"
        ],

        типВозврата:
            "число" as ТипЗначения,

        инициализирован:
            true
    }
];

// ============================================================
// ТЕСТОВЫЕ ОШИБКИ
// ============================================================

const ошибки:
    РезультатСемантическогоАнализа["ошибки"] = [];

// ============================================================
// РЕЗУЛЬТАТ СЕМАНТИЧЕСКОГО АНАЛИЗА
// ============================================================

const результат:
    РезультатСемантическогоАнализа = {

    успешно:
        true,

    ошибки,

    глобальныеСимволы
};

// ============================================================
// ТИПЫ AST-УЗЛОВ
// ============================================================

const типыУзлов =
    new Map<object, ТипЗначения>();

типыУзлов.set(
    программа,
    "пусто"
);

// ============================================================
// СОЗДАНИЕ ЕДИНОЙ ВНУТРЕННЕЙ МОДЕЛИ
// ============================================================

const модель =
    создатьМодельИзРезультатаСемантики(
        дерево,
        результат,
        типыУзлов
    );

// ============================================================
// СОЗДАНИЕ 3D-ЯДРА
// ============================================================

const ядро =
    new Ядро3D();

// ============================================================
// СОЗДАНИЕ СИНХРОНИЗАТОРА
// ============================================================

const синхронизатор =
    создатьСинхронизаторМодели3D(
        ядро
    );

// ============================================================
// СИНХРОНИЗАЦИЯ
// ============================================================

const результатСинхронизации =
    синхронизатор.синхронизировать(
        модель
    );

// ============================================================
// ПОЛУЧЕНИЕ УЗЛОВ 3D-ЯДРА
// ============================================================

const узлы =
    ядро.получитьУзлы();

// ============================================================
// ПРОВЕРКА РЕЗУЛЬТАТА
// ============================================================

проверить(

    результатСинхронизации.успешно
        === true,

    "Синхронизация успешной модели завершена успешно"
);

// ============================================================
// ПРОВЕРКА ПРОГРАММЫ
// ============================================================

проверить(

    результатСинхронизации
        .идентификаторПрограммы
        !== null,

    "Создан идентификатор узла программы"
);

const узелПрограммы =
    узлы.find(

        узел =>
            узел.идентификатор
            ===
            результатСинхронизации
                .идентификаторПрограммы
    );

проверить(

    узелПрограммы !== undefined,

    "Узел программы найден в 3D-ядре"
);

проверить(

    узелПрограммы?.тип
        === "программа",

    "Узел программы имеет подтверждённый тип «программа»"
);

проверить(

    узелПрограммы?.имя
        ===
        "тест_синхронизации_модели_3d",

    "Имя программы передано в 3D-ядро"
);

// ============================================================
// ПРОВЕРКА ПЕРЕМЕННЫХ
// ============================================================

const идентификаторЧисла =
    результатСинхронизации
        .идентификаторыПеременных
        .get("число");

const идентификаторТекста =
    результатСинхронизации
        .идентификаторыПеременных
        .get("текст");

проверить(

    идентификаторЧисла
        !== undefined,

    "Создан узел переменной «число»"
);

проверить(

    идентификаторТекста
        !== undefined,

    "Создан узел переменной «текст»"
);

const узелЧисла =
    узлы.find(

        узел =>
            узел.идентификатор
            ===
            идентификаторЧисла
    );

const узелТекста =
    узлы.find(

        узел =>
            узел.идентификатор
            ===
            идентификаторТекста
    );

проверить(

    узелЧисла?.тип
        === "переменная",

    "Узел «число» имеет тип «переменная»"
);

проверить(

    узелТекста?.тип
        === "переменная",

    "Узел «текст» имеет тип «переменная»"
);

// ============================================================
// ПРОВЕРКА ФУНКЦИИ
// ============================================================

const идентификаторФункции =
    результатСинхронизации
        .идентификаторыФункций
        .get("сложить");

проверить(

    идентификаторФункции
        !== undefined,

    "Создан узел функции «сложить»"
);

const узелФункции =
    узлы.find(

        узел =>
            узел.идентификатор
            ===
            идентификаторФункции
    );

проверить(

    узелФункции?.тип
        === "функция",

    "Узел «сложить» имеет тип «функция»"
);

проверить(

    узелФункции?.имя
        === "сложить",

    "Имя функции передано в 3D-ядро"
);

// ============================================================
// ПРОВЕРКА ПАРАМЕТРОВ
// ============================================================

проверить(

    !результатСинхронизации
        .идентификаторыПеременных
        .has("первое"),

    "Параметр «первое» не создан как глобальная переменная"
);

проверить(

    !результатСинхронизации
        .идентификаторыПеременных
        .has("второе"),

    "Параметр «второе» не создан как глобальная переменная"
);

// ============================================================
// ПРОВЕРКА ОШИБОК
// ============================================================

проверить(

    результатСинхронизации
        .идентификаторыОшибок
        .length
        === 0,

    "При успешной модели узлы ошибок не созданы"
);

// ============================================================
// ПРОВЕРКА КОЛИЧЕСТВА УЗЛОВ
// ============================================================

проверить(

    результатСинхронизации
        .созданоУзлов
        === 4,

    "Создано ровно четыре подтверждённых узла"
);

проверить(

    узлы.length
        === 4,

    "В 3D-ядре находится ровно четыре узла"
);

// ============================================================
// ПРОВЕРКА СОСТАВА УЗЛОВ
// ============================================================

проверить(

    узлы.filter(
        узел =>
            узел.тип === "программа"
    ).length
        === 1,

    "В 3D-ядре ровно один узел программы"
);

проверить(

    узлы.filter(
        узел =>
            узел.тип === "переменная"
    ).length
        === 2,

    "В 3D-ядре ровно два узла переменных"
);

проверить(

    узлы.filter(
        узел =>
            узел.тип === "функция"
    ).length
        === 1,

    "В 3D-ядре ровно один узел функции"
);

проверить(

    узлы.filter(
        узел =>
            узел.тип === "ошибка"
    ).length
        === 0,

    "В 3D-ядре нет узлов ошибок"
);

// ============================================================
// ИТОГ
// ============================================================

console.log("");

console.log(
    "🐌 ============================================================"
);

console.log(
    "🐌 ТЕСТ 3.5.1 — СИНХРОНИЗАЦИЯ МОДЕЛИ С 3D"
);

console.log(
    "🐌 ============================================================"
);

console.log(
    `🐌 Создано узлов: ${
        результатСинхронизации.созданоУзлов
    }`
);

console.log(
    `🐌 Узлов в 3D-ядре: ${
        узлы.length
    }`
);

console.log(
    "🐌 Программа: тест_синхронизации_модели_3d"
);

console.log(
    "🐌 Переменные: число, текст"
);

console.log(
    "🐌 Функция: сложить"
);

console.log(
    "🐌 Ошибок: 0"
);

console.log(
    "🐌 ============================================================"
);

console.log(
    `🐌 ✅ ТЕСТ 3.5.1 УСПЕШЕН: ${
        количествоПроверок
    } проверок пройдено.`
);

console.log(
    "🐌 ============================================================"
);
