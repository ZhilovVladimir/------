import { readFileSync } from "node:fs";

import { разобрать } from "./лексический_анализатор.js";

import { Парсер } from "./ядро/парсер.js";

import { СистемаУлитки3D } from "./система_улитки_3d.js";

// ============================================================
// 🐌 КОМПИЛЯТОР «УЛИТКА»
// Главная точка запуска
// ============================================================

// ------------------------------------------------------------
// Путь к программе на языке «Улитка»
// ------------------------------------------------------------

const путь = "примеры/тест_3d.ул";

// ------------------------------------------------------------
// Читаем исходный код
// ------------------------------------------------------------

const исходныйКод = readFileSync(
путь,
"utf8"
);

// ------------------------------------------------------------
// Сообщение о запуске
// ------------------------------------------------------------

console.log("🐌 Компилятор «Улитка» запущен.");
console.log("");

// ------------------------------------------------------------
// Показываем исходный код
// ------------------------------------------------------------

console.log("Исходный код:");
console.log(исходныйКод);

// ------------------------------------------------------------
// Лексический анализ
// ------------------------------------------------------------

console.log("Лексемы:");

const лексемы = разобрать(
исходныйКод
);

// ------------------------------------------------------------
// Показываем лексемы
// ------------------------------------------------------------

for (const лексема of лексемы) {
console.log(лексема);
}

// ------------------------------------------------------------
// Создаём парсер
// ------------------------------------------------------------

const парсер = new Парсер(
лексемы
);

// ------------------------------------------------------------
// Запускаем синтаксический разбор
// ------------------------------------------------------------

const дерево = парсер.разобрать();

// ------------------------------------------------------------
// Показываем результат разбора
// ------------------------------------------------------------

console.log("");

console.log("🐌 ДЕРЕВО ПРОГРАММЫ:");

console.dir(
дерево,
{
depth: null
}
);

// ============================================================
// 🐌 3D-СИСТЕМА УЛИТКИ
// ============================================================

// ------------------------------------------------------------
// Создаём центральную систему
// ------------------------------------------------------------

const система = new СистемаУлитки3D();

// ------------------------------------------------------------
// Получаем исполнителя
// ------------------------------------------------------------

const исполнитель = система.получитьИсполнитель();

// ------------------------------------------------------------
// Исполняем реальное дерево программы
// ------------------------------------------------------------

console.log("");

console.log("🐌 ЗАПУСК 3D-ИСПОЛНЕНИЯ:");

const результат = исполнитель.исполнить(
дерево
);

// ------------------------------------------------------------
// Получаем состояние 3D-ядра
// ------------------------------------------------------------

const ядро = система.получитьЯдро();

const узлы = ядро.получитьУзлы();

const связи = ядро.получитьСвязи();

const события = ядро.получитьСобытия();

// ------------------------------------------------------------
// Показываем результат выполнения
// ------------------------------------------------------------

console.log("");

console.log("🐌 РЕЗУЛЬТАТ ИСПОЛНЕНИЯ:");

console.dir(
результат,
{
depth: null
}
);

// ------------------------------------------------------------
// Показываем состояние 3D-системы
// ------------------------------------------------------------

console.log("");

console.log("🐌 СОСТОЯНИЕ 3D-СИСТЕМЫ:");

console.log(
`3D-узлов: ${узлы.length}`
);

console.log(
`3D-связей: ${связи.length}`
);

console.log(
`Событий: ${события.length}`
);

// ------------------------------------------------------------
// Завершение
// ------------------------------------------------------------

console.log("");

console.log(
"🐌 Программа прошла путь: Парсер → Исполнитель → Интегратор → Ядро3D."
);
