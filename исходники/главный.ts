import { readFileSync } from "node:fs";

import { разобрать } from "./лексический_анализатор.js";

import { Парсер } from "./ядро/парсер.js";


// ============================================================
// 🐌 КОМПИЛЯТОР «УЛИТКА»
// Главная точка запуска
// ============================================================


// ------------------------------------------------------------
// Путь к программе на языке «Улитка»
// ------------------------------------------------------------

const путь = "примеры/приветствие.ул";


// ------------------------------------------------------------
// Читаем исходный код
// ------------------------------------------------------------

const исходныйКод = readFileSync(
    путь,
    "utf8"
);


// ------------------------------------------------------------
// Сообщение о запуске
// ------------------------------------------------------------

console.log("🐌 Компилятор «Улитка» запущен.");


// ------------------------------------------------------------
// Показываем исходный код
// ------------------------------------------------------------

console.log("Исходный код:");

console.log(исходныйКод);


// ------------------------------------------------------------
// Лексический анализ
// ------------------------------------------------------------

console.log("Лексемы:");

const лексемы = разобрать(
    исходныйКод
);


// ------------------------------------------------------------
// Показываем лексемы
// ------------------------------------------------------------

for (const лексема of лексемы) {

    console.log(лексема);
}


// ------------------------------------------------------------
// Создаём парсер
// ------------------------------------------------------------

const парсер = new Парсер(
    лексемы
);


// ------------------------------------------------------------
// Запускаем синтаксический разбор
// ------------------------------------------------------------

const дерево = парсер.разобрать();


// ------------------------------------------------------------
// Показываем результат
// ------------------------------------------------------------

console.log("");

console.log("🐌 ДЕРЕВО ПРОГРАММЫ:");

console.dir(
    дерево,
    {
        depth: null
    }
);