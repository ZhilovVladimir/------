// ============================================================
// 🐌 УЛИТКА — 3D-ЯДРО
// Менеджер объектов 3D-мира
// Реестр, поиск и управление иерархией объектов
// ============================================================

import type {
    Объект3D,
    ТипОбъекта3D,
    СостояниеОбъекта3D
} from "./объект_3d";

import {
    создатьОбъект3D,
    клонироватьОбъект3D,
    проверитьОбъект3D,
    установитьРодителя3D,
    добавитьРебёнка3D,
    удалитьРебёнка3D
} from "./объект_3d";

export class МенеджерОбъектов3D {

    private объекты: Map<string, Объект3D>;

    constructor() {
        this.объекты = new Map<string, Объект3D>();
    }

    // ========================================================
    // СОЗДАНИЕ
    // ========================================================

    создатьОбъект(
        идентификатор: string,
        имя: string,
        тип: ТипОбъекта3D
    ): Объект3D {

        if (
            this.объекты.has(
                идентификатор
            )
        ) {
            throw new Error(
                `Объект с идентификатором "${идентификатор}" уже существует.`
            );
        }

        const объект =
            создатьОбъект3D(
                идентификатор,
                имя,
                тип
            );

        this.объекты.set(
            идентификатор,
            объект
        );

        return объект;
    }

    // ========================================================
    // ДОБАВЛЕНИЕ ГОТОВОГО ОБЪЕКТА
    // ========================================================

    добавитьОбъект(
        объект: Объект3D
    ): void {

        if (
            !проверитьОбъект3D(
                объект
            )
        ) {
            throw new Error(
                "Нельзя добавить некорректный 3D-объект."
            );
        }

        if (
            this.объекты.has(
                объект.идентификатор
            )
        ) {
            throw new Error(
                `Объект с идентификатором "${объект.идентификатор}" уже существует.`
            );
        }

        this.объекты.set(
            объект.идентификатор,
            клонироватьОбъект3D(
                объект
            )
        );
    }

    // ========================================================
    // ПОЛУЧЕНИЕ
    // ========================================================

    получитьОбъект(
        идентификатор: string
    ): Объект3D | null {

        const объект =
            this.объекты.get(
                идентификатор
            );

        if (!объект) {
            return null;
        }

        return объект;
    }

    получитьКопиюОбъекта(
        идентификатор: string
    ): Объект3D | null {

        const объект =
            this.объекты.get(
                идентификатор
            );

        if (!объект) {
            return null;
        }

        return клонироватьОбъект3D(
            объект
        );
    }

    получитьВсеОбъекты(): Объект3D[] {

        return Array.from(
            this.объекты.values()
        );
    }

    получитьКопииВсехОбъектов(): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .map(
                объект =>
                    клонироватьОбъект3D(
                        объект
                    )
            );
    }

    // ========================================================
    // ИНТЕЛЛЕКТУАЛЬНЫЙ ПОИСК
    // ========================================================

    найтиПоИдентификатору(
        идентификатор: string
    ): Объект3D | null {

        return this.получитьОбъект(
            идентификатор
        );
    }

    найтиПоИмени(
        имя: string
    ): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.имя === имя
            );
    }

    найтиПоТипу(
        тип: ТипОбъекта3D
    ): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.тип === тип
            );
    }

    найтиПоСостоянию(
        состояние: СостояниеОбъекта3D
    ): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.состояние === состояние
            );
    }

    найтиАктивные(): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.активен
            );
    }

    найтиВидимые(): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.видим
            );
    }

    найтиПоРодителю(
        идентификаторРодителя: string
    ): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.родитель ===
                    идентификаторРодителя
            );
    }

    // ========================================================
    // ПРОВЕРКА
    // ========================================================

    существует(
        идентификатор: string
    ): boolean {

        return this.объекты.has(
            идентификатор
        );
    }

    // ========================================================
    // КОЛИЧЕСТВО
    // ========================================================

    получитьКоличество(): number {

        return this.объекты.size;
    }

    получитьКоличествоПоТипу(
        тип: ТипОбъекта3D
    ): number {

        return this
            .найтиПоТипу(тип)
            .length;
    }

    получитьКоличествоПоСостоянию(
        состояние: СостояниеОбъекта3D
    ): number {

        return this
            .найтиПоСостоянию(состояние)
            .length;
    }

    получитьКоличествоАктивных(): number {

        return this
            .найтиАктивные()
            .length;
    }

    // ========================================================
    // УДАЛЕНИЕ
    // ========================================================

    удалитьОбъект(
        идентификатор: string
    ): boolean {

        const объект =
            this.объекты.get(
                идентификатор
            );

        if (!объект) {
            return false;
        }

        // Если объект является ребёнком,
        // удаляем его из списка детей родителя.

        if (
            объект.родитель !== null
        ) {

            const родитель =
                this.объекты.get(
                    объект.родитель
                );

            if (родитель) {

                удалитьРебёнка3D(
                    родитель,
                    объект.идентификатор
                );
            }
        }

        // Если объект имеет детей,
        // снимаем с них родительскую связь.

        const дети =
            [...объект.дети];

        for (
            const идентификаторРебёнка
            of дети
        ) {

            const ребёнок =
                this.объекты.get(
                    идентификаторРебёнка
                );

            if (ребёнок) {

                установитьРодителя3D(
                    ребёнок,
                    null
                );
            }
        }

        return this.объекты.delete(
            идентификатор
        );
    }

    // ========================================================
    // ОЧИСТКА
    // ========================================================

    очистить(): void {

        this.объекты.clear();
    }

    // ========================================================
    // РОДИТЕЛЬСКАЯ СВЯЗЬ
    // ========================================================

    установитьРодителя(
        идентификаторРебёнка: string,
        идентификаторРодителя: string | null
    ): void {

        const ребёнок =
            this.объекты.get(
                идентификаторРебёнка
            );

        if (!ребёнок) {

            throw new Error(
                `Ребёнок "${идентификаторРебёнка}" не найден.`
            );
        }

        // Снятие родителя.

        if (
            идентификаторРодителя === null
        ) {

            if (
                ребёнок.родитель !== null
            ) {

                const старыйРодитель =
                    this.объекты.get(
                        ребёнок.родитель
                    );

                if (старыйРодитель) {

                    удалитьРебёнка3D(
                        старыйРодитель,
                        идентификаторРебёнка
                    );
                }
            }

            установитьРодителя3D(
                ребёнок,
                null
            );

            return;
        }

        // Сам объект не может быть своим родителем.

        if (
            идентификаторРебёнка ===
            идентификаторРодителя
        ) {

            throw new Error(
                "Объект не может быть собственным родителем."
            );
        }

        // Проверяем существование нового родителя
        // ДО изменения текущей структуры.

        const новыйРодитель =
            this.объекты.get(
                идентификаторРодителя
            );

        if (!новыйРодитель) {

            throw new Error(
                `Родитель "${идентификаторРодителя}" не найден.`
            );
        }

        // Проверяем, не станет ли новый родитель
        // потомком самого ребёнка.
        //
        // Иначе получится цикл:
        //
        // A -> B -> C -> A

        if (
            this.являетсяПотомком(
                идентификаторРодителя,
                идентификаторРебёнка
            )
        ) {

            throw new Error(
                "Нельзя создать циклическую родительскую связь."
            );
        }

        // Запоминаем старого родителя.

        const старыйРодительИдентификатор =
            ребёнок.родитель;

        // Удаляем ребёнка из старого родителя.

        if (
            старыйРодительИдентификатор !== null
        ) {

            const старыйРодитель =
                this.объекты.get(
                    старыйРодительИдентификатор
                );

            if (старыйРодитель) {

                удалитьРебёнка3D(
                    старыйРодитель,
                    идентификаторРебёнка
                );
            }
        }

        // Устанавливаем нового родителя.

        установитьРодителя3D(
            ребёнок,
            идентификаторРодителя
        );

        добавитьРебёнка3D(
            новыйРодитель,
            идентификаторРебёнка
        );
    }

    // ========================================================
    // ПРОВЕРКА ПОТОМКА
    // ========================================================

    private являетсяПотомком(
        идентификаторКандидата: string,
        идентификаторПредка: string
    ): boolean {

        let текущий =
            this.объекты.get(
                идентификаторКандидата
            );

        const посещённые =
            new Set<string>();

        while (текущий) {

            if (
                посещённые.has(
                    текущий.идентификатор
                )
            ) {
                return true;
            }

            посещённые.add(
                текущий.идентификатор
            );

            if (
                текущий.родитель === null
            ) {
                return false;
            }

            if (
                текущий.родитель ===
                идентификаторПредка
            ) {
                return true;
            }

            текущий =
                this.объекты.get(
                    текущий.родитель
                );
        }

        return false;
    }

    // ========================================================
    // ПОЛУЧЕНИЕ ДЕТЕЙ
    // ========================================================

    получитьДетей(
        идентификаторРодителя: string
    ): Объект3D[] {

        const родитель =
            this.объекты.get(
                идентификаторРодителя
            );

        if (!родитель) {
            return [];
        }

        const дети: Объект3D[] = [];

        for (
            const идентификаторРебёнка
            of родитель.дети
        ) {

            const ребёнок =
                this.объекты.get(
                    идентификаторРебёнка
                );

            if (ребёнок) {

                дети.push(
                    ребёнок
                );
            }
        }

        return дети;
    }

    // ========================================================
    // ПОЛУЧЕНИЕ КОРНЕВЫХ ОБЪЕКТОВ
    // ========================================================

    получитьКорневыеОбъекты(): Объект3D[] {

        return this
            .получитьВсеОбъекты()
            .filter(
                объект =>
                    объект.родитель === null
            );
    }

    // ========================================================
    // ПОИСК ПО ТИПУ
    // ========================================================

    получитьОбъектыПоТипу(
        тип: ТипОбъекта3D
    ): Объект3D[] {

        return this.найтиПоТипу(
            тип
        );
    }

    // ========================================================
    // ПРОВЕРКА ВСЕГО МЕНЕДЖЕРА
    // ========================================================

    проверить(): boolean {

        for (
            const объект
            of this.объекты.values()
        ) {

            if (
                !проверитьОбъект3D(
                    объект
                )
            ) {
                return false;
            }

            // Проверяем родителя.

            if (
                объект.родитель !== null
            ) {

                if (
                    !this.объекты.has(
                        объект.родитель
                    )
                ) {
                    return false;
                }

                if (
                    объект.родитель ===
                    объект.идентификатор
                ) {
                    return false;
                }
            }

            // Проверяем детей.

            const уникальныеДети =
                new Set(
                    объект.дети
                );

            if (
                уникальныеДети.size !==
                объект.дети.length
            ) {
                return false;
            }

            for (
                const идентификаторРебёнка
                of объект.дети
            ) {

                if (
                    !this.объекты.has(
                        идентификаторРебёнка
                    )
                ) {
                    return false;
                }

                const ребёнок =
                    this.объекты.get(
                        идентификаторРебёнка
                    );

                if (!ребёнок) {
                    return false;
                }

                if (
                    ребёнок.родитель !==
                    объект.идентификатор
                ) {
                    return false;
                }
            }

            // Проверяем отсутствие циклов.

            const посещённые =
                new Set<string>();

            let текущий: Объект3D | undefined =
                объект;

            while (
                текущий &&
                текущий.родитель !== null
            ) {

                if (
                    посещённые.has(
                        текущий.идентификатор
                    )
                ) {
                    return false;
                }

                посещённые.add(
                    текущий.идентификатор
                );

                текущий =
                    this.объекты.get(
                        текущий.родитель
                    );
            }
        }

        return true;
    }
}