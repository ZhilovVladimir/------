// ============================================================
// 🐌 УЛИТКА
// Тест причинного графа исполнения → 3D
// ============================================================

import {
    Исполнитель
} from "./исполнитель.js";

import {
    Ядро3D
} from "./ядро_3d.js";

import {
    ИнтеграторИсполнения3D
} from "./интегратор_исполнения_3d.js";

import type {
    Узел
} from "./дерево/узлы.js";

// ============================================================
// ПРОСТАЯ ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {
    if (!условие) {
        throw new Error(
            `❌ ${сообщение}`
        );
    }
}

// ============================================================
// ТЕСТ
// ============================================================

const дерево: Узел[] = [
    {
        вид: "ФУНКЦИЯ",
        имя: "сложить",
        параметры: [],
        тело: {
            вид: "БЛОК",
            команды: [
                {
                    вид: "ВОЗВРАТ",
                    значение: {
                        вид: "ОПЕРАЦИЯ",
                        оператор: "+",
                        левое: {
                            вид: "ЧИСЛО",
                            значение: 10
                        },
                        правое: {
                            вид: "ЧИСЛО",
                            значение: 20
                        }
                    }
                }
            ]
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "а",
        значение: {
            вид: "ЧИСЛО",
            значение: 10
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "б",
        значение: {
            вид: "ОПЕРАЦИЯ",
            оператор: "+",
            левое: {
                вид: "ИМЯ",
                значение: "а"
            },
            правое: {
                вид: "ЧИСЛО",
                значение: 5
            }
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "результат",
        значение: {
            вид: "ВЫЗОВ_ФУНКЦИИ",
            имя: "сложить",
            аргументы: []
        }
    }
];

// ============================================================
// СОЗДАНИЕ СИСТЕМЫ
// ============================================================

const ядро =
    new Ядро3D();

const интегратор =
    new ИнтеграторИсполнения3D(
        ядро
    );

const исполнитель =
    new Исполнитель();

исполнитель.установитьОбработчикСобытий(
    интегратор.создатьОбработчик()
);

// ============================================================
// ВЫПОЛНЕНИЕ
// ============================================================

const результат =
    исполнитель.исполнить(
        дерево
    );

// ============================================================
// ПРОВЕРКА РЕЗУЛЬТАТА
// ============================================================

проверить(
    результат.переменные.а === 10,
    "Переменная «а» должна быть равна 10."
);

проверить(
    результат.переменные.б === 15,
    "Переменная «б» должна быть равна 15."
);

проверить(
    результат.переменные.результат === 30,
    "Переменная «результат» должна быть равна 30."
);

// ============================================================
// ПОЛУЧЕНИЕ 3D ДАННЫХ
// ============================================================

const узлы =
    ядро.получитьУзлы();

const связи =
    ядро.получитьСвязи();

// ============================================================
// ПРОВЕРКА УЗЛОВ
// ============================================================

проверить(
    узлы.some(
        узел =>
            узел.тип === "переменная" &&
            узел.имя === "а"
    ),
    "Не найден 3D-узел переменной «а»."
);

проверить(
    узлы.some(
        узел =>
            узел.тип === "переменная" &&
            узел.имя === "б"
    ),
    "Не найден 3D-узел переменной «б»."
);

проверить(
    узлы.some(
        узел =>
            узел.тип === "переменная" &&
            узел.имя === "результат"
    ),
    "Не найден 3D-узел переменной «результат»."
);

проверить(
    узлы.some(
        узел =>
            узел.тип === "функция" &&
            узел.имя === "сложить"
    ),
    "Не найден 3D-узел функции «сложить»."
);

проверить(
    узлы.some(
        узел =>
            узел.тип === "выполнение"
    ),
    "Не создан ни один узел выполнения."
);

// ============================================================
// ПРОВЕРКА СВЯЗИ А → Б
// ============================================================

const узелА =
    узлы.find(
        узел =>
            узел.тип === "переменная" &&
            узел.имя === "а"
    );

const узелБ =
    узлы.find(
        узел =>
            узел.тип === "переменная" &&
            узел.имя === "б"
    );

проверить(
    узелА !== undefined,
    "Узел «а» не найден для проверки связи."
);

проверить(
    узелБ !== undefined,
    "Узел «б» не найден для проверки связи."
);

проверить(
    связи.some(
        связь =>
            связь.откуда === узелА!.идентификатор &&
            связь.тип === "зависимость"
    ),
    "Не найдена причинная зависимость от «а»."
);

проверить(
    связи.some(
        связь =>
            связь.куда === узелБ!.идентификатор &&
            связь.тип === "передача"
    ),
    "Не найдена передача результата в «б»."
);

// ============================================================
// ПРОВЕРКА ФУНКЦИИ → РЕЗУЛЬТАТ
// ============================================================

const узелФункции =
    узлы.find(
        узел =>
            узел.тип === "функция" &&
            узел.имя === "сложить"
    );

const узелРезультата =
    узлы.find(
        узел =>
            узел.тип === "переменная" &&
            узел.имя === "результат"
    );

проверить(
    узелФункции !== undefined,
    "Функция «сложить» не найдена."
);

проверить(
    узелРезультата !== undefined,
    "Переменная «результат» не найдена."
);

проверить(
    связи.some(
        связь =>
            связь.откуда ===
                узелФункции!.идентификатор &&
            связь.тип === "вызов"
    ),
    "Не найдена связь вызова функции «сложить»."
);

проверить(
    связи.some(
        связь =>
            связь.куда ===
                узелРезультата!.идентификатор &&
            связь.тип === "передача"
    ),
    "Не найдена передача результата функции."
);

// ============================================================
// ИНФОРМАЦИЯ
// ============================================================

console.log(
    "🐌 Тест причинного графа 3D"
);

console.log(
    `Узлов: ${узлы.length}`
);

console.log(
    `Связей: ${связи.length}`
);

console.log(
    "Причинная связь «а → б» найдена."
);

console.log(
    "Причинная связь «сложить → результат» найдена."
);

console.log(
    "✅ Тест причинного графа 3D: ПРОЙДЕН."
);