let всегоПроверок = 0;
let успешныхПроверок = 0;


// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (!условие) {
        throw new Error(
            `❌ ПРОВЕРКА НЕ ПРОШЛА: ${сообщение}`
        );
    }

    успешныхПроверок++;

    console.log(
        `✅ ${сообщение}`
    );
}


// ============================================================
// ОЖИДАНИЕ
// ============================================================

function ждать(
    миллисекунды: number
): Promise<void> {

    return new Promise(
        разрешить => {

            setTimeout(
                разрешить,
                миллисекунды
            );

        }
    );
}


