    проверить(
        исполнительОбычно.получитьСкоростьВыполнения() ===
        "обычно",

        "Скорость «обычно» установлена."
    );

    проверить(
        исполнительОбычно.получитьЗадержкуВыполнения() ===
        300,

        "Задержка «обычно» равна 300 мс."
    );


