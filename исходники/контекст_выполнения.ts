// ============================================================
// 🐌 УЛИТКА
// Единый контекст компиляции и выполнения программы
// ============================================================

import type {
    Узел
} from "./дерево/узлы.js";

import type {
    РезультатВыполнения,
    ЗначениеИсполнения,
    СобытиеИсполнения
} from "./исполнитель.js";

import type {
    ОшибкаСемантики,
    Символ
} from "./семантика/типы.js";

// ============================================================
// ФАЗЫ КОНВЕЙЕРА
// ============================================================

export type ФазаКонвейера =
    | "создание"
    | "лексический_анализ"
    | "синтаксический_анализ"
    | "семантический_анализ"
    | "готово_к_выполнению"
    | "выполнение"
    | "завершено"
    | "ошибка";

// ============================================================
// ЭТАП ДИАГНОСТИКИ
// ============================================================

export type ЭтапДиагностики =
    | "лексика"
    | "синтаксис"
    | "семантика"
    | "выполнение"
    | "система";

// ============================================================
// ДИАГНОСТИКА КОНВЕЙЕРА
// ============================================================

export interface ДиагностикаКонвейера {
    этап: ЭтапДиагностики;
    сообщение: string;
    время: number;
}

// ============================================================
// СНИМОК КОНТЕКСТА
// ============================================================

export interface СнимокКонтекста {

    идентификатор: string;

    исходныйКод: string;

    фаза: ФазаКонвейера;

    дерево: Узел[] | null;

    семантика: {
        ошибки: ОшибкаСемантики[];
        глобальныеСимволы: Символ[];
    };

    выполнение: РезультатВыполнения | null;

    вывод: string[];

    переменные:
        Record<string, ЗначениеИсполнения>;

    события: СобытиеИсполнения[];

    диагностика: ДиагностикаКонвейера[];

    времяСоздания: number;

    времяЗавершения: number | null;
}

// ============================================================
// КОНТЕКСТ ВЫПОЛНЕНИЯ
// ============================================================

export class КонтекстВыполнения {

    private readonly идентификатор: string;

    private readonly исходныйКод: string;

    private фаза:
        ФазаКонвейера = "создание";

    private дерево:
        Узел[] | null = null;

    private семантика: {
        ошибки: ОшибкаСемантики[];
        глобальныеСимволы: Символ[];
    } = {
        ошибки: [],
        глобальныеСимволы: []
    };

    private выполнение:
        РезультатВыполнения | null = null;

    private вывод:
        string[] = [];

    private переменные:
        Record<string, ЗначениеИсполнения> = {};

    private события:
        СобытиеИсполнения[] = [];

    private диагностика:
        ДиагностикаКонвейера[] = [];

    private readonly времяСоздания:
        number;

    private времяЗавершения:
        number | null = null;

    public constructor(
        исходныйКод: string
    ) {

        this.исходныйКод =
            исходныйКод;

        this.времяСоздания =
            Date.now();

        this.идентификатор =
            `контекст_${this.времяСоздания}_${Math.random()
                .toString(36)
                .slice(2, 10)}`;
    }

    // ========================================================
    // ИДЕНТИФИКАТОР
    // ========================================================

    public получитьИдентификатор(): string {

        return this.идентификатор;
    }

    // ========================================================
    // ИСХОДНЫЙ КОД
    // ========================================================

    public получитьИсходныйКод(): string {

        return this.исходныйКод;
    }

    // ========================================================
    // ФАЗА
    // ========================================================

    public установитьФазу(
        фаза: ФазаКонвейера
    ): void {

        this.фаза =
            фаза;

        if (
            фаза === "завершено" ||
            фаза === "ошибка"
        ) {
            this.времяЗавершения =
                Date.now();
        }
    }

    public получитьФазу(): ФазаКонвейера {

        return this.фаза;
    }

    // ========================================================
    // AST
    // ========================================================

    public установитьДерево(
        дерево: Узел[]
    ): void {

        this.дерево =
            дерево;
    }

    public получитьДерево():
        Узел[] | null {

        return this.дерево;
    }

    // ========================================================
    // СЕМАНТИКА
    // ========================================================

    public установитьСемантику(
        ошибки: ОшибкаСемантики[],
        глобальныеСимволы: Символ[]
    ): void {

        this.семантика = {
            ошибки: [...ошибки],
            глобальныеСимволы: [
                ...глобальныеСимволы
            ]
        };
    }

    public получитьСемантику(): {
        ошибки: ОшибкаСемантики[];
        глобальныеСимволы: Символ[];
    } {

        return {
            ошибки: [
                ...this.семантика.ошибки
            ],
            глобальныеСимволы: [
                ...this.семантика.глобальныеСимволы
            ]
        };
    }

    // ========================================================
    // РЕЗУЛЬТАТ ВЫПОЛНЕНИЯ
    // ========================================================

    public установитьВыполнение(
        выполнение: РезультатВыполнения
    ): void {

        this.выполнение =
            выполнение;

        this.вывод =
            [...выполнение.вывод];

        this.переменные = {
            ...выполнение.переменные
        };

        this.события =
            выполнение.события.map(
                событие => ({
                    ...событие
                })
            );
    }

    public получитьВыполнение():
        РезультатВыполнения | null {

        if (this.выполнение === null) {
            return null;
        }

        return {
            ...this.выполнение,
            вывод: [
                ...this.выполнение.вывод
            ],
            переменные: {
                ...this.выполнение.переменные
            },
            события:
                this.выполнение.события.map(
                    событие => ({
                        ...событие
                    })
                )
        };
    }

    // ========================================================
    // ЖИВОЕ СОСТОЯНИЕ
    // ========================================================

    public обновитьСобытия(
        события: СобытиеИсполнения[]
    ): void {

        this.события =
            события.map(
                событие => ({
                    ...событие
                })
            );
    }

    public обновитьВывод(
        вывод: string[]
    ): void {

        this.вывод =
            [...вывод];
    }

    public обновитьПеременные(
        переменные:
            Record<string, ЗначениеИсполнения>
    ): void {

        this.переменные = {
            ...переменные
        };
    }

    public получитьВывод(): string[] {

        return [
            ...this.вывод
        ];
    }

    public получитьПеременные():
        Record<string, ЗначениеИсполнения> {

        return {
            ...this.переменные
        };
    }

    public получитьСобытия():
        СобытиеИсполнения[] {

        return this.события.map(
            событие => ({
                ...событие
            })
        );
    }

    // ========================================================
    // ДИАГНОСТИКА
    // ========================================================

    public добавитьДиагностику(
        этап: ЭтапДиагностики,
        сообщение: string
    ): void {

        this.диагностика.push({
            этап,
            сообщение,
            время: Date.now()
        });
    }

    public получитьДиагностику():
        ДиагностикаКонвейера[] {

        return this.диагностика.map(
            запись => ({
                ...запись
            })
        );
    }

    // ========================================================
    // ЗАВЕРШЕНИЕ
    // ========================================================

    public завершитьУспешно(): void {

        this.установитьФазу(
            "завершено"
        );
    }

    public завершитьСОшибкой(): void {

        this.установитьФазу(
            "ошибка"
        );
    }

    // ========================================================
    // СНИМОК
    // ========================================================

    public получитьСнимок():
        СнимокКонтекста {

        return {
            идентификатор:
                this.идентификатор,

            исходныйКод:
                this.исходныйКод,

            фаза:
                this.фаза,

            дерево:
                this.дерево,

            семантика: {
                ошибки: [
                    ...this.семантика.ошибки
                ],
                глобальныеСимволы: [
                    ...this.семантика.глобальныеСимволы
                ]
            },

            выполнение:
                this.получитьВыполнение(),

            вывод:
                this.получитьВывод(),

            переменные:
                this.получитьПеременные(),

            события:
                this.получитьСобытия(),

            диагностика:
                this.получитьДиагностику(),

            времяСоздания:
                this.времяСоздания,

            времяЗавершения:
                this.времяЗавершения
        };
    }
}
