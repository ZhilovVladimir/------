// ============================================================
// 🐌 УЛИТКА
// Подтверждённое происхождение элементов программы
// ============================================================
//
// Этот файл описывает связь внутреннего представления
// программы с исходным текстом.
//
// ВАЖНО:
// Здесь не хранится предположение о происхождении.
// Координаты должны поступать непосредственно из лексического
// анализа.
//
// Пока файл является самостоятельным фундаментом.
// AST и парсер на этом этапе не изменяются.
// ============================================================


// ============================================================
// ПОЛОЖЕНИЕ В ИСХОДНОМ ТЕКСТЕ
// ============================================================

export interface ПозицияИсточника {

    /**
     * Номер строки исходного текста.
     *
     * Нумерация начинается с 1.
     */
    строка: number;

    /**
     * Позиция символа в строке.
     *
     * Нумерация начинается с 1.
     */
    позиция: number;
}


// ============================================================
// ДИАПАЗОН ИСХОДНОГО ТЕКСТА
// ============================================================

export interface Источник {

    /**
     * Начало фрагмента исходного текста.
     */
    начало: ПозицияИсточника;

    /**
     * Конец фрагмента исходного текста.
     *
     * Координата указывает на последний подтверждённый
     * символ соответствующего фрагмента.
     */
    конец: ПозицияИсточника;
}


// ============================================================
// СОЗДАНИЕ ПОЛОЖЕНИЯ
// ============================================================

export function создатьПозициюИсточника(
    строка: number,
    позиция: number
): ПозицияИсточника {

    return {
        строка,
        позиция
    };
}


// ============================================================
// СОЗДАНИЕ ДИАПАЗОНА
// ============================================================

export function создатьИсточник(
    начало: ПозицияИсточника,
    конец: ПозицияИсточника
): Источник {

    return {
        начало: {
            строка: начало.строка,
            позиция: начало.позиция
        },

        конец: {
            строка: конец.строка,
            позиция: конец.позиция
        }
    };
}


// ============================================================
// ТАБЛИЦА ПРОИСХОЖДЕНИЯ
// ============================================================
//
// Ключом является сам объект внутреннего представления.
//
// Это соответствует уже существующей архитектуре семантики:
//
//     Map<object, ТипЗначения>
//
// Поэтому происхождение не добавляется непосредственно
// в AST-узлы.
// ============================================================

export type ТаблицаПроисхождения =
    Map<object, Источник>;


// ============================================================
// СОЗДАНИЕ ТАБЛИЦЫ
// ============================================================

export function создатьТаблицуПроисхождения():
    ТаблицаПроисхождения {

    return new Map();
}


// ============================================================
// ЗАПИСЬ ПРОИСХОЖДЕНИЯ
// ============================================================

export function установитьИсточник(
    таблица: ТаблицаПроисхождения,
    объект: object,
    источник: Источник
): void {

    таблица.set(
        объект,
        источник
    );
}


// ============================================================
// ПОЛУЧЕНИЕ ПРОИСХОЖДЕНИЯ
// ============================================================

export function получитьИсточник(
    таблица: ТаблицаПроисхождения,
    объект: object
): Источник | null {

    return (
        таблица.get(объект)
        ?? null
    );
}


// ============================================================
// КОПИЯ ТАБЛИЦЫ
// ============================================================
//
// Возвращается новая Map.
//
// Само описание источника также копируется,
// чтобы внешняя сторона не могла изменить
// внутреннюю таблицу через полученную ссылку.
// ============================================================

export function скопироватьТаблицуПроисхождения(
    таблица: ТаблицаПроисхождения
): ТаблицаПроисхождения {

    const результат:
        ТаблицаПроисхождения =
        new Map();

    for (
        const [объект, источник]
        of таблица
    ) {

        результат.set(
            объект,
            {
                начало: {
                    строка:
                        источник.начало.строка,

                    позиция:
                        источник.начало.позиция
                },

                конец: {
                    строка:
                        источник.конец.строка,

                    позиция:
                        источник.конец.позиция
                }
            }
        );
    }

    return результат;
}
