import type {
    Символ
} from "./типы.js";

// ============================================================
// ОБЛАСТЬ СИМВОЛОВ
// ============================================================

export class ОбластьСимволов {
    private символы:
        Map<string, Символ> = new Map();

    constructor(
        private readonly родитель:
            ОбластьСимволов | null = null,
        public readonly имяОбласти:
            string = "область"
    ) {}

    // ========================================================
    // ОБЪЯВИТЬ СИМВОЛ
    // ========================================================

    public объявить(
        символ: Символ
    ): boolean {
        if (this.символы.has(символ.имя)) {
            return false;
        }

        this.символы.set(
            символ.имя,
            символ
        );

        return true;
    }

    // ========================================================
    // НАЙТИ В ТЕКУЩЕЙ ОБЛАСТИ
    // ========================================================

    public найтиВТекущейОбласти(
        имя: string
    ): Символ | undefined {
        return this.символы.get(имя);
    }

    // ========================================================
    // НАЙТИ С УЧЁТОМ РОДИТЕЛЕЙ
    // ========================================================

    public найти(
        имя: string
    ): Символ | undefined {
        const собственный =
            this.символы.get(имя);

        if (собственный) {
            return собственный;
        }

        if (this.родитель === null) {
            return undefined;
        }

        return this.родитель.найти(имя);
    }

    // ========================================================
    // ПОЛУЧИТЬ ТЕКУЩИЕ СИМВОЛЫ
    // ========================================================

    public получитьТекущиеСимволы():
        Символ[] {
        return Array.from(
            this.символы.values()
        );
    }

    // ========================================================
    // ПОЛУЧИТЬ ВСЕ СИМВОЛЫ
    // ========================================================

    public получитьВсеСимволы():
        Символ[] {
        const результат: Символ[] = [];

        if (this.родитель !== null) {
            результат.push(
                ...this.родитель.получитьВсеСимволы()
            );
        }

        результат.push(
            ...this.получитьТекущиеСимволы()
        );

        return результат;
    }
}