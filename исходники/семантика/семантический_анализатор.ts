// ============================================================
// 🐌 УЛИТКА
// Семантический анализатор
// ============================================================

import type {
    Узел,
    Операция,
    ОбъявлениеПеременной,
    ВызовФункции,
    Функция,
    Возврат,
    Показать,
    Условие
} from "../дерево/узлы.js";

import {
    ОбластьСимволов
} from "./таблица_символов.js";

import type {
    ТипЗначения,
    Символ,
    ОшибкаСемантики,
    РезультатСемантическогоАнализа
} from "./типы.js";

// ============================================================
// ВНУТРЕННИЙ КЛЮЧ AST
// ============================================================

type УзелКлюч = object;

// ============================================================
// СЕМАНТИЧЕСКИЙ АНАЛИЗАТОР
// ============================================================

export class СемантическийАнализатор {

    private глобальнаяОбласть:
        ОбластьСимволов =
        new ОбластьСимволов(
            null,
            "глобальная область"
        );

    private текущаяОбласть:
        ОбластьСимволов =
        this.глобальнаяОбласть;

    private ошибки:
        ОшибкаСемантики[] = [];

    private типыУзлов:
        Map<УзелКлюч, ТипЗначения> =
        new Map();

    private текущаяФункция:
        Символ | null = null;

    // ========================================================
    // АНАЛИЗ ПРОГРАММЫ
    // ========================================================

    public анализировать(
        дерево: Узел[]
    ): РезультатСемантическогоАнализа {

        this.сбросить();

        // ----------------------------------------------------
        // Первый проход:
        // регистрируем все верхнеуровневые функции.
        // ----------------------------------------------------

        for (const узел of дерево) {

            if (
                узел.вид !== "ФУНКЦИЯ"
            ) {
                continue;
            }

            this.зарегистрироватьФункцию(
                узел
            );
        }

        // ----------------------------------------------------
        // Второй проход:
        // анализируем глобальные узлы.
        // ----------------------------------------------------

        for (const узел of дерево) {

            if (
                узел.вид === "ФУНКЦИЯ"
            ) {
                continue;
            }

            this.анализироватьУзел(
                узел
            );
        }

        // ----------------------------------------------------
        // Третий проход:
        // анализируем тела функций.
        // ----------------------------------------------------

        for (const узел of дерево) {

            if (
                узел.вид !== "ФУНКЦИЯ"
            ) {
                continue;
            }

            this.анализироватьФункцию(
                узел
            );
        }

        return {

            успешно:
                this.ошибки.length === 0,

            ошибки:
                [...this.ошибки],

            глобальныеСимволы:
                this.глобальнаяОбласть
                    .получитьТекущиеСимволы()
                    .map(
                        символ => ({
                            ...символ,

                            параметры:
                                символ.параметры
                                    ? [
                                        ...символ.параметры
                                    ]
                                    : undefined
                        })
                    )
        };
    }

    // ========================================================
    // СБРОС
    // ========================================================

    private сбросить(): void {

        this.глобальнаяОбласть =
            new ОбластьСимволов(
                null,
                "глобальная область"
            );

        this.текущаяОбласть =
            this.глобальнаяОбласть;

        this.ошибки = [];

        this.типыУзлов =
            new Map();

        this.текущаяФункция =
            null;
    }

    // ========================================================
    // РЕГИСТРАЦИЯ ФУНКЦИИ
    // ========================================================

    private зарегистрироватьФункцию(
        узел: Функция
    ): void {

        const символ: Символ = {

            имя:
                узел.имя,

            вид:
                "функция",

            тип:
                "функция",

            параметры:
                [...узел.параметры],

            типВозврата:
                "неизвестно",

            инициализирован:
                true
        };

        if (
            !this.глобальнаяОбласть.объявить(
                символ
            )
        ) {

            this.добавитьОшибку({

                код:
                    "ПОВТОРНОЕ_ИМЯ",

                сообщение:
                    `Функция «${узел.имя}» уже объявлена.`,

                имя:
                    узел.имя
            });
        }
    }

    // ========================================================
    // АНАЛИЗ УЗЛА
    // ========================================================

    private анализироватьУзел(
        узел: Узел
    ): ТипЗначения {

        switch (узел.вид) {

            case "ЧИСЛО":

                return this.установитьТип(
                    узел,
                    "число"
                );

            case "ТЕКСТ":

                return this.установитьТип(
                    узел,
                    "текст"
                );

            case "ИМЯ":

                return this.анализироватьИмя(
                    узел
                );

            case "ОПЕРАЦИЯ":

                return this.анализироватьОперацию(
                    узел
                );

            case "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ":

                return this.анализироватьПеременную(
                    узел
                );

            case "ВЫЗОВ_ФУНКЦИИ":

                return this.анализироватьВызовФункции(
                    узел
                );

            case "ПОКАЗАТЬ":

                return this.анализироватьПоказать(
                    узел
                );

            case "УСЛОВИЕ":

                return this.анализироватьУсловие(
                    узел
                );

            case "ВОЗВРАТ":

                return this.анализироватьВозврат(
                    узел
                );

            case "ФУНКЦИЯ":

                return this.анализироватьФункцию(
                    узел
                );

            case "БЛОК":

                return this.анализироватьБлок(
                    узел.команды
                );

            case "ПРОГРАММА":

                return this.анализироватьБлок(
                    узел.тело.команды
                );
        }
    }

    // ========================================================
    // ИМЯ
    // ========================================================

    private анализироватьИмя(
        узел: {
            вид: "ИМЯ";
            значение: string;
        }
    ): ТипЗначения {

        const символ =
            this.текущаяОбласть.найти(
                узел.значение
            );

        if (!символ) {

            this.добавитьОшибку({

                код:
                    "НЕИЗВЕСТНОЕ_ИМЯ",

                сообщение:
                    `Имя «${узел.значение}» не объявлено.`,

                имя:
                    узел.значение
            });

            return this.установитьТип(
                узел,
                "неизвестно"
            );
        }

        if (
            !символ.инициализирован
        ) {

            this.добавитьОшибку({

                код:
                    "НЕИЗВЕСТНОЕ_ИМЯ",

                сообщение:
                    `Переменная «${узел.значение}» используется до инициализации.`,

                имя:
                    узел.значение
            });

            return this.установитьТип(
                узел,
                "неизвестно"
            );
        }

        return this.установитьТип(
            узел,
            символ.тип
        );
    }

    // ========================================================
    // ПЕРЕМЕННАЯ
    // ========================================================

    private анализироватьПеременную(
        узел: ОбъявлениеПеременной
    ): ТипЗначения {

        const типЗначения =
            this.анализироватьУзел(
                узел.значение
            );

        const существующий =
            this.текущаяОбласть
                .найтиВТекущейОбласти(
                    узел.имя
                );

        if (существующий) {

            this.добавитьОшибку({

                код:
                    "ПОВТОРНОЕ_ИМЯ",

                сообщение:
                    `Имя «${узел.имя}» уже объявлено в текущей области.`,

                имя:
                    узел.имя
            });

            return this.установитьТип(
                узел,
                "пусто"
            );
        }

        const символ: Символ = {

            имя:
                узел.имя,

            вид:
                "переменная",

            тип:
                типЗначения,

            инициализирован:
                true
        };

        this.текущаяОбласть.объявить(
            символ
        );

        return this.установитьТип(
            узел,
            "пусто"
        );
    }

    // ========================================================
    // ОПЕРАЦИЯ
    // ========================================================

    private анализироватьОперацию(
        узел: Операция
    ): ТипЗначения {

        const левыйТип =
            this.анализироватьУзел(
                узел.левое
            );

        const правыйТип =
            this.анализироватьУзел(
                узел.правое
            );

        const оператор =
            узел.оператор;

        if (
            левыйТип === "неизвестно" ||
            правыйТип === "неизвестно"
        ) {

            return this.установитьТип(
                узел,
                "неизвестно"
            );
        }

        if (
            оператор === "+"
        ) {

            if (
                левыйТип === "число" &&
                правыйТип === "число"
            ) {

                return this.установитьТип(
                    узел,
                    "число"
                );
            }

            if (
                левыйТип === "текст" &&
                правыйТип === "текст"
            ) {

                return this.установитьТип(
                    узел,
                    "текст"
                );
            }

            this.добавитьОшибку({

                код:
                    "НЕСОВМЕСТИМЫЕ_ТИПЫ",

                сообщение:
                    `Оператор «+» нельзя применить к типам «${левыйТип}» и «${правыйТип}».`,

                ожидаемыйТип:
                    левыйТип,

                полученныйТип:
                    правыйТип
            });

            return this.установитьТип(
                узел,
                "неизвестно"
            );
        }

        if (
            [
                "-",
                "*",
                "/",
                "%"
            ].includes(оператор)
        ) {

            if (
                левыйТип !== "число" ||
                правыйТип !== "число"
            ) {

                this.добавитьОшибку({

                    код:
                        "НЕСОВМЕСТИМЫЕ_ТИПЫ",

                    сообщение:
                        `Оператор «${оператор}» работает только с числами, получены «${левыйТип}» и «${правыйТип}».`,

                    ожидаемыйТип:
                        "число",

                    полученныйТип:
                        левыйТип !== "число"
                            ? левыйТип
                            : правыйТип
                });

                return this.установитьТип(
                    узел,
                    "неизвестно"
                );
            }

            return this.установитьТип(
                узел,
                "число"
            );
        }

        if (
            [
                ">",
                "<",
                ">=",
                "<="
            ].includes(оператор)
        ) {

            if (
                левыйТип !== "число" ||
                правыйТип !== "число"
            ) {

                this.добавитьОшибку({

                    код:
                        "НЕСОВМЕСТИМЫЕ_ТИПЫ",

                    сообщение:
                        `Оператор «${оператор}» требует два числа.`,

                    ожидаемыйТип:
                        "число",

                    полученныйТип:
                        левыйТип !== "число"
                            ? левыйТип
                            : правыйТип
                });

                return this.установитьТип(
                    узел,
                    "неизвестно"
                );
            }

            return this.установитьТип(
                узел,
                "логика"
            );
        }

        if (
            оператор === "==" ||
            оператор === "!="
        ) {

            if (
                левыйТип !== правыйТип
            ) {

                this.добавитьОшибку({

                    код:
                        "НЕСОВМЕСТИМЫЕ_ТИПЫ",

                    сообщение:
                        `Нельзя сравнивать тип «${левыйТип}» с типом «${правыйТип}».`
                });
            }

            return this.установитьТип(
                узел,
                "логика"
            );
        }

        this.добавитьОшибку({

            код:
                "НЕСОВМЕСТИМЫЕ_ТИПЫ",

            сообщение:
                `Неизвестный оператор «${оператор}».`
        });

        return this.установитьТип(
            узел,
            "неизвестно"
        );
    }

    // ========================================================
    // ПОКАЗАТЬ
    // ========================================================

    private анализироватьПоказать(
        узел: Показать
    ): ТипЗначения {

        for (
            const значение
            of узел.значения
        ) {

            this.анализироватьУзел(
                значение
            );
        }

        return this.установитьТип(
            узел,
            "пусто"
        );
    }

    // ========================================================
    // УСЛОВИЕ
    // ========================================================

    private анализироватьУсловие(
        узел: Условие
    ): ТипЗначения {

        const типУсловия =
            this.анализироватьУзел(
                узел.условие
            );

        if (
            типУсловия !== "логика" &&
            типУсловия !== "неизвестно"
        ) {

            this.добавитьОшибку({

                код:
                    "УСЛОВИЕ_НЕ_ЛОГИЧЕСКОЕ",

                сообщение:
                    `Условие должно иметь логический тип, получен «${типУсловия}».`,

                ожидаемыйТип:
                    "логика",

                полученныйТип:
                    типУсловия
            });
        }

        this.анализироватьБлок(
            узел.тогда.команды
        );

        if (
            узел.иначе !== null
        ) {

            this.анализироватьБлок(
                узел.иначе.команды
            );
        }

        return this.установитьТип(
            узел,
            "пусто"
        );
    }

    // ========================================================
    // БЛОК
    // ========================================================

    private анализироватьБлок(
        команды: Узел[]
    ): ТипЗначения {

        for (
            const команда
            of команды
        ) {

            this.анализироватьУзел(
                команда
            );
        }

        return "пусто";
    }

    // ========================================================
    // ВЫЗОВ ФУНКЦИИ
    // ========================================================

    private анализироватьВызовФункции(
        узел: ВызовФункции
    ): ТипЗначения {

        const символ =
            this.текущаяОбласть.найти(
                узел.имя
            );

        if (!символ) {

            this.добавитьОшибку({

                код:
                    "НЕИЗВЕСТНАЯ_ФУНКЦИЯ",

                сообщение:
                    `Функция «${узел.имя}» не объявлена.`,

                имя:
                    узел.имя
            });

            for (
                const аргумент
                of узел.аргументы
            ) {

                this.анализироватьУзел(
                    аргумент
                );
            }

            return this.установитьТип(
                узел,
                "неизвестно"
            );
        }

        if (
            символ.вид !== "функция"
        ) {

            this.добавитьОшибку({

                код:
                    "НЕИЗВЕСТНАЯ_ФУНКЦИЯ",

                сообщение:
                    `Имя «${узел.имя}» обозначает не функцию.`,

                имя:
                    узел.имя
            });

            return this.установитьТип(
                узел,
                "неизвестно"
            );
        }

        for (
            const аргумент
            of узел.аргументы
        ) {

            this.анализироватьУзел(
                аргумент
            );
        }

        const параметры =
            символ.параметры ?? [];

        if (
            параметры.length !==
            узел.аргументы.length
        ) {

            this.добавитьОшибку({

                код:
                    "НЕВЕРНОЕ_КОЛИЧЕСТВО_АРГУМЕНТОВ",

                сообщение:
                    `Функция «${узел.имя}» ожидает ${параметры.length} аргумент(ов), получено ${узел.аргументы.length}.`,

                имя:
                    узел.имя
            });
        }

        return this.установитьТип(
            узел,
            символ.типВозврата ??
                "неизвестно"
        );
    }

    // ========================================================
    // ВОЗВРАТ
    // ========================================================

    private анализироватьВозврат(
        узел: Возврат
    ): ТипЗначения {

        if (
            this.текущаяФункция === null
        ) {

            this.добавитьОшибку({

                код:
                    "ВОЗВРАТ_ВНЕ_ФУНКЦИИ",

                сообщение:
                    "Оператор «вернуть» можно использовать только внутри функции."
            });

            this.анализироватьУзел(
                узел.значение
            );

            return this.установитьТип(
                узел,
                "пусто"
            );
        }

        const типВозврата =
            this.анализироватьУзел(
                узел.значение
            );

        const текущийТип =
            this.текущаяФункция
                .типВозврата ??
                "неизвестно";

        if (
            текущийТип === "неизвестно"
        ) {

            this.текущаяФункция.типВозврата =
                типВозврата;

            return this.установитьТип(
                узел,
                "пусто"
            );
        }

        if (
            типВозврата !== "неизвестно" &&
            типВозврата !== текущийТип
        ) {

            this.добавитьОшибку({

                код:
                    "НЕСОВМЕСТИМЫЙ_ВОЗВРАТ",

                сообщение:
                    `Функция «${this.текущаяФункция.имя}» возвращает несовместимые типы «${текущийТип}» и «${типВозврата}».`,

                имя:
                    this.текущаяФункция.имя
            });
        }

        return this.установитьТип(
            узел,
            "пусто"
        );
    }

    // ========================================================
    // ФУНКЦИЯ
    // ========================================================

    private анализироватьФункцию(
        узел: Функция
    ): ТипЗначения {

        const символ =
            this.глобальнаяОбласть.найти(
                узел.имя
            );

        if (
            !символ ||
            символ.вид !== "функция"
        ) {

            return this.установитьТип(
                узел,
                "функция"
            );
        }

        const предыдущаяОбласть =
            this.текущаяОбласть;

        const предыдущаяФункция =
            this.текущаяФункция;

        const областьФункции =
            new ОбластьСимволов(
                this.глобальнаяОбласть,
                `функция:${узел.имя}`
            );

        this.текущаяОбласть =
            областьФункции;

        this.текущаяФункция =
            символ;

        символ.типВозврата =
            "неизвестно";

        for (
            const параметр
            of узел.параметры
        ) {

            const параметрСимвол: Символ = {

                имя:
                    параметр,

                вид:
                    "параметр",

                тип:
                    "неизвестно",

                инициализирован:
                    true
            };

            if (
                !областьФункции.объявить(
                    параметрСимвол
                )
            ) {

                this.добавитьОшибку({

                    код:
                        "ПОВТОРНОЕ_ИМЯ",

                    сообщение:
                        `Параметр «${параметр}» функции «${узел.имя}» объявлен повторно.`,

                    имя:
                        параметр
                });
            }
        }

        this.анализироватьБлок(
            узел.тело.команды
        );

        this.текущаяОбласть =
            предыдущаяОбласть;

        this.текущаяФункция =
            предыдущаяФункция;

        return this.установитьТип(
            узел,
            "функция"
        );
    }

    // ========================================================
    // СОХРАНИТЬ ТИП AST-УЗЛА
    // ========================================================

    private установитьТип(
        узел: УзелКлюч,
        тип: ТипЗначения
    ): ТипЗначения {

        this.типыУзлов.set(
            узел,
            тип
        );

        return тип;
    }

    // ========================================================
    // ПОЛУЧИТЬ ТИП AST-УЗЛА
    // ========================================================

    public получитьТип(
        узел: Узел
    ): ТипЗначения {

        return (
            this.типыУзлов.get(
                узел
            )
            ?? "неизвестно"
        );
    }

    // ========================================================
    // ПОЛУЧИТЬ ВСЕ ТИПЫ AST-УЗЛОВ
    // ========================================================

    public получитьТипыУзлов():
        Map<object, ТипЗначения> {

        return new Map(
            this.типыУзлов
        );
    }

    // ========================================================
    // ПОЛУЧИТЬ ОШИБКИ
    // ========================================================

    public получитьОшибки():
        ОшибкаСемантики[] {

        return this.ошибки.map(
            ошибка => ({
                ...ошибка
            })
        );
    }

    // ========================================================
    // ДОБАВИТЬ ОШИБКУ
    // ========================================================

    private добавитьОшибку(
        ошибка: ОшибкаСемантики
    ): void {

        this.ошибки.push(
            ошибка
        );
    }
}

// ============================================================
// СОВМЕСТИМОСТЬ ТИПОВ
// ============================================================

export function типыСовместимы(
    первый: ТипЗначения,
    второй: ТипЗначения
): boolean {

    if (
        первый === "неизвестно" ||
        второй === "неизвестно"
    ) {
        return true;
    }

    return первый === второй;
}