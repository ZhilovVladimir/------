// ============================================================
// 🐌 УЛИТКА
// Типы семантического ядра
// ============================================================

// ============================================================
// ТИП ЗНАЧЕНИЯ
// ============================================================

export type ТипЗначения =
    | "число"
    | "текст"
    | "логика"
    | "пусто"
    | "функция"
    | "неизвестно";

// ============================================================
// ВИД СИМВОЛА
// ============================================================

export type ВидСимвола =
    | "переменная"
    | "параметр"
    | "функция";

// ============================================================
// СИМВОЛ
// ============================================================

export interface Символ {
    имя: string;
    вид: ВидСимвола;
    тип: ТипЗначения;

    // Для функций.
    параметры?: string[];
    типВозврата?: ТипЗначения;

    // Для переменных и параметров.
    инициализирован: boolean;
}

// ============================================================
// ОШИБКА СЕМАНТИКИ
// ============================================================

export type КодСемантическойОшибки =
    | "ПОВТОРНОЕ_ИМЯ"
    | "НЕИЗВЕСТНОЕ_ИМЯ"
    | "НЕИЗВЕСТНАЯ_ФУНКЦИЯ"
    | "НЕВЕРНОЕ_КОЛИЧЕСТВО_АРГУМЕНТОВ"
    | "НЕСОВМЕСТИМЫЕ_ТИПЫ"
    | "УСЛОВИЕ_НЕ_ЛОГИЧЕСКОЕ"
    | "ВОЗВРАТ_ВНЕ_ФУНКЦИИ"
    | "НЕСОВМЕСТИМЫЙ_ВОЗВРАТ"
    | "ДЕЛЕНИЕ_ТИПОВ";

// ============================================================
// ОШИБКА
// ============================================================

export interface ОшибкаСемантики {
    код: КодСемантическойОшибки;
    сообщение: string;
    имя?: string;
    ожидаемыйТип?: ТипЗначения;
    полученныйТип?: ТипЗначения;
}

// ============================================================
// РЕЗУЛЬТАТ АНАЛИЗА
// ============================================================

export interface РезультатСемантическогоАнализа {
    успешно: boolean;
    ошибки: ОшибкаСемантики[];

    // Снимок символов глобальной области.
    глобальныеСимволы: Символ[];
}