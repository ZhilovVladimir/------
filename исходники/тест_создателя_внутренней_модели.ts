// ============================================================



// 🐌 УЛИТКА



// Тест создателя единой внутренней модели



// Этап 3.4.5



// ============================================================



import {



    создатьМодельИзРезультатаСемантики



} from "./модель/создатель_внутренней_модели.js";



import type {



    Узел,



    Программа



} from "./дерево/узлы.js";



import type {



    ТипЗначения,



    РезультатСемантическогоАнализа



} from "./семантика/типы.js";



// ============================================================



// СЧЁТЧИК ПРОВЕРОК



// ============================================================



let количествоПроверок = 0;



// ============================================================



// ПРОВЕРКА



// ============================================================



function проверить(



    условие: boolean,



    сообщение: string



): void {



    количествоПроверок++;



    if (!условие) {



        throw new Error(



            `❌ ПРОВЕРКА НЕ ПРОЙДЕНА: ${сообщение}`



        );



    }



    console.log(



        `✅ ${сообщение}`



    );



}



// ============================================================



// ТЕСТОВАЯ ПРОГРАММА



// ============================================================



const программа: Программа = {



    вид: "ПРОГРАММА",



    имя:



        "тест_создателя_модели",



    тело: {



        вид: "БЛОК",



        команды: []



    }



};



// ============================================================



// ДЕРЕВО ПРОГРАММЫ



// ============================================================



const дерево: Узел[] = [



    программа



];



// ============================================================



// ТЕСТОВЫЕ ГЛОБАЛЬНЫЕ СИМВОЛЫ



// ============================================================



const глобальныеСимволы = [



    {



        имя:



            "число",



        вид:



            "переменная" as const,



        тип:



            "число" as ТипЗначения,



        инициализирован:



    true



    }



];



// ============================================================



// ТЕСТОВЫЕ ОШИБКИ



// ============================================================



const ошибки:



    РезультатСемантическогоАнализа["ошибки"] = [];



// ============================================================



// РЕЗУЛЬТАТ СЕМАНТИЧЕСКОГО АНАЛИЗА



// ============================================================



const результат:



    РезультатСемантическогоАнализа = {



    успешно:



        true,



    ошибки,



    глобальныеСимволы



};



// ============================================================



// ТИПЫ AST-УЗЛОВ



// ============================================================



const типыУзлов =



    new Map<object, ТипЗначения>();



типыУзлов.set(



    программа,



    "пусто"



);



// ============================================================



// СОЗДАНИЕ ЕДИНОЙ ВНУТРЕННЕЙ МОДЕЛИ



// ============================================================



const модель =



    создатьМодельИзРезультатаСемантики(



        дерево,



        результат,



        типыУзлов



    );



// ============================================================



// ПРОВЕРКА ИМЕНИ ПРОГРАММЫ



// ============================================================



проверить(



    модель.получитьИмяПрограммы()



        === "тест_создателя_модели",



    "Имя программы передано в модель"



);



// ============================================================



// ПРОВЕРКА ДЕРЕВА



// ============================================================



проверить(



    модель.получитьДерево().length === 1,



    "Дерево программы передано в модель"



);



проверить(



    модель.получитьДерево()[0]



        === программа,



    "Исходный узел программы сохранён"



);



// ============================================================



// ПРОВЕРКА ГЛОБАЛЬНЫХ СИМВОЛОВ



// ============================================================



проверить(



    модель.получитьГлобальныеСимволы().length === 1,



    "Глобальные символы переданы из семантического анализа"



);



проверить(



    модель.получитьГлобальныеСимволы()[0].имя



        === "число",



    "Имя глобального символа сохранено"



);



проверить(



    модель.получитьГлобальныеСимволы()[0].тип



        === "число",



    "Тип глобального символа сохранён"



);



// ============================================================



// ПРОВЕРКА ТИПА AST-УЗЛА



// ============================================================



проверить(



    модель.получитьТипУзла(программа)



        === "пусто",



    "Тип AST-узла передан в единую модель"



);



// ============================================================



// ПРОВЕРКА ОШИБОК



// ============================================================



проверить(



    модель.получитьОшибки().length === 0,



    "Ошибки семантического анализа переданы в модель"



);



// ============================================================



// ПРОВЕРКА УСПЕШНОСТИ



// ============================================================



проверить(



    модель.успешна() === true,



    "Состояние успешного семантического анализа передано"



);



// ============================================================



// ПОЛУЧЕНИЕ ПОЛНЫХ ДАННЫХ



// ============================================================



const данные =



    модель.получитьДанные();



// ============================================================



// ПРОВЕРКА ПОЛНЫХ ДАННЫХ



// ============================================================



проверить(



    данные.имяПрограммы



        === "тест_создателя_модели",



    "Полные данные содержат имя программы"



);



проверить(



    данные.дерево.length === 1,



    "Полные данные содержат дерево"



);



проверить(



    данные.глобальныеСимволы.length === 1,



    "Полные данные содержат глобальные символы"



);



проверить(



    данные.типыУзлов.get(программа)



        === "пусто",



    "Полные данные содержат типы узлов"



);



проверить(



    данные.ошибки.length === 0,



    "Полные данные содержат ошибки семантики"



);



проверить(



    данные.успешно === true,



    "Полные данные содержат состояние успешности"



);



// ============================================================



// ИТОГ



// ============================================================



console.log("");



console.log(



    `🐌 ТЕСТ 3.4.5 УСПЕШЕН: ${количествоПроверок} проверок пройдено.`



);
