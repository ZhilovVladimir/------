import type {
    Узел,
    Программа
} from "../дерево/узлы.js";

import type {
    Символ,
    ТипЗначения,
    ОшибкаСемантики
} from "../семантика/типы.js";

// ============================================================
// 🐌 УЛИТКА
// Единая внутренняя модель программы
// Этап 1 — семантическое представление
// ============================================================

// ============================================================
// ТИПЫ УЗЛОВ
// ============================================================

export type ТипыУзлов =
    Map<object, ТипЗначения>;

// ============================================================
// ДАННЫЕ МОДЕЛИ
// ============================================================

export interface ДанныеВнутреннейМодели {

    // Имя программы.
    имяПрограммы: string;

    // Исходное AST.
    дерево: Узел[];

    // Символы глобальной области.
    глобальныеСимволы: Символ[];

    // Семантические типы конкретных AST-узлов.
    типыУзлов: ТипыУзлов;

    // Ошибки семантического анализа.
    ошибки: ОшибкаСемантики[];

    // Успешность семантического анализа.
    успешно: boolean;
}

// ============================================================
// ЕДИНАЯ ВНУТРЕННЯЯ МОДЕЛЬ
// ============================================================

export class ЕдинаяВнутренняяМодельПрограммы {

    private readonly данные: ДанныеВнутреннейМодели;

    constructor(
        данные: ДанныеВнутреннейМодели
    ) {
        this.данные = {
            имяПрограммы:
                данные.имяПрограммы,

            дерево:
                данные.дерево,

            глобальныеСимволы:
                [...данные.глобальныеСимволы],

            типыУзлов:
                new Map(данные.типыУзлов),

            ошибки:
                данные.ошибки.map(
                    ошибка => ({
                        ...ошибка
                    })
                ),

            успешно:
                данные.успешно
        };
    }

    // ========================================================
    // ИМЯ ПРОГРАММЫ
    // ========================================================

    public получитьИмяПрограммы():
        string {

        return this.данные.имяПрограммы;
    }

    // ========================================================
    // ДЕРЕВО
    // ========================================================

    public получитьДерево():
        Узел[] {

        return this.данные.дерево;
    }

    // ========================================================
    // ГЛОБАЛЬНЫЕ СИМВОЛЫ
    // ========================================================

    public получитьГлобальныеСимволы():
        Символ[] {

        return [
            ...this.данные.глобальныеСимволы
        ];
    }

    // ========================================================
    // ТИП УЗЛА
    // ========================================================

    public получитьТипУзла(
        узел: object
    ):
        ТипЗначения {

        return (
            this.данные.типыУзлов.get(узел)
            ?? "неизвестно"
        );
    }

    // ========================================================
    // ОШИБКИ
    // ========================================================

    public получитьОшибки():
        ОшибкаСемантики[] {

        return this.данные.ошибки.map(
            ошибка => ({
                ...ошибка
            })
        );
    }

    // ========================================================
    // УСПЕШНОСТЬ
    // ========================================================

    public успешна():
        boolean {

        return this.данные.успешно;
    }

    // ========================================================
    // ПОЛУЧИТЬ ПОЛНЫЕ ДАННЫЕ
    // ========================================================

    public получитьДанные():
        ДанныеВнутреннейМодели {

        return {
            имяПрограммы:
                this.данные.имяПрограммы,

            дерево:
                this.данные.дерево,

            глобальныеСимволы:
                [
                    ...this.данные.глобальныеСимволы
                ],

            типыУзлов:
                new Map(
                    this.данные.типыУзлов
                ),

            ошибки:
                this.данные.ошибки.map(
                    ошибка => ({
                        ...ошибка
                    })
                ),

            успешно:
                this.данные.успешно
        };
    }
}

// ============================================================
// СОЗДАНИЕ МОДЕЛИ
// ============================================================

export function создатьЕдинуюВнутреннююМодель(
    данные: ДанныеВнутреннейМодели
):
    ЕдинаяВнутренняяМодельПрограммы {

    return new ЕдинаяВнутренняяМодельПрограммы(
        данные
    );
}

// ============================================================
// ПОЛУЧЕНИЕ ИМЕНИ ПРОГРАММЫ
// ============================================================

export function получитьИмяПрограммыИзДерева(
    дерево: Узел[]
):
    string {

    const программа =
        дерево.find(
            (узел): узел is Программа =>
                узел.вид === "ПРОГРАММА"
        );

    return программа?.имя ?? "безымянная_программа";
}
