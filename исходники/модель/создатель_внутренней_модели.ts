import type {
    Узел
} from "../дерево/узлы.js";

import type {
    ТипЗначения,
    РезультатСемантическогоАнализа
} from "../семантика/типы.js";

import {
    создатьЕдинуюВнутреннююМодель,
    получитьИмяПрограммыИзДерева
} from "./единая_внутренняя_модель.js";

import type {
    ДанныеВнутреннейМодели,
    ЕдинаяВнутренняяМодельПрограммы
} from "./единая_внутренняя_модель.js";

// ============================================================
// СОЗДАНИЕ МОДЕЛИ ИЗ РЕЗУЛЬТАТА СЕМАНТИЧЕСКОГО АНАЛИЗА
// ============================================================

export function создатьМодельИзРезультатаСемантики(
    дерево: Узел[],
    результат: РезультатСемантическогоАнализа,
    типыУзлов: Map<object, ТипЗначения>
):
    ЕдинаяВнутренняяМодельПрограммы {

    const данные:
        ДанныеВнутреннейМодели = {

        имяПрограммы:
            получитьИмяПрограммыИзДерева(
                дерево
            ),

        дерево,

        глобальныеСимволы:
            результат.глобальныеСимволы,

        типыУзлов,

        ошибки:
            результат.ошибки,

        успешно:
            результат.успешно
    };

    return создатьЕдинуюВнутреннююМодель(
        данные
    );
}
