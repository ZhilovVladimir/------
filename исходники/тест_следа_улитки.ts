// ============================================================
// 🐌 УЛИТКА
// Тест движка «След Улитки»
// ============================================================

import {
    Исполнитель
} from "./исполнитель.js";

import {
    СледУлитки
} from "./след_улитки.js";

import type {
    Узел
} from "./дерево/узлы.js";

// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {
    if (!условие) {
        throw new Error(
            `❌ ${сообщение}`
        );
    }
}

// ============================================================
// ПРОГРАММА
// ============================================================

const дерево: Узел[] = [
    {
        вид: "ФУНКЦИЯ",
        имя: "сложить",
        параметры: [
            "первое",
            "второе"
        ],
        тело: {
            вид: "БЛОК",
            команды: [
                {
                    вид: "ВОЗВРАТ",
                    значение: {
                        вид: "ОПЕРАЦИЯ",
                        оператор: "+",
                        левое: {
                            вид: "ИМЯ",
                            значение: "первое"
                        },
                        правое: {
                            вид: "ИМЯ",
                            значение: "второе"
                        }
                    }
                }
            ]
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "а",
        значение: {
            вид: "ЧИСЛО",
            значение: 10
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "б",
        значение: {
            вид: "ОПЕРАЦИЯ",
            оператор: "+",
            левое: {
                вид: "ИМЯ",
                значение: "а"
            },
            правое: {
                вид: "ЧИСЛО",
                значение: 5
            }
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "результат",
        значение: {
            вид: "ВЫЗОВ_ФУНКЦИИ",
            имя: "сложить",
            аргументы: [
                {
                    вид: "ИМЯ",
                    значение: "а"
                },
                {
                    вид: "ЧИСЛО",
                    значение: 20
                }
            ]
        }
    }
];

// ============================================================
// ВЫПОЛНЕНИЕ
// ============================================================

const исполнитель =
    new Исполнитель();

const результат =
    исполнитель.исполнить(
        дерево
    );

// ============================================================
// ПРОВЕРКА ИСПОЛНЕНИЯ
// ============================================================

проверить(
    результат.переменные.а === 10,
    "Переменная «а» должна быть равна 10."
);

проверить(
    результат.переменные.б === 15,
    "Переменная «б» должна быть равна 15."
);

проверить(
    результат.переменные.результат === 30,
    "Переменная «результат» должна быть равна 30."
);

// ============================================================
// СОЗДАНИЕ СЛЕДА
// ============================================================

const след =
    new СледУлитки(
        результат.события
    );

// ============================================================
// СЛЕД ПЕРЕМЕННОЙ Б
// ============================================================

const следБ =
    след.получитьСледПеременной(
        "б"
    );

проверить(
    следБ.найден,
    "След переменной «б» должен быть найден."
);

проверить(
    следБ.узлы.some(
        узел =>
            узел.тип === "результат" &&
            узел.имя ===
                "переменная:б" &&
            узел.значение === 15
    ),
    "След должен содержать результат «б = 15»."
);

проверить(
    следБ.узлы.some(
        узел =>
            узел.тип === "вычисление" &&
            узел.имя ===
                "вычисление «+»" &&
            узел.значение === 15
    ),
    "След должен содержать вычисление «+»."
);

проверить(
    следБ.узлы.some(
        узел =>
            узел.тип === "результат" &&
            узел.имя ===
                "переменная:а" &&
            узел.значение === 10
    ),
    "След должен содержать исходную переменную «а = 10»."
);

const узелА =
    следБ.узлы.find(
        узел =>
            узел.тип === "результат" &&
            узел.имя ===
                "переменная:а"
    );

const узелВычисления =
    следБ.узлы.find(
        узел =>
            узел.тип === "вычисление"
    );

const узелБ =
    следБ.узлы.find(
        узел =>
            узел.тип === "результат" &&
            узел.имя ===
                "переменная:б"
    );

проверить(
    узелА !== undefined,
    "Узел «а» должен существовать."
);

проверить(
    узелВычисления !== undefined,
    "Узел вычисления должен существовать."
);

проверить(
    узелБ !== undefined,
    "Узел «б» должен существовать."
);

проверить(
    следБ.связи.some(
        связь =>
            связь.откуда ===
                узелА!.идентификатор &&
            связь.куда ===
                узелВычисления!.идентификатор &&
            связь.тип ===
                "зависимость"
    ),
    "След должен содержать зависимость «а → вычисление»."
);

проверить(
    следБ.связи.some(
        связь =>
            связь.откуда ===
                узелВычисления!.идентификатор &&
            связь.куда ===
                узелБ!.идентификатор &&
            связь.тип ===
                "передача"
    ),
    "След должен содержать передачу «вычисление → б»."
);

// ============================================================
// СЛЕД ПЕРЕМЕННОЙ РЕЗУЛЬТАТ
// ============================================================

const следРезультат =
    след.получитьСледПеременной(
        "результат"
    );

проверить(
    следРезультат.найден,
    "След результата должен быть найден."
);

проверить(
    следРезультат.узлы.some(
        узел =>
            узел.тип === "функция" &&
            узел.имя === "сложить"
    ),
    "След результата должен содержать функцию «сложить»."
);

проверить(
    следРезультат.узлы.some(
        узел =>
            узел.тип === "вызов" &&
            узел.имя ===
                "вызов:сложить"
    ),
    "След результата должен содержать вызов функции."
);

проверить(
    следРезультат.узлы.some(
        узел =>
            узел.тип === "результат_функции" &&
            узел.имя ===
                "возврат:сложить" &&
            узел.значение === 30
    ),
    "След результата должен содержать возврат функции со значением 30."
);

const узелФункции =
    следРезультат.узлы.find(
        узел =>
            узел.тип === "функция" &&
            узел.имя ===
                "сложить"
    );

const узелВызова =
    следРезультат.узлы.find(
        узел =>
            узел.тип === "вызов" &&
            узел.имя ===
                "вызов:сложить"
    );

const узелВозврата =
    следРезультат.узлы.find(
        узел =>
            узел.тип ===
                "результат_функции" &&
            узел.имя ===
                "возврат:сложить"
    );

проверить(
    узелФункции !== undefined,
    "Узел функции должен существовать."
);

проверить(
    узелВызова !== undefined,
    "Узел вызова должен существовать."
);

проверить(
    узелВозврата !== undefined,
    "Узел возврата должен существовать."
);

проверить(
    следРезультат.связи.some(
        связь =>
            связь.откуда ===
                узелФункции!.идентификатор &&
            связь.куда ===
                узелВызова!.идентификатор &&
            связь.тип === "вызов"
    ),
    "След должен содержать «функция → вызов»."
);

проверить(
    следРезультат.связи.some(
        связь =>
            связь.откуда ===
                узелВызова!.идентификатор &&
            связь.куда ===
                узелВозврата!.идентификатор &&
            связь.тип === "передача"
    ),
    "След должен содержать «вызов → возврат»."
);

console.log(
    "🐌 Тест «След Улитки»"
);

console.log(
    `След «б»: узлов ${следБ.узлы.length}, связей ${следБ.связи.length}`
);

console.log(
    `След «результат»: узлов ${следРезультат.узлы.length}, связей ${следРезультат.связи.length}`
);

console.log(
    "✅ Причина «б = 15» восстановлена."
);

console.log(
    "✅ Причина результата функции восстановлена."
);

console.log(
    "✅ Тест «След Улитки»: ПРОЙДЕН."
);