import { Ядро3D } from "./ядро_3d";

const ядро = new Ядро3D();

console.log("🐌 3D-ЯДРО «УЛИТКИ»");
console.log("====================");

ядро.добавитьПеременную({
    имя: "имя",
    значение: "Владимир",
    тип: "текст"
});

ядро.добавитьФункцию({
    имя: "сложить",
    параметры: ["первое", "второе"]
});

const узлы = ядро.получитьУзлы();

const идентификаторПеременной =
    узлы[0].идентификатор;

const идентификаторФункции =
    узлы[1].идентификатор;

const идентификаторСвязи =
    ядро.добавитьСвязь(
        идентификаторПеременной,
        идентификаторФункции,
        "передача"
    );

ядро.установитьСостояние("выполнение");

ядро.установитьТекущуюСтроку(5);

ядро.активироватьУзел(
    идентификаторПеременной,
    1
);

ядро.активироватьУзел(
    идентификаторФункции,
    0.8
);

ядро.активироватьСвязь(
    идентификаторСвязи,
    0.6
);

console.log("");
console.log("Состояние:");
console.log(ядро.получитьСостояние());

console.log("");
console.log("Узлы:");
console.log(ядро.получитьУзлы());

console.log("");
console.log("Связи:");
console.log(ядро.получитьСвязи());

console.log("");
console.log("События:");
console.log(ядро.получитьСобытия());