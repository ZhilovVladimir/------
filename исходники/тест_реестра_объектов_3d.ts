import {
    МенеджерОбъектов3D
} from "./менеджер_объектов_3d";

import {
    активироватьОбъект3D,
    установитьСостояниеОбъекта3D
} from "./объект_3d";

function проверить(
    условие: boolean,
    сообщение: string
): void {

    if (!условие) {
        throw new Error(
            `❌ ПРОВЕРКА НЕ ПРОЙДЕНА: ${сообщение}`
        );
    }

    console.log(
        `✅ ${сообщение}`
    );
}

console.log(
    "============================================================"
);

console.log(
    "🐌 ТЕСТ ИНТЕЛЛЕКТУАЛЬНОГО РЕЕСТРА ОБЪЕКТОВ 3D"
);

console.log(
    "============================================================"
);

// ============================================================
// 1. СОЗДАНИЕ МЕНЕДЖЕРА
// ============================================================

console.log(
    "\n1. Создание менеджера"
);

const менеджер =
    new МенеджерОбъектов3D();

проверить(
    менеджер.получитьКоличество() === 0,
    "Пустой менеджер создан."
);

// ============================================================
// 2. СОЗДАНИЕ ОБЪЕКТОВ
// ============================================================

console.log(
    "\n2. Создание объектов"
);

менеджер.создатьОбъект(
    "программа_1",
    "Главная программа",
    "программа"
);

менеджер.создатьОбъект(
    "переменная_1",
    "имя",
    "переменная"
);

менеджер.создатьОбъект(
    "переменная_2",
    "результат",
    "переменная"
);

менеджер.создатьОбъект(
    "функция_1",
    "сложить",
    "функция"
);

менеджер.создатьОбъект(
    "ошибка_1",
    "Ошибка",
    "ошибка"
);

проверить(
    менеджер.получитьКоличество() === 5,
    "Пять объектов зарегистрированы."
);

// ============================================================
// 3. ПОИСК ПО ИДЕНТИФИКАТОРУ
// ============================================================

console.log(
    "\n3. Поиск по идентификатору"
);

const найденнаяПрограмма =
    менеджер.найтиПоИдентификатору(
        "программа_1"
    );

проверить(
    найденнаяПрограмма !== null,
    "Объект найден по идентификатору."
);

проверить(
    найденнаяПрограмма?.имя ===
        "Главная программа",
    "Найден правильный объект."
);

проверить(
    менеджер.найтиПоИдентификатору(
        "несуществующий"
    ) === null,
    "Несуществующий объект возвращается как null."
);

// ============================================================
// 4. ПОИСК ПО ИМЕНИ
// ============================================================

console.log(
    "\n4. Поиск по имени"
);

const найденныеПеременные =
    менеджер.найтиПоИмени(
        "имя"
    );

проверить(
    найденныеПеременные.length === 1,
    "Объект найден по имени."
);

проверить(
    найденныеПеременные[0]?.идентификатор ===
        "переменная_1",
    "Найден правильный объект по имени."
);

// ============================================================
// 5. ПОИСК ПО ТИПУ
// ============================================================

console.log(
    "\n5. Поиск по типу"
);

const переменные =
    менеджер.найтиПоТипу(
        "переменная"
    );

const функции =
    менеджер.найтиПоТипу(
        "функция"
    );

const ошибки =
    менеджер.найтиПоТипу(
        "ошибка"
    );

проверить(
    переменные.length === 2,
    "Найдено две переменные."
);

проверить(
    функции.length === 1,
    "Найдена одна функция."
);

проверить(
    ошибки.length === 1,
    "Найдена одна ошибка."
);

// ============================================================
// 6. ПОИСК ПО СОСТОЯНИЮ
// ============================================================

console.log(
    "\n6. Поиск по состоянию"
);

const созданные =
    менеджер.найтиПоСостоянию(
        "создан"
    );

проверить(
    созданные.length === 5,
    "Найдены все объекты в состоянии «создан»."
);

const функция =
    менеджер.найтиПоИдентификатору(
        "функция_1"
    );

проверить(
    функция !== null,
    "Функция найдена перед изменением состояния."
);

if (функция) {

    установитьСостояниеОбъекта3D(
        функция,
        "активен"
    );
}

const активныеПоСостоянию =
    менеджер.найтиПоСостоянию(
        "активен"
    );

проверить(
    активныеПоСостоянию.length === 1,
    "Поиск по состоянию обнаружил активную функцию."
);

// ============================================================
// 7. ПОИСК АКТИВНЫХ ОБЪЕКТОВ
// ============================================================

console.log(
    "\n7. Поиск активных объектов"
);

const программа =
    менеджер.найтиПоИдентификатору(
        "программа_1"
    );

проверить(
    программа !== null,
    "Программа найдена."
);

// Здесь специально используем именно
// активироватьОбъект3D(), потому что поиск
// активных объектов проверяет поле «активен».

if (программа) {

    активироватьОбъект3D(
        программа,
        0.8
    );
}

if (функция) {

    активироватьОбъект3D(
        функция,
        0.6
    );
}

const активные =
    менеджер.найтиАктивные();

проверить(
    активные.length === 2,
    "Найдены два действительно активных объекта."
);

проверить(
    активные.some(
        объект =>
            объект.идентификатор ===
            "программа_1"
    ),
    "Активная программа присутствует в результатах."
);

проверить(
    активные.some(
        объект =>
            объект.идентификатор ===
            "функция_1"
    ),
    "Активная функция присутствует в результатах."
);

// ============================================================
// 8. ПОИСК ВИДИМЫХ ОБЪЕКТОВ
// ============================================================

console.log(
    "\n8. Поиск видимых объектов"
);

const видимые =
    менеджер.найтиВидимые();

проверить(
    видимые.length === 5,
    "Найдены все видимые объекты."
);

// ============================================================
// 9. СОЗДАНИЕ РОДИТЕЛЬСКОЙ СТРУКТУРЫ
// ============================================================

console.log(
    "\n9. Создание иерархии"
);

менеджер.установитьРодителя(
    "переменная_1",
    "программа_1"
);

менеджер.установитьРодителя(
    "переменная_2",
    "программа_1"
);

менеджер.установитьРодителя(
    "функция_1",
    "программа_1"
);

менеджер.установитьРодителя(
    "ошибка_1",
    "функция_1"
);

проверить(
    менеджер.получитьДетей(
        "программа_1"
    ).length === 3,
    "У программы три ребёнка."
);

проверить(
    менеджер.получитьДетей(
        "функция_1"
    ).length === 1,
    "У функции один ребёнок."
);

// ============================================================
// 10. ПОИСК ПО РОДИТЕЛЮ
// ============================================================

console.log(
    "\n10. Поиск по родителю"
);

const детиПрограммы =
    менеджер.найтиПоРодителю(
        "программа_1"
    );

проверить(
    детиПрограммы.length === 3,
    "Найдены все объекты программы."
);

const детиФункции =
    менеджер.найтиПоРодителю(
        "функция_1"
    );

проверить(
    детиФункции.length === 1,
    "Найден объект функции."
);

проверить(
    детиФункции[0]?.идентификатор ===
        "ошибка_1",
    "Найден правильный дочерний объект."
);

// ============================================================
// 11. ПОДСЧЁТ ПО ТИПУ
// ============================================================

console.log(
    "\n11. Подсчёт объектов по типу"
);

проверить(
    менеджер.получитьКоличествоПоТипу(
        "переменная"
    ) === 2,
    "Количество переменных равно двум."
);

проверить(
    менеджер.получитьКоличествоПоТипу(
        "функция"
    ) === 1,
    "Количество функций равно одному."
);

проверить(
    менеджер.получитьКоличествоПоТипу(
        "ошибка"
    ) === 1,
    "Количество ошибок равно одному."
);

// ============================================================
// 12. ПОДСЧЁТ ПО СОСТОЯНИЮ
// ============================================================

console.log(
    "\n12. Подсчёт по состоянию"
);

проверить(
    менеджер.получитьКоличествоПоСостоянию(
        "активен"
    ) === 2,
    "Количество активных состояний равно двум."
);

проверить(
    менеджер.получитьКоличествоПоСостоянию(
        "создан"
    ) === 3,
    "Количество объектов в состоянии «создан» равно трём."
);

// ============================================================
// 13. ПОДСЧЁТ АКТИВНЫХ
// ============================================================

console.log(
    "\n13. Подсчёт активных объектов"
);

проверить(
    менеджер.получитьКоличествоАктивных() === 2,
    "Активны два объекта."
);

// ============================================================
// 14. КОРНЕВЫЕ ОБЪЕКТЫ
// ============================================================

console.log(
    "\n14. Проверка корневых объектов"
);

const корневые =
    менеджер.получитьКорневыеОбъекты();

проверить(
    корневые.length === 1,
    "Остался один корневой объект."
);

проверить(
    корневые[0]?.идентификатор ===
        "программа_1",
    "Главная программа является корнем."
);

// ============================================================
// 15. ЗАЩИТА ОТ САМОРОДИТЕЛЬСТВА
// ============================================================

console.log(
    "\n15. Проверка самородительства"
);

let ошибкаСамородителя =
    false;

try {

    менеджер.установитьРодителя(
        "программа_1",
        "программа_1"
    );

} catch {

    ошибкаСамородителя =
        true;
}

проверить(
    ошибкаСамородителя,
    "Самородительство запрещено."
);

// ============================================================
// 16. ЗАЩИТА ОТ ЦИКЛА
// ============================================================

console.log(
    "\n16. Проверка защиты от циклической связи"
);

let ошибкаЦикла =
    false;

try {

    // Сейчас:
    //
    // программа_1
    // ├── переменная_1
    // ├── переменная_2
    // └── функция_1
    //     └── ошибка_1
    //
    // Нельзя сделать программу ребёнком ошибки.

    менеджер.установитьРодителя(
        "программа_1",
        "ошибка_1"
    );

} catch {

    ошибкаЦикла =
        true;
}

проверить(
    ошибкаЦикла,
    "Создание циклической связи запрещено."
);

// ============================================================
// 17. ЗАЩИТА ОТ НЕСУЩЕСТВУЮЩЕГО РОДИТЕЛЯ
// ============================================================

console.log(
    "\n17. Проверка несуществующего родителя"
);

let ошибкаРодителя =
    false;

try {

    менеджер.установитьРодителя(
        "переменная_1",
        "несуществующий_объект"
    );

} catch {

    ошибкаРодителя =
        true;
}

проверить(
    ошибкаРодителя,
    "Несуществующий родитель отклонён."
);

// Проверяем, что старая связь не была разрушена.

const переменнаяПослеОшибки =
    менеджер.найтиПоИдентификатору(
        "переменная_1"
    );

проверить(
    переменнаяПослеОшибки?.родитель ===
        "программа_1",
    "После ошибки старая родительская связь сохранена."
);

// ============================================================
// 18. ПРОВЕРКА ЦЕЛОСТНОСТИ
// ============================================================

console.log(
    "\n18. Проверка целостности реестра"
);

проверить(
    менеджер.проверить(),
    "Реестр объектов полностью целостен."
);

// ============================================================
// 19. ПРОВЕРКА КОПИЙ
// ============================================================

console.log(
    "\n19. Проверка копирования объектов"
);

const копии =
    менеджер.получитьКопииВсехОбъектов();

проверить(
    копии.length === 5,
    "Получены копии всех пяти объектов."
);

проверить(
    копии !== менеджер.получитьВсеОбъекты(),
    "Массив копий отделён от внутреннего реестра."
);

// ============================================================
// 20. ФИНАЛЬНАЯ ПРОВЕРКА
// ============================================================

console.log(
    "\n20. Финальная проверка"
);

проверить(
    менеджер.получитьКоличество() === 5,
    "Количество объектов осталось неизменным."
);

проверить(
    менеджер.существует("программа_1"),
    "Главная программа существует."
);

проверить(
    менеджер.существует("переменная_1"),
    "Переменная существует."
);

проверить(
    менеджер.существует("переменная_2"),
    "Вторая переменная существует."
);

проверить(
    менеджер.существует("функция_1"),
    "Функция существует."
);

проверить(
    менеджер.существует("ошибка_1"),
    "Ошибка существует."
);

проверить(
    менеджер.проверить(),
    "Финальная целостность реестра подтверждена."
);

console.log(
    "\n============================================================"
);

console.log(
    "🐌 ТЕСТ ИНТЕЛЛЕКТУАЛЬНОГО РЕЕСТРА ОБЪЕКТОВ 3D ЗАВЕРШЁН УСПЕШНО"
);

console.log(
    "============================================================"
);
