import {
    Исполнитель
} from "./исполнитель";

import {
    КонтекстВыполнения
} from "./контекст_выполнения";

import {
    УправлениеВыполнением
} from "./управление_выполнением";


// ============================================================
// ПРОВЕРКА
// ============================================================

let всегоПроверок = 0;

let успешныхПроверок = 0;


function проверить(
    условие: boolean,
    название: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✓ ${название}`
        );

    } else {

        console.error(
            `✗ ${название}`
        );
    }
}


// ============================================================
// ТЕСТОВАЯ ПРОГРАММА
// ============================================================

const дерево = [

    {

        вид: "ПРОГРАММА" as const,

        имя: "тест_жизненного_цикла",

        тело: {

            вид: "БЛОК" as const,

            команды: [

                {

                    вид:
                        "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ" as const,

                    имя: "число",

                    значение: {

                        вид: "ЧИСЛО" as const,

                        значение: 10

                    }

                },

                {

                    вид:
                        "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ" as const,

                    имя: "результат",

                    значение: {

                        вид: "ОПЕРАЦИЯ" as const,

                        оператор: "+",

                        левое: {

                            вид: "ИМЯ" as const,

                            значение: "число"

                        },

                        правое: {

                            вид: "ЧИСЛО" as const,

                            значение: 20

                        }

                    }

                },

                {

                    вид: "ПОКАЗАТЬ" as const,

                    значения: [

                        {

                            вид: "ИМЯ" as const,

                            значение: "результат"

                        }

                    ]

                }

            ]

        }

    }

];


// ============================================================
// СОЗДАНИЕ ОБЪЕКТОВ
// ============================================================

const исполнитель =
    new Исполнитель();

const контекст =
    new КонтекстВыполнения(
        "программа тест_жизненного_цикла"
    );

контекст.установитьДерево(
    дерево
);

const управление =
    new УправлениеВыполнением(
        исполнитель,
        контекст
    );


// ============================================================
// 1. СОЗДАНИЕ
// ============================================================

console.log(
    "\n🐌 1. Создание"
);

проверить(
    управление.получитьСостояние() ===
        "ожидание",
    "начальное состояние управления — ожидание"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "ожидание",
    "начальное состояние исполнителя — ожидание"
);

проверить(
    управление.получитьТекущийШаг() ===
        0,
    "начальный шаг равен 0"
);


// ============================================================
// 2. ЗАПУСК
// ============================================================

console.log(
    "\n🐌 2. Запуск"
);

let результат =
    управление.начать();

проверить(
    результат.успешно,
    "первый запуск принят"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "после запуска управление — выполнение"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "выполнение",
    "после запуска исполнитель — выполнение"
);

проверить(
    управление.получитьТекущийШаг() ===
        0,
    "после запуска текущий шаг равен 0"
);

проверить(
    управление.получитьВывод().length ===
        0,
    "после запуска вывод пуст"
);

проверить(
    Object.keys(
        управление.получитьПеременные()
    ).length === 0,
    "после запуска переменные пусты"
);


// ============================================================
// 3. ПЕРВЫЙ ШАГ И ПАУЗА
// ============================================================

console.log(
    "\n🐌 3. Первый шаг и пауза"
);

результат =
    управление.выполнитьШаг();

проверить(
    результат !== null,
    "первый шаг выполнен"
);

проверить(
    управление.получитьСостояние() ===
        "приостановлено",
    "после первого шага управление приостановлено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "приостановлено",
    "после первого шага исполнитель приостановлен"
);

проверить(
    управление.получитьТекущийШаг() ===
        1,
    "после первого шага номер шага равен 1"
);

проверить(
    управление.получитьПеременные().число ===
        10,
    "после первого шага переменная «число» равна 10"
);


// ============================================================
// 4. ПРОДОЛЖЕНИЕ ДО ЗАВЕРШЕНИЯ
// ============================================================

console.log(
    "\n🐌 4. Продолжение до завершения"
);

проверить(
    управление.продолжить(),
    "продолжение после паузы выполнено"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "после продолжения управление завершено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "завершено",
    "после продолжения исполнитель завершён"
);

проверить(
    управление.получитьТекущийШаг() ===
        3,
    "после продолжения выполнены 3 шага"
);

проверить(
    управление.получитьПеременные().результат ===
        30,
    "после продолжения результат равен 30"
);

проверить(
    управление.получитьВывод().length ===
        1,
    "после продолжения получен один элемент вывода"
);

проверить(
    управление.получитьВывод()[0] ===
        "30",
    "после продолжения вывод содержит 30"
);


// ============================================================
// 5. ПОВТОРНЫЙ ЗАПУСК ПОСЛЕ ЗАВЕРШЕНИЯ
// ============================================================

console.log(
    "\n🐌 5. Повторный запуск после завершения"
);

результат =
    управление.начать();

проверить(
    результат.успешно,
    "повторный запуск после завершения принят"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "после повторного запуска управление — выполнение"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "выполнение",
    "после повторного запуска исполнитель — выполнение"
);

проверить(
    управление.получитьТекущийШаг() ===
        0,
    "после повторного запуска шаг сброшен"
);

проверить(
    управление.получитьВывод().length ===
        0,
    "после повторного запуска старый вывод очищен"
);

проверить(
    Object.keys(
        управление.получитьПеременные()
    ).length === 0,
    "после повторного запуска старые переменные очищены"
);


// ============================================================
// 6. ОСТАНОВКА
// ============================================================

console.log(
    "\n🐌 6. Остановка"
);

проверить(
    управление.остановить(),
    "остановка после повторного запуска выполнена"
);

проверить(
    управление.получитьСостояние() ===
        "остановлено",
    "управление перешло в состояние остановлено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "остановлено",
    "исполнитель перешёл в состояние остановлено"
);


// ============================================================
// 7. НОВЫЙ ЗАПУСК ПОСЛЕ ОСТАНОВКИ
// ============================================================

console.log(
    "\n🐌 7. Новый запуск после остановки"
);

результат =
    управление.начать();

проверить(
    результат.успешно,
    "новый запуск после остановки принят"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "после нового запуска управление — выполнение"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "выполнение",
    "после нового запуска исполнитель — выполнение"
);

проверить(
    управление.получитьТекущийШаг() ===
        0,
    "после нового запуска шаг снова равен 0"
);


// ============================================================
// 8. НОВЫЙ ПЕРВЫЙ ШАГ
// ============================================================

console.log(
    "\n🐌 8. Новый первый шаг"
);

результат =
    управление.выполнитьШаг();

проверить(
    результат !== null,
    "новый первый шаг выполнен"
);

проверить(
    управление.получитьСостояние() ===
        "приостановлено",
    "после нового первого шага наступила пауза"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "приостановлено",
    "исполнитель после нового первого шага приостановлен"
);

проверить(
    управление.получитьТекущийШаг() ===
        1,
    "после нового первого шага номер равен 1"
);

проверить(
    управление.получитьПеременные().число ===
        10,
    "после нового первого шага число равно 10"
);


// ============================================================
// 9. ПОЛНОЕ ЗАВЕРШЕНИЕ НОВОГО ЦИКЛА
// ============================================================

console.log(
    "\n🐌 9. Полное завершение нового цикла"
);

проверить(
    управление.продолжить(),
    "новое продолжение выполнено"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "после нового продолжения состояние — завершено"
);

проверить(
    управление.получитьСостояниеИсполнителя() ===
        "завершено",
    "после нового продолжения исполнитель — завершён"
);

проверить(
    управление.получитьТекущийШаг() ===
        3,
    "после нового цикла выполнены 3 шага"
);

проверить(
    управление.получитьПеременные().результат ===
        30,
    "после нового цикла результат равен 30"
);

проверить(
    управление.получитьВывод().length ===
        1,
    "после нового цикла получен один вывод"
);

проверить(
    управление.получитьВывод()[0] ===
        "30",
    "после нового цикла вывод содержит 30"
);


// ============================================================
// ИТОГ
// ============================================================

console.log(
    "\n============================================================"
);

console.log(
    `🐌 Тест 3.2.5 завершён: ${успешныхПроверок}/${всегоПроверок} проверок пройдено.`
);

if (
    успешныхПроверок !==
    всегоПроверок
) {

    throw new Error(
        "Тест 3.2.5 завершён с ошибками."
    );
}

console.log(
    "✓ Полный жизненный цикл управления подтверждён."
);