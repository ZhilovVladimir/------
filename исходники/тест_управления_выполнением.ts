// ============================================================
// 🐌 УЛИТКА — ТЕСТ УПРАВЛЕНИЯ ВЫПОЛНЕНИЕМ
// ============================================================
//
// ЭТАП:
// 3.2.1 — Управление жизненным циклом выполнения
//
// Актуальный контракт:
// начать()
//      ↓
// выполнение
//      ↓
// выполнитьШаг()
//      ↓
// приостановлено
//      ↓
// продолжить()
//      ↓
// завершено
//
// ============================================================

import {
    Компилятор
} from "./компилятор";

import {
    Исполнитель
} from "./исполнитель";

import {
    КонтекстВыполнения
} from "./контекст_выполнения";

import {
    УправлениеВыполнением
} from "./управление_выполнением";


// ============================================================
// СЧЁТЧИК ПРОВЕРОК
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;


// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

    } else {

        ошибок++;

        console.error(
            `❌ ${сообщение}`
        );
    }
}


// ============================================================
// ЗАГОЛОВОК
// ============================================================

console.log("");

console.log(
    "🐌 ТЕСТ УПРАВЛЕНИЯ ВЫПОЛНЕНИЕМ"
);

console.log(
    "============================================"
);


// ============================================================
// ИСХОДНЫЙ КОД
// ============================================================

const код = `
программа управление

начало

    пусть число = 100

    показать число

конец
`;


// ============================================================
// СОЗДАНИЕ КОМПИЛЯТОРА
// ============================================================

const компилятор =
    new Компилятор();


// ============================================================
// ПОДГОТОВКА ПРОГРАММЫ
// ============================================================

const подготовка =
    компилятор.подготовить(
        код
    );


// ============================================================
// ПРОВЕРКА AST
// ============================================================

проверить(
    Array.isArray(
        подготовка.дерево
    ),
    "Компилятор успешно создал AST"
);

проверить(
    подготовка.дерево.length > 0,
    "AST содержит узлы программы"
);


// ============================================================
// ПОЛУЧЕНИЕ ИСПОЛНИТЕЛЯ
// ============================================================

const исполнитель =
    компилятор.получитьИсполнитель();

проверить(
    исполнитель instanceof Исполнитель,
    "Компилятор предоставляет Исполнитель"
);


// ============================================================
// СОЗДАНИЕ КОНТЕКСТА
// ============================================================

const контекст =
    new КонтекстВыполнения(
        код
    );


// ============================================================
// ПЕРЕДАЧА AST В КОНТЕКСТ
// ============================================================

контекст.установитьДерево(
    подготовка.дерево
);

проверить(
    контекст.получитьДерево() !== null,
    "Контекст получил AST"
);


// ============================================================
// СОЗДАНИЕ УПРАВЛЕНИЯ
// ============================================================

const управление =
    new УправлениеВыполнением(
        исполнитель,
        контекст
    );


// ============================================================
// НАЧАЛЬНОЕ СОСТОЯНИЕ
// ============================================================

проверить(
    управление.получитьСостояние() ===
        "ожидание",
    "Начальное состояние управления = ожидание"
);


// ============================================================
// ЕДИНСТВО ОБЪЕКТОВ
// ============================================================

проверить(
    управление.получитьИсполнитель() ===
        исполнитель,
    "Управление использует тот же экземпляр Исполнителя"
);

проверить(
    управление.получитьКонтекст() ===
        контекст,
    "Управление использует переданный КонтекстВыполнения"
);


// ============================================================
// НАЧАЛО ВЫПОЛНЕНИЯ
// ============================================================

const результатНачала =
    управление.начать();


// ============================================================
// ПРОВЕРКА НАЧАЛА
// ============================================================

проверить(
    результатНачала.успешно === true,
    "Запуск программы принят"
);

проверить(
    результатНачала.состояние ===
        "выполнение",
    "Результат запуска сообщает состояние выполнение"
);

проверить(
    управление.получитьСостояние() ===
        "выполнение",
    "Управление перешло в состояние выполнение"
);

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "выполнение",
    "Исполнитель перешёл в состояние выполнение"
);

проверить(
    управление.получитьВывод().length ===
        0,
    "До первого шага вывод отсутствует"
);

проверить(
    Object.keys(
        управление.получитьПеременные()
    ).length === 0,
    "До первого шага переменные отсутствуют"
);


// ============================================================
// ПЕРВЫЙ ШАГ
// ============================================================

const результатПервогоШага =
    управление.выполнитьШаг();

проверить(
    результатПервогоШага !== null,
    "Первый шаг выполнен"
);

проверить(
    управление.получитьСостояние() ===
        "приостановлено",
    "После первого шага управление приостановлено"
);

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "приостановлено",
    "После первого шага исполнитель приостановлен"
);

проверить(
    управление.получитьПеременные().число ===
        100,
    "После первого шага переменная число = 100"
);

проверить(
    управление.получитьВывод().length ===
        0,
    "После первого шага вывод ещё пуст"
);


// ============================================================
// ПРОДОЛЖЕНИЕ
// ============================================================

const продолжение =
    управление.продолжить();

проверить(
    продолжение === true,
    "Продолжение после паузы выполнено"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "После продолжения управление завершено"
);

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "завершено",
    "После продолжения исполнитель завершён"
);


// ============================================================
// РЕЗУЛЬТАТ ИСПОЛНЕНИЯ
// ============================================================

const выполнение =
    управление.получитьРезультат();

проверить(
    выполнение !== null,
    "Результат выполнения сохранён"
);

проверить(
    выполнение !== null &&
    выполнение.вывод.length === 1,
    "Результат содержит один элемент вывода"
);

проверить(
    выполнение !== null &&
    выполнение.вывод[0] === "100",
    "Результат содержит вывод программы = 100"
);

проверить(
    выполнение !== null &&
    выполнение.переменные.число === 100,
    "Результат содержит переменную число = 100"
);


// ============================================================
// ВЫВОД
// ============================================================

const вывод =
    управление.получитьВывод();

проверить(
    вывод.length === 1,
    "Получен один результат вывода"
);

проверить(
    вывод[0] === "100",
    "Вывод программы = 100"
);


// ============================================================
// ПЕРЕМЕННЫЕ
// ============================================================

const переменные =
    управление.получитьПеременные();

проверить(
    переменные.число === 100,
    "Переменная число = 100"
);


// ============================================================
// СОБЫТИЯ
// ============================================================

const события =
    управление.получитьСобытия();

проверить(
    события.length > 0,
    "События выполнения переданы в КонтекстВыполнения"
);

проверить(
    события.some(
        событие =>
            событие.тип ===
            "начало_программы"
    ),
    "Есть событие начала программы"
);

проверить(
    события.some(
        событие =>
            событие.тип ===
            "объявление_переменной"
    ),
    "Есть событие объявления переменной"
);

проверить(
    события.some(
        событие =>
            событие.тип ===
            "показ"
    ),
    "Есть событие показа"
);

проверить(
    события.some(
        событие =>
            событие.тип ===
            "завершение_программы"
    ),
    "Есть событие завершения программы"
);


// ============================================================
// ФАЗА КОНТЕКСТА
// ============================================================

проверить(
    контекст.получитьФазу() ===
        "завершено",
    "Фаза КонтекстВыполнения = завершено"
);

проверить(
    контекст.получитьВывод()[0] ===
        "100",
    "Контекст содержит вывод программы"
);

проверить(
    контекст.получитьПеременные().число ===
        100,
    "Контекст содержит переменную число = 100"
);


// ============================================================
// ПРИОСТАНОВКА ПОСЛЕ ЗАВЕРШЕНИЯ
// ============================================================

проверить(
    управление.приостановить() ===
        false,
    "Завершённую программу нельзя приостановить"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "После неудачной паузы состояние остаётся завершено"
);


// ============================================================
// ПРОДОЛЖЕНИЕ ПОСЛЕ ЗАВЕРШЕНИЯ
// ============================================================

проверить(
    управление.продолжить() ===
        false,
    "Завершённую программу нельзя продолжить"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "После неудачного продолжения состояние остаётся завершено"
);


// ============================================================
// ОСТАНОВКА ПОСЛЕ ЗАВЕРШЕНИЯ
// ============================================================

проверить(
    управление.остановить() ===
        false,
    "Завершённую программу нельзя остановить"
);

проверить(
    управление.получитьСостояние() ===
        "завершено",
    "После неудачной остановки состояние остаётся завершено"
);


// ============================================================
// СООБЩЕНИЕ ОБ ОШИБКЕ
// ============================================================

проверить(
    управление.получитьСообщениеОшибки() ===
        null,
    "После успешного выполнения сообщение об ошибке отсутствует"
);


// ============================================================
// СНИМОК
// ============================================================

const снимок =
    контекст.получитьСнимок();

проверить(
    снимок !== null,
    "Контекст создаёт снимок"
);

проверить(
    снимок.исходныйКод ===
        код,
    "Снимок сохраняет исходный код"
);

проверить(
    снимок.вывод.length ===
        1,
    "Снимок сохраняет вывод"
);

проверить(
    снимок.события.length ===
        события.length,
    "Снимок сохраняет события"
);


// ============================================================
// ИТОГ
// ============================================================

console.log("");

console.log(
    "============================================"
);

console.log(
    `Всего проверок: ${всегоПроверок}`
);

console.log(
    `Успешных проверок: ${успешныхПроверок}`
);

console.log(
    `Ошибок: ${ошибок}`
);

console.log(
    "============================================"
);

if (
    ошибок === 0
) {

    console.log("");

    console.log(
        "🐌 ✅ УПРАВЛЕНИЕ ВЫПОЛНЕНИЕМ ПРОШЛО ПРОВЕРКУ"
    );

    console.log(
        "🐌 ЭТАП 3.2.1 ЗАВЕРШЁН"
    );

} else {

    console.error("");

    console.error(
        "🐌 ❌ ТЕСТ УПРАВЛЕНИЯ ВЫПОЛНЕНИЕМ НЕ ПРОЙДЕН"
    );

    process.exitCode = 1;
}