// ============================================================
// 🐌 УЛИТКА — 3D-ЯДРО
// Мост между событиями исполнения и 3D-состоянием
// ============================================================

import {
    Ядро3D
} from "./ядро_3d.js";

import type {
    СобытиеИсполнения
} from "./исполнитель.js";

// ============================================================
// ДАННЫЕ СОБЫТИЯ
// ============================================================

type ДанныеСобытия =
    Record<string, unknown>;

// ============================================================
// ИНТЕГРАТОР
// ============================================================

export class ИнтеграторИсполнения3D {
    private readonly ядро: Ядро3D;

    private readonly узлыПоИсточнику:
        Map<string, string> = new Map();

    private readonly связиПоКлючу:
        Map<string, string> = new Map();

    public constructor(
        ядро: Ядро3D
    ) {
        this.ядро = ядро;
    }

    // ========================================================
    // ПОЛУЧИТЬ ЯДРО
    // ========================================================

    public получитьЯдро(): Ядро3D {
        return this.ядро;
    }

    // ========================================================
    // ОБРАБОТАТЬ СОБЫТИЕ
    // ========================================================

    public обработатьСобытие(
        событие: СобытиеИсполнения
    ): void {
        const данные =
            this.получитьДанные(
                событие.данные
            );

        switch (событие.тип) {
            // ------------------------------------------------
            // НАЧАЛО ПРОГРАММЫ
            // ------------------------------------------------

            case "начало_программы": {
                this.ядро.установитьСостояние(
                    "выполнение"
                );

                break;
            }

            // ------------------------------------------------
            // ЗАВЕРШЕНИЕ ПРОГРАММЫ
            // ------------------------------------------------

            case "завершение_программы": {
                this.ядро.установитьСостояние(
                    "завершено"
                );

                break;
            }

            // ------------------------------------------------
            // ОБЪЯВЛЕНИЕ / ИЗМЕНЕНИЕ ПЕРЕМЕННОЙ
            // ------------------------------------------------

            case "объявление_переменной":
            case "изменение_переменной": {
                this.обработатьИзменениеПеременной(
                    событие,
                    данные
                );

                break;
            }

            // ------------------------------------------------
            // ВЫЗОВ ФУНКЦИИ
            // ------------------------------------------------

            case "вызов_функции": {
                this.обработатьВызовФункции(
                    событие,
                    данные
                );

                break;
            }

            // ------------------------------------------------
            // ВОЗВРАТ ИЗ ФУНКЦИИ
            // ------------------------------------------------

            case "возврат": {
                const имя =
                    this.получитьСтроку(
                        данные?.имя
                    );

                if (имя === null) {
                    break;
                }

                const идентификатор =
                    this.узлыПоИсточнику.get(
                        `функция:${имя}`
                    );

                if (
                    идентификатор ===
                    undefined
                ) {
                    break;
                }

                this.ядро.деактивироватьУзел(
                    идентификатор
                );

                break;
            }

            // ------------------------------------------------
            // ПРОВЕРКА УСЛОВИЯ
            // ------------------------------------------------

            case "проверка_условия": {
                this.обработатьУсловие(
                    событие,
                    данные
                );

                break;
            }

            // ------------------------------------------------
            // ОШИБКА
            // ------------------------------------------------

            case "ошибка": {
                const идентификатор =
                    this.ядро.добавитьУзел(
                        "ошибка",
                        событие.источник
                    );

                this.ядро.активироватьУзел(
                    идентификатор,
                    1
                );

                break;
            }

            // ------------------------------------------------
            // ПОКА НЕ СОЗДАЮТ ОТДЕЛЬНЫЙ УЗЕЛ
            // ------------------------------------------------

            case "показ":
            case "ветка_тогда":
            case "ветка_иначе":
                break;

            default:
                break;
        }
    }

    // ========================================================
    // ПОДКЛЮЧИТЬСЯ К ПОТОКУ СОБЫТИЙ
    // ========================================================

    public создатьОбработчик():
        (событие: СобытиеИсполнения) => void {
        return (
            событие: СобытиеИсполнения
        ) => {
            this.обработатьСобытие(
                событие
            );
        };
    }

    // ========================================================
    // ОБРАБОТАТЬ ИЗМЕНЕНИЕ ПЕРЕМЕННОЙ
    // ========================================================

    private обработатьИзменениеПеременной(
        событие: СобытиеИсполнения,
        данные: ДанныеСобытия | null
    ): void {
        const имя =
            this.получитьСтроку(
                данные?.имя
            );

        if (имя === null) {
            return;
        }

        const идентификаторПеременной =
            this.получитьИлиСоздатьУзел(
                `переменная:${имя}`,
                "переменная",
                имя
            );

        this.ядро.активироватьУзел(
            идентификаторПеременной,
            1
        );

        const источники =
            this.получитьМассивСтрок(
                данные?.источники
            );

        const оператор =
            this.получитьСтроку(
                данные?.оператор
            );

        // ----------------------------------------------------
        // Простое присваивание:
        //
        // пусть число = 10
        //
        // Для сохранения старого поведения здесь не создаём
        // отдельный узел "выполнение".
        // ----------------------------------------------------

        if (
            источники.length === 0 &&
            оператор === null
        ) {
            return;
        }

        // ----------------------------------------------------
        // Причинное вычисление:
        //
        // а → выполнение → б
        // ----------------------------------------------------

        const идентификаторВыполнения =
            this.создатьУзелВыполнения(
                событие,
                `вычисление:${имя}`
            );

        for (
            const источник
            of источники
        ) {
            const идентификаторИсточника =
                this.получитьИлиСоздатьИсточник(
                    источник
                );

            if (
                идентификаторИсточника === null
            ) {
                continue;
            }

            const типСвязи =
                источник.startsWith(
                    "функция:"
                )
                    ? "вызов"
                    : "зависимость";

            this.создатьИлиАктивироватьСвязь(
                идентификаторИсточника,
                идентификаторВыполнения,
                типСвязи
            );
        }

        this.создатьИлиАктивироватьСвязь(
            идентификаторВыполнения,
            идентификаторПеременной,
            "передача"
        );

        this.ядро.активироватьУзел(
            идентификаторВыполнения,
            1
        );
    }

    // ========================================================
    // ОБРАБОТАТЬ ВЫЗОВ ФУНКЦИИ
    // ========================================================

    private обработатьВызовФункции(
        событие: СобытиеИсполнения,
        данные: ДанныеСобытия | null
    ): void {
        const имя =
            this.получитьСтроку(
                данные?.имя
            );

        if (имя === null) {
            return;
        }

        const идентификаторФункции =
            this.получитьИлиСоздатьУзел(
                `функция:${имя}`,
                "функция",
                имя
            );

        this.ядро.активироватьУзел(
            идентификаторФункции,
            1
        );

        const идентификаторВыполнения =
            this.создатьУзелВыполнения(
                событие,
                `вызов:${имя}`
            );

        this.создатьИлиАктивироватьСвязь(
            идентификаторФункции,
            идентификаторВыполнения,
            "вызов"
        );

        const источники =
            this.получитьМассивСтрок(
                данные?.источники
            );

        for (
            const источник
            of источники
        ) {
            if (
                источник ===
                `функция:${имя}`
            ) {
                continue;
            }

            const идентификаторИсточника =
                this.получитьИлиСоздатьИсточник(
                    источник
                );

            if (
                идентификаторИсточника === null
            ) {
                continue;
            }

            this.создатьИлиАктивироватьСвязь(
                идентификаторИсточника,
                идентификаторФункции,
                "передача"
            );
        }

        this.ядро.активироватьУзел(
            идентификаторВыполнения,
            1
        );
    }

    // ========================================================
    // ОБРАБОТАТЬ УСЛОВИЕ
    // ========================================================

    private обработатьУсловие(
        событие: СобытиеИсполнения,
        данные: ДанныеСобытия | null
    ): void {
        const идентификаторВыполнения =
            this.создатьУзелВыполнения(
                событие,
                "условие"
            );

        const источники =
            this.получитьМассивСтрок(
                данные?.источники
            );

        for (
            const источник
            of источники
        ) {
            const идентификаторИсточника =
                this.получитьИлиСоздатьИсточник(
                    источник
                );

            if (
                идентификаторИсточника === null
            ) {
                continue;
            }

            this.создатьИлиАктивироватьСвязь(
                идентификаторИсточника,
                идентификаторВыполнения,
                "зависимость"
            );
        }

        const результат =
            данные?.результат;

        const интенсивность =
            результат === true
                ? 1
                : 0.4;

        this.ядро.активироватьУзел(
            идентификаторВыполнения,
            интенсивность
        );
    }

    // ========================================================
    // СОЗДАТЬ УЗЕЛ ВЫПОЛНЕНИЯ
    // ========================================================

    private создатьУзелВыполнения(
        событие: СобытиеИсполнения,
        имя: string
    ): string {
        const источник =
            `выполнение:${событие.идентификатор}`;

        const существующий =
            this.узлыПоИсточнику.get(
                источник
            );

        if (
            существующий !== undefined
        ) {
            return существующий;
        }

        const идентификатор =
            this.ядро.добавитьУзел(
                "выполнение",
                имя
            );

        this.узлыПоИсточнику.set(
            источник,
            идентификатор
        );

        return идентификатор;
    }

    // ========================================================
    // ПОЛУЧИТЬ ИЛИ СОЗДАТЬ УЗЕЛ ИСТОЧНИКА
    // ========================================================

    private получитьИлиСоздатьИсточник(
        источник: string
    ): string | null {
        if (
            источник.startsWith(
                "переменная:"
            )
        ) {
            const имя =
                источник.slice(
                    "переменная:".length
                );

            if (имя.length === 0) {
                return null;
            }

            return this.получитьИлиСоздатьУзел(
                источник,
                "переменная",
                имя
            );
        }

        if (
            источник.startsWith(
                "функция:"
            )
        ) {
            const имя =
                источник.slice(
                    "функция:".length
                );

            if (имя.length === 0) {
                return null;
            }

            return this.получитьИлиСоздатьУзел(
                источник,
                "функция",
                имя
            );
        }

        return null;
    }

    // ========================================================
    // ПОЛУЧИТЬ ИЛИ СОЗДАТЬ УЗЕЛ
    // ========================================================

    private получитьИлиСоздатьУзел(
        источник: string,
        тип:
            "переменная"
            | "функция",
        имя: string
    ): string {
        const существующий =
            this.узлыПоИсточнику.get(
                источник
            );

        if (
            существующий !== undefined
        ) {
            return существующий;
        }

        const идентификатор =
            this.ядро.добавитьУзел(
                тип,
                имя
            );

        this.узлыПоИсточнику.set(
            источник,
            идентификатор
        );

        return идентификатор;
    }

    // ========================================================
    // СОЗДАТЬ ИЛИ АКТИВИРОВАТЬ СВЯЗЬ
    // ========================================================

    private создатьИлиАктивироватьСвязь(
        откуда: string,
        куда: string,
        тип:
            | "зависимость"
            | "вызов"
            | "передача"
            | "выполнение"
            | "ошибка"
    ): string {
        const ключ =
            `${откуда}->${куда}:${тип}`;

        const существующий =
            this.связиПоКлючу.get(
                ключ
            );

        if (
            существующий !== undefined
        ) {
            this.ядро.активироватьСвязь(
                существующий,
                1
            );

            return существующий;
        }

        const идентификатор =
            this.ядро.добавитьСвязь(
                откуда,
                куда,
                тип
            );

        this.связиПоКлючу.set(
            ключ,
            идентификатор
        );

        this.ядро.активироватьСвязь(
            идентификатор,
            1
        );

        return идентификатор;
    }

    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ
    // ========================================================

    private получитьДанные(
        данные: unknown
    ): ДанныеСобытия | null {
        if (
            typeof данные !== "object" ||
            данные === null
        ) {
            return null;
        }

        return данные as ДанныеСобытия;
    }

    // ========================================================
    // ПОЛУЧИТЬ СТРОКУ
    // ========================================================

    private получитьСтроку(
        значение: unknown
    ): string | null {
        return typeof значение === "string"
            ? значение
            : null;
    }

    // ========================================================
    // ПОЛУЧИТЬ МАССИВ СТРОК
    // ========================================================

    private получитьМассивСтрок(
        значение: unknown
    ): string[] {
        if (!Array.isArray(значение)) {
            return [];
        }

        return значение.filter(
            элемент =>
                typeof элемент === "string"
        );
    }

    // ========================================================
    // СБРОС СОПРОВОЖДЕНИЯ
    // ========================================================

    public очиститьПривязки(): void {
        this.узлыПоИсточнику.clear();
        this.связиПоКлючу.clear();
    }
}