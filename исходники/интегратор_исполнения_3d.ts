// ============================================================
// 🐌 УЛИТКА — 3D-ЯДРО
// Мост между событиями исполнения и 3D-состоянием
// ============================================================

import {
    Ядро3D
} from "./ядро_3d.js";

import type {
    СобытиеИсполнения
} from "./исполнитель.js";

// ============================================================
// ДАННЫЕ СОБЫТИЯ
// ============================================================

type ДанныеСобытия =
    Record<string, unknown>;

// ============================================================
// ИНТЕГРАТОР
// ============================================================

export class ИнтеграторИсполнения3D {

    private readonly ядро: Ядро3D;

    private readonly узлыПоИсточнику:
        Map<string, string> = new Map();

    public constructor(
        ядро: Ядро3D
    ) {
        this.ядро = ядро;
    }

    // ========================================================
    // ПОЛУЧИТЬ ЯДРО
    // ========================================================

    public получитьЯдро(): Ядро3D {
        return this.ядро;
    }

    // ========================================================
    // ОБРАБОТАТЬ СОБЫТИЕ
    // ========================================================

    public обработатьСобытие(
        событие: СобытиеИсполнения
    ): void {

        const данные =
            this.получитьДанные(
                событие.данные
            );

        switch (событие.тип) {

            // ------------------------------------------------
            // НАЧАЛО ПРОГРАММЫ
            // ------------------------------------------------

            case "начало_программы": {

                this.ядро.установитьСостояние(
                    "выполнение"
                );

                break;
            }

            // ------------------------------------------------
            // ЗАВЕРШЕНИЕ ПРОГРАММЫ
            // ------------------------------------------------

            case "завершение_программы": {

                this.ядро.установитьСостояние(
                    "завершено"
                );

                break;
            }

            // ------------------------------------------------
            // ОБЪЯВЛЕНИЕ ПЕРЕМЕННОЙ
            // ------------------------------------------------

            case "объявление_переменной": {

                const имя =
                    this.получитьСтроку(
                        данные?.имя
                    );

                if (имя === null) {
                    break;
                }

                const идентификатор =
                    this.получитьИлиСоздатьУзел(
                        `переменная:${имя}`,
                        "переменная",
                        имя
                    );

                this.ядро.активироватьУзел(
                    идентификатор,
                    1
                );

                break;
            }

            // ------------------------------------------------
            // ИЗМЕНЕНИЕ ПЕРЕМЕННОЙ
            // ------------------------------------------------

            case "изменение_переменной": {

                const имя =
                    this.получитьСтроку(
                        данные?.имя
                    );

                if (имя === null) {
                    break;
                }

                const идентификатор =
                    this.получитьИлиСоздатьУзел(
                        `переменная:${имя}`,
                        "переменная",
                        имя
                    );

                this.ядро.активироватьУзел(
                    идентификатор,
                    1
                );

                break;
            }

            // ------------------------------------------------
            // ВЫЗОВ ФУНКЦИИ
            // ------------------------------------------------

            case "вызов_функции": {

                const имя =
                    this.получитьСтроку(
                        данные?.имя
                    );

                if (имя === null) {
                    break;
                }

                const идентификатор =
                    this.получитьИлиСоздатьУзел(
                        `функция:${имя}`,
                        "функция",
                        имя
                    );

                this.ядро.активироватьУзел(
                    идентификатор,
                    1
                );

                break;
            }

            // ------------------------------------------------
            // ВОЗВРАТ ИЗ ФУНКЦИИ
            // ------------------------------------------------

            case "возврат": {

                const имя =
                    this.получитьСтроку(
                        данные?.имя
                    );

                if (имя === null) {
                    break;
                }

                const идентификатор =
                    this.узлыПоИсточнику.get(
                        `функция:${имя}`
                    );

                if (
                    идентификатор === undefined
                ) {
                    break;
                }

                this.ядро.деактивироватьУзел(
                    идентификатор
                );

                break;
            }

            // ------------------------------------------------
            // ОШИБКА
            // ------------------------------------------------

            case "ошибка": {

                const идентификатор =
                    this.ядро.добавитьУзел(
                        "ошибка",
                        событие.источник
                    );

                this.ядро.активироватьУзел(
                    идентификатор,
                    1
                );

                break;
            }

            // ------------------------------------------------
            // ПОКА НЕ ТРЕБУЮТ ОТДЕЛЬНОГО УЗЛА
            // ------------------------------------------------

            case "показ":
            case "проверка_условия":
            case "ветка_тогда":
            case "ветка_иначе":
                break;

            default:
                break;
        }
    }

    // ========================================================
    // ПОДКЛЮЧИТЬСЯ К ПОТОКУ СОБЫТИЙ
    // ========================================================

    public создатьОбработчик():
        (событие: СобытиеИсполнения) => void {

        return (
            событие: СобытиеИсполнения
        ) => {

            this.обработатьСобытие(
                событие
            );
        };
    }

    // ========================================================
    // ПОЛУЧИТЬ ИЛИ СОЗДАТЬ УЗЕЛ
    // ========================================================

    private получитьИлиСоздатьУзел(
        источник: string,
        тип:
            "переменная"
            | "функция",
        имя: string
    ): string {

        const существующий =
            this.узлыПоИсточнику.get(
                источник
            );

        if (
            существующий !== undefined
        ) {
            return существующий;
        }

        const идентификатор =
            this.ядро.добавитьУзел(
                тип,
                имя
            );

        this.узлыПоИсточнику.set(
            источник,
            идентификатор
        );

        return идентификатор;
    }

    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ
    // ========================================================

    private получитьДанные(
        данные: unknown
    ): ДанныеСобытия | null {

        if (
            typeof данные !== "object" ||
            данные === null
        ) {
            return null;
        }

        return данные as ДанныеСобытия;
    }

    // ========================================================
    // ПОЛУЧИТЬ СТРОКУ
    // ========================================================

    private получитьСтроку(
        значение: unknown
    ): string | null {

        return typeof значение === "string"
            ? значение
            : null;
    }

    // ========================================================
    // СБРОС СОПРОВОЖДЕНИЯ
    // ========================================================

    public очиститьПривязки(): void {

        this.узлыПоИсточнику.clear();
    }
}
