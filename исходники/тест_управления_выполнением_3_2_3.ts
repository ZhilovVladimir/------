// ============================================================
// 🐌 УЛИТКА
// Тест управления выполнением 3.2.3
// Интеграция управления с пошаговым исполнением
// ============================================================

import {
    Исполнитель,
} from "./исполнитель.js";

import {
    КонтекстВыполнения,
} from "./контекст_выполнения.js";

import {
    УправлениеВыполнением,
} from "./управление_выполнением.js";

import type {
    Узел,
} from "./дерево/узлы.js";


// ============================================================
// ВСПОМОГАТЕЛЬНАЯ ПРОВЕРКА
// ============================================================

let номерПроверки = 0;
let количествоОшибок = 0;

function проверить(
    условие: boolean,
    сообщение: string,
): void {

    номерПроверки += 1;

    if (условие) {

        console.log(
            `✓ Проверка ${номерПроверки}: ${сообщение}`,
        );

        return;
    }

    количествоОшибок += 1;

    console.error(
        `✗ Проверка ${номерПроверки}: ${сообщение}`,
    );
}


// ============================================================
// ТЕСТОВАЯ ПРОГРАММА
// ============================================================

const исходныйКод = `
программа тест_управления
начало
    пусть число = 10
    пусть результат = число + 20
    показать результат
конец
`;


// ============================================================
// ДЕРЕВО ПРОГРАММЫ
// ============================================================

const дерево: Узел[] = [

    {
        вид: "ПРОГРАММА",

        имя: "тест_управления",

        тело: {

            вид: "БЛОК",

            команды: [

                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",

                    имя: "число",

                    значение: {

                        вид: "ЧИСЛО",

                        значение: 10,
                    },
                },

                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",

                    имя: "результат",

                    значение: {

                        вид: "ОПЕРАЦИЯ",

                        оператор: "+",

                        левое: {

                            вид: "ИМЯ",

                            значение: "число",
                        },

                        правое: {

                            вид: "ЧИСЛО",

                            значение: 20,
                        },
                    },
                },

                {
                    вид: "ПОКАЗАТЬ",

                    значения: [

                        {
                            вид: "ИМЯ",

                            значение: "результат",
                        },
                    ],
                },
            ],
        },
    },
];


// ============================================================
// СОЗДАНИЕ ОБЪЕКТОВ
// ============================================================

const исполнитель =
    new Исполнитель();

const контекст =
    new КонтекстВыполнения(
        исходныйКод,
    );

контекст.установитьДерево(
    дерево,
);

const управление =
    new УправлениеВыполнением(
        исполнитель,
        контекст,
    );


// ============================================================
// 1. НАЧАЛЬНОЕ СОСТОЯНИЕ
// ============================================================

проверить(
    управление.получитьСостояние() === "ожидание",
    "до запуска управление находится в состоянии «ожидание»",
);

проверить(
    управление.получитьСостояниеИсполнителя() === "ожидание",
    "до запуска исполнитель находится в состоянии «ожидание»",
);


// ============================================================
// 2. НАЧАЛО ПОШАГОВОГО ВЫПОЛНЕНИЯ
// ============================================================

управление.начать();

проверить(
    управление.получитьСостояние() === "выполнение",
    "после начала управление находится в состоянии «выполнение»",
);

проверить(
    управление.получитьСостояниеИсполнителя() === "выполнение",
    "после начала исполнитель находится в состоянии «выполнение»",
);

проверить(
    управление.получитьТекущийШаг() === 0,
    "после начала текущий шаг равен 0",
);

проверить(
    управление.получитьКоличествоШагов() === 3,
    "подготовлено 3 шага выполнения",
);

проверить(
    управление.получитьТекущийУзел() === null,
    "до выполнения первого шага текущий узел отсутствует",
);


// ============================================================
// 3. ВЫПОЛНЕНИЕ ПЕРВОГО ШАГА
// ============================================================

const результатПервогоШага =
    управление.выполнитьШаг();

проверить(
    управление.получитьТекущийШаг() === 1,
    "после первого шага текущий шаг равен 1",
);

проверить(
    управление.получитьСостояниеИсполнителя() === "приостановлено",
    "после первого шага исполнитель приостановлен",
);

проверить(
    управление.получитьСостояние() === "приостановлено",
    "управление синхронизировало состояние «приостановлено»",
);

проверить(
    результатПервогоШага.результат?.переменные["число"] === 10,
    "после первого шага переменная «число» равна 10",
);


// ============================================================
// 4. ПРОДОЛЖЕНИЕ
// ============================================================

управление.продолжить();

проверить(
    управление.получитьСостояниеИсполнителя() === "выполнение",
    "после продолжения исполнитель снова выполняется",
);

проверить(
    управление.получитьСостояние() === "выполнение",
    "после продолжения управление снова выполняется",
);

проверить(
    управление.получитьТекущийШаг() === 1,
    "продолжение само по себе не выполняет следующий шаг",
);


// ============================================================
// 5. ВЫПОЛНЕНИЕ ВТОРОГО ШАГА
// ============================================================

const результатВторогоШага =
    управление.выполнитьШаг();

проверить(
    управление.получитьТекущийШаг() === 2,
    "после второго шага текущий шаг равен 2",
);

проверить(
    управление.получитьСостояниеИсполнителя() === "приостановлено",
    "после второго шага исполнитель приостановлен",
);

проверить(
    результатВторогоШага.результат?.переменные["число"] === 10,
    "переменная «число» сохранилась",
);

проверить(
    результатВторогоШага.результат?.переменные["результат"] === 30,
    "переменная «результат» равна 30",
);


// ============================================================
// 6. ПРОДОЛЖЕНИЕ И ТРЕТИЙ ШАГ
// ============================================================

управление.продолжить();

проверить(
    управление.получитьСостояние() === "выполнение",
    "перед третьим шагом управление находится в состоянии «выполнение»",
);

const результатТретьегоШага =
    управление.выполнитьШаг();

проверить(
    управление.получитьТекущийШаг() === 3,
    "после третьего шага текущий шаг равен 3",
);

проверить(
    управление.получитьСостояниеИсполнителя() === "завершено",
    "после последнего шага исполнитель завершён",
);

проверить(
    управление.получитьСостояние() === "завершено",
    "после последнего шага управление завершено",
);

проверить(
    результатТретьегоШага.результат?.вывод.length === 1,
    "получен один результат вывода",
);

проверить(
    результатТретьегоШага.результат?.вывод[0] === "30",
    "вывод программы равен 30",
);

проверить(
    контекст.получитьФазу() === "завершено",
    "контекст выполнения переведён в фазу «завершено»",
);


// ============================================================
// 7. ПРОВЕРКА ПОСЛЕ ЗАВЕРШЕНИЯ
// ============================================================

const результатПослеЗавершения =
    управление.выполнитьШаг();

проверить(
    управление.получитьСостояние() === "завершено",
    "после завершения состояние не изменяется",
);

проверить(
    результатПослеЗавершения.результат?.вывод[0] === "30",
    "после завершения результат сохраняется",
);


// ============================================================
// 8. ОТДЕЛЬНАЯ ПРОВЕРКА ОСТАНОВКИ
// ============================================================

const исполнительОстановки =
    new Исполнитель();

const контекстОстановки =
    new КонтекстВыполнения(
        исходныйКод,
    );

контекстОстановки.установитьДерево(
    дерево,
);

const управлениеОстановки =
    new УправлениеВыполнением(
        исполнительОстановки,
        контекстОстановки,
    );

управлениеОстановки.начать();

проверить(
    управлениеОстановки.получитьСостояние() === "выполнение",
    "новое выполнение успешно запущено",
);

управлениеОстановки.остановить();

проверить(
    управлениеОстановки.получитьСостояние() === "остановлено",
    "остановка переводит управление в состояние «остановлено»",
);

проверить(
    управлениеОстановки.получитьСостояниеИсполнителя() === "остановлено",
    "остановка передаётся реальному исполнителю",
);


// ============================================================
// ИТОГ
// ============================================================

console.log("");

console.log(
    "============================================================",
);

if (количествоОшибок === 0) {

    console.log(
        `🐌 Тест 3.2.3 завершён успешно: ${номерПроверки}/${номерПроверки} проверок пройдено.`,
    );

} else {

    console.error(
        `❌ Тест 3.2.3 завершён с ошибками: ${количествоОшибок} из ${номерПроверки} проверок не пройдено.`,
    );
}

console.log(
    "============================================================",
);

if (количествоОшибок > 0) {

    process.exitCode = 1;
}
