// ============================================================
// 🐌 УЛИТКА
// ТЕСТ 3.2.2.7
// ЗАЩИТА РЕЗУЛЬТАТОВ ИСПОЛНИТЕЛЯ
// ============================================================

import {
    Исполнитель
} from "./исполнитель.js";

import type {
    Узел
} from "./дерево/узлы.js";

// ============================================================
// ПРОВЕРКА
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибок++;

    console.error(
        `❌ ${сообщение}`
    );
}

// ============================================================
// ЗАГОЛОВОК
// ============================================================

console.log(
    ""
);

console.log(
    "============================================================"
);

console.log(
    "🐌 ТЕСТ 3.2.2.7 — ЗАЩИТА РЕЗУЛЬТАТОВ ИСПОЛНИТЕЛЯ"
);

console.log(
    "============================================================"
);

console.log(
    ""
);

// ============================================================
// ТЕСТОВАЯ ПРОГРАММА
// ============================================================

const дерево: Узел[] = [

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "имя",
        значение: {
            вид: "ТЕКСТ",
            значение: "Владимир"
        }
    },

    {
        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        имя: "возраст",
        значение: {
            вид: "ЧИСЛО",
            значение: 42
        }
    },

    {
        вид: "ПОКАЗАТЬ",
        значения: [
            {
                вид: "ИМЯ",
                значение: "имя"
            }
        ]
    }

];

// ============================================================
// СОЗДАНИЕ ИСПОЛНИТЕЛЯ
// ============================================================

const исполнитель =
    new Исполнитель();

// ============================================================
// ВЫПОЛНЕНИЕ
// ============================================================

const результат =
    исполнитель.исполнить(
        дерево
    );

// ============================================================
// БАЗОВОЕ СОСТОЯНИЕ
// ============================================================

проверить(
    результат.вывод.length === 1,
    "Результат содержит один элемент вывода"
);

проверить(
    результат.вывод[0] === "Владимир",
    "Исходный вывод содержит «Владимир»"
);

проверить(
    результат.переменные.имя === "Владимир",
    "Результат содержит переменную «имя»"
);

проверить(
    результат.переменные.возраст === 42,
    "Результат содержит переменную «возраст»"
);

проверить(
    результат.события.length > 0,
    "Результат содержит события исполнения"
);

// ============================================================
// 1. ЗАЩИТА ВЫВОДА
// ============================================================

const выводРезультата =
    результат.вывод;

выводРезультата[0] =
    "ПОДМЕНА";

выводРезультата.push(
    "ЛИШНИЙ ВЫВОД"
);

const выводИсполнителя =
    исполнитель.получитьВывод();

проверить(
    выводИсполнителя.length === 1,
    "Внешнее изменение массива результата не изменило внутренний вывод"
);

проверить(
    выводИсполнителя[0] === "Владимир",
    "Внутренний вывод сохранил исходное значение"
);

// ============================================================
// 2. ЗАЩИТА ПЕРЕМЕННЫХ
// ============================================================

const переменныеРезультата =
    результат.переменные;

переменныеРезультата.имя =
    "ПОДМЕНА";

delete переменныеРезультата.возраст;

переменныеРезультата.новая =
    "ЛИШНЯЯ";

const переменныеИсполнителя =
    исполнитель.получитьПеременные();

проверить(
    переменныеИсполнителя.имя === "Владимир",
    "Внешнее изменение переменной не изменило внутреннее значение"
);

проверить(
    переменныеИсполнителя.возраст === 42,
    "Удаление переменной во внешнем объекте не изменило внутреннее состояние"
);

проверить(
    !("новая" in переменныеИсполнителя),
    "Добавление внешней переменной не изменило внутреннее состояние"
);

// ============================================================
// 3. ЗАЩИТА МАССИВА СОБЫТИЙ
// ============================================================

const событияРезультата =
    результат.события;

const количествоСобытий =
    событияРезультата.length;

событияРезультата.pop();

событияРезультата.pop();

const событияИсполнителя =
    исполнитель.получитьСобытия();

проверить(
    событияИсполнителя.length ===
        количествоСобытий,
    "Изменение массива событий результата не изменило внутреннюю историю"
);

// ============================================================
// 4. ЗАЩИТА ВЕРХНЕГО УРОВНЯ СОБЫТИЯ
// ============================================================

const публичныеСобытия =
    исполнитель.получитьСобытия();

const первоеСобытие =
    публичныеСобытия[0];

const исходныйИдентификатор =
    первоеСобытие.идентификатор;

первоеСобытие.идентификатор =
    "ПОДМЕНЁННЫЙ_ИДЕНТИФИКАТ";

const событияПослеИзменения =
    исполнитель.получитьСобытия();

проверить(
    событияПослеИзменения[0]
        .идентификатор ===
        исходныйИдентификатор,
    "Изменение верхнего уровня события не изменило внутреннее событие"
);

// ============================================================
// 5. ПОИСК ВЛОЖЕННЫХ ДАННЫХ
// ============================================================

const событиеСПеременной =
    публичныеСобытия.find(
        событие =>
            событие.тип ===
            "объявление_переменной"
    );

проверить(
    событиеСПеременной !== undefined,
    "Найдено событие объявления переменной"
);

// ============================================================
// 6. ПРОВЕРКА ВЛОЖЕННЫХ ДАННЫХ
// ============================================================

if (
    событиеСПеременной !== undefined &&
    событиеСПеременной.данные !== null &&
    typeof событиеСПеременной.данные ===
        "object"
) {

    const данные =
        событиеСПеременной.данные as Record<
            string,
            unknown
        >;

    const исходноеИмя =
        данные.имя;

    данные.имя =
        "ПОДМЕНА";

    const событияПослеВложенногоИзменения =
        исполнитель.получитьСобытия();

    const повторноеСобытие =
        событияПослеВложенногоИзменения.find(
            событие =>
                событие.тип ===
                "объявление_переменной"
        );

    if (
        повторноеСобытие !== undefined &&
        повторноеСобытие.данные !== null &&
        typeof повторноеСобытие.данные ===
            "object"
    ) {

        const повторныеДанные =
            повторноеСобытие.данные as Record<
                string,
                unknown
            >;

        проверить(
            повторныеДанные.имя ===
                исходноеИмя,
            "Вложенные данные события защищены от внешнего изменения"
        );

    } else {

        проверить(
            false,
            "Повторное событие объявления переменной доступно для проверки"
        );
    }

} else {

    проверить(
        false,
        "Событие объявления содержит объект данных"
    );
}

// ============================================================
// 7. ПРОВЕРКА ТЕКУЩЕГО УЗЛА В СОБЫТИИ
// ============================================================

const событиеСПоказом =
    публичныеСобытия.find(
        событие =>
            событие.тип ===
            "показ"
    );

проверить(
    событиеСПоказом !== undefined,
    "Найдено событие показа"
);

if (
    событиеСПоказом !== undefined &&
    событиеСПоказом.данные !== null &&
    typeof событиеСПоказом.данные ===
        "object"
) {

    const данныеПоказа =
        событиеСПоказом.данные as Record<
            string,
            unknown
        >;

    const текущийУзел =
        данныеПоказа.текущийУзел;

    проверить(
        текущийУзел !== undefined &&
        текущийУзел !== null,
        "Событие показа содержит текущий узел"
    );

    if (
        текущийУзел !== undefined &&
        текущийУзел !== null &&
        typeof текущийУзел === "object"
    ) {

        const узел =
            текущийУзел as Record<
                string,
                unknown
            >;

        const исходныйВид =
            узел.вид;

        узел.вид =
            "ПОДМЕНЁННЫЙ_УЗЕЛ";

        const событияПослеИзмененияУзла =
            исполнитель.получитьСобытия();

        const событиеПоказаПослеИзменения =
            событияПослеИзмененияУзла.find(
                событие =>
                    событие.тип ===
                    "показ"
            );

        if (
            событиеПоказаПослеИзменения !==
                undefined &&
            событиеПоказаПослеИзменения.данные !==
                null &&
            typeof событиеПоказаПослеИзменения.данные ===
                "object"
        ) {

            const данныеПослеИзменения =
                событиеПоказаПослеИзменения.данные as Record<
                    string,
                    unknown
                >;

            const узелПослеИзменения =
                данныеПослеИзменения.текущийУзел;

            if (
                узелПослеИзменения !==
                    undefined &&
                узелПослеИзменения !==
                    null &&
                typeof узелПослеИзменения ===
                    "object"
            ) {

                const повторныйВид =
                    (
                        узелПослеИзменения as Record<
                            string,
                            unknown
                        >
                    ).вид;

                проверить(
                    повторныйВид ===
                        исходныйВид,
                    "Текущий узел события защищён от внешнего изменения"
                );

            } else {

                проверить(
                    false,
                    "Текущий узел события доступен после повторного получения"
                );
            }

        } else {

            проверить(
                false,
                "Событие показа доступно после изменения вложенного узла"
            );
        }
    }
}

// ============================================================
// 8. ПОВТОРНАЯ ПРОВЕРКА СОСТОЯНИЯ ИСПОЛНИТЕЛЯ
// ============================================================

const окончательныйВывод =
    исполнитель.получитьВывод();

const окончательныеПеременные =
    исполнитель.получитьПеременные();

const окончательныеСобытия =
    исполнитель.получитьСобытия();

проверить(
    окончательныйВывод.length === 1 &&
    окончательныйВывод[0] === "Владимир",
    "После всех внешних изменений внутренний вывод полностью сохранён"
);

проверить(
    окончательныеПеременные.имя ===
        "Владимир" &&
    окончательныеПеременные.возраст ===
        42 &&
    !("новая" in окончательныеПеременные),
    "После всех внешних изменений внутренние переменные полностью сохранены"
);

проверить(
    окончательныеСобытия.length ===
        количествоСобытий,
    "После всех внешних изменений внутренняя история событий полностью сохранена"
);

// ============================================================
// ИТОГ
// ============================================================

console.log(
    ""
);

console.log(
    "============================================================"
);

console.log(
    `🐌 Всего проверок: ${всегоПроверок}`
);

console.log(
    `🐌 Успешных: ${успешныхПроверок}`
);

console.log(
    `🐌 Ошибок: ${ошибок}`
);

console.log(
    "============================================================"
);

if (ошибок === 0) {

    console.log(
        "🐌 ✅ ТЕСТ 3.2.2.7 УСПЕШНО ЗАВЕРШЁН."
    );

} else {

    console.error(
        "🐌 ❌ ТЕСТ 3.2.2.7 ОБНАРУЖИЛ ПРОБЛЕМЫ."
    );

    process.exitCode = 1;
}
