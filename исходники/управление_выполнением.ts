import {
    Исполнитель,
    РезультатВыполнения,
    СобытиеИсполнения,
    ЗначениеИсполнения
} from "./исполнитель";

import {
    КонтекстВыполнения
} from "./контекст_выполнения";


// ============================================================
// СОСТОЯНИЕ УПРАВЛЕНИЯ
// ============================================================

export type СостояниеУправления =
    | "ожидание"
    | "выполнение"
    | "приостановлено"
    | "остановлено"
    | "завершено"
    | "ошибка";


// ============================================================
// РЕЗУЛЬТАТ УПРАВЛЕНИЯ
// ============================================================

export interface РезультатУправленияВыполнением {

    успешно: boolean;

    состояние:
        СостояниеУправления;

    результат:
        РезультатВыполнения | null;

    сообщение:
        string | null;
}


// ============================================================
// КЛАСС УПРАВЛЕНИЯ
// ============================================================

export class УправлениеВыполнением {

    // --------------------------------------------------------
    // ОБЪЕКТЫ
    // --------------------------------------------------------

    private readonly исполнитель:
        Исполнитель;

    private readonly контекст:
        КонтекстВыполнения;


    // --------------------------------------------------------
    // СОСТОЯНИЕ
    // --------------------------------------------------------

    private состояние:
        СостояниеУправления =
            "ожидание";


    // --------------------------------------------------------
    // РЕЗУЛЬТАТ
    // --------------------------------------------------------

    private результат:
        РезультатВыполнения | null =
            null;


    // --------------------------------------------------------
    // ОШИБКА
    // --------------------------------------------------------

    private сообщениеОшибки:
        string | null =
            null;


    // ========================================================
    // КОНСТРУКТОР
    // ========================================================

    public constructor(
        исполнитель: Исполнитель,
        контекст: КонтекстВыполнения
    ) {

        this.исполнитель =
            исполнитель;

        this.контекст =
            контекст;

        this.настроитьОбработчикСобытий();
    }


    // ========================================================
    // НАСТРОЙКА ОБРАБОТЧИКА СОБЫТИЙ
    // ========================================================

    private настроитьОбработчикСобытий(): void {

        this.исполнитель.установитьОбработчикСобытий(
            (событие: СобытиеИсполнения) => {

                this.обработатьСобытие(
                    событие
                );
            }
        );
    }


    // ========================================================
    // ОБРАБОТКА СОБЫТИЯ
    // ========================================================

    private обработатьСобытие(
        событие: СобытиеИсполнения
    ): void {

        const события =
            this.контекст.получитьСобытия();


        this.контекст.обновитьСобытия([
            ...события,
            {
                ...событие
            }
        ]);


        if (
            событие.тип ===
            "ошибка"
        ) {

            this.сообщениеОшибки =
                this.извлечьСообщениеОшибки(
                    событие
                );
        }
    }


    // ========================================================
    // ИЗВЛЕЧЕНИЕ СООБЩЕНИЯ ОШИБКИ
    // ========================================================

    private извлечьСообщениеОшибки(
        событие: СобытиеИсполнения
    ): string {

        const данные =
            событие.данные;


        if (
            typeof данные ===
            "object" &&
            данные !== null &&
            "сообщение" in данные
        ) {

            const объект =
                данные as {
                    сообщение?: unknown;
                };


            if (
                typeof объект.сообщение ===
                "string"
            ) {

                return объект.сообщение;
            }
        }


        return "При выполнении программы произошла ошибка.";
    }


    // ========================================================
    // НАЧАТЬ
    // ========================================================

    public начать():
        РезультатУправленияВыполнением {

        if (
            this.состояние ===
            "выполнение"
        ) {

            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    "Выполнение уже запущено."
            };
        }


        if (
            this.состояние ===
            "приостановлено"
        ) {

            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    "Выполнение приостановлено. Используйте продолжить()."
            };
        }


        const дерево =
            this.контекст.получитьДерево();


        if (
            дерево === null
        ) {

            this.состояние =
                "ошибка";


            this.контекст.завершитьСОшибкой();


            this.сообщениеОшибки =
                "Невозможно начать выполнение: AST отсутствует.";


            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    null,
                сообщение:
                    this.сообщениеОшибки
            };
        }


        this.состояние =
            "выполнение";

        this.сообщениеОшибки =
            null;

        this.результат =
            null;


        this.контекст.установитьФазу(
            "выполнение"
        );


        try {

            const результат =
                this.исполнитель.исполнить(
                    дерево
                );


            this.результат =
                результат;


            this.контекст.установитьВыполнение(
                результат
            );


            this.контекст.обновитьВывод(
                результат.вывод
            );


            this.контекст.обновитьПеременные(
                результат.переменные
            );


            this.контекст.обновитьСобытия(
                результат.события
            );


            this.состояние =
                "завершено";


            this.контекст.завершитьУспешно();


            return {
                успешно: true,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    null
            };

        } catch (ошибка) {

            this.состояние =
                "ошибка";


            this.сообщениеОшибки =
                this.получитьТекстОшибки(
                    ошибка
                );


            this.контекст.завершитьСОшибкой();


            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    this.сообщениеОшибки
            };
        }
    }


    // ========================================================
    // ПРИОСТАНОВИТЬ
    // ========================================================

    public приостановить(): boolean {

        if (
            this.состояние !==
            "выполнение"
        ) {

            return false;
        }


        this.состояние =
            "приостановлено";


        return true;
    }


    // ========================================================
    // ПРОДОЛЖИТЬ
    // ========================================================

    public продолжить(): boolean {

        if (
            this.состояние !==
            "приостановлено"
        ) {

            return false;
        }


        this.состояние =
            "выполнение";


        return true;
    }


    // ========================================================
    // ОСТАНОВИТЬ
    // ========================================================

    public остановить(): boolean {

        if (
            this.состояние !==
                "выполнение" &&
            this.состояние !==
                "приостановлено"
        ) {

            return false;
        }


        this.состояние =
            "остановлено";


        return true;
    }


    // ========================================================
    // ПОЛУЧИТЬ СОСТОЯНИЕ
    // ========================================================

    public получитьСостояние():
        СостояниеУправления {

        return this.состояние;
    }


    // ========================================================
    // ПОЛУЧИТЬ КОНТЕКСТ
    // ========================================================

    public получитьКонтекст():
        КонтекстВыполнения {

        return this.контекст;
    }


    // ========================================================
    // ПОЛУЧИТЬ ИСПОЛНИТЕЛЬ
    // ========================================================

    public получитьИсполнитель():
        Исполнитель {

        return this.исполнитель;
    }


    // ========================================================
    // ПОЛУЧИТЬ РЕЗУЛЬТАТ
    // ========================================================

    public получитьРезультат():
        РезультатВыполнения | null {

        if (
            this.результат ===
            null
        ) {

            return null;
        }


        return {
            ...this.результат,

            вывод: [
                ...this.результат.вывод
            ],

            переменные: {
                ...this.результат.переменные
            },

            события:
                this.результат.события.map(
                    событие => ({
                        ...событие
                    })
                )
        };
    }


    // ========================================================
    // ПОЛУЧИТЬ СООБЩЕНИЕ ОШИБКИ
    // ========================================================

    public получитьСообщениеОшибки():
        string | null {

        return this.сообщениеОшибки;
    }


    // ========================================================
    // ПОЛУЧИТЬ ВЫВОД
    // ========================================================

    public получитьВывод():
        string[] {

        return this.контекст.получитьВывод();
    }


    // ========================================================
    // ПОЛУЧИТЬ ПЕРЕМЕННЫЕ
    // ========================================================

    public получитьПеременные():
        Record<
            string,
            ЗначениеИсполнения
        > {

        return this.контекст.получитьПеременные();
    }


    // ========================================================
    // ПОЛУЧИТЬ СОБЫТИЯ
    // ========================================================

    public получитьСобытия():
        СобытиеИсполнения[] {

        return this.контекст.получитьСобытия();
    }


    // ========================================================
    // ПРЕОБРАЗОВАНИЕ ОШИБКИ
    // ========================================================

    private получитьТекстОшибки(
        ошибка: unknown
    ): string {

        if (
            ошибка instanceof Error
        ) {

            return ошибка.message;
        }


        if (
            typeof ошибка ===
            "string"
        ) {

            return ошибка;
        }


        return "Неизвестная ошибка выполнения.";
    }
}


