import {
    Исполнитель,
    РезультатВыполнения,
    СобытиеИсполнения,
    ЗначениеИсполнения,
    СостояниеПошаговогоВыполнения
} from "./исполнитель";

import {
    КонтекстВыполнения
} from "./контекст_выполнения";


// ============================================================
// СОСТОЯНИЕ УПРАВЛЕНИЯ
// ============================================================

export type СостояниеУправления =
    | "ожидание"
    | "выполнение"
    | "приостановлено"
    | "остановлено"
    | "завершено"
    | "ошибка";


// ============================================================
// РЕЗУЛЬТАТ УПРАВЛЕНИЯ
// ============================================================

export interface РезультатУправленияВыполнением {

    успешно: boolean;

    состояние:
        СостояниеУправления;

    результат:
        РезультатВыполнения | null;

    сообщение:
        string | null;
}


// ============================================================
// КЛАСС УПРАВЛЕНИЯ
// ============================================================

export class УправлениеВыполнением {

    // --------------------------------------------------------
    // ОБЪЕКТЫ
    // --------------------------------------------------------

    private readonly исполнитель:
        Исполнитель;

    private readonly контекст:
        КонтекстВыполнения;


    // --------------------------------------------------------
    // СОСТОЯНИЕ
    // --------------------------------------------------------

    private состояние:
        СостояниеУправления =
        "ожидание";


    // --------------------------------------------------------
    // РЕЗУЛЬТАТ
    // --------------------------------------------------------

    private результат:
        РезультатВыполнения | null =
        null;


    // --------------------------------------------------------
    // ОШИБКА
    // --------------------------------------------------------

    private сообщениеОшибки:
        string | null =
        null;


    // ========================================================
    // КОНСТРУКТОР
    // ========================================================

    public constructor(
        исполнитель: Исполнитель,
        контекст: КонтекстВыполнения
    ) {

        this.исполнитель =
            исполнитель;

        this.контекст =
            контекст;

        this.настроитьОбработчикСобытий();
    }


    // ========================================================
    // НАСТРОЙКА ОБРАБОТЧИКА СОБЫТИЙ
    // ========================================================

    private настроитьОбработчикСобытий(): void {

        this.исполнитель.установитьОбработчикСобытий(
            (событие: СобытиеИсполнения) => {

                this.обработатьСобытие(
                    событие
                );
            }
        );
    }


    // ========================================================
    // ОБРАБОТКА СОБЫТИЯ
    // ========================================================

    private обработатьСобытие(
        событие: СобытиеИсполнения
    ): void {

        const события =
            this.контекст.получитьСобытия();


        this.контекст.обновитьСобытия([
            ...события,
            {
                ...событие
            }
        ]);


        if (
            событие.тип ===
            "ошибка"
        ) {

            this.сообщениеОшибки =
                this.извлечьСообщениеОшибки(
                    событие
                );
        }
    }


    // ========================================================
    // ИЗВЛЕЧЕНИЕ СООБЩЕНИЯ ОШИБКИ
    // ========================================================

    private извлечьСообщениеОшибки(
        событие: СобытиеИсполнения
    ): string {

        const данные =
            событие.данные;


        if (
            typeof данные ===
                "object" &&
            данные !== null &&
            "сообщение" in данные
        ) {

            const объект =
                данные as {
                    сообщение?: unknown;
                };


            if (
                typeof объект.сообщение ===
                "string"
            ) {

                return объект.сообщение;
            }
        }


        return "При выполнении программы произошла ошибка.";
    }


    // ========================================================
    // СИНХРОНИЗАЦИЯ РЕЗУЛЬТАТА С КОНТЕКСТОМ
    // ========================================================

    private синхронизироватьРезультатСКонтекстом(
        результат: РезультатВыполнения | null
    ): void {

        if (
            результат ===
            null
        ) {
            return;
        }


        this.результат =
            результат;


        this.контекст.установитьВыполнение(
            результат
        );


        this.контекст.обновитьВывод(
            результат.вывод
        );


        this.контекст.обновитьПеременные(
            результат.переменные
        );


        this.контекст.обновитьСобытия(
            результат.события
        );
    }


    // ========================================================
    // СИНХРОНИЗАЦИЯ РЕЗУЛЬТАТА ИСПОЛНИТЕЛЯ
    // ========================================================

    private получитьИЗаписатьАктуальныйРезультат():
        РезультатВыполнения | null {

        const результат =
            this.исполнитель.получитьРезультат();


        this.синхронизироватьРезультатСКонтекстом(
            результат
        );


        return результат;
    }


    // ========================================================
    // НАЧАТЬ
    // ========================================================

    public начать():
        РезультатУправленияВыполнением {

        if (
            this.состояние ===
            "выполнение"
        ) {

            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    "Выполнение уже запущено."
            };
        }


        if (
            this.состояние ===
            "приостановлено"
        ) {

            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    "Выполнение приостановлено. Используйте продолжить()."
            };
        }


        const дерево =
            this.контекст.получитьДерево();


        if (
            дерево === null
        ) {

            this.состояние =
                "ошибка";


            this.контекст.завершитьСОшибкой();


            this.сообщениеОшибки =
                "Невозможно начать выполнение: AST отсутствует.";


            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    null,
                сообщение:
                    this.сообщениеОшибки
            };
        }


        // ----------------------------------------------------
        // НОВЫЙ ЗАПУСК
        //
        // Старый вывод, переменные, события и результат
        // предыдущего выполнения больше не должны попадать
        // в новое выполнение.
        // ----------------------------------------------------

        this.контекст.начатьНовоеВыполнение();


        this.состояние =
            "выполнение";

        this.сообщениеОшибки =
            null;

        this.результат =
            null;


        try {

            this.исполнитель.начатьПошаговоеВыполнение(
                дерево
            );


            this.синхронизироватьСостояние();


            return {
                успешно: true,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    null
            };

        } catch (ошибка) {

            this.состояние =
                "ошибка";


            this.сообщениеОшибки =
                this.получитьТекстОшибки(
                    ошибка
                );


            this.контекст.завершитьСОшибкой();


            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    this.сообщениеОшибки
            };
        }
    }


    // ========================================================
    // ВЫПОЛНИТЬ ОДИН ШАГ
    // ========================================================

    public выполнитьШаг():
        РезультатУправленияВыполнением {

        if (
            this.состояние !==
                "выполнение" &&
            this.состояние !==
                "приостановлено"
        ) {

            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    "Невозможно выполнить шаг в текущем состоянии."
            };
        }


        try {

            const результат =
                this.исполнитель.выполнитьШаг();


            this.синхронизироватьРезультатСКонтекстом(
                результат
            );


            this.синхронизироватьСостояние();


            const состояниеИсполнителя =
                this.исполнитель
                    .получитьСостояниеПошаговогоВыполнения();


            if (
                состояниеИсполнителя ===
                "завершено"
            ) {

                this.контекст.завершитьУспешно();
            }


            return {
                успешно: true,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    null
            };

        } catch (ошибка) {

            this.состояние =
                "ошибка";


            this.сообщениеОшибки =
                this.получитьТекстОшибки(
                    ошибка
                );


            this.контекст.завершитьСОшибкой();


            return {
                успешно: false,
                состояние:
                    this.состояние,
                результат:
                    this.результат,
                сообщение:
                    this.сообщениеОшибки
            };
        }
    }


    // ========================================================
    // ПРИОСТАНОВИТЬ
    // ========================================================

    public приостановить(): boolean {

        // ----------------------------------------------------
        // Если выполнение уже приостановлено,
        // считаем операцию успешной.
        //
        // Это важно для пошагового режима:
        // выполнитьШаг() после шага само переводит
        // исполнителя в состояние "приостановлено".
        // ----------------------------------------------------

        if (
            this.состояние ===
            "приостановлено"
        ) {

            const состояниеИсполнителя =
                this.исполнитель
                    .получитьСостояниеПошаговогоВыполнения();

            return (
                состояниеИсполнителя ===
                "приостановлено"
            );
        }


        if (
            this.состояние !==
            "выполнение"
        ) {

            return false;
        }


        this.исполнитель.приостановитьПошаговоеВыполнение();


        this.синхронизироватьСостояние();


        const состояниеИсполнителя =
            this.исполнитель
                .получитьСостояниеПошаговогоВыполнения();


        return (
            состояниеИсполнителя ===
            "приостановлено"
        );
    }


    // ========================================================
    // ПРОДОЛЖИТЬ
    // ========================================================

    public продолжить(): boolean {

        if (
            this.состояние !==
            "приостановлено"
        ) {

            return false;
        }


        try {

            this.исполнитель.продолжитьПошаговоеВыполнение();


            // ------------------------------------------------
            // Продолжение в синхронном пошаговом режиме
            // выполняет все оставшиеся команды.
            //
            // Поэтому после возврата из исполнителя
            // необходимо получить именно финальный результат
            // и записать его в контекст.
            // ------------------------------------------------

            this.получитьИЗаписатьАктуальныйРезультат();


            this.синхронизироватьСостояние();


            const состояниеИсполнителя =
                this.исполнитель
                    .получитьСостояниеПошаговогоВыполнения();


            if (
                состояниеИсполнителя ===
                "завершено"
            ) {

                this.контекст.завершитьУспешно();
            }


            return (
                состояниеИсполнителя ===
                "выполнение" ||
                состояниеИсполнителя ===
                "завершено"
            );

        } catch (ошибка) {

            this.состояние =
                "ошибка";


            this.сообщениеОшибки =
                this.получитьТекстОшибки(
                    ошибка
                );


            this.контекст.завершитьСОшибкой();


            return false;
        }
    }


    // ========================================================
    // ОСТАНОВИТЬ
    // ========================================================

    public остановить(): boolean {

        if (
            this.состояние !==
                "выполнение" &&
            this.состояние !==
                "приостановлено"
        ) {

            return false;
        }


        this.исполнитель.остановитьПошаговоеВыполнение();


        this.синхронизироватьСостояние();


        const состояниеИсполнителя =
            this.исполнитель
                .получитьСостояниеПошаговогоВыполнения();


        return (
            состояниеИсполнителя ===
            "остановлено"
        );
    }


    // ========================================================
    // СИНХРОНИЗАЦИЯ СОСТОЯНИЯ
    // ========================================================

    private синхронизироватьСостояние():
        void {

        const состояниеИсполнителя =
            this.исполнитель
                .получитьСостояниеПошаговогоВыполнения();


        // ----------------------------------------------------
        // Ошибка управления может существовать независимо
        // от состояния исполнителя.
        //
        // Например:
        // AST отсутствует → управление = "ошибка",
        // исполнитель при этом остаётся в "ожидание".
        //
        // Нельзя затирать такую ошибку состоянием
        // "ожидание".
        // ----------------------------------------------------

        if (
            this.состояние ===
            "ошибка" &&
            состояниеИсполнителя ===
            "ожидание"
        ) {

            return;
        }


        switch (
            состояниеИсполнителя
        ) {

            case "ожидание":

                this.состояние =
                    "ожидание";

                break;


            case "выполнение":

                this.состояние =
                    "выполнение";

                break;


            case "приостановлено":

                this.состояние =
                    "приостановлено";

                break;


            case "завершено":

                this.состояние =
                    "завершено";

                break;


            case "остановлено":

                this.состояние =
                    "остановлено";

                break;


            case "ошибка":

                this.состояние =
                    "ошибка";

                break;
        }
    }


    // ========================================================
    // ПОЛУЧИТЬ СОСТОЯНИЕ
    // ========================================================

    public получитьСостояние():
        СостояниеУправления {

        this.синхронизироватьСостояние();

        return this.состояние;
    }


    // ========================================================
    // ПОЛУЧИТЬ СОСТОЯНИЕ ИСПОЛНИТЕЛЯ
    // ========================================================

    public получитьСостояниеИсполнителя():
        СостояниеПошаговогоВыполнения {

        return this.исполнитель
            .получитьСостояниеПошаговогоВыполнения();
    }


    // ========================================================
    // ПОЛУЧИТЬ ТЕКУЩИЙ ШАГ
    // ========================================================

    public получитьТекущийШаг():
        number {

        return this.исполнитель
            .получитьТекущийШаг();
    }


    // ========================================================
    // ПОЛУЧИТЬ ТЕКУЩИЙ УЗЕЛ
    // ========================================================

    public получитьТекущийУзел():
        ReturnType<
            Исполнитель["получитьТекущийУзел"]
        > {

        // ----------------------------------------------------
        // Управление выполнением представляет внешний
        // интерфейс пошагового выполнения.
        //
        // После полного завершения текущего шага уже нет:
        // выполнение закончено, поэтому наружу возвращается
        // null.
        //
        // Сам Исполнитель при этом сохраняет последний
        // выполненный узел. Это необходимо для диагностики,
        // истории и проверки фактического места завершения.
        // ----------------------------------------------------

        if (
            this.состояние ===
            "завершено"
        ) {

            return null;
        }


        return this.исполнитель
            .получитьТекущийУзел();
    }


    // ========================================================
    // ПОЛУЧИТЬ КОЛИЧЕСТВО ШАГОВ
    // ========================================================

    public получитьКоличествоШагов():
        number {

        return this.исполнитель
            .получитьКоличествоШагов();
    }


    // ========================================================
    // ПОЛУЧИТЬ КОНТЕКСТ
    // ========================================================

    public получитьКонтекст():
        КонтекстВыполнения {

        return this.контекст;
    }


    // ========================================================
    // ПОЛУЧИТЬ ИСПОЛНИТЕЛЬ
    // ========================================================

    public получитьИсполнитель():
        Исполнитель {

        return this.исполнитель;
    }


    // ========================================================
    // ПОЛУЧИТЬ РЕЗУЛЬТАТ
    // ========================================================

    public получитьРезультат():
        РезультатВыполнения | null {

        if (
            this.результат ===
            null
        ) {

            return null;
        }


        return {
            ...this.результат,

            вывод: [
                ...this.результат.вывод
            ],

            переменные: {
                ...this.результат.переменные
            },

            события:
                this.результат.события.map(
                    событие => ({
                        ...событие
                    })
                )
        };
    }


    // ========================================================
    // ПОЛУЧИТЬ СООБЩЕНИЕ ОШИБКИ
    // ========================================================

    public получитьСообщениеОшибки():
        string | null {

        return this.сообщениеОшибки;
    }


    // ========================================================
    // ПОЛУЧИТЬ ВЫВОД
    // ========================================================

    public получитьВывод():
        string[] {

        return this.контекст.получитьВывод();
    }


    // ========================================================
    // ПОЛУЧИТЬ ПЕРЕМЕННЫЕ
    // ========================================================

    public получитьПеременные():
        Record<
            string,
            ЗначениеИсполнения
        > {

        return this.контекст.получитьПеременные();
    }


    // ========================================================
    // ПОЛУЧИТЬ СОБЫТИЯ
    // ========================================================

    public получитьСобытия():
        СобытиеИсполнения[] {

        return this.контекст.получитьСобытия();
    }


    // ========================================================
    // ПРЕОБРАЗОВАНИЕ ОШИБКИ
    // ========================================================

    private получитьТекстОшибки(
        ошибка: unknown
    ): string {

        if (
            ошибка instanceof Error
        ) {

            return ошибка.message;
        }


        if (
            typeof ошибка ===
            "string"
        ) {

            return ошибка;
        }


        return "Неизвестная ошибка выполнения.";
    }
}


