import {
    создатьЕдинуюВнутреннююМодель
} from "./модель/единая_внутренняя_модель.js";

import type {
    Число
} from "./дерево/узлы.js";

import type {
    Символ,
    ТипЗначения
} from "./семантика/типы.js";

// ============================================================
// 🐌 УЛИТКА
// Тест единой внутренней модели программы
// ============================================================

let всего = 0;
let прошло = 0;
let ошибок = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всего++;

    if (условие) {
        прошло++;

        console.log(
            `✅ ${сообщение}`
        );

    } else {
        ошибок++;

        console.error(
            `❌ ${сообщение}`
        );
    }
}

// ============================================================
// ТЕСТОВЫЕ ДАННЫЕ
// ============================================================

const число: Число = {
    вид: "ЧИСЛО",
    значение: 42
};

const дерево = [
    число
];

const символ: Символ = {
    имя: "ответ",
    вид: "переменная",
    тип: "число",
    инициализирован: true
};

const типыУзлов = new Map<
    object,
    ТипЗначения
>();

типыУзлов.set(
    число,
    "число"
);

// ============================================================
// СОЗДАНИЕ МОДЕЛИ
// ============================================================

const модель =
    создатьЕдинуюВнутреннююМодель({

        имяПрограммы:
            "тестовая_программа",

        дерево,

        глобальныеСимволы:
            [символ],

        типыУзлов,

        ошибки:
            [],

        успешно:
            true
    });

// ============================================================
// ПРОВЕРКА ИМЕНИ
// ============================================================

проверить(
    модель.получитьИмяПрограммы() ===
        "тестовая_программа",
    "Имя программы сохранено."
);

// ============================================================
// ПРОВЕРКА AST
// ============================================================

проверить(
    модель.получитьДерево()[0] === число,
    "AST сохранён в модели."
);

// ============================================================
// ПРОВЕРКА СИМВОЛОВ
// ============================================================

const символы =
    модель.получитьГлобальныеСимволы();

проверить(
    символы.length === 1,
    "Глобальные символы сохранены."
);

проверить(
    символы[0]?.имя === "ответ",
    "Имя глобального символа сохранено."
);

проверить(
    символы[0]?.тип === "число",
    "Тип глобального символа сохранён."
);

// ============================================================
// ПРОВЕРКА ТИПА AST-УЗЛА
// ============================================================

проверить(
    модель.получитьТипУзла(число) ===
        "число",
    "Тип конкретного AST-узла сохранён."
);

// ============================================================
// ПРОВЕРКА НЕИЗВЕСТНОГО УЗЛА
// ============================================================

const неизвестныйОбъект = {};

проверить(
    модель.получитьТипУзла(
        неизвестныйОбъект
    ) === "неизвестно",
    "Для неизвестного AST-узла возвращается «неизвестно»."
);

// ============================================================
// ПРОВЕРКА ОШИБОК
// ============================================================

проверить(
    модель.получитьОшибки().length === 0,
    "Ошибки семантики сохранены."
);

// ============================================================
// ПРОВЕРКА УСПЕШНОСТИ
// ============================================================

проверить(
    модель.успешна() === true,
    "Успешность модели сохранена."
);

// ============================================================
// ПРОВЕРКА НЕЗАВИСИМОСТИ МАССИВА СИМВОЛОВ
// ============================================================

символы.push({
    имя: "лишний",
    вид: "переменная",
    тип: "текст",
    инициализирован: true
});

проверить(
    модель.получитьГлобальныеСимволы().length === 1,
    "Полученный список символов нельзя изменить снаружи."
);

// ============================================================
// ПРОВЕРКА ПОЛНЫХ ДАННЫХ
// ============================================================

const данные =
    модель.получитьДанные();

проверить(
    данные.имяПрограммы ===
        "тестовая_программа",
    "Полные данные содержат имя программы."
);

проверить(
    данные.дерево[0] === число,
    "Полные данные содержат AST."
);

проверить(
    данные.глобальныеСимволы.length === 1,
    "Полные данные содержат глобальные символы."
);

проверить(
    данные.типыУзлов.get(число) ===
        "число",
    "Полные данные содержат типы AST-узлов."
);

проверить(
    данные.ошибки.length === 0,
    "Полные данные содержат ошибки семантики."
);

проверить(
    данные.успешно === true,
    "Полные данные содержат состояние успешности."
);

// ============================================================
// ИТОГ
// ============================================================

console.log("");

console.log(
    "============================================================"
);

console.log(
    "🐌 ТЕСТ ЕДИНОЙ ВНУТРЕННЕЙ МОДЕЛИ"
);

console.log(
    "============================================================"
);

console.log(
    `Всего проверок: ${всего}`
);

console.log(
    `Прошло: ${прошло}`
);

console.log(
    `Ошибок: ${ошибок}`
);

console.log(
    "============================================================"
);

if (ошибок > 0) {
    process.exitCode = 1;
}
