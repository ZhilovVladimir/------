// ============================================================
// 🐌 УЛИТКА — СНИМОК 3D-СОСТОЯНИЯ
// Полная независимая копия состояния 3D-ядра
// ============================================================

import type {
    СостояниеПрограммы
} from "./состояние_программы";

import type {
    УзелСистемы
} from "./узел_системы";

import type {
    СвязьСистемы
} from "./связь_системы";

import type {
    СобытиеСистемы
} from "./события_системы";

// ============================================================
// РЕЖИМ ВОСПРОИЗВЕДЕНИЯ СНИМКА
// ============================================================

export type РежимСнимка3D =
    | "остановлено"
    | "воспроизведение";

// ============================================================
// ПОЛНАЯ СТРУКТУРА СНИМКА
// ============================================================

export interface Снимок3D {

    // Полное состояние программы
    состояние: СостояниеПрограммы;

    // Все визуальные узлы
    узлы: УзелСистемы[];

    // Все связи между узлами
    связи: СвязьСистемы[];

    // Текущая позиция в истории событий
    текущаяПозицияИстории: number;

    // Количество событий в истории
    количествоСобытий: number;

    // Текущий режим воспроизведения
    режимВоспроизведения: РежимСнимка3D;

    // Событие, на котором находится снимок.
    // Поле необязательное, потому что старые
    // снимки ядра могут его не содержать.
    текущееСобытие?: СобытиеСистемы | null;
}

// ============================================================
// СОЗДАНИЕ ПОЛНОГО СНИМКА 3D-СОСТОЯНИЯ
// ============================================================

export function создатьСнимок3D(
    состояние: СостояниеПрограммы,
    узлы: УзелСистемы[],
    связи: СвязьСистемы[],
    текущаяПозицияИстории: number,
    режимВоспроизведения: РежимСнимка3D,
    текущееСобытие: СобытиеСистемы | null = null,
    количествоСобытий: number = 0
): Снимок3D {

    return {
        состояние:
            structuredClone(состояние),

        узлы:
            structuredClone(узлы),

        связи:
            structuredClone(связи),

        текущаяПозицияИстории,

        количествоСобытий,

        режимВоспроизведения,

        текущееСобытие:
            текущееСобытие === null
                ? null
                : structuredClone(
                    текущееСобытие
                )
    };
}

// ============================================================
// КЛОНИРОВАНИЕ СУЩЕСТВУЮЩЕГО СНИМКА
// ============================================================

export function клонироватьСнимок3D(
    снимок: Снимок3D
): Снимок3D {

    return structuredClone(
        снимок
    );
}

// ============================================================
// ПРОВЕРКА СНИМКА
// ============================================================

export function проверитьСнимок3D(
    снимок: Снимок3D
): boolean {

    if (!снимок) {
        return false;
    }

    if (!снимок.состояние) {
        return false;
    }

    if (!Array.isArray(снимок.узлы)) {
        return false;
    }

    if (!Array.isArray(снимок.связи)) {
        return false;
    }

    if (
        typeof снимок.текущаяПозицияИстории !==
        "number"
    ) {
        return false;
    }

    if (
        typeof снимок.количествоСобытий !==
        "number"
    ) {
        return false;
    }

    if (
        снимок.количествоСобытий < 0
    ) {
        return false;
    }

    if (
        снимок.режимВоспроизведения !==
            "остановлено" &&
        снимок.режимВоспроизведения !==
            "воспроизведение"
    ) {
        return false;
    }

    if (
        снимок.текущееСобытие !== undefined &&
        снимок.текущееСобытие !== null &&
        typeof снимок.текущееСобытие !==
            "object"
    ) {
        return false;
    }

    return true;
}

// ============================================================
// ПОЛУЧЕНИЕ КОЛИЧЕСТВА УЗЛОВ
// ============================================================

export function получитьКоличествоУзловСнимка(
    снимок: Снимок3D
): number {

    return снимок.узлы.length;
}

// ============================================================
// ПОЛУЧЕНИЕ КОЛИЧЕСТВА СВЯЗЕЙ
// ============================================================

export function получитьКоличествоСвязейСнимка(
    снимок: Снимок3D
): number {

    return снимок.связи.length;
}

// ============================================================
// ПОЛУЧЕНИЕ КОЛИЧЕСТВА СОБЫТИЙ
// ============================================================

export function получитьКоличествоСобытийСнимка(
    снимок: Снимок3D
): number {

    return снимок.количествоСобытий;
}

// ============================================================
// ПОЛУЧЕНИЕ ПОЗИЦИИ ИСТОРИИ
// ============================================================

export function получитьПозициюИсторииСнимка(
    снимок: Снимок3D
): number {

    return снимок.текущаяПозицияИстории;
}

// ============================================================
// ПОЛУЧЕНИЕ ТЕКУЩЕГО СОБЫТИЯ
// ============================================================

export function получитьТекущееСобытиеСнимка(
    снимок: Снимок3D
): СобытиеСистемы | null {

    if (
        снимок.текущееСобытие === undefined
    ) {
        return null;
    }

    return снимок.текущееСобытие;
}

