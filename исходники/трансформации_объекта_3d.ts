import {
    Объект3D,
    Позиция3D,
    Поворот3D,
    Масштаб3D,
    Трансформация3D,
    установитьПозицию3D,
    установитьПоворот3D,
    установитьМасштаб3D
} from "./объект_3d";

// ============================================================
// Результат операции
// ============================================================

export interface РезультатТрансформации3D {
    успешно: boolean;
    сообщение: string;
    трансформация: Трансформация3D;
}

// ============================================================
// Событие изменения трансформации
// ============================================================

export type ТипИзмененияТрансформации3D =
    | "позиция"
    | "поворот"
    | "масштаб"
    | "трансформация";

export interface СобытиеТрансформации3D {
    идентификаторОбъекта: string;
    тип: ТипИзмененияТрансформации3D;
    предыдущаяТрансформация: Трансформация3D;
    новаяТрансформация: Трансформация3D;
    время: number;
}

// ============================================================
// Обработчик события
// ============================================================

export type ОбработчикТрансформации3D =
    (
        событие: СобытиеТрансформации3D
    ) => void;

// ============================================================
// Проверка числового значения
// ============================================================

export function проверитьЧисло3D(
    значение: number
): boolean {
    return (
        typeof значение === "number" &&
        Number.isFinite(значение)
    );
}

// ============================================================
// Проверка позиции
// ============================================================

export function проверитьПозицию3D(
    позиция: Позиция3D
): boolean {
    if (!позиция) {
        return false;
    }

    return (
        проверитьЧисло3D(позиция.x) &&
        проверитьЧисло3D(позиция.y) &&
        проверитьЧисло3D(позиция.z)
    );
}

// ============================================================
// Проверка поворота
// ============================================================

export function проверитьПоворот3D(
    поворот: Поворот3D
): boolean {
    if (!поворот) {
        return false;
    }

    return (
        проверитьЧисло3D(поворот.x) &&
        проверитьЧисло3D(поворот.y) &&
        проверитьЧисло3D(поворот.z)
    );
}

// ============================================================
// Проверка масштаба
// ============================================================

export function проверитьМасштаб3D(
    масштаб: Масштаб3D
): boolean {
    if (!масштаб) {
        return false;
    }

    return (
        проверитьЧисло3D(масштаб.x) &&
        проверитьЧисло3D(масштаб.y) &&
        проверитьЧисло3D(масштаб.z) &&
        масштаб.x > 0 &&
        масштаб.y > 0 &&
        масштаб.z > 0
    );
}

// ============================================================
// Проверка полной трансформации
// ============================================================

export function проверитьТрансформацию3D(
    трансформация: Трансформация3D
): boolean {
    if (!трансформация) {
        return false;
    }

    return (
        проверитьПозицию3D(
            трансформация.позиция
        ) &&
        проверитьПоворот3D(
            трансформация.поворот
        ) &&
        проверитьМасштаб3D(
            трансформация.масштаб
        )
    );
}

// ============================================================
// Клонирование трансформации
// ============================================================

export function клонироватьТрансформацию3D(
    трансформация: Трансформация3D
): Трансформация3D {
    return structuredClone(
        трансформация
    );
}

// ============================================================
// Создание результата
// ============================================================

function создатьРезультат(
    успешно: boolean,
    сообщение: string,
    трансформация: Трансформация3D
): РезультатТрансформации3D {
    return {
        успешно,
        сообщение,
        трансформация:
            клонироватьТрансформацию3D(
                трансформация
            )
    };
}

// ============================================================
// Менеджер трансформаций
// ============================================================

export class МенеджерТрансформацийОбъектов3D {

    private обработчики:
        ОбработчикТрансформации3D[] = [];

    // ========================================================
    // Обработчики событий
    // ========================================================

    добавитьОбработчик(
        обработчик: ОбработчикТрансформации3D
    ): void {
        if (
            this.обработчики.includes(
                обработчик
            )
        ) {
            return;
        }

        this.обработчики.push(
            обработчик
        );
    }

    удалитьОбработчик(
        обработчик: ОбработчикТрансформации3D
    ): void {
        this.обработчики =
            this.обработчики.filter(
                текущий =>
                    текущий !== обработчик
            );
    }

    очиститьОбработчики(): void {
        this.обработчики = [];
    }

    // ========================================================
    // Получение трансформации
    // ========================================================

    получитьТрансформацию(
        объект: Объект3D
    ): Трансформация3D {
        return клонироватьТрансформацию3D(
            объект.трансформация
        );
    }

    // ========================================================
    // Установка позиции
    // ========================================================

    установитьПозицию(
        объект: Объект3D,
        x: number,
        y: number,
        z: number
    ): РезультатТрансформации3D {

        if (
            !проверитьЧисло3D(x) ||
            !проверитьЧисло3D(y) ||
            !проверитьЧисло3D(z)
        ) {
            return создатьРезультат(
                false,
                "Позиция содержит недопустимое числовое значение.",
                объект.трансформация
            );
        }

        const предыдущая =
            клонироватьТрансформацию3D(
                объект.трансформация
            );

        установитьПозицию3D(
            объект,
            x,
            y,
            z
        );

        this.сообщитьОбИзменении(
            объект,
            "позиция",
            предыдущая
        );

        return создатьРезультат(
            true,
            "Позиция объекта изменена.",
            объект.трансформация
        );
    }

    // ========================================================
    // Перемещение относительно текущей позиции
    // ========================================================

    переместить(
        объект: Объект3D,
        x: number,
        y: number,
        z: number
    ): РезультатТрансформации3D {

        if (
            !проверитьЧисло3D(x) ||
            !проверитьЧисло3D(y) ||
            !проверитьЧисло3D(z)
        ) {
            return создатьРезультат(
                false,
                "Смещение содержит недопустимое числовое значение.",
                объект.трансформация
            );
        }

        const текущая =
            объект.трансформация.позиция;

        return this.установитьПозицию(
            объект,
            текущая.x + x,
            текущая.y + y,
            текущая.z + z
        );
    }

    // ========================================================
    // Установка поворота
    // ========================================================

    установитьПоворот(
        объект: Объект3D,
        x: number,
        y: number,
        z: number
    ): РезультатТрансформации3D {

        if (
            !проверитьЧисло3D(x) ||
            !проверитьЧисло3D(y) ||
            !проверитьЧисло3D(z)
        ) {
            return создатьРезультат(
                false,
                "Поворот содержит недопустимое числовое значение.",
                объект.трансформация
            );
        }

        const предыдущая =
            клонироватьТрансформацию3D(
                объект.трансформация
            );

        установитьПоворот3D(
            объект,
            x,
            y,
            z
        );

        this.сообщитьОбИзменении(
            объект,
            "поворот",
            предыдущая
        );

        return создатьРезультат(
            true,
            "Поворот объекта изменён.",
            объект.трансформация
        );
    }

    // ========================================================
    // Вращение относительно текущего поворота
    // ========================================================

    повернуть(
        объект: Объект3D,
        x: number,
        y: number,
        z: number
    ): РезультатТрансформации3D {

        if (
            !проверитьЧисло3D(x) ||
            !проверитьЧисло3D(y) ||
            !проверитьЧисло3D(z)
        ) {
            return создатьРезультат(
                false,
                "Изменение поворота содержит недопустимое числовое значение.",
                объект.трансформация
            );
        }

        const текущий =
            объект.трансформация.поворот;

        return this.установитьПоворот(
            объект,
            текущий.x + x,
            текущий.y + y,
            текущий.z + z
        );
    }

    // ========================================================
    // Установка масштаба
    // ========================================================

    установитьМасштаб(
        объект: Объект3D,
        x: number,
        y: number,
        z: number
    ): РезультатТрансформации3D {

        const масштаб: Масштаб3D = {
            x,
            y,
            z
        };

        if (
            !проверитьМасштаб3D(
                масштаб
            )
        ) {
            return создатьРезультат(
                false,
                "Масштаб должен содержать конечные числа больше нуля.",
                объект.трансформация
            );
        }

        const предыдущая =
            клонироватьТрансформацию3D(
                объект.трансформация
            );

        установитьМасштаб3D(
            объект,
            x,
            y,
            z
        );

        this.сообщитьОбИзменении(
            объект,
            "масштаб",
            предыдущая
        );

        return создатьРезультат(
            true,
            "Масштаб объекта изменён.",
            объект.трансформация
        );
    }

    // ========================================================
    // Изменение масштаба относительно текущего
    // ========================================================

    изменитьМасштаб(
        объект: Объект3D,
        x: number,
        y: number,
        z: number
    ): РезультатТрансформации3D {

        if (
            !проверитьМасштаб3D({
                x,
                y,
                z
            })
        ) {
            return создатьРезультат(
                false,
                "Коэффициенты масштаба должны быть конечными числами больше нуля.",
                объект.трансформация
            );
        }

        const текущий =
            объект.трансформация.масштаб;

        return this.установитьМасштаб(
            объект,
            текущий.x * x,
            текущий.y * y,
            текущий.z * z
        );
    }

    // ========================================================
    // Установка полной трансформации
    // ========================================================

    установитьТрансформацию(
        объект: Объект3D,
        трансформация: Трансформация3D
    ): РезультатТрансформации3D {

        if (
            !проверитьТрансформацию3D(
                трансформация
            )
        ) {
            return создатьРезультат(
                false,
                "Трансформация содержит недопустимые значения.",
                объект.трансформация
            );
        }

        const предыдущая =
            клонироватьТрансформацию3D(
                объект.трансформация
            );

        объект.трансформация =
            клонироватьТрансформацию3D(
                трансформация
            );

        this.сообщитьОбИзменении(
            объект,
            "трансформация",
            предыдущая
        );

        return создатьРезультат(
            true,
            "Полная трансформация объекта изменена.",
            объект.трансформация
        );
    }

    // ========================================================
    // Проверка возможности изменения
    // ========================================================

    можноУстановитьПозицию(
        x: number,
        y: number,
        z: number
    ): boolean {
        return (
            проверитьЧисло3D(x) &&
            проверитьЧисло3D(y) &&
            проверитьЧисло3D(z)
        );
    }

    можноУстановитьПоворот(
        x: number,
        y: number,
        z: number
    ): boolean {
        return (
            проверитьЧисло3D(x) &&
            проверитьЧисло3D(y) &&
            проверитьЧисло3D(z)
        );
    }

    можноУстановитьМасштаб(
        x: number,
        y: number,
        z: number
    ): boolean {
        return проверитьМасштаб3D({
            x,
            y,
            z
        });
    }

    // ========================================================
    // Внутренняя отправка события
    // ========================================================

    private сообщитьОбИзменении(
        объект: Объект3D,
        тип: ТипИзмененияТрансформации3D,
        предыдущаяТрансформация:
            Трансформация3D
    ): void {

        const событие:
            СобытиеТрансформации3D = {
                идентификаторОбъекта:
                    объект.идентификатор,
                тип,
                предыдущаяТрансформация:
                    клонироватьТрансформацию3D(
                        предыдущаяТрансформация
                    ),
                новаяТрансформация:
                    клонироватьТрансформацию3D(
                        объект.трансформация
                    ),
                время: Date.now()
            };

        for (
            const обработчик
            of this.обработчики
        ) {
            обработчик(
                событие
            );
        }
    }
}