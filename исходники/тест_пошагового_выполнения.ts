// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {
    всегоПроверок++;

    if (условие) {
        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибок++;

    console.log(
        `❌ ${сообщение}`
    );
}

