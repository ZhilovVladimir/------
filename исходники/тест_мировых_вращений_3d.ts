let количествоТестов = 0;
let количествоОшибок = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {
    количествоТестов++;

    if (условие) {
        console.log(`✓ ${сообщение}`);
    } else {
        количествоОшибок++;
        console.error(`✗ ОШИБКА: ${сообщение}`);
    }
}

function почтиРавно(
    первое: number,
    второе: number,
    точность = 0.000001
): boolean {
    return Math.abs(первое - второе) < точность;
}

function точкиРавны(
    первое: { x: number; y: number; z: number },
    второе: { x: number; y: number; z: number }
): boolean {
    return (
        почтиРавно(первое.x, второе.x) &&
        почтиРавно(первое.y, второе.y) &&
        почтиРавно(первое.z, второе.z)
    );
}

function поворотыРавны(
    первое: { x: number; y: number; z: number },
    второе: { x: number; y: number; z: number }
): boolean {
    return (
        почтиРавно(первое.x, второе.x) &&
        почтиРавно(первое.y, второе.y) &&
        почтиРавно(первое.z, второе.z)
    );
}

function масштабыРавны(
    первое: { x: number; y: number; z: number },
    второе: { x: number; y: number; z: number }
): boolean {
    return (
        почтиРавно(первое.x, второе.x) &&
        почтиРавно(первое.y, второе.y) &&
        почтиРавно(первое.z, второе.z)
    );
}

