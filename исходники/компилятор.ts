// ============================================================
// 🐌 УЛИТКА
// Единый конвейер компиляции и выполнения
// ============================================================

import {
    разобрать
} from "./лексический_анализатор.js";

import {
    Парсер
} from "./ядро/парсер.js";

import {
    СемантическийАнализатор
} from "./семантика/семантический_анализатор.js";

import {
    КонтекстВыполнения
} from "./контекст_выполнения.js";

import type {
    Узел
} from "./дерево/узлы.js";

import {
    Исполнитель
} from "./исполнитель.js";

import type {
    РезультатВыполнения,
    СобытиеИсполнения
} from "./исполнитель.js";

import type {
    ОшибкаСемантики,
    Символ
} from "./семантика/типы.js";

import type {
    СнимокКонтекста
} from "./контекст_выполнения.js";

import {
    создатьЕдинуюВнутреннююМодель,
    получитьИмяПрограммыИзДерева
} from "./модель/единая_внутренняя_модель.js";

import type {
    ЕдинаяВнутренняяМодельПрограммы
} from "./модель/единая_внутренняя_модель.js";

// ============================================================
// РЕЗУЛЬТАТ ПОДГОТОВКИ
// ============================================================

export interface РезультатПодготовки {

    дерево: Узел[];
}

// ============================================================
// РЕЗУЛЬТАТ КОМПИЛЯЦИИ
// ============================================================

export interface РезультатКомпиляции {

    успешно: boolean;

    дерево: Узел[] | null;

    модель:
        ЕдинаяВнутренняяМодельПрограммы | null;

    семантика: {

        ошибки: ОшибкаСемантики[];

        глобальныеСимволы: Символ[];
    };

    выполнение:
        РезультатВыполнения | null;

    контекст:
        СнимокКонтекста;
}

// ============================================================
// КОМПИЛЯТОР
// ============================================================

export class Компилятор {

    private readonly семантическийАнализатор:
        СемантическийАнализатор;

    private readonly исполнитель:
        Исполнитель;

    private текущаяМодель:
        ЕдинаяВнутренняяМодельПрограммы | null =
            null;

    private текущийКонтекст:
        КонтекстВыполнения | null = null;

    private обработчикСобытий:
        ((событие: СобытиеИсполнения) => void) | null =
            null;

    public constructor() {

        this.семантическийАнализатор =
            new СемантическийАнализатор();

        this.исполнитель =
            new Исполнитель();

        // ----------------------------------------------------
        // Исполнитель всегда работает через единый
        // внутренний диспетчер событий.
        //
        // Благодаря этому внешний обработчик, например
        // 3D-интегратор, подключается через Компилятор,
        // не перезаписывая внутренний механизм.
        // ----------------------------------------------------

        this.исполнитель
            .установитьОбработчикСобытий(
                событие => {

                    this.распространитьСобытие(
                        событие
                    );
                }
            );
    }

    // ========================================================
    // ПОЛУЧИТЬ ИСПОЛНИТЕЛЬ
    // ========================================================

    /**
     * Возвращает единственный Исполнитель,
     * принадлежащий этому Компилятору.
     *
     * Центральная 3D-система использует именно этот
     * экземпляр и не создаёт второго Исполнителя.
     */
    public получитьИсполнитель():
        Исполнитель {

        return this.исполнитель;
    }

    // ========================================================
    // ПОЛУЧИТЬ ВНУТРЕННЮЮ МОДЕЛЬ
    // ========================================================

    /**
     * Возвращает последнюю созданную
     * единую внутреннюю модель программы.
     *
     * Модель появляется после успешного построения AST
     * и семантического анализа.
     */
    public получитьМодель():
        ЕдинаяВнутренняяМодельПрограммы | null {

        return this.текущаяМодель;
    }

    // ========================================================
    // ПОДГОТОВКА
    // ========================================================

    public подготовить(
        код: string
    ): РезультатПодготовки {

        const лексемы =
            разобрать(
                код
            );

        const парсер =
            new Парсер(
                лексемы
            );

        const дерево =
            парсер.разобрать();

        return {
            дерево
        };
    }

    // ========================================================
    // СОЗДАТЬ ВНУТРЕННЮЮ МОДЕЛЬ
    // ========================================================

    private создатьМодель(
        дерево: Узел[],
        ошибки: ОшибкаСемантики[],
        глобальныеСимволы: Символ[],
        успешно: boolean
    ):
        ЕдинаяВнутренняяМодельПрограммы {

        const имяПрограммы =
            получитьИмяПрограммыИзДерева(
                дерево
            );

        const типыУзлов =
            this.семантическийАнализатор
                .получитьТипыУзлов();

        const модель =
            создатьЕдинуюВнутреннююМодель({

                имяПрограммы,

                дерево,

                глобальныеСимволы,

                типыУзлов,

                ошибки,

                успешно
            });

        this.текущаяМодель =
            модель;

        return модель;
    }

    // ========================================================
    // СОЗДАТЬ КОНТЕКСТ
    // ========================================================

    private создатьКонтекст(
        код: string
    ): КонтекстВыполнения {

        const контекст =
            new КонтекстВыполнения(
                код
            );

        this.текущийКонтекст =
            контекст;

        return контекст;
    }

    // ========================================================
    // ПОЛУЧИТЬ ТЕКУЩИЙ КОНТЕКСТ
    // ========================================================

    public получитьКонтекст():
        СнимокКонтекста | null {

        if (
            this.текущийКонтекст === null
        ) {

            return null;
        }

        return this.текущийКонтекст
            .получитьСнимок();
    }

    // ========================================================
    // РАСПРОСТРАНИТЬ СОБЫТИЕ
    // ========================================================

    private распространитьСобытие(
        событие: СобытиеИсполнения
    ): void {

        // ----------------------------------------------------
        // Сначала обновляем единый контекст.
        // ----------------------------------------------------

        if (
            this.текущийКонтекст !== null
        ) {

            const события =
                this.текущийКонтекст
                    .получитьСобытия();

            this.текущийКонтекст
                .обновитьСобытия(
                    [
                        ...события,
                        событие
                    ]
                );
        }

        // ----------------------------------------------------
        // Затем передаём событие наружу.
        //
        // Например:
        //
        // Компилятор → Интегратор3D
        // ----------------------------------------------------

        if (
            this.обработчикСобытий !== null
        ) {

            this.обработчикСобытий(
                событие
            );
        }
    }

    // ========================================================
    // ПРОВЕРКА
    // ========================================================

    public проверить(
        код: string
    ): РезультатКомпиляции {

        const контекст =
            this.создатьКонтекст(
                код
            );

        this.текущаяМодель =
            null;

        try {

            контекст.установитьФазу(
                "лексический_анализ"
            );

            контекст.добавитьДиагностику(
                "система",
                "Начат единый компиляционный конвейер."
            );

            const лексемы =
                разобрать(
                    код
                );

            контекст.установитьФазу(
                "синтаксический_анализ"
            );

            const парсер =
                new Парсер(
                    лексемы
                );

            const дерево =
                парсер.разобрать();

            контекст.установитьДерево(
                дерево
            );

            контекст.установитьФазу(
                "семантический_анализ"
            );

            const результатСемантики =
                this.семантическийАнализатор
                    .анализировать(
                        дерево
                    );

            контекст.установитьСемантику(
                результатСемантики.ошибки,
                результатСемантики
                    .глобальныеСимволы
            );

            const модель =
                this.создатьМодель(
                    дерево,
                    результатСемантики.ошибки,
                    результатСемантики
                        .глобальныеСимволы,
                    результатСемантики.успешно
                );

            if (
                !результатСемантики.успешно
            ) {

                for (
                    const ошибка
                    of результатСемантики.ошибки
                ) {

                    контекст.добавитьДиагностику(
                        "семантика",
                        ошибка.сообщение
                    );
                }

                контекст.завершитьСОшибкой();

            } else {

                контекст.установитьФазу(
                    "готово_к_выполнению"
                );
            }

            return {

                успешно:
                    результатСемантики.успешно,

                дерево,

                модель,

                семантика: {

                    ошибки:
                        результатСемантики
                            .ошибки,

                    глобальныеСимволы:
                        результатСемантики
                            .глобальныеСимволы
                },

                выполнение:
                    null,

                контекст:
                    контекст
                        .получитьСнимок()
            };

        } catch (ошибка: unknown) {

            const сообщение =
                ошибка instanceof Error
                    ? ошибка.message
                    : String(ошибка);

            this.текущаяМодель =
                null;

            контекст.добавитьДиагностику(
                "система",
                сообщение
            );

            контекст.добавитьДиагностику(
                "синтаксис",
                сообщение
            );

            контекст.завершитьСОшибкой();

            return {

                успешно: false,

                дерево:
                    контекст
                        .получитьДерево(),

                модель:
                    null,

                семантика:
                    контекст
                        .получитьСемантику(),

                выполнение:
                    null,

                контекст:
                    контекст
                        .получитьСнимок()
            };
        }
    }

    // ========================================================
    // ПОЛНОЕ ВЫПОЛНЕНИЕ
    // ========================================================

    public выполнить(
        код: string
    ): РезультатКомпиляции {

        const проверка =
            this.проверить(
                код
            );

        const контекст =
            this.текущийКонтекст!;

        if (
            !проверка.успешно
        ) {

            return {

                успешно: false,

                дерево:
                    проверка.дерево,

                модель:
                    проверка.модель,

                семантика:
                    проверка.семантика,

                выполнение:
                    null,

                контекст:
                    контекст
                        .получитьСнимок()
            };
        }

        try {

            контекст.установитьФазу(
                "готово_к_выполнению"
            );

            контекст.добавитьДиагностику(
                "система",
                "Семантическая проверка пройдена."
            );

            контекст.установитьФазу(
                "выполнение"
            );

            // ------------------------------------------------
            // Обработчик Исполнителя уже установлен
            // в конструкторе Компилятора.
            //
            // Его не нужно переустанавливать перед запуском.
            // ------------------------------------------------

            const выполнение =
                this.исполнитель.исполнить(
                    проверка.дерево!
                );

            контекст.установитьВыполнение(
                выполнение
            );

            контекст.обновитьВывод(
                выполнение.вывод
            );

            контекст.обновитьПеременные(
                выполнение.переменные
            );

            контекст.обновитьСобытия(
                выполнение.события
            );

            контекст.добавитьДиагностику(
                "система",
                "Выполнение программы завершено успешно."
            );

            контекст.завершитьУспешно();

            return {

                успешно: true,

                дерево:
                    проверка.дерево,

                модель:
                    проверка.модель,

                семантика:
                    проверка.семантика,

                выполнение,

                контекст:
                    контекст
                        .получитьСнимок()
            };

        } catch (ошибка: unknown) {

            const сообщение =
                ошибка instanceof Error
                    ? ошибка.message
                    : String(ошибка);

            контекст.добавитьДиагностику(
                "выполнение",
                сообщение
            );

            контекст.завершитьСОшибкой();

            return {

                успешно: false,

                дерево:
                    проверка.дерево,

                модель:
                    проверка.модель,

                семантика:
                    проверка.семантика,

                выполнение:
                    null,

                контекст:
                    контекст
                        .получитьСнимок()
            };
        }
    }

    // ========================================================
    // ВНЕШНИЙ ОБРАБОТЧИК СОБЫТИЙ
    // ========================================================

    public установитьОбработчикСобытий(
        обработчик:
            ((событие: СобытиеИсполнения) => void)
            | null
    ): void {

        this.обработчикСобытий =
            обработчик;
    }
}
