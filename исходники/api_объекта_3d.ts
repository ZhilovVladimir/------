import {
    type Объект3D,
    type СостояниеОбъекта3D,
    type Позиция3D,
    type Поворот3D,
    type Масштаб3D,
    type Трансформация3D,
    клонироватьОбъект3D,
    проверитьОбъект3D,
    установитьПозицию3D,
    установитьПоворот3D,
    установитьМасштаб3D,
    установитьСостояниеОбъекта3D,
    активироватьОбъект3D,
    деактивироватьОбъект3D,
    установитьРодителя3D,
    добавитьРебёнка3D,
    удалитьРебёнка3D,
    установитьМетаданные3D,
    получитьМетаданные3D
} from "./объект_3d";


export interface РезультатОперацииОбъекта3D {
    успешно: boolean;
    сообщение: string;
}


export interface СобытиеAPIОбъекта3D {
    тип: string;
    идентификаторОбъекта: string;
    данные: unknown;
    время: number;
}


export type ОбработчикAPIОбъекта3D =
    (событие: СобытиеAPIОбъекта3D) => void;


export class APIОбъекта3D {

    private объект: Объект3D;

    private обработчики: ОбработчикAPIОбъекта3D[] = [];


    constructor(объект: Объект3D) {

        if (!проверитьОбъект3D(объект)) {
            throw new Error(
                "Нельзя создать API для некорректного объекта 3D."
            );
        }

        this.объект = клонироватьОбъект3D(объект);
    }


    получитьОбъект(): Объект3D {

        return клонироватьОбъект3D(this.объект);
    }


    получитьИдентификатор(): string {

        return this.объект.идентификатор;
    }


    получитьИмя(): string {

        return this.объект.имя;
    }


    получитьТип(): Объект3D["тип"] {

        return this.объект.тип;
    }


    получитьСостояние(): СостояниеОбъекта3D {

        return this.объект.состояние;
    }


    получитьПозицию(): Позиция3D {

        return {
            ...this.объект.трансформация.позиция
        };
    }


    получитьПоворот(): Поворот3D {

        return {
            ...this.объект.трансформация.поворот
        };
    }


    получитьМасштаб(): Масштаб3D {

        return {
            ...this.объект.трансформация.масштаб
        };
    }


    получитьТрансформацию(): Трансформация3D {

        return {
            позиция: {
                ...this.объект.трансформация.позиция
            },

            поворот: {
                ...this.объект.трансформация.поворот
            },

            масштаб: {
                ...this.объект.трансформация.масштаб
            }
        };
    }


    видим(): boolean {

        return this.объект.видим;
    }


    активен(): boolean {

        return this.объект.активен;
    }


    получитьИнтенсивность(): number {

        return this.объект.интенсивность;
    }


    получитьРодителя(): string | null {

        return this.объект.родитель;
    }


    получитьДетей(): string[] {

        return [...this.объект.дети];
    }


    установитьПозицию(
        x: number,
        y: number,
        z: number
    ): РезультатОперацииОбъекта3D {

        if (
            !Number.isFinite(x) ||
            !Number.isFinite(y) ||
            !Number.isFinite(z)
        ) {
            return this.ошибка(
                "Координаты позиции должны быть конечными числами."
            );
        }

        установитьПозицию3D(
            this.объект,
            x,
            y,
            z
        );

        this.сообщить(
            "изменение_позиции",
            this.получитьПозицию()
        );

        return this.успех(
            "Позиция объекта изменена."
        );
    }


    установитьПоворот(
        x: number,
        y: number,
        z: number
    ): РезультатОперацииОбъекта3D {

        if (
            !Number.isFinite(x) ||
            !Number.isFinite(y) ||
            !Number.isFinite(z)
        ) {
            return this.ошибка(
                "Углы поворота должны быть конечными числами."
            );
        }

        установитьПоворот3D(
            this.объект,
            x,
            y,
            z
        );

        this.сообщить(
            "изменение_поворота",
            this.получитьПоворот()
        );

        return this.успех(
            "Поворот объекта изменён."
        );
    }


    установитьМасштаб(
        x: number,
        y: number,
        z: number
    ): РезультатОперацииОбъекта3D {

        if (
            !Number.isFinite(x) ||
            !Number.isFinite(y) ||
            !Number.isFinite(z)
        ) {
            return this.ошибка(
                "Масштаб должен содержать конечные числа."
            );
        }

        установитьМасштаб3D(
            this.объект,
            x,
            y,
            z
        );

        this.сообщить(
            "изменение_масштаба",
            this.получитьМасштаб()
        );

        return this.успех(
            "Масштаб объекта изменён."
        );
    }


    установитьСостояние(
        состояние: СостояниеОбъекта3D
    ): РезультатОперацииОбъекта3D {

        установитьСостояниеОбъекта3D(
            this.объект,
            состояние
        );

        this.сообщить(
            "изменение_состояния",
            {
                состояние
            }
        );

        return this.успех(
            "Состояние объекта изменено."
        );
    }


    активировать(
        интенсивность: number = 1
    ): РезультатОперацииОбъекта3D {

        if (!Number.isFinite(интенсивность)) {
            return this.ошибка(
                "Интенсивность должна быть конечным числом."
            );
        }

        активироватьОбъект3D(
            this.объект,
            интенсивность
        );

        this.сообщить(
            "активация",
            {
                интенсивность
            }
        );

        return this.успех(
            "Объект активирован."
        );
    }


    деактивировать(): РезультатОперацииОбъекта3D {

        деактивироватьОбъект3D(
            this.объект
        );

        this.сообщить(
            "деактивация",
            null
        );

        return this.успех(
            "Объект деактивирован."
        );
    }


    установитьВидимость(
        видим: boolean
    ): РезультатОперацииОбъекта3D {

        this.объект.видим = видим;

        this.сообщить(
            "изменение_видимости",
            {
                видим
            }
        );

        return this.успех(
            "Видимость объекта изменена."
        );
    }


    установитьРодителя(
        родитель: string | null
    ): РезультатОперацииОбъекта3D {

        if (родитель === this.объект.идентификатор) {
            return this.ошибка(
                "Объект не может быть родителем самого себя."
            );
        }

        установитьРодителя3D(
            this.объект,
            родитель
        );

        this.сообщить(
            "изменение_родителя",
            {
                родитель
            }
        );

        return this.успех(
            "Родитель объекта изменён."
        );
    }


    добавитьРебёнка(
        идентификаторРебёнка: string
    ): РезультатОперацииОбъекта3D {

        if (
            идентификаторРебёнка ===
            this.объект.идентификатор
        ) {
            return this.ошибка(
                "Объект не может быть собственным ребёнком."
            );
        }

        добавитьРебёнка3D(
            this.объект,
            идентификаторРебёнка
        );

        this.сообщить(
            "добавление_ребёнка",
            {
                идентификаторРебёнка
            }
        );

        return this.успех(
            "Ребёнок добавлен."
        );
    }


    удалитьРебёнка(
        идентификаторРебёнка: string
    ): РезультатОперацииОбъекта3D {

        удалитьРебёнка3D(
            this.объект,
            идентификаторРебёнка
        );

        this.сообщить(
            "удаление_ребёнка",
            {
                идентификаторРебёнка
            }
        );

        return this.успех(
            "Ребёнок удалён."
        );
    }


    установитьМетаданные(
        ключ: string,
        значение: unknown
    ): РезультатОперацииОбъекта3D {

        if (ключ.trim() === "") {
            return this.ошибка(
                "Ключ метаданных не может быть пустым."
            );
        }

        установитьМетаданные3D(
            this.объект,
            ключ,
            значение
        );

        this.сообщить(
            "изменение_метаданных",
            {
                ключ,
                значение
            }
        );

        return this.успех(
            "Метаданные изменены."
        );
    }


    получитьМетаданные(
        ключ: string
    ): unknown {

        return получитьМетаданные3D(
            this.объект,
            ключ
        );
    }


    добавитьОбработчик(
        обработчик: ОбработчикAPIОбъекта3D
    ): void {

        if (!this.обработчики.includes(обработчик)) {
            this.обработчики.push(обработчик);
        }
    }


    удалитьОбработчик(
        обработчик: ОбработчикAPIОбъекта3D
    ): void {

        this.обработчики =
            this.обработчики.filter(
                текущий => текущий !== обработчик
            );
    }


    проверить(): boolean {

        return проверитьОбъект3D(
            this.объект
        );
    }


    клонировать(): Объект3D {

        return клонироватьОбъект3D(
            this.объект
        );
    }


    private успех(
        сообщение: string
    ): РезультатОперацииОбъекта3D {

        return {
            успешно: true,
            сообщение
        };
    }


    private ошибка(
        сообщение: string
    ): РезультатОперацииОбъекта3D {

        return {
            успешно: false,
            сообщение
        };
    }


    private сообщить(
        тип: string,
        данные: unknown
    ): void {

        const событие: СобытиеAPIОбъекта3D = {
            тип,
            идентификаторОбъекта:
                this.объект.идентификатор,
            данные,
            время: Date.now()
        };

        for (
            const обработчик of this.обработчики
        ) {
            обработчик(событие);
        }
    }
}