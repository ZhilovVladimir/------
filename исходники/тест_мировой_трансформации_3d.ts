function проверить(
    условие: boolean,
    название: string
): void {
    if (условие) {
        успешно++;
        console.log(`✅ ${название}`);
    } else {
        ошибки++;
        console.error(`❌ ${название}`);
    }
}

function близко(
    первое: number,
    второе: number,
    точность = 0.000000001
): boolean {
    return Math.abs(первое - второе) <= точность;
}

function точкиРавны(
    первое: { x: number; y: number; z: number },
    второе: { x: number; y: number; z: number }
): boolean {
    return (
        близко(первое.x, второе.x) &&
        близко(первое.y, второе.y) &&
        близко(первое.z, второе.z)
    );
}

function создатьТестовыйОбъект(
    идентификатор: string,
    имя: string,
    трансформация: ReturnType<typeof создатьТрансформацию3D>
): Объект3D {
    const объект = создатьОбъект3D(
        идентификатор,
        имя,
        "система"
    );

    объект.трансформация = трансформация;

    return объект;
}

