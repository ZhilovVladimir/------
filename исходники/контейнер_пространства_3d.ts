import type {
    Объект3D
} from "./объект_3d.js";

import type {
    Позиция3D
} from "./объект_3d.js";

import type {
    Трансформация3D
} from "./пространство_3d.js";

import {
    клонироватьТрансформацию3D
} from "./пространство_3d.js";

import {
    вычислитьМировуюТрансформациюОбъекта3D
} from "./мировая_трансформация_3d.js";

/**
 * Прямоугольная область пространства 3D.
 */
export interface Область3D {

    /**
     * Минимальная точка области.
     */
    минимум: Позиция3D;

    /**
     * Максимальная точка области.
     */
    максимум: Позиция3D;
}

/**
 * Результат операции пространственного контейнера.
 */
export interface РезультатОперацииПространства3D {

    /**
     * Успешно ли выполнена операция.
     */
    успешно: boolean;

    /**
     * Человекочитаемое описание результата.
     */
    сообщение: string;
}

/**
 * Результат пространственного поиска.
 */
export interface РезультатПоискаПространства3D {

    /**
     * Найденные объекты.
     */
    объекты: Объект3D[];

    /**
     * Количество найденных объектов.
     */
    количество: number;
}

/**
 * Результат получения мировой трансформации.
 */
export interface РезультатМировойТрансформацииКонтейнера3D {

    /**
     * Успешно ли выполнена операция.
     */
    успешно: boolean;

    /**
     * Описание результата.
     */
    сообщение: string;

    /**
     * Мировая трансформация.
     */
    трансформация?: Трансформация3D;
}

/**
 * Контейнер пространственного 3D-мира.
 *
 * Ответственность контейнера:
 *
 * - хранение объектов в пространстве;
 * - пространственная иерархия;
 * - получение корневых и дочерних объектов;
 * - перемещение объектов;
 * - автоматический пересчёт мировых трансформаций;
 * - расчёт расстояний;
 * - поиск по радиусу;
 * - поиск в области;
 * - проверка пространственной целостности.
 *
 * Контейнер не отвечает за:
 *
 * - графику;
 * - Three.js;
 * - WebGL;
 * - DOM;
 * - визуальный интерфейс;
 * - жизненный цикл программы.
 */
export class КонтейнерПространства3D {

    /**
     * Все объекты пространства.
     */
    private readonly объекты:
        Map<string, Объект3D>;

    /**
     * Кэш мировых трансформаций.
     *
     * Здесь хранится результат автоматического
     * пересчёта всей иерархии.
     *
     * Локальная трансформация объекта при этом
     * не изменяется.
     */
    private readonly мировыеТрансформации:
        Map<string, Трансформация3D>;

    /**
     * Создаёт пустой пространственный контейнер.
     */
    public constructor() {
        this.объекты =
            new Map<string, Объект3D>();

        this.мировыеТрансформации =
            new Map<string, Трансформация3D>();
    }

    /**
     * Возвращает количество объектов.
     */
    public получитьКоличество(): number {
        return this.объекты.size;
    }

    /**
     * Проверяет, пуст ли контейнер.
     */
    public пуст(): boolean {
        return this.объекты.size === 0;
    }

    /**
     * Добавляет объект в пространство.
     */
    public добавитьОбъект(
        объект: Объект3D
    ): РезультатОперацииПространства3D {

        if (!объект || typeof объект !== "object") {
            return {
                успешно: false,
                сообщение:
                    "Нельзя добавить некорректный объект 3D."
            };
        }

        if (
            typeof объект.идентификатор !== "string" ||
            объект.идентификатор.length === 0
        ) {
            return {
                успешно: false,
                сообщение:
                    "Объект 3D должен иметь непустой идентификатор."
            };
        }

        if (!this.проверитьБазовуюСтруктуруОбъекта(объект)) {
            return {
                успешно: false,
                сообщение:
                    `Объект "${объект.идентификатор}" имеет некорректную структуру.`
            };
        }

        if (
            this.объекты.has(
                объект.идентификатор
            )
        ) {
            return {
                успешно: false,
                сообщение:
                    `Объект с идентификатором "${объект.идентификатор}" уже существует.`
            };
        }

        if (
            объект.родитель !== null &&
            !this.объекты.has(объект.родитель)
        ) {
            return {
                успешно: false,
                сообщение:
                    `Родитель "${объект.родитель}" ещё не существует в пространстве.`
            };
        }

        this.объекты.set(
            объект.идентификатор,
            объект
        );

        this.пересобратьДетей();
        this.пересчитатьМировыеТрансформации();

        return {
            успешно: true,
            сообщение:
                `Объект "${объект.идентификатор}" добавлен в пространство 3D.`
        };
    }

    /**
     * Получает объект по идентификатору.
     */
    public получитьОбъект(
        идентификатор: string
    ): Объект3D | undefined {

        return this.объекты.get(
            идентификатор
        );
    }

    /**
     * Проверяет существование объекта.
     */
    public существует(
        идентификатор: string
    ): boolean {

        return this.объекты.has(
            идентификатор
        );
    }

    /**
     * Возвращает копию списка всех объектов.
     *
     * Сами объекты не клонируются.
     */
    public получитьВсеОбъекты(): Объект3D[] {
        return Array.from(
            this.объекты.values()
        );
    }

    /**
     * Возвращает корневые объекты.
     *
     * Корневой объект не имеет родителя.
     */
    public получитьКорневыеОбъекты(): Объект3D[] {

        return this.получитьВсеОбъекты().filter(
            объект =>
                объект.родитель === null
        );
    }

    /**
     * Возвращает дочерние объекты указанного родителя.
     */
    public получитьДочерниеОбъекты(
        идентификаторРодителя: string
    ): Объект3D[] {

        return this.получитьВсеОбъекты().filter(
            объект =>
                объект.родитель ===
                идентификаторРодителя
        );
    }

    /**
     * Устанавливает родителя объекта.
     *
     * После изменения иерархии мировые трансформации
     * автоматически пересчитываются для всей структуры.
     */
    public установитьРодителя(
        идентификаторОбъекта: string,
        идентификаторРодителя: string | null
    ): РезультатОперацииПространства3D {

        const объект =
            this.объекты.get(
                идентификаторОбъекта
            );

        if (!объект) {
            return {
                успешно: false,
                сообщение:
                    `Объект "${идентификаторОбъекта}" не найден.`
            };
        }

        if (
            идентификаторРодителя ===
            идентификаторОбъекта
        ) {
            return {
                успешно: false,
                сообщение:
                    "Объект не может быть родителем самого себя."
            };
        }

        if (
            идентификаторРодителя !== null
        ) {
            const родитель =
                this.объекты.get(
                    идентификаторРодителя
                );

            if (!родитель) {
                return {
                    успешно: false,
                    сообщение:
                        `Родитель "${идентификаторРодителя}" не найден.`
                };
            }

            if (
                this.являетсяПотомком(
                    идентификаторРодителя,
                    идентификаторОбъекта
                )
            ) {
                return {
                    успешно: false,
                    сообщение:
                        "Нельзя создать циклическую пространственную иерархию."
                };
            }
        }

        объект.родитель =
            идентификаторРодителя;

        this.пересобратьДетей();
        this.пересчитатьМировыеТрансформации();

        return {
            успешно: true,
            сообщение:
                идентификаторРодителя === null
                    ? `Объект "${идентификаторОбъекта}" стал корневым.`
                    : `Объект "${идентификаторОбъекта}" получил родителя "${идентификаторРодителя}".`
        };
    }

    /**
     * Убирает родителя у объекта.
     */
    public убратьРодителя(
        идентификаторОбъекта: string
    ): РезультатОперацииПространства3D {

        return this.установитьРодителя(
            идентификаторОбъекта,
            null
        );
    }

    /**
     * Удаляет объект из пространства.
     *
     * Дочерние объекты остаются в пространстве,
     * но становятся корневыми.
     */
    public удалитьОбъект(
        идентификатор: string
    ): РезультатОперацииПространства3D {

        const объект =
            this.объекты.get(
                идентификатор
            );

        if (!объект) {
            return {
                успешно: false,
                сообщение:
                    `Объект "${идентификатор}" не найден.`
            };
        }

        this.объекты.delete(
            идентификатор
        );

        this.мировыеТрансформации.delete(
            идентификатор
        );

        for (
            const другойОбъект
            of this.объекты.values()
        ) {
            if (
                другойОбъект.родитель ===
                идентификатор
            ) {
                другойОбъект.родитель =
                    null;
            }
        }

        this.пересобратьДетей();
        this.пересчитатьМировыеТрансформации();

        return {
            успешно: true,
            сообщение:
                `Объект "${идентификатор}" удалён из пространства 3D.`
        };
    }

    /**
     * Полностью очищает контейнер.
     */
    public очистить(): void {
        this.объекты.clear();
        this.мировыеТрансформации.clear();
    }

    /**
     * Перемещает объект в указанную локальную позицию.
     *
     * После перемещения автоматически пересчитывается
     * мировая трансформация объекта и всех его потомков.
     */
    public переместитьОбъект(
        идентификатор: string,
        позиция: Позиция3D
    ): РезультатОперацииПространства3D {

        const объект =
            this.объекты.get(
                идентификатор
            );

        if (!объект) {
            return {
                успешно: false,
                сообщение:
                    `Объект "${идентификатор}" не найден.`
            };
        }

        if (
            !this.проверитьПозицию(
                позиция
            )
        ) {
            return {
                успешно: false,
                сообщение:
                    "Передана некорректная позиция 3D."
            };
        }

        объект.трансформация.позиция = {
            x: позиция.x,
            y: позиция.y,
            z: позиция.z
        };

        this.пересчитатьМировыеТрансформации();

        return {
            успешно: true,
            сообщение:
                `Объект "${идентификатор}" перемещён.`
        };
    }

    /**
     * Возвращает текущую локальную позицию объекта.
     */
    public получитьПозицию(
        идентификатор: string
    ): Позиция3D | undefined {

        const объект =
            this.объекты.get(
                идентификатор
            );

        if (!объект) {
            return undefined;
        }

        return {
            x: объект.трансформация.позиция.x,
            y: объект.трансформация.позиция.y,
            z: объект.трансформация.позиция.z
        };
    }

    /**
     * Получает актуальную мировую трансформацию объекта.
     *
     * Возвращается копия, поэтому внешний код не может
     * случайно изменить внутренний кэш контейнера.
     */
    public получитьМировуюТрансформацию(
        идентификатор: string
    ): Трансформация3D | undefined {

        if (
            !this.объекты.has(
                идентификатор
            )
        ) {
            return undefined;
        }

        const трансформация =
            this.мировыеТрансформации.get(
                идентификатор
            );

        if (!трансформация) {
            this.пересчитатьМировыеТрансформации();
        }

        const актуальная =
            this.мировыеТрансформации.get(
                идентификатор
            );

        if (!актуальная) {
            return undefined;
        }

        return клонироватьТрансформацию3D(
            актуальная
        );
    }

    /**
     * Получает актуальную мировую позицию объекта.
     */
    public получитьМировуюПозицию(
        идентификатор: string
    ): Позиция3D | undefined {

        const трансформация =
            this.получитьМировуюТрансформацию(
                идентификатор
            );

        if (!трансформация) {
            return undefined;
        }

        return {
            x: трансформация.позиция.x,
            y: трансформация.позиция.y,
            z: трансформация.позиция.z
        };
    }

    /**
     * Принудительно пересчитывает мировые трансформации.
     *
     * Обычно внешний код не должен вызывать этот метод:
     * контейнер делает это автоматически после структурных
     * и пространственных изменений.
     *
     * Метод оставлен открытым для случаев, когда внешний
     * системный код напрямую изменил локальную трансформацию
     * объекта.
     */
    public обновитьМировыеТрансформации(): void {
        this.пересчитатьМировыеТрансформации();
    }

    /**
     * Вычисляет расстояние между двумя объектами
     * по их мировым позициям.
     */
    public расстояниеМежду(
        первыйИдентификатор: string,
        второйИдентификатор: string
    ): number | undefined {

        const перваяПозиция =
            this.получитьМировуюПозицию(
                первыйИдентификатор
            );

        const втораяПозиция =
            this.получитьМировуюПозицию(
                второйИдентификатор
            );

        if (
            !перваяПозиция ||
            !втораяПозиция
        ) {
            return undefined;
        }

        const dx =
            втораяПозиция.x -
            перваяПозиция.x;

        const dy =
            втораяПозиция.y -
            перваяПозиция.y;

        const dz =
            втораяПозиция.z -
            перваяПозиция.z;

        return Math.sqrt(
            dx * dx +
            dy * dy +
            dz * dz
        );
    }

    /**
     * Находит объекты внутри заданного радиуса
     * относительно мировой точки.
     */
    public найтиРядом(
        точка: Позиция3D,
        радиус: number
    ): РезультатПоискаПространства3D {

        if (
            !this.проверитьПозицию(
                точка
            )
        ) {
            return {
                объекты: [],
                количество: 0
            };
        }

        if (
            !Number.isFinite(радиус) ||
            радиус < 0
        ) {
            return {
                объекты: [],
                количество: 0
            };
        }

        const радиусКвадрат =
            радиус * радиус;

        const найденные =
            this.получитьВсеОбъекты().filter(
                объект => {

                    const мироваяПозиция =
                        this.получитьМировуюПозицию(
                            объект.идентификатор
                        );

                    if (!мироваяПозиция) {
                        return false;
                    }

                    const dx =
                        мироваяПозиция.x -
                        точка.x;

                    const dy =
                        мироваяПозиция.y -
                        точка.y;

                    const dz =
                        мироваяПозиция.z -
                        точка.z;

                    const расстояниеКвадрат =
                        dx * dx +
                        dy * dy +
                        dz * dz;

                    return (
                        расстояниеКвадрат <=
                        радиусКвадрат
                    );
                }
            );

        return {
            объекты: найденные,
            количество: найденные.length
        };
    }

    /**
     * Находит объекты внутри прямоугольной области
     * по мировым координатам.
     */
    public найтиВОбласти(
        область: Область3D
    ): РезультатПоискаПространства3D {

        if (
            !this.проверитьПозицию(
                область.минимум
            ) ||
            !this.проверитьПозицию(
                область.максимум
            )
        ) {
            return {
                объекты: [],
                количество: 0
            };
        }

        const минимумX =
            Math.min(
                область.минимум.x,
                область.максимум.x
            );

        const максимумX =
            Math.max(
                область.минимум.x,
                область.максимум.x
            );

        const минимумY =
            Math.min(
                область.минимум.y,
                область.максимум.y
            );

        const максимумY =
            Math.max(
                область.минимум.y,
                область.максимум.y
            );

        const минимумZ =
            Math.min(
                область.минимум.z,
                область.максимум.z
            );

        const максимумZ =
            Math.max(
                область.минимум.z,
                область.максимум.z
            );

        const найденные =
            this.получитьВсеОбъекты().filter(
                объект => {

                    const мироваяПозиция =
                        this.получитьМировуюПозицию(
                            объект.идентификатор
                        );

                    if (!мироваяПозиция) {
                        return false;
                    }

                    return (
                        мироваяПозиция.x >= минимумX &&
                        мироваяПозиция.x <= максимумX &&
                        мироваяПозиция.y >= минимумY &&
                        мироваяПозиция.y <= максимумY &&
                        мироваяПозиция.z >= минимумZ &&
                        мироваяПозиция.z <= максимумZ
                    );
                }
            );

        return {
            объекты: найденные,
            количество: найденные.length
        };
    }

    /**
     * Проверяет целостность пространственного контейнера.
     */
    public проверитьЦелостность():
        РезультатОперацииПространства3D {

        for (
            const объект
            of this.объекты.values()
        ) {

            if (
                !this.проверитьБазовуюСтруктуруОбъекта(
                    объект
                )
            ) {
                return {
                    успешно: false,
                    сообщение:
                        `Объект "${объект.идентификатор}" имеет некорректную структуру.`
                };
            }

            if (
                объект.родитель !== null
            ) {
                if (
                    !this.объекты.has(
                        объект.родитель
                    )
                ) {
                    return {
                        успешно: false,
                        сообщение:
                            `У объекта "${объект.идентификатор}" отсутствует родитель "${объект.родитель}".`
                    };
                }

                if (
                    объект.родитель ===
                    объект.идентификатор
                ) {
                    return {
                        успешно: false,
                        сообщение:
                            `Объект "${объект.идентификатор}" ссылается сам на себя.`
                    };
                }
            }

            if (
                this.естьЦиклДля(
                    объект.идентификатор
                )
            ) {
                return {
                    успешно: false,
                    сообщение:
                        `Обнаружен цикл в пространственной иерархии объекта "${объект.идентификатор}".`
                };
            }
        }

        for (
            const объект
            of this.объекты.values()
        ) {

            const ожидаемыеДети =
                this.получитьДочерниеОбъекты(
                    объект.идентификатор
                );

            const множествоОжидаемыхДетей =
                new Set(
                    ожидаемыеДети.map(
                        ребёнок =>
                            ребёнок.идентификатор
                    )
                );

            const множествоФактическихДетей =
                new Set(
                    объект.дети
                );

            if (
                множествоОжидаемыхДетей.size !==
                множествоФактическихДетей.size
            ) {
                return {
                    успешно: false,
                    сообщение:
                        `У объекта "${объект.идентификатор}" некорректный список детей.`
                };
            }

            for (
                const идентификаторРебёнка
                of множествоОжидаемыхДетей
            ) {
                if (
                    !множествоФактическихДетей.has(
                        идентификаторРебёнка
                    )
                ) {
                    return {
                        успешно: false,
                        сообщение:
                            `У объекта "${объект.идентификатор}" отсутствует ребёнок "${идентификаторРебёнка}".`
                    };
                }
            }

            if (
                объект.дети.length !==
                множествоФактическихДетей.size
            ) {
                return {
                    успешно: false,
                    сообщение:
                        `У объекта "${объект.идентификатор}" обнаружены дублированные дети.`
                };
            }
        }

        if (
            this.мировыеТрансформации.size !==
            this.объекты.size
        ) {
            this.пересчитатьМировыеТрансформации();
        }

        for (
            const объект
            of this.объекты.values()
        ) {

            if (
                !this.мировыеТрансформации.has(
                    объект.идентификатор
                )
            ) {
                return {
                    успешно: false,
                    сообщение:
                        `Для объекта "${объект.идентификатор}" отсутствует мировая трансформация.`
                };
            }
        }

        return {
            успешно: true,
            сообщение:
                "Пространственный контейнер корректен."
        };
    }

    /**
     * Проверяет базовую структуру объекта.
     */
    private проверитьБазовуюСтруктуруОбъекта(
        объект: Объект3D
    ): boolean {

        if (!объект) {
            return false;
        }

        if (
            typeof объект.идентификатор !==
            "string" ||
            объект.идентификатор.length === 0
        ) {
            return false;
        }

        if (
            !объект.трансформация ||
            !объект.трансформация.позиция ||
            !объект.трансформация.поворот ||
            !объект.трансформация.масштаб
        ) {
            return false;
        }

        if (
            !this.проверитьПозицию(
                объект.трансформация.позиция
            )
        ) {
            return false;
        }

        if (!Array.isArray(объект.дети)) {
            return false;
        }

        if (
            объект.родитель !== null &&
            typeof объект.родитель !== "string"
        ) {
            return false;
        }

        return true;
    }

    /**
     * Проверяет корректность позиции.
     */
    private проверитьПозицию(
        позиция: Позиция3D
    ): boolean {

        return (
            !!позиция &&
            Number.isFinite(позиция.x) &&
            Number.isFinite(позиция.y) &&
            Number.isFinite(позиция.z)
        );
    }

    /**
     * Проверяет, является ли один объект потомком другого.
     *
     * Используется для защиты от циклов.
     */
    private являетсяПотомком(
        кандидат: string,
        предок: string
    ): boolean {

        let текущий =
            this.объекты.get(
                кандидат
            );

        const посещённые =
            new Set<string>();

        while (
            текущий &&
            текущий.родитель !== null
        ) {

            if (
                посещённые.has(
                    текущий.идентификатор
                )
            ) {
                return true;
            }

            посещённые.add(
                текущий.идентификатор
            );

            if (
                текущий.родитель ===
                предок
            ) {
                return true;
            }

            текущий =
                this.объекты.get(
                    текущий.родитель
                );
        }

        return false;
    }

    /**
     * Проверяет наличие цикла для объекта.
     */
    private естьЦиклДля(
        идентификатор: string
    ): boolean {

        const посещённые =
            new Set<string>();

        let текущий =
            this.объекты.get(
                идентификатор
            );

        while (
            текущий &&
            текущий.родитель !== null
        ) {

            if (
                посещённые.has(
                    текущий.идентификатор
                )
            ) {
                return true;
            }

            посещённые.add(
                текущий.идентификатор
            );

            текущий =
                this.объекты.get(
                    текущий.родитель
                );
        }

        return false;
    }

    /**
     * Полностью пересобирает списки детей.
     *
     * Это предотвращает рассинхронизацию между
     * полем "родитель" и полем "дети".
     */
    private пересобратьДетей(): void {

        for (
            const объект
            of this.объекты.values()
        ) {
            объект.дети = [];
        }

        for (
            const объект
            of this.объекты.values()
        ) {

            if (
                объект.родитель === null
            ) {
                continue;
            }

            const родитель =
                this.объекты.get(
                    объект.родитель
                );

            if (!родитель) {
                continue;
            }

            if (
                !родитель.дети.includes(
                    объект.идентификатор
                )
            ) {
                родитель.дети.push(
                    объект.идентификатор
                );
            }
        }
    }

    /**
     * Полностью пересчитывает мировые трансформации
     * всего пространства.
     *
     * Сначала обрабатываются корневые объекты,
     * затем их дети, затем внуки и так далее.
     */
    private пересчитатьМировыеТрансформации(): void {

        this.мировыеТрансформации.clear();

        const корневые =
            this.получитьКорневыеОбъекты();

        for (
            const корневой
            of корневые
        ) {
            this.пересчитатьМировуюВетку(
                корневой,
                undefined,
                new Set<string>()
            );
        }
    }

    /**
     * Рекурсивно пересчитывает мировую трансформацию
     * объекта и всей его ветки.
     */
    private пересчитатьМировуюВетку(
        объект: Объект3D,
        мироваяТрансформацияРодителя:
            Трансформация3D | undefined,
        посещённые: Set<string>
    ): void {

        if (
            посещённые.has(
                объект.идентификатор
            )
        ) {
            return;
        }

        посещённые.add(
            объект.идентификатор
        );

        const мировая =
            вычислитьМировуюТрансформациюОбъекта3D(
                объект,
                мироваяТрансформацияРодителя
            );

        this.мировыеТрансформации.set(
            объект.идентификатор,
            клонироватьТрансформацию3D(
                мировая
            )
        );

        const дети =
            this.получитьДочерниеОбъекты(
                объект.идентификатор
            );

        for (
            const ребёнок
            of дети
        ) {
            this.пересчитатьМировуюВетку(
                ребёнок,
                мировая,
                посещённые
            );
        }
    }
}