// ============================================================
// 🐌 УЛИТКА
// Тест защиты HTTP-мостов (день 9)
// ============================================================
//
// Проверяется: Origin, токен (cookie и заголовок), лимит тела
// 2 МБ → 413, пропуск не-API запросов (страница, статика).
// ============================================================

import http from "node:http";

import type {
    IncomingMessage,
    ServerResponse,
} from "node:http";

import {
    ИМЯ_COOKIE_ТОКЕНА,
    ЗАГОЛОВОК_ТОКЕНА,
    ЛИМИТ_ТЕЛА_ЗАПРОСА,
    защититьМост,
} from "./защита_мостов.js";


// ============================================================
// СЧЁТЧИКИ
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибокТеста = 0;


// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string,
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(`✅ ${сообщение}`);

        return;
    }

    ошибокТеста++;

    console.log(`❌ ${сообщение}`);
}


// ============================================================
// ТЕСТОВЫЙ СЕРВЕР
// ============================================================

const ТОКЕН = "test-token-ulitki";

process.env.УЛИТКА_ТОКЕН = ТОКЕН;

// Путь в запросе — в percent-кодировке: Node.js не принимает
// кириллицу в строке запроса без экранирования.
const ПУТЬ_API = "/api/" + encodeURIComponent("проба");

let вызововМоста = 0;
let пропущеноНеAPI = 0;

const обработчикМоста = (
    _запрос: IncomingMessage,
    ответ: ServerResponse,
): void => {

    вызововМоста++;

    ответ.statusCode = 200;
    ответ.setHeader("Content-Type", "application/json; charset=utf-8");
    ответ.end(JSON.stringify({ успешно: true }));
};

const защищённыйМост = защититьМост(обработчикМоста);

const сервер = http.createServer((запрос, ответ) => {

    защищённыйМост(запрос, ответ, () => {

        // Сюда попадают только не-API запросы: страница, статика.
        пропущеноНеAPI++;

        ответ.statusCode = 200;
        ответ.setHeader("Content-Type", "text/html; charset=utf-8");
        ответ.end("<html>страница</html>");
    });
});


// ============================================================
// HTTP-КЛИЕНТ
// ============================================================

interface Ответ {

    код: number;
    текст: string;
}

interface Запрос {

    путь: string;
    метод?: string;
    заголовки?: Record<string, string>;
    тело?: string;
}

function выполнить(настройки: Запрос): Promise<Ответ> {

    return new Promise((разрешить, отклонить) => {

        const адрес = сервер.address();

        if (typeof адрес !== "object" || адрес === null) {

            отклонить(new Error("Сервер не запущен."));

            return;
        }

        const тело = настройки.тело ?? "";
        const заголовки: Record<string, string> = {
            ...(настройки.заголовки ?? {}),
        };

        if (тело.length > 0) {

            заголовки["Content-Type"] = "application/json; charset=utf-8";
            заголовки["Content-Length"] = String(
                Buffer.byteLength(тело, "utf8"),
            );
        }

        const исходный = http.request(
            {
                host: "127.0.0.1",
                port: адрес.port,
                path: настройки.путь,
                method: настройки.метод ?? "GET",
                headers: заголовки,
            },
            ответ => {

                let текст = "";

                ответ.setEncoding("utf8");

                ответ.on("data", часть => {

                    текст += часть;
                });

                ответ.on("end", () => {

                    разрешить({
                        код: ответ.statusCode ?? 0,
                        текст,
                    });
                });
            },
        );

        исходный.on("error", отклонить);

        исходный.end(тело);
    });
}


// ============================================================
// ЗАПУСК
// ============================================================

async function запустить(): Promise<void> {

    await new Promise<void>(разрешить => {

        сервер.listen(0, "127.0.0.1", разрешить);
    });

    const куки = `${ИМЯ_COOKIE_ТОКЕНА}=${ТОКЕН}`;

    // 1. Не-API запрос без токена — страница должна открываться.
    const страница = await выполнить({ путь: "/index.html" });

    проверить(
        страница.код === 200 && пропущеноНеAPI === 1,
        "не-API запрос проходит без токена (страница открывается)",
    );

    // 2. API без токена — отказ.
    вызововМоста = 0;

    const безТокена = await выполнить({ путь: ПУТЬ_API });

    проверить(
        безТокена.код === 401 && вызововМоста === 0,
        "API без токена → 401, обработчик моста не вызывается",
    );

    // 3. API с верным токеном в cookie — работает.
    const сCookie = await выполнить({
        путь: ПУТЬ_API,
        заголовки: { Cookie: куки },
    });

    проверить(
        сCookie.код === 200 && вызововМоста === 1,
        "API с cookie токена → 200",
    );

    // 4. API с неверным токеном — отказ.
    const чужойТокен = await выполнить({
        путь: ПУТЬ_API,
        заголовки: { Cookie: `${ИМЯ_COOKIE_ТОКЕНА}=chuzhoy-token` },
    });

    проверить(
        чужойТокен.код === 401,
        "API с чужим cookie → 401",
    );

    // 5. API с верным заголовком (без cookie) — работает.
    const сЗаголовком = await выполнить({
        путь: ПУТЬ_API,
        заголовки: { [ЗАГОЛОВОК_ТОКЕНА]: ТОКЕН },
    });

    проверить(
        сЗаголовком.код === 200,
        "API с заголовком токена → 200",
    );

    // 6. Чужой Origin — отказ даже с токеном.
    const чужойOrigin = await выполнить({
        путь: ПУТЬ_API,
        заголовки: {
            Cookie: куки,
            Origin: "http://evil.example",
        },
    });

    проверить(
        чужойOrigin.код === 403,
        "API с чужим Origin → 403",
    );

    // 7. Свой Origin — работает.
    const адрес = сервер.address();

    const свойOrigin = await выполнить({
        путь: ПУТЬ_API,
        заголовки: {
            Cookie: куки,
            Origin:
                typeof адрес === "object" && адрес !== null
                    ? `http://127.0.0.1:${адрес.port}`
                    : "http://127.0.0.1",
        },
    });

    проверить(
        свойOrigin.код === 200,
        "API со своим Origin → 200",
    );

    // 8. Большое тело по Content-Length — 413.
    const большое = "я".repeat(ЛИМИТ_ТЕЛА_ЗАПРОСА + 1024);

    const лишнееТело = await выполнить({
        путь: ПУТЬ_API,
        метод: "POST",
        заголовки: { Cookie: куки },
        тело: большое,
    });

    проверить(
        лишнееТело.код === 413,
        "тело больше 2 МБ → 413 (клиент видит ответ)",
    );

    // 9. Тело в пределах лимита — проходит.
    const нормальное = await выполнить({
        путь: ПУТЬ_API,
        метод: "POST",
        заголовки: { Cookie: куки },
        тело: JSON.stringify({ код: "показать 1" }),
    });

    проверить(
        нормальное.код === 200,
        "тело в пределах лимита → 200",
    );
}


// ============================================================
// ИТОГ
// ============================================================

запустить()
    .catch(ошибка => {

        ошибокТеста++;

        console.log(`❌ Тест упал: ${ошибка.message}`);
    })
    .finally(async () => {

        // Сервер закрываем и в случае падения — иначе процесс
        // останется висеть с открытым сокетом.
        if (сервер.listening) {

            await new Promise<void>(разрешить => {

                сервер.close(() => разрешить());
            });
        }

        console.log("");
        console.log(`Всего проверок: ${всегоПроверок}`);
        console.log(`Успешных: ${успешныхПроверок}`);
        console.log(`Ошибок: ${ошибокТеста}`);
        console.log("");

        if (ошибокТеста === 0) {

            console.log("🐌 ✅ ЗАЩИТА МОСТОВ РАБОТАЕТ");

        } else {

            console.log("🐌 ❌ ТЕСТ ЗАЩИТЫ МОСТОВ ОБНАРУЖИЛ ОШИБКИ");
        }

        process.exitCode = ошибокТеста === 0 ? 0 : 1;
    });
