заголовок(30, "АРХИТЕКТУРНЫЕ ПРОВЕРКИ");

{
    const дерево = разобратьКод(`
        пусть результат = 2 + 3 * 4
    `);

    const переменная = дерево[0] as ОбъявлениеПеременной;
    const корень = переменная.значение as Операция;

    // Сейчас парсер разбирает операции слева направо.
    // Поэтому дерево должно выглядеть так:
    // (2 + 3) * 4

    const леваяЧасть = корень.левое as Операция;

    проверить(
        корень.оператор === "*",
        "Текущая версия фиксирует левую ассоциативность операций"
    );

    проверить(
        леваяЧасть.оператор === "+",
        "Текущая версия строит дерево (2 + 3) * 4"
    );

    предупредить(
        "Приоритет операций пока не реализован: * и / должны иметь приоритет над + и -."
    );
}

