import { разобрать } from "./лексический_анализатор.js";
import { Парсер } from "./ядро/парсер.js";

import type {
    Узел,
    Число,
    Текст,
    Имя,
    Операция,
    ОбъявлениеПеременной,
    ВызовФункции,
    Функция,
    Возврат
} from "./дерево/узлы.js";

// ============================================================
// СЧЁТЧИКИ
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;
let предупреждений = 0;

// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(условие: boolean, сообщение: string): void {
    всегоПроверок++;

    if (условие) {
        успешныхПроверок++;
        console.log(`✅ ${сообщение}`);
        return;
    }

    ошибок++;
    console.log(`❌ ${сообщение}`);
}

// ============================================================
// ПРЕДУПРЕЖДЕНИЕ
// ============================================================

function предупредить(сообщение: string): void {
    предупреждений++;
    console.log(`⚠️ ${сообщение}`);
}

// ============================================================
// ЗАГОЛОВОК
// ============================================================

function заголовок(номер: number, название: string): void {
    console.log("");
    console.log("================================");
    console.log(`[${номер}] ${название}`);
    console.log("================================");
}

// ============================================================
// ПОЛУЧИТЬ ДЕРЕВО
// ============================================================

function разобратьКод(код: string): Узел[] {
    const лексемы = разобрать(код);
    const парсер = new Парсер(лексемы);
    return парсер.разобрать();
}

// ============================================================
// ПОЛУЧИТЬ ОШИБКУ
// ============================================================

function получитьОшибка(код: string): string {
    try {
        разобратьКод(код);

        return "";
    } catch (ошибка: unknown) {
        if (ошибка instanceof Error) {
            return ошибка.message;
        }

        return String(ошибка);
    }
}

