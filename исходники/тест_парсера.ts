// [28] СМЕШАННОЕ ДЕРЕВО
// ============================================================

заголовок(28, "СЛОЖНОЕ ДЕРЕВО");

{
    const дерево = разобратьКод(`
        функция сложить(первое, второе)

            пусть промежуточное = первое + второе

            вернуть промежуточное

        конец

        пусть число = 100
        пусть результат = сложить(число, 50)
    `);

    проверить(
        дерево.length === 3,
        "Сложная программа создаёт три верхнеуровневых узла"
    );

    const функция = дерево[0] as Функция;
    const число = дерево[1] as ОбъявлениеПеременной;
    const результат = дерево[2] as ОбъявлениеПеременной;

    проверить(
        функция.вид === "ФУНКЦИЯ",
        "Первый узел — функция"
    );

    проверить(
        число.вид === "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        "Второй узел — переменная"
    );

    проверить(
        результат.вид === "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
        "Третий узел — переменная"
    );

    проверить(
        функция.тело.команды.length === 2,
        "Внутри функции две команды"
    );

    const промежуточное =
        функция.тело.команды[0] as ОбъявлениеПеременной;

    проверить(
        промежуточное.имя === "промежуточное",
        "Локальная переменная имеет правильное имя"
    );

    const возврат =
        функция.тело.команды[1] as Возврат;

    проверить(
        (возврат.значение as Имя).значение === "промежуточное",
        "Возврат использует локальную переменную"
    );

    const вызов =
        результат.значение as ВызовФункции;

    проверить(
        вызов.имя === "сложить",
        "Имя вызванной функции правильное"
    );

    проверить(
        вызов.аргументы.length === 2,
        "Вызов содержит два аргумента"
    );
}

