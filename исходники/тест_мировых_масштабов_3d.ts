function проверить(
    условие: boolean,
    название: string
): void {
    if (условие) {
        успешно++;
        console.log(`✓ ${название}`);
    } else {
        ошибок++;
        console.error(`✗ ${название}`);
    }
}

function создатьТестовыйОбъект(
    идентификатор: string,
    имя: string,
    трансформация: ReturnType<typeof создатьТрансформацию3D>
) {
    const объект = создатьОбъект3D(
        идентификатор,
        имя,
        "система"
    );

    объект.трансформация = трансформация;

    return объект;
}

