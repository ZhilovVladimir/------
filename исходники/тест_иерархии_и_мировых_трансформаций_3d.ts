/**
 * Простая проверка.
 */
function проверить(
    условие: boolean,
    сообщение: string
): void {

    if (!условие) {
        throw new Error(
            `ТЕСТ НЕ ПРОЙДЕН: ${сообщение}`
        );
    }

    console.log(
        `✓ ${сообщение}`
    );
}

/**
 * Проверка числового равенства.
 */
function проверитьЧисло(
    фактическое: number,
    ожидаемое: number,
    сообщение: string
): void {

    const погрешность = 0.000001;

    проверить(
        Math.abs(
            фактическое - ожидаемое
        ) < погрешность,
        `${сообщение} — получено ${фактическое}, ожидалось ${ожидаемое}`
    );
}

