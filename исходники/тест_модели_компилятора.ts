const компилятор =
    new Компилятор();


const исходныйКод = `
программа модель_проверка

начало

    пусть число = 10
    пусть другое = 20
    пусть сумма = число + другое

конец
`;


const проверка =
    компилятор.проверить(
        исходныйКод
    );


проверить(
    проверка.успешно,
    "Программа проходит компиляцию без семантических ошибок"
);


проверить(
    проверка.модель !== null,
    "После успешной проверки создаётся единая внутренняя модель"
);


const модель =
    проверка.модель;


проверить(
    модель !== null,
    "Компилятор возвращает объект единой внутренней модели"
);


if (модель !== null) {

    проверить(
        модель.успешна(),
        "Модель помечена как успешно прошедшая проверку"
    );

    проверить(
        модель.получитьДерево().length > 0,
        "Модель содержит дерево программы"
    );

    проверить(
        модель.получитьОшибки().length === 0,
        "В модели отсутствуют семантические ошибки"
    );

    проверить(
        модель.получитьГлобальныеСимволы().some(
            символ =>
                символ.имя === "число"
        ),
        "Модель содержит глобальный символ «число»"
    );

    проверить(
        модель.получитьГлобальныеСимволы().some(
            символ =>
                символ.имя === "другое"
        ),
        "Модель содержит глобальный символ «другое»"
    );

    проверить(
        модель.получитьГлобальныеСимволы().some(
            символ =>
                символ.имя === "сумма"
        ),
        "Модель содержит глобальный символ «сумма»"
    );

    проверить(
        компилятор.получитьМодель() === модель,
        "Компилятор возвращает текущую модель"
    );
}


