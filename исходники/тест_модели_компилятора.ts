let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибокТеста = 0;


// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибокТеста++;

    console.log(
        `❌ ${сообщение}`
    );
}


