import type {
    Объект3D
} from "./объект_3d.js";

import type {
    Трансформация3D
} from "./пространство_3d.js";

import {
    вычислитьМировуюТрансформацию,
    клонироватьТрансформацию3D
} from "./пространство_3d.js";

import type {
    КонтейнерПространства3D
} from "./контейнер_пространства_3d.js";

/* ============================================================
 * РЕЗУЛЬТАТЫ
 * ========================================================== */

/**
 * Результат получения мировой трансформации.
 */
export interface РезультатМировойТрансформации3D {

    /**
     * Успешно ли выполнена операция.
     */
    успешно: boolean;

    /**
     * Человекочитаемое описание результата.
     */
    сообщение: string;

    /**
     * Полученная мировая трансформация.
     */
    трансформация?: Трансформация3D;
}

/* ============================================================
 * МИРОВАЯ ТРАНСФОРМАЦИЯ
 * ========================================================== */

/**
 * Вычисляет мировую трансформацию одного объекта.
 *
 * Если объект корневой, его локальная трансформация
 * одновременно является мировой.
 *
 * Если у объекта есть родитель, учитывается
 * трансформация родителя.
 */
export function вычислитьМировуюТрансформациюОбъекта3D(
    объект: Объект3D,
    родительская?: Трансформация3D
): Трансформация3D {

    if (
        !объект ||
        typeof объект !== "object"
    ) {
        throw new Error(
            "Нельзя вычислить мировую трансформацию некорректного объекта 3D."
        );
    }

    if (
        !объект.трансформация
    ) {
        throw new Error(
            `У объекта "${объект.идентификатор}" отсутствует трансформация 3D.`
        );
    }

    return вычислитьМировуюТрансформацию(
        объект.трансформация,
        родительская
    );
}

/**
 * Получает мировую трансформацию объекта
 * через весь родительский путь.
 *
 * Например:
 *
 * система
 *   ↓
 * программа
 *   ↓
 * функция
 *   ↓
 * переменная
 *
 * Для переменной будут последовательно учтены
 * все трансформации выше неё.
 */
export function получитьМировуюТрансформацию3D(
    контейнер: КонтейнерПространства3D,
    идентификаторОбъекта: string
): РезультатМировойТрансформации3D {

    if (
        !контейнер
    ) {
        return {
            успешно: false,
            сообщение:
                "Не передан пространственный контейнер 3D."
        };
    }

    if (
        typeof идентификаторОбъекта !== "string" ||
        идентификаторОбъекта.length === 0
    ) {
        return {
            успешно: false,
            сообщение:
                "Идентификатор объекта 3D должен быть непустой строкой."
        };
    }

    const объект =
        контейнер.получитьОбъект(
            идентификаторОбъекта
        );

    if (
        !объект
    ) {
        return {
            успешно: false,
            сообщение:
                `Объект "${идентификаторОбъекта}" не найден в пространстве 3D.`
        };
    }

    const цепочка:
        Объект3D[] = [];

    const посещённые =
        new Set<string>();

    let текущий:
        Объект3D | undefined = объект;

    while (
        текущий
    ) {

        if (
            посещённые.has(
                текущий.идентификатор
            )
        ) {
            return {
                успешно: false,
                сообщение:
                    "Обнаружен цикл при вычислении мировой трансформации 3D."
            };
        }

        посещённые.add(
            текущий.идентификатор
        );

        цепочка.push(
            текущий
        );

        if (
            текущий.родитель === null
        ) {
            break;
        }

        текущий =
            контейнер.получитьОбъект(
                текущий.родитель
            );

        if (
            !текущий
        ) {
            return {
                успешно: false,
                сообщение:
                    "У объекта отсутствует родитель в пространственном контейнере 3D."
            };
        }
    }

    let мировая:
        Трансформация3D =
        клонироватьТрансформацию3D(
            цепочка[цепочка.length - 1]
                .трансформация
        );

    for (
        let индекс =
            цепочка.length - 2;
        индекс >= 0;
        индекс--
    ) {

        мировая =
            вычислитьМировуюТрансформацию(
                цепочка[индекс].трансформация,
                мировая
            );
    }

    return {
        успешно: true,
        сообщение:
            `Мировая трансформация объекта "${идентификаторОбъекта}" вычислена.`,
        трансформация:
            мировая
    };
}

/**
 * Получает мировую позицию объекта.
 */
export function получитьМировуюПозицию3D(
    контейнер: КонтейнерПространства3D,
    идентификаторОбъекта: string
): РезультатМировойТрансформации3D {

    const результат =
        получитьМировуюТрансформацию3D(
            контейнер,
            идентификаторОбъекта
        );

    if (
        !результат.успешно ||
        !результат.трансформация
    ) {
        return результат;
    }

    return {
        успешно: true,
        сообщение:
            `Мировая позиция объекта "${идентификаторОбъекта}" получена.`,
        трансформация:
            клонироватьТрансформацию3D(
                результат.трансформация
            )
    };
}

/* ============================================================
 * ПРОВЕРКА
 * ========================================================== */

/**
 * Проверяет результат мировой трансформации.
 */
export function мироваяТрансформация3DКорректна(
    результат: РезультатМировойТрансформации3D
): boolean {

    if (
        !результат ||
        typeof результат !== "object"
    ) {
        return false;
    }

    if (
        !результат.успешно
    ) {
        return false;
    }

    if (
        !результат.трансформация
    ) {
        return false;
    }

    const трансформация =
        результат.трансформация;

    const позиция =
        трансформация.позиция;

    const поворот =
        трансформация.поворот;

    const масштаб =
        трансформация.масштаб;

    return (
        Number.isFinite(позиция.x) &&
        Number.isFinite(позиция.y) &&
        Number.isFinite(позиция.z) &&
        Number.isFinite(поворот.x) &&
        Number.isFinite(поворот.y) &&
        Number.isFinite(поворот.z) &&
        Number.isFinite(масштаб.x) &&
        Number.isFinite(масштаб.y) &&
        Number.isFinite(масштаб.z) &&
        масштаб.x !== 0 &&
        масштаб.y !== 0 &&
        масштаб.z !== 0
    );
}