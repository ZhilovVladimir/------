// ============================================================
// 🐌 УЛИТКА
// Самотест интегратора исполнения и 3D-ядра
// ============================================================

import {
    Компилятор
} from "./компилятор.js";

import {
    Ядро3D
} from "./ядро_3d.js";

import {
    ИнтеграторИсполнения3D
} from "./интегратор_исполнения_3d.js";

// ============================================================
// СЧЁТЧИКИ
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;

// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {
    всегоПроверок++;

    if (условие) {
        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибок++;

    console.log(
        `❌ ${сообщение}`
    );
}

// ============================================================
// ЗАГОЛОВОК
// ============================================================

function заголовок(
    номер: number,
    название: string
): void {
    console.log("");

    console.log(
        "================================"
    );

    console.log(
        `[${номер}] ${название}`
    );

    console.log(
        "================================"
    );
}

// ============================================================
// [1] ПРОСТАЯ ПЕРЕМЕННАЯ
// ============================================================

заголовок(
    1,
    "СОБЫТИЕ ПЕРЕМЕННОЙ → 3D"
);

{
    const ядро =
        new Ядро3D();

    const интегратор =
        new ИнтеграторИсполнения3D(
            ядро
        );

    const компилятор =
        new Компилятор();

    компилятор.установитьОбработчикСобытий(
        интегратор.создатьОбработчик()
    );

    const результат =
        компилятор.выполнить(`
            пусть число = 10
            показать число
        `);

    const узлы =
        ядро.получитьУзлы();

    const узлыПеременных =
        узлы.filter(
            узел =>
                узел.тип === "переменная" &&
                узел.имя === "число"
        );

    проверить(
        результат.успешно,
        "Программа успешно выполняется"
    );

    проверить(
        узлыПеременных.length === 1,
        "В 3D создан один узел переменной"
    );

    проверить(
        узлыПеременных[0]?.тип === "переменная",
        "Созданный 3D-узел имеет тип переменная"
    );

    проверить(
        узлыПеременных[0]?.имя === "число",
        "3D-узел содержит имя переменной"
    );

    проверить(
        узлыПеременных[0]?.активен === true,
        "Узел переменной становится активным"
    );

    проверить(
        ядро.получитьСостояние().состояние ===
            "завершено",
        "3D-ядро получает завершение программы"
    );
}

// ============================================================
// [2] ФУНКЦИЯ
// ============================================================

заголовок(
    2,
    "СОБЫТИЯ ФУНКЦИИ → 3D"
);

{
    const ядро =
        new Ядро3D();

    const интегратор =
        new ИнтеграторИсполнения3D(
            ядро
        );

    const компилятор =
        new Компилятор();

    компилятор.установитьОбработчикСобытий(
        интегратор.создатьОбработчик()
    );

    const результат =
        компилятор.выполнить(`
            функция сложить(первое, второе)
                вернуть первое + второе
            конец

            пусть результат =
                сложить(10, 20)

            показать результат
        `);

    const узлы =
        ядро.получитьУзлы();

    const функция =
        узлы.find(
            узел =>
                узел.тип ===
                    "функция" &&
                узел.имя ===
                    "сложить"
        );

    проверить(
        результат.успешно,
        "Программа с функцией выполняется"
    );

    проверить(
        функция !== undefined,
        "В 3D появляется узел функции"
    );

    проверить(
        функция?.активен === false,
        "После возврата узел функции деактивирован"
    );

    проверить(
        узлы.some(
            узел =>
                узел.тип ===
                    "переменная" &&
                узел.имя ===
                    "результат"
        ),
        "В 3D появляется узел результата"
    );
}

// ============================================================
// [3] СОСТОЯНИЕ
// ============================================================

заголовок(
    3,
    "СИНХРОНИЗАЦИЯ СОСТОЯНИЯ"
);

{
    const ядро =
        new Ядро3D();

    const интегратор =
        new ИнтеграторИсполнения3D(
            ядро
        );

    интегратор.обработатьСобытие({
        идентификатор: "тест_1",

        тип: "начало_программы",

        время: Date.now(),

        источник: "тест",

        данные: null
    });

    проверить(
        ядро.получитьСостояние().состояние ===
            "выполнение",
        "Событие начала переводит 3D-ядро в выполнение"
    );

    интегратор.обработатьСобытие({
        идентификатор: "тест_2",

        тип: "завершение_программы",

        время: Date.now(),

        источник: "тест",

        данные: null
    });

    проверить(
        ядро.получитьСостояние().состояние ===
            "завершено",
        "Событие завершения переводит 3D-ядро в завершено"
    );
}

// ============================================================
// [4] ОШИБКА
// ============================================================

заголовок(
    4,
    "СОБЫТИЕ ОШИБКИ → 3D"
);

{
    const ядро =
        new Ядро3D();

    const интегратор =
        new ИнтеграторИсполнения3D(
            ядро
        );

    интегратор.обработатьСобытие({
        идентификатор: "тест_ошибка",

        тип: "ошибка",

        время: Date.now(),

        источник: "исполнитель",

        данные: {
            сообщение:
                "Тестовая ошибка"
        }
    });

    const узлы =
        ядро.получитьУзлы();

    проверить(
        узлы.length === 1,
        "Для ошибки создаётся 3D-узел"
    );

    проверить(
        узлы[0]?.тип === "ошибка",
        "3D-узел ошибки имеет правильный тип"
    );

    проверить(
        узлы[0]?.активен === true,
        "3D-узел ошибки активен"
    );
}

