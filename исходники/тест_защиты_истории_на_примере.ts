import { Ядро3D } from "./ядро_3d.js";

console.log("");
console.log("============================================================");
console.log("🐌 ПРОВЕРКА ЗАЩИТЫ ИСТОРИИ НА РЕАЛЬНОМ ПРИМЕРЕ");
console.log("============================================================");
console.log("");

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибокПроверки = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

    } else {

        ошибокПроверки++;

        console.log(
            `❌ ОШИБКА: ${сообщение}`
        );
    }
}

console.log("[1] СОЗДАНИЕ ЯДРА");

const ядро =
    new Ядро3D();

проверить(
    ядро.получитьКоличествоСобытий() === 0,
    "История изначально пустая"
);

console.log("");
console.log("[2] СОЗДАНИЕ ПЕРЕМЕННОЙ");

ядро.добавитьПеременную({
    имя: "имя",
    значение: "Владимир",
    тип: "текст"
});

const состояниеПослеСоздания =
    ядро.получитьСостояние();

console.log(
    "Переменная:",
    состояниеПослеСоздания.переменные[0]
);

проверить(
    состояниеПослеСоздания.переменные.length === 1,
    "Создана одна переменная"
);

проверить(
    состояниеПослеСоздания.переменные[0]?.имя === "имя",
    "Имя переменной равно 'имя'"
);

проверить(
    состояниеПослеСоздания.переменные[0]?.значение === "Владимир",
    "Значение переменной равно 'Владимир'"
);

console.log("");
console.log("[3] ПОЛУЧЕНИЕ ИСТОРИИ");

const история =
    ядро.получитьСобытия();

console.log(
    "Количество событий:",
    история.length
);

проверить(
    история.length === 1,
    "В истории записано одно событие"
);

проверить(
    история[0] !== undefined,
    "Событие получено через публичный метод"
);

console.log("");
console.log("[4] ПОПЫТКА ИЗМЕНЕНИЯ ИСТОРИИ ИЗВНЕ");

const внешняяКопия =
    история[0];

const данныеУзла =
    внешняяКопия?.данные as {
        данные?: {
            значение?: unknown;
        };
    } | undefined;

const значениеДоИзменения =
    данныеУзла?.данные?.значение;

console.log(
    "Значение во внешней копии ДО изменения:",
    значениеДоИзменения
);

if (
    данныеУзла?.данные !== undefined
) {

    данныеУзла.данные.значение =
        "ПОДМЕНА";
}

const значениеПослеИзменения =
    данныеУзла?.данные?.значение;

console.log(
    "Значение во внешней копии ПОСЛЕ изменения:",
    значениеПослеИзменения
);

проверить(
    значениеДоИзменения === "Владимир",
    "Во внешней копии до изменения было значение 'Владимир'"
);

проверить(
    значениеПослеИзменения === "ПОДМЕНА",
    "Внешнюю копию удалось изменить"
);

console.log("");
console.log("[5] ПРОВЕРКА НАСТОЯЩЕЙ ИСТОРИИ");

const новаяИстория =
    ядро.получитьСобытия();

const данныеНовойИстории =
    новаяИстория[0]?.данные as {
        данные?: {
            значение?: unknown;
        };
    } | undefined;

const настоящееЗначение =
    данныеНовойИстории?.данные?.значение;

console.log(
    "Значение во внутренней истории:",
    настоящееЗначение
);

проверить(
    настоящееЗначение === "Владимир",
    "Внутренняя история сохранила значение 'Владимир'"
);

проверить(
    настоящееЗначение !== "ПОДМЕНА",
    "Внутренняя история не приняла внешнюю подмену"
);

console.log("");
console.log("[6] ПРОВЕРКА СОСТОЯНИЯ ЯДРА");

const состояние =
    ядро.получитьСостояние();

console.log(
    "Состояние:",
    состояние
);

проверить(
    состояние.переменные[0]?.значение === "Владимир",
    "Состояние ядра по-прежнему содержит 'Владимир'"
);

console.log("");
console.log("[7] ВОСПРОИЗВЕДЕНИЕ ИСТОРИИ");

ядро.начатьВоспроизведение();

проверить(
    ядро.получитьРежимВоспроизведения() === "воспроизведение",
    "Ядро перешло в режим воспроизведения"
);

const первоеСобытие =
    ядро.следующееСобытие();

проверить(
    первоеСобытие !== null,
    "Первое событие успешно воспроизведено"
);

ядро.остановитьВоспроизведение();

console.log("");
console.log("[8] ПРОВЕРКА ПОСЛЕ REPLAY");

const состояниеПослеReplay =
    ядро.получитьСостояние();

console.log(
    "Переменные после replay:",
    состояниеПослеReplay.переменные
);

проверить(
    состояниеПослеReplay.переменные.length === 1,
    "После replay восстановлена одна переменная"
);

проверить(
    состояниеПослеReplay.переменные[0]?.имя === "имя",
    "После replay восстановлено имя переменной"
);

проверить(
    состояниеПослеReplay.переменные[0]?.значение === "Владимир",
    "После replay восстановлено значение 'Владимир'"
);

console.log("");
console.log("============================================================");
console.log("🐌 ИТОГ ПРОВЕРКИ");
console.log("============================================================");

console.log(
    `Всего проверок: ${всегоПроверок}`
);

console.log(
    `Успешных проверок: ${успешныхПроверок}`
);

console.log(
    `Ошибок: ${ошибокПроверки}`
);

console.log("");

if (ошибокПроверки === 0) {

    console.log(
        "🐌 ✅ ВСЕ ПРОВЕРКИ ЗАЩИТЫ ИСТОРИИ ПРОЙДЕНЫ"
    );

} else {

    console.log(
        "🐌 ❌ ОБНАРУЖЕНЫ ОШИБКИ"
    );
}

console.log("");
console.log("🐌 ПРОВЕРКА ЗАВЕРШЕНА");
