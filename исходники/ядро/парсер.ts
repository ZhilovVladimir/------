import {
    Узел,
    Число,
    Текст,
    Имя,
    Операция,
    ОбъявлениеПеременной,
    ВызовФункции,
    Функция,
    Возврат
} from "../дерево/узлы.js";

export interface Лексема {
    тип: string;
    значение: string;
    строка: number;
    позиция: number;
}

export class Парсер {
    private лексемы: Лексема[];
    private текущаяПозиция: number = 0;
    private функции: Map<string, Функция> = new Map();

    // Имена, доступные внутри текущей функции.
    // Сюда входят параметры и локальные переменные.
    private именаТекущейФункции: Set<string> | null = null;

    constructor(лексемы: Лексема[]) {
        this.лексемы = лексемы;
    }

    private текущаяЛексема(): Лексема {
        return this.лексемы[this.текущаяПозиция];
    }

    private следующийШаг(): void {
        this.текущаяПозиция++;
    }

    private проверитьТип(тип: string): boolean {
        return this.текущаяЛексема()?.тип === тип;
    }

    private проверитьЗначение(значение: string): boolean {
        return this.текущаяЛексема()?.значение === значение;
    }

    private разобратьЧисло(): Число {
        const лексема = this.текущаяЛексема();

        const результат: Число = {
            вид: "ЧИСЛО",
            значение: Number(лексема.значение)
        };

        this.следующийШаг();

        return результат;
    }

    private разобратьТекст(): Текст {
        const лексема = this.текущаяЛексема();

        const результат: Текст = {
            вид: "ТЕКСТ",
            значение: лексема.значение
        };

        this.следующийШаг();

        return результат;
    }

    private разобратьИмя(): Имя {
        const лексема = this.текущаяЛексема();

        // Если мы внутри функции,
        // имя обязано существовать в её области видимости.
        if (this.именаТекущейФункции !== null) {
            if (!this.именаТекущейФункции.has(лексема.значение)) {
                throw new Error(
                    `🐌 Ошибка парсера: неизвестное имя «${лексема.значение}» внутри функции.`
                );
            }
        }

        const результат: Имя = {
            вид: "ИМЯ",
            значение: лексема.значение
        };

        this.следующийШаг();

        return результат;
    }

    private разобратьВызовФункции(): ВызовФункции {
        const имя = this.текущаяЛексема().значение;

        this.следующийШаг();

        if (!this.проверитьТип("СКОБКА_ЛЕВАЯ")) {
            throw new Error(
                `🐌 Ошибка парсера: после имени функции «${имя}» ожидалась «(».`
            );
        }

        this.следующийШаг();

        const аргументы: Узел[] = [];

        if (!this.проверитьТип("СКОБКА_ПРАВАЯ")) {
            while (true) {
                аргументы.push(this.разобратьВыражение());

                if (this.проверитьТип("ЗАПЯТАЯ")) {
                    this.следующийШаг();
                    continue;
                }

                break;
            }
        }

        if (!this.проверитьТип("СКОБКА_ПРАВАЯ")) {
            throw new Error(
                `🐌 Ошибка парсера: после аргументов функции «${имя}» ожидалась «)».`
            );
        }

        this.следующийШаг();

        const функция = this.функции.get(имя);

        if (!функция) {
            throw new Error(
                `🐌 Ошибка парсера: функция «${имя}» не объявлена.`
            );
        }

        const ожидается = функция.параметры.length;
        const получено = аргументы.length;

        if (ожидается !== получено) {
            throw new Error(
                `🐌 Ошибка парсера: функция «${имя}» ожидает ${ожидается} аргумента(ов), но получено ${получено}.`
            );
        }

        return {
            вид: "ВЫЗОВ_ФУНКЦИИ",
            имя,
            аргументы
        };
    }

    private разобратьПервичное(): Узел {
        if (this.проверитьТип("ЧИСЛО")) {
            return this.разобратьЧисло();
        }

        if (this.проверитьТип("ТЕКСТ")) {
            return this.разобратьТекст();
        }

        if (this.проверитьТип("ИМЯ")) {
            if (
                this.лексемы[this.текущаяПозиция + 1]?.тип ===
                "СКОБКА_ЛЕВАЯ"
            ) {
                return this.разобратьВызовФункции();
            }

            return this.разобратьИмя();
        }

        if (this.проверитьТип("СКОБКА_ЛЕВАЯ")) {
            this.следующийШаг();

            const выражение = this.разобратьВыражение();

            if (!this.проверитьТип("СКОБКА_ПРАВАЯ")) {
                throw new Error(
                    "🐌 Ошибка парсера: ожидалась закрывающая скобка «)»."
                );
            }

            this.следующийШаг();

            return выражение;
        }

        throw new Error(
            `🐌 Ошибка парсера: неожиданная лексема "${this.текущаяЛексема()?.значение}"`
        );
    }

    // ========================================================
    // ВЫРАЖЕНИЕ
    //
    // Уровни приоритета:
    //
    // 1. Первичное выражение:
    //    число, текст, имя, вызов функции, скобки
    //
    // 2. Умножение:
    //    *, /, %
    //
    // 3. Сложение:
    //    +, -
    //
    // 4. Сравнение:
    //    ==, !=, >, <, >=, <=
    //
    // Поэтому:
    //
    // 2 + 3 * 4
    //
    // превращается в:
    //
    // 2 + (3 * 4)
    // ========================================================

    private разобратьВыражение(): Узел {
        return this.разобратьСравнение();
    }

    private разобратьСравнение(): Узел {
        let левое = this.разобратьСложение();

        while (
            this.проверитьТип("ОПЕРАТОР") &&
            [
                "==",
                "!=",
                ">",
                "<",
                ">=",
                "<="
            ].includes(this.текущаяЛексема().значение)
        ) {
            const оператор = this.текущаяЛексема().значение;

            this.следующийШаг();

            const правое = this.разобратьСложение();

            const операция: Операция = {
                вид: "ОПЕРАЦИЯ",
                оператор,
                левое,
                правое
            };

            левое = операция;
        }

        return левое;
    }

    private разобратьСложение(): Узел {
        let левое = this.разобратьУмножение();

        while (
            this.проверитьТип("ОПЕРАТОР") &&
            [
                "+",
                "-"
            ].includes(this.текущаяЛексема().значение)
        ) {
            const оператор = this.текущаяЛексема().значение;

            this.следующийШаг();

            const правое = this.разобратьУмножение();

            const операция: Операция = {
                вид: "ОПЕРАЦИЯ",
                оператор,
                левое,
                правое
            };

            левое = операция;
        }

        return левое;
    }

    private разобратьУмножение(): Узел {
        let левое = this.разобратьПервичное();

        while (
            this.проверитьТип("ОПЕРАТОР") &&
            [
                "*",
                "/",
                "%"
            ].includes(this.текущаяЛексема().значение)
        ) {
            const оператор = this.текущаяЛексема().значение;

            this.следующийШаг();

            const правое = this.разобратьПервичное();

            const операция: Операция = {
                вид: "ОПЕРАЦИЯ",
                оператор,
                левое,
                правое
            };

            левое = операция;
        }

        return левое;
    }

    private разобратьПеременную(): ОбъявлениеПеременной {
        this.следующийШаг();

        const имя = this.текущаяЛексема();

        if (!имя || имя.тип !== "ИМЯ") {
            throw new Error(
                "🐌 Ошибка парсера: после «пусть» ожидалось имя переменной."
            );
        }

        // Внутри функции проверяем,
        // не занято ли это имя параметром
        // или предыдущей локальной переменной.
        if (this.именаТекущейФункции !== null) {
            if (this.именаТекущейФункции.has(имя.значение)) {
                throw new Error(
                    `🐌 Ошибка парсера: имя «${имя.значение}» уже объявлено в текущей функции.`
                );
            }
        }

        this.следующийШаг();

        if (
            !this.проверитьТип("ОПЕРАТОР") ||
            !this.проверитьЗначение("=")
        ) {
            throw new Error(
                "🐌 Ошибка парсера: после имени переменной ожидался оператор «=»."
            );
        }

        this.следующийШаг();

        // Сначала разбираем значение.
        // Поэтому переменная не может ссылаться сама на себя
        // во время собственного объявления.
        const значение = this.разобратьВыражение();

        // Только после успешного разбора выражения
        // добавляем имя в область видимости.
        if (this.именаТекущейФункции !== null) {
            this.именаТекущейФункции.add(имя.значение);
        }

        return {
            вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
            имя: имя.значение,
            значение
        };
    }

    private разобратьВозврат(): Возврат {
        this.следующийШаг();

        const значение = this.разобратьВыражение();

        return {
            вид: "ВОЗВРАТ",
            значение
        };
    }

    private разобратьФункцию(): Функция {
        this.следующийШаг();

        const имя = this.текущаяЛексема();

        if (!имя || имя.тип !== "ИМЯ") {
            throw new Error(
                "🐌 Ошибка парсера: после «функция» ожидалось имя функции."
            );
        }

        const имяФункции = имя.значение;

        this.следующийШаг();

        if (!this.проверитьТип("СКОБКА_ЛЕВАЯ")) {
            throw new Error(
                `🐌 Ошибка парсера: после имени функции «${имяФункции}» ожидалась «(».`
            );
        }

        this.следующийШаг();

        const параметры: string[] = [];

        if (!this.проверитьТип("СКОБКА_ПРАВАЯ")) {
            while (true) {
                const параметр = this.текущаяЛексема();

                if (!параметр || параметр.тип !== "ИМЯ") {
                    throw new Error(
                        `🐌 Ошибка парсера: в параметрах функции «${имяФункции}» ожидалось имя.`
                    );
                }

                if (параметры.includes(параметр.значение)) {
                    throw new Error(
                        `🐌 Ошибка парсера: параметр «${параметр.значение}» функции «${имяФункции}» объявлен повторно.`
                    );
                }

                параметры.push(параметр.значение);

                this.следующийШаг();

                if (this.проверитьТип("ЗАПЯТАЯ")) {
                    this.следующийШаг();
                    continue;
                }

                break;
            }
        }

        if (!this.проверитьТип("СКОБКА_ПРАВАЯ")) {
            throw new Error(
                `🐌 Ошибка парсера: в объявлении функции «${имяФункции}» ожидалась «)».`
            );
        }

        this.следующийШаг();

        // Сохраняем предыдущую область видимости.
        // Это важно, если в будущем функции будут вкладываться
        // или появятся другие области видимости.
        const предыдущиеИмена = this.именаТекущейФункции;

        // В начале функции доступны её параметры.
        this.именаТекущейФункции = new Set(параметры);

        const команды: Узел[] = [];

        while (
            this.текущаяПозиция < this.лексемы.length &&
            !this.проверитьТип("КОНЕЦ_ФАЙЛА") &&
            !(
                this.проверитьТип("КЛЮЧЕВОЕ_СЛОВО") &&
                this.проверитьЗначение("конец")
            )
        ) {
            if (
                this.проверитьТип("КЛЮЧЕВОЕ_СЛОВО") &&
                this.проверитьЗначение("вернуть")
            ) {
                команды.push(this.разобратьВозврат());
                continue;
            }

            if (
                this.проверитьТип("КЛЮЧЕВОЕ_СЛОВО") &&
                this.проверитьЗначение("пусть")
            ) {
                команды.push(this.разобратьПеременную());
                continue;
            }

            // Пока неизвестные конструкции пропускаем.
            this.следующийШаг();
        }

        if (
            !this.проверитьТип("КЛЮЧЕВОЕ_СЛОВО") ||
            !this.проверитьЗначение("конец")
        ) {
            // Восстанавливаем область видимости
            // даже при ошибке.
            this.именаТекущейФункции = предыдущиеИмена;

            throw new Error(
                `🐌 Ошибка парсера: функция «${имяФункции}» не завершена словом «конец».`
            );
        }

        this.следующийШаг();

        const функция: Функция = {
            вид: "ФУНКЦИЯ",
            имя: имяФункции,
            параметры,
            тело: {
                вид: "БЛОК",
                команды
            }
        };

        // Функция становится известна после разбора.
        this.функции.set(имяФункции, функция);

        // Возвращаем предыдущую область видимости.
        this.именаТекущейФункции = предыдущиеИмена;

        return функция;
    }

    public разобрать(): Узел[] {
        const результаты: Узел[] = [];

        while (
            this.текущаяПозиция < this.лексемы.length &&
            !this.проверитьТип("КОНЕЦ_ФАЙЛА")
        ) {
            if (
                this.проверитьТип("КЛЮЧЕВОЕ_СЛОВО") &&
                this.проверитьЗначение("функция")
            ) {
                результаты.push(this.разобратьФункцию());
                continue;
            }

            if (
                this.проверитьТип("КЛЮЧЕВОЕ_СЛОВО") &&
                this.проверитьЗначение("пусть")
            ) {
                результаты.push(this.разобратьПеременную());
                continue;
            }

            this.следующийШаг();
        }

        return результаты;
    }
}