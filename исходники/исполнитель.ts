    private выполнитьУзел(
        узел: Узел,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {

        switch (узел.вид) {

            case "ЧИСЛО":
                return this.выполнитьЧисло(
                    узел
                );

            case "ТЕКСТ":
                return this.выполнитьТекст(
                    узел
                );

            case "ИМЯ":
                return this.выполнитьИмя(
                    узел,
                    область
                );

            case "ОПЕРАЦИЯ":
                return this.выполнитьОперацию(
                    узел,
                    область
                );

            case "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ":
                return this.выполнитьОбъявлениеПеременной(
                    узел,
                    область
                );

            case "ПОКАЗАТЬ":
                return this.выполнитьПоказать(
                    узел,
                    область
                );

            case "УСЛОВИЕ":
                return this.выполнитьУсловие(
                    узел,
                    область
                );

            case "ВЫЗОВ_ФУНКЦИИ":
                return this.выполнитьВызовФункции(
                    узел,
                    область
                );

            case "ВОЗВРАТ":
                return this.выполнитьВозврат(
                    узел,
                    область
                );

            case "ФУНКЦИЯ":
                return null;

            case "БЛОК":
                return this.выполнитьБлок(
                    узел.команды,
                    область
                );

            case "ПРОГРАММА":
                return this.выполнитьБлок(
                    узел.тело.команды,
                    область
                );
        }
    }

