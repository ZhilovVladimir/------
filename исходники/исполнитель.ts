    // ========================================================

    private выполнитьИмя(
        узел: Имя,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {

        if (!область.has(узел.значение)) {
            throw new Error(
                `🐌 Ошибка выполнения: переменная «${узел.значение}» не существует.`
            );
        }

        return область.get(
            узел.значение
        )!;
    }

    // ========================================================
    // ПЕРЕМЕННАЯ
    // ========================================================

    private выполнитьОбъявлениеПеременной(
        узел: ОбъявлениеПеременной,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {

        const значение =
            this.вычислитьВыражение(
                узел.значение,
                область
            );

        const новоеОбъявление =
            !область.has(узел.имя);

        область.set(
            узел.имя,
            значение
        );

        this.создатьСобытие(
            новоеОбъявление
                ? "объявление_переменной"
                : "изменение_переменной",

            `переменная:${узел.имя}`,

            {
                имя: узел.имя,
                значение,

                источники:
                    this.получитьИсточникиВыражения(
                        узел.значение
                    ),

                оператор:
                    this.получитьОператорВыражения(
                        узел.значение
                    )
            }
        );

        return null;
    }

    // ========================================================
    // ПОКАЗ
    // ========================================================

    private выполнитьПоказать(
        узел: Показать,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {

        const значения =
            узел.значения.map(
                значение =>
                    this.вычислитьВыражение(
                        значение,
                        область
                    )
            );

        const текст =
            значения
                .map(
                    значение =>
                        this.преобразоватьВДисплей(
                            значение
                        )
                )
                .join("");

        this.вывод.push(
            текст
        );

        this.создатьСобытие(
            "показ",
            "показать",
            {
                значения,
                текст,

                источники:
                    узел.значения.flatMap(
                        значение =>
                            this.получитьИсточникиВыражения(
                                значение
                            )
                    )
            }
        );

        return null;
    }

    // ========================================================
    // УСЛОВИЕ
    // ========================================================

    private выполнитьУсловие(
        узел: Условие,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {

        const результат =
            this.вычислитьВыражение(
                узел.условие,
                область
            );

        if (
            typeof результат !==
            "boolean"
        ) {
            throw new Error(
                "🐌 Ошибка выполнения: условие должно давать истину или ложь."
            );
        }

        this.создатьСобытие(
            "проверка_условия",
            "условие",
            {
                результат,

                источники:
                    this.получитьИсточникиВыражения(
                        узел.условие
                    ),

                оператор:
                    this.получитьОператорВыражения(
                        узел.условие
                    )
            }
        );

        if (результат) {

            this.создатьСобытие(
                "ветка_тогда",
                "условие",
                {
                    ветка: "тогда"
                }
            );

            this.выполнитьБлок(
                узел.тогда.команды,
                область
            );

            return null;
        }

        if (узел.иначе !== null) {

            this.создатьСобытие(
                "ветка_иначе",
                "условие",
                {
                    ветка: "иначе"
                }
            );

            this.выполнитьБлок(
                узел.иначе.команды,
                область
            );
        }

        return null;
    }

