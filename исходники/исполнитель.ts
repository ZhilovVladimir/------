// ============================================================
// 🐌 УЛИТКА
// Исполнитель дерева программы
// ============================================================

import type {
    Узел,
    Число,
    Текст,
    Имя,
    Операция,
    ОбъявлениеПеременной,
    ВызовФункции,
    Функция,
    Возврат,
    Показать,
    Условие
} from "./дерево/узлы.js";

// ============================================================
// ДОПУСТИМЫЕ ЗНАЧЕНИЯ ВО ВРЕМЯ ВЫПОЛНЕНИЯ
// ============================================================

export type ЗначениеИсполнения =
    | number
    | string
    | boolean
    | null;

// ============================================================
// СОБЫТИЕ ИСПОЛНЕНИЯ
// ============================================================

export type ТипСобытияИсполнения =
    | "начало_программы"
    | "завершение_программы"
    | "объявление_переменной"
    | "изменение_переменной"
    | "показ"
    | "проверка_условия"
    | "ветка_тогда"
    | "ветка_иначе"
    | "вызов_функции"
    | "возврат"
    | "ошибка";

export interface СобытиеИсполнения {
    идентификатор: string;
    тип: ТипСобытияИсполнения;
    время: number;
    источник: string;
    данные: unknown;
}

// ============================================================
// РЕЗУЛЬТАТ ВЫПОЛНЕНИЯ
// ============================================================

export interface РезультатВыполнения {
    вывод: string[];
    переменные: Record<string, ЗначениеИсполнения>;
    события: СобытиеИсполнения[];
}

// ============================================================
// ВНУТРЕННЕЕ ИСКЛЮЧЕНИЕ ВОЗВРАТА
// ============================================================

class СигналВозврата {
    public readonly значение: ЗначениеИсполнения;

    constructor(
        значение: ЗначениеИсполнения
    ) {
        this.значение = значение;
    }
}

// ============================================================
// ИСПОЛНИТЕЛЬ
// ============================================================

export class Исполнитель {
    private функции: Map<string, Функция> = new Map();

    private переменные: Map<
        string,
        ЗначениеИсполнения
    > = new Map();

    private вывод: string[] = [];

    private события: СобытиеИсполнения[] = [];

    private счётчикСобытий = 0;

    private обработчикСобытия:
        ((событие: СобытиеИсполнения) => void) | null = null;

    // ========================================================
    // НАСТРОЙКА ОБРАБОТЧИКА СОБЫТИЙ
    // ========================================================

    public установитьОбработчикСобытий(
        обработчик:
            ((событие: СобытиеИсполнения) => void) | null
    ): void {
        this.обработчикСобытия = обработчик;
    }

    // ========================================================
    // СОЗДАНИЕ СОБЫТИЯ
    // ========================================================

    private создатьСобытие(
        тип: ТипСобытияИсполнения,
        источник: string,
        данные: unknown = null
    ): void {
        this.счётчикСобытий++;

        const событие: СобытиеИсполнения = {
            идентификатор:
                `исполнение_${this.счётчикСобытий}`,
            тип,
            время: Date.now(),
            источник,
            данные
        };

        this.события.push(событие);

        if (this.обработчикСобытия !== null) {
            this.обработчикСобытия(событие);
        }
    }

    // ========================================================
    // СБРОС СОСТОЯНИЯ
    // ========================================================

    private сброситьСостояние(): void {
        this.функции.clear();
        this.переменные.clear();
        this.вывод = [];
        this.события = [];
        this.счётчикСобытий = 0;
    }

    // ========================================================
    // ПУБЛИЧЕСКИЙ ЗАПУСК
    // ========================================================

    public исполнить(
        дерево: Узел[]
    ): РезультатВыполнения {
        this.сброситьСостояние();

        this.создатьСобытие(
            "начало_программы",
            "исполнитель",
            {
                количествоУзлов: дерево.length
            }
        );

        try {
            // ------------------------------------------------
            // Сначала регистрируем все функции.
            // ------------------------------------------------

            for (const узел of дерево) {
                if (узел.вид === "ФУНКЦИЯ") {
                    this.функции.set(
                        узел.имя,
                        узел
                    );
                }
            }

            // ------------------------------------------------
            // Затем выполняем остальные верхнеуровневые узлы.
            // ------------------------------------------------

            for (const узел of дерево) {
                if (узел.вид === "ФУНКЦИЯ") {
                    continue;
                }

                this.выполнитьУзел(
                    узел,
                    this.переменные
                );
            }

            this.создатьСобытие(
                "завершение_программы",
                "исполнитель",
                {
                    вывод: [...this.вывод]
                }
            );

            return this.получитьРезультат();
        } catch (ошибка: unknown) {
            const сообщение =
                ошибка instanceof Error
                    ? ошибка.message
                    : String(ошибка);

            this.создатьСобытие(
                "ошибка",
                "исполнитель",
                {
                    сообщение
                }
            );

            throw ошибка;
        }
    }

    // ========================================================
    // ВЫПОЛНЕНИЕ УЗЛА
    // ========================================================

    private выполнитьУзел(
        узел: Узел,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {
        switch (узел.вид) {
            case "ЧИСЛО":
                return this.выполнитьЧисло(узел);

            case "ТЕКСТ":
                return this.выполнитьТекст(узел);

            case "ИМЯ":
                return this.выполнитьИмя(
                    узел,
                    область
                );

            case "ОПЕРАЦИЯ":
                return this.выполнитьОперацию(
                    узел,
                    область
                );

            case "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ":
                return this.выполнитьОбъявлениеПеременной(
                    узел,
                    область
                );

            case "ПОКАЗАТЬ":
                return this.выполнитьПоказать(
                    узел,
                    область
                );

            case "УСЛОВИЕ":
                return this.выполнитьУсловие(
                    узел,
                    область
                );

            case "ВЫЗОВ_ФУНКЦИИ":
                return this.выполнитьВызовФункции(
                    узел,
                    область
                );

            case "ВОЗВРАТ":
                return this.выполнитьВозврат(
                    узел,
                    область
                );

            case "ФУНКЦИЯ":
                return null;

            case "БЛОК":
                return this.выполнитьБлок(
                    узел.команды,
                    область
                );

            case "ПРОГРАММА":
                return this.выполнитьБлок(
                    узел.тело.команды,
                    область
                );
        }
    }

    // ========================================================
    // ЧИСЛО
    // ========================================================

    private выполнитьЧисло(
        узел: Число
    ): number {
        return узел.значение;
    }

    // ========================================================
    // ТЕКСТ
    // ========================================================

    private выполнитьТекст(
        узел: Текст
    ): string {
        return узел.значение;
    }

    // ========================================================
    // ИМЯ
    // ========================================================

    private выполнитьИмя(
        узел: Имя,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {
        if (!область.has(узел.значение)) {
            throw new Error(
                `🐌 Ошибка выполнения: переменная «${узел.значение}» не существует.`
            );
        }

        return область.get(
            узел.значение
        )!;
    }

    // ========================================================
    // ОБЪЯВЛЕНИЕ ПЕРЕМЕННОЙ
    // ========================================================

    private выполнитьОбъявлениеПеременной(
        узел: ОбъявлениеПеременной,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {
        const значение =
            this.вычислитьВыражение(
                узел.значение,
                область
            );

        const новоеОбъявление =
            !область.has(узел.имя);

        область.set(
            узел.имя,
            значение
        );

        this.создатьСобытие(
            новоеОбъявление
                ? "объявление_переменной"
                : "изменение_переменной",
            `переменная:${узел.имя}`,
            {
                имя: узел.имя,
                значение
            }
        );

        return null;
    }

    // ========================================================
    // ПОКАЗАТЬ
    // ========================================================

    private выполнитьПоказать(
        узел: Показать,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {
        const значения =
            узел.значения.map(
                значение =>
                    this.вычислитьВыражение(
                        значение,
                        область
                    )
            );

        const текст =
            значения
                .map(значение =>
                    this.преобразоватьВДисплей(
                        значение
                    )
                )
                .join("");

        this.вывод.push(текст);

        this.создатьСобытие(
            "показ",
            "показать",
            {
                значения,
                текст
            }
        );

        return null;
    }

    // ========================================================
    // УСЛОВИЕ
    // ========================================================

    private выполнитьУсловие(
        узел: Условие,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {
        const результат =
            this.вычислитьВыражение(
                узел.условие,
                область
            );

        if (typeof результат !== "boolean") {
            throw new Error(
                "🐌 Ошибка выполнения: условие должно давать истину или ложь."
            );
        }

        this.создатьСобытие(
            "проверка_условия",
            "условие",
            {
                результат
            }
        );

        if (результат) {
            this.создатьСобытие(
                "ветка_тогда",
                "условие",
                {
                    ветка: "тогда"
                }
            );

            this.выполнитьБлок(
                узел.тогда.команды,
                область
            );

            return null;
        }

        if (узел.иначе !== null) {
            this.создатьСобытие(
                "ветка_иначе",
                "условие",
                {
                    ветка: "иначе"
                }
            );

            this.выполнитьБлок(
                узел.иначе.команды,
                область
            );
        }

        return null;
    }

    // ========================================================
    // БЛОК
    // ========================================================

    private выполнитьБлок(
        команды: Узел[],
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {
        for (const команда of команды) {
            this.выполнитьУзел(
                команда,
                область
            );
        }

        return null;
    }

    // ========================================================
    // ВОЗВРАТ
    // ========================================================

    private выполнитьВозврат(
        узел: Возврат,
        область:
            Map<string, ЗначениеИсполнения>
    ): null {
        const значение =
            this.вычислитьВыражение(
                узел.значение,
                область
            );

        throw new СигналВозврата(
            значение
        );
    }

    // ========================================================
    // ВЫЗОВ ФУНКЦИИ
    // ========================================================

    private выполнитьВызовФункции(
        узел: ВызовФункции,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {
        const функция =
            this.функции.get(
                узел.имя
            );

        if (!функция) {
            throw new Error(
                `🐌 Ошибка выполнения: функция «${узел.имя}» не объявлена.`
            );
        }

        if (
            функция.параметры.length !==
            узел.аргументы.length
        ) {
            throw new Error(
                `🐌 Ошибка выполнения: функция «${узел.имя}» ожидает ${функция.параметры.length} аргумент(ов), но получено ${узел.аргументы.length}.`
            );
        }

        const значенияАргументов =
            узел.аргументы.map(
                аргумент =>
                    this.вычислитьВыражение(
                        аргумент,
                        область
                    )
            );

        this.создатьСобытие(
            "вызов_функции",
            `функция:${узел.имя}`,
            {
                имя: узел.имя,
                аргументы: [...значенияАргументов]
            }
        );

        const локальнаяОбласть =
            new Map<
                string,
                ЗначениеИсполнения
            >();

        for (
            let индекс = 0;
            индекс < функция.параметры.length;
            индекс++
        ) {
            локальнаяОбласть.set(
                функция.параметры[индекс],
                значенияАргументов[индекс]
            );
        }

        try {
            this.выполнитьБлок(
                функция.тело.команды,
                локальнаяОбласть
            );
        } catch (ошибка: unknown) {
            if (ошибка instanceof СигналВозврата) {
                this.создатьСобытие(
                    "возврат",
                    `функция:${узел.имя}`,
                    {
                        имя: узел.имя,
                        значение: ошибка.значение
                    }
                );

                return ошибка.значение;
            }

            throw ошибка;
        }

        this.создатьСобытие(
            "возврат",
            `функция:${узел.имя}`,
            {
                имя: узел.имя,
                значение: null
            }
        );

        return null;
    }

    // ========================================================
    // ВЫРАЖЕНИЕ
    // ========================================================

    private вычислитьВыражение(
        узел: Узел,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {
        switch (узел.вид) {
            case "ЧИСЛО":
                return узел.значение;

            case "ТЕКСТ":
                return узел.значение;

            case "ИМЯ":
                return this.выполнитьИмя(
                    узел,
                    область
                );

            case "ОПЕРАЦИЯ":
                return this.выполнитьОперацию(
                    узел,
                    область
                );

            case "ВЫЗОВ_ФУНКЦИИ":
                return this.выполнитьВызовФункции(
                    узел,
                    область
                );

            default:
                throw new Error(
                    `🐌 Ошибка выполнения: узел «${узел.вид}» нельзя использовать как выражение.`
                );
        }
    }

    // ========================================================
    // ОПЕРАЦИЯ
    // ========================================================

    private выполнитьОперацию(
        узел: Операция,
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {
        const левое =
            this.вычислитьВыражение(
                узел.левое,
                область
            );

        const правое =
            this.вычислитьВыражение(
                узел.правое,
                область
            );

        switch (узел.оператор) {
            case "+":
                if (
                    typeof левое === "number" &&
                    typeof правое === "number"
                ) {
                    return левое + правое;
                }

                if (
                    typeof левое === "string" ||
                    typeof правое === "string"
                ) {
                    return (
                        this.преобразоватьВДисплей(левое) +
                        this.преобразоватьВДисплей(правое)
                    );
                }

                throw new Error(
                    "🐌 Ошибка выполнения: оператор «+» требует числа или текста."
                );

            case "-":
                this.проверитьЧисла(
                    левое,
                    правое,
                    "-"
                );

                return (
                    (левое as number) -
                    (правое as number)
                );

            case "*":
                this.проверитьЧисла(
                    левое,
                    правое,
                    "*"
                );

                return (
                    (левое as number) *
                    (правое as number)
                );

            case "/":
                this.проверитьЧисла(
                    левое,
                    правое,
                    "/"
                );

                if (правое === 0) {
                    throw new Error(
                        "🐌 Ошибка выполнения: деление на ноль невозможно."
                    );
                }

                return (
                    (левое as number) /
                    (правое as number)
                );

            case "%":
                this.проверитьЧисла(
                    левое,
                    правое,
                    "%"
                );

                if (правое === 0) {
                    throw new Error(
                        "🐌 Ошибка выполнения: остаток от деления на ноль невозможен."
                    );
                }

                return (
                    (левое as number) %
                    (правое as number)
                );

            case "==":
                return левое === правое;

            case "!=":
                return левое !== правое;

            case ">":
                this.проверитьЧисла(
                    левое,
                    правое,
                    ">"
                );

                return (
                    (левое as number) >
                    (правое as number)
                );

            case "<":
                this.проверитьЧисла(
                    левое,
                    правое,
                    "<"
                );

                return (
                    (левое as number) <
                    (правое as number)
                );

            case ">=":
                this.проверитьЧисла(
                    левое,
                    правое,
                    ">="
                );

                return (
                    (левое as number) >=
                    (правое as number)
                );

            case "<=":
                this.проверитьЧисла(
                    левое,
                    правое,
                    "<="
                );

                return (
                    (левое as number) <=
                    (правое as number)
                );

            default:
                throw new Error(
                    `🐌 Ошибка выполнения: неизвестный оператор «${узел.оператор}».`
                );
        }
    }

    // ========================================================
    // ПРОВЕРКА ЧИСЕЛ
    // ========================================================

    private проверитьЧисла(
        левое: ЗначениеИсполнения,
        правое: ЗначениеИсполнения,
        оператор: string
    ): void {
        if (
            typeof левое !== "number" ||
            typeof правое !== "number"
        ) {
            throw new Error(
                `🐌 Ошибка выполнения: оператор «${оператор}» работает только с числами.`
            );
        }
    }

    // ========================================================
    // ПРЕОБРАЗОВАНИЕ В ТЕКСТ ВЫВОДА
    // ========================================================

    private преобразоватьВДисплей(
        значение: ЗначениеИсполнения
    ): string {
        if (значение === null) {
            return "";
        }

        if (значение === true) {
            return "истина";
        }

        if (значение === false) {
            return "ложь";
        }

        return String(значение);
    }

    // ========================================================
    // ПОЛУЧИТЬ РЕЗУЛЬТАТ
    // ========================================================

    private получитьРезультат(): РезультатВыполнения {
        const переменные:
            Record<string, ЗначениеИсполнения> = {};

        for (
            const [имя, значение]
            of this.переменные
        ) {
            переменные[имя] = значение;
        }

        return {
            вывод: [...this.вывод],
            переменные,
            события: this.события.map(
                событие => ({
                    ...событие
                })
            )
        };
    }

    // ========================================================
    // ДОПОЛНИТЕЛЬНЫЕ СНИМКИ
    // ========================================================

    public получитьВывод(): string[] {
        return [...this.вывод];
    }

    public получитьПеременные():
        Record<string, ЗначениеИсполнения> {
        const результат:
            Record<string, ЗначениеИсполнения> = {};

        for (
            const [имя, значение]
            of this.переменные
        ) {
            результат[имя] = значение;
        }

        return результат;
    }

    public получитьСобытия():
        СобытиеИсполнения[] {
        return this.события.map(
            событие => ({
                ...событие
            })
        );
    }
}