    private выполнитьБлок(
        команды: Узел[],
        область:
            Map<string, ЗначениеИсполнения>
    ): ЗначениеИсполнения {

        for (const команда of команды) {
            this.выполнитьУзел(
                команда,
                область
            );
        }

        return null;
    }

