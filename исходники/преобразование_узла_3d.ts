import type {
    УзелСистемы,
    ТипУзла
} from "./узел_системы";

import type {
    Объект3D,
    ТипОбъекта3D
} from "./объект_3d";

import {
    создатьОбъект3D,
    установитьПозицию3D,
    активироватьОбъект3D,
    деактивироватьОбъект3D,
    установитьМетаданные3D,
    проверитьОбъект3D
} from "./объект_3d";

/**
 * Преобразует тип узла системы
 * в соответствующий тип 3D-объекта.
 */
export function преобразоватьТипУзлаВТипОбъекта3D(
    тип: ТипУзла
): ТипОбъекта3D {
    switch (тип) {
        case "программа":
            return "программа";

        case "переменная":
            return "переменная";

        case "функция":
            return "функция";

        case "выполнение":
            return "выполнение";

        case "ошибка":
            return "ошибка";

        default:
            return "система";
    }
}

/**
 * Преобразует узел системы в объект 3D.
 *
 * Сам узел не изменяется.
 *
 * Создаётся независимая 3D-модель,
 * которую в дальнейшем сможет использовать
 * 3D-ядро и визуальный терминал.
 */
export function преобразоватьУзелВОбъект3D(
    узел: УзелСистемы
): Объект3D {

    const типОбъекта =
        преобразоватьТипУзлаВТипОбъекта3D(
            узел.тип
        );

    const объект =
        создатьОбъект3D(
            узел.идентификатор,
            узел.имя,
            типОбъекта
        );

    установитьПозицию3D(
        объект,
        узел.позиция.x,
        узел.позиция.y,
        узел.позиция.z
    );

    if (узел.активен) {
        активироватьОбъект3D(
            объект,
            узел.интенсивность
        );
    } else {
        деактивироватьОбъект3D(
            объект
        );
    }

    установитьМетаданные3D(
        объект,
        "источник",
        "узел_системы"
    );

    установитьМетаданные3D(
        объект,
        "идентификаторУзла",
        узел.идентификатор
    );

    установитьМетаданные3D(
        объект,
        "типУзла",
        узел.тип
    );

    установитьМетаданные3D(
        объект,
        "имяУзла",
        узел.имя
    );

    установитьМетаданные3D(
        объект,
        "активенУзла",
        узел.активен
    );

    установитьМетаданные3D(
        объект,
        "интенсивностьУзла",
        узел.интенсивность
    );

    if (!проверитьОбъект3D(объект)) {
        throw new Error(
            `Не удалось создать корректный 3D-объект из узла "${узел.идентификатор}".`
        );
    }

    return объект;
}

/**
 * Преобразует массив узлов в массив 3D-объектов.
 */
export function преобразоватьУзлыВОбъекты3D(
    узлы: УзелСистемы[]
): Объект3D[] {

    return узлы.map(
        узел =>
            преобразоватьУзелВОбъект3D(
                узел
            )
    );
}

/**
 * Синхронизирует состояние существующего
 * 3D-объекта с узлом системы.
 *
 * Идентификатор 3D-объекта должен совпадать
 * с идентификатором узла.
 */
export function синхронизироватьОбъект3DСУзлом(
    объект: Объект3D,
    узел: УзелСистемы
): void {

    if (
        объект.идентификатор !==
        узел.идентификатор
    ) {
        throw new Error(
            "Нельзя синхронизировать объект и узел с разными идентификаторами."
        );
    }

    объект.имя = узел.имя;

    установитьПозицию3D(
        объект,
        узел.позиция.x,
        узел.позиция.y,
        узел.позиция.z
    );

    if (узел.активен) {
        активироватьОбъект3D(
            объект,
            узел.интенсивность
        );
    } else {
        деактивироватьОбъект3D(
            объект
        );
    }

    установитьМетаданные3D(
        объект,
        "типУзла",
        узел.тип
    );

    установитьМетаданные3D(
        объект,
        "имяУзла",
        узел.имя
    );

    установитьМетаданные3D(
        объект,
        "активенУзла",
        узел.активен
    );

    установитьМетаданные3D(
        объект,
        "интенсивностьУзла",
        узел.интенсивность
    );
}

/**
 * Создаёт объект 3D и сразу устанавливает
 * его связь с узлом системы через метаданные.
 */
export function создатьОбъект3DИзУзла(
    узел: УзелСистемы
): Объект3D {

    return преобразоватьУзелВОбъект3D(
        узел
    );
}

/**
 * Проверяет, соответствует ли объект 3D
 * указанному узлу системы.
 *
 * Проверяется:
 * - идентификатор;
 * - имя;
 * - тип;
 * - позиция;
 * - активность;
 * - интенсивность.
 */
export function проверитьСоответствиеОбъектаУзлу(
    объект: Объект3D,
    узел: УзелСистемы
): boolean {

    if (
        объект.идентификатор !==
        узел.идентификатор
    ) {
        return false;
    }

    if (
        объект.имя !==
        узел.имя
    ) {
        return false;
    }

    if (
        объект.трансформация.позиция.x !==
        узел.позиция.x
    ) {
        return false;
    }

    if (
        объект.трансформация.позиция.y !==
        узел.позиция.y
    ) {
        return false;
    }

    if (
        объект.трансформация.позиция.z !==
        узел.позиция.z
    ) {
        return false;
    }

    if (
        объект.активен !==
        узел.активен
    ) {
        return false;
    }

    if (
        объект.интенсивность !==
        узел.интенсивность
    ) {
        return false;
    }

    const типОбъекта =
        преобразоватьТипУзлаВТипОбъекта3D(
            узел.тип
        );

    if (
        объект.тип !==
        типОбъекта
    ) {
        return false;
    }

    return true;
}
