function получитьДерево(
    код: string
) {
    const лексемы = разобрать(код);
    const парсер = new Парсер(лексемы);

    return парсер.разобрать();
}

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {
    всегоПроверок++;

    if (условие) {
        успешныхПроверок++;
        console.log(`✅ ${сообщение}`);
    } else {
        ошибок++;
        console.log(`❌ ${сообщение}`);
    }
}

function найтиСобытие(
    события: СобытиеИсполнения[],
    тип: СобытиеИсполнения["тип"]
): СобытиеИсполнения | undefined {
    return события.find(
        событие => событие.тип === тип
    );
}

function индексыСобытий(
    события: СобытиеИсполнения[],
    тип: СобытиеИсполнения["тип"]
): number[] {
    const индексы: number[] = [];

    события.forEach(
        (событие, индекс) => {
            if (событие.тип === тип) {
                индексы.push(индекс);
            }
        }
    );

    return индексы;
}

