let успешно = 0;
let ошибок = 0;

function проверить(
    название: string,
    условие: boolean
): void {

    if (условие) {
        console.log(`✅ ${название}`);
        успешно++;
    } else {
        console.log(`❌ ${название}`);
        ошибок++;
    }
}

function создатьБазовуюСтруктуру(): {
    корень: Объект3D;
    ребёнок: Объект3D;
    внук: Объект3D;
} {

    const корень =
        создатьОбъект3D(
            "объект_1",
            "Корень",
            "система"
        );

    const ребёнок =
        создатьОбъект3D(
            "объект_2",
            "Ребёнок",
            "группа"
        );

    const внук =
        создатьОбъект3D(
            "объект_3",
            "Внук",
            "переменная"
        );

    корень.дети.push(
        ребёнок.идентификатор
    );

    ребёнок.родитель =
        корень.идентификатор;

    ребёнок.дети.push(
        внук.идентификатор
    );

    внук.родитель =
        ребёнок.идентификатор;

    return {
        корень,
        ребёнок,
        внук
    };
}

