// ------------------------------------------------------------
// Типы лексем
// ------------------------------------------------------------

export type ТипЛексемы =

    | "КЛЮЧЕВОЕ_СЛОВО"

    | "ИМЯ"

    | "ЧИСЛО"

    | "ТЕКСТ"

    | "ОПЕРАТОР"

    | "СКОБКА_ЛЕВАЯ"

    | "СКОБКА_ПРАВАЯ"

    | "КВАДРАТНАЯ_СКОБКА_ЛЕВАЯ"

    | "КВАДРАТНАЯ_СКОБКА_ПРАВАЯ"

    | "ФИГУРНАЯ_СКОБКА_ЛЕВАЯ"

    | "ФИГУРНАЯ_СКОБКА_ПРАВАЯ"

    | "ЗАПЯТАЯ"

    | "КОНЕЦ_ФАЙЛА";


// ------------------------------------------------------------
// Лексема
// ------------------------------------------------------------

export interface Лексема {

    тип: ТипЛексемы;

    значение: string;

    строка: number;

    позиция: number;
}


// ============================================================
// 🐌 СЛОВАРЬ ЯЗЫКА «УЛИТКА»
// ============================================================

const ключевыеСлова = new Set([

    // Структура программы
    "программа",
    "начало",
    "конец",

    // Вывод
    "показать",

    // Переменные
    "пусть",

    // Условия
    "если",
    "тогда",
    "иначе",

    // Логика
    "истина",
    "ложь",

    // Функции
    "функция",
    "вернуть",

    // Циклы — фундамент на будущее
    "пока",
    "для",

    // Дополнительные конструкции
    "из",
    "в",
    "новый"
]);


// ============================================================
// 🐌 ОШИБКА УЛИТКИ
// ============================================================

function ошибкаУлитки(

    сообщение: string,

    исходныйКод: string,

    строка: number,

    позиция: number

): never {

    const строки = исходныйКод.split(/\r?\n/);

    const исходнаяСтрока = строки[строка - 1] ?? "";


    console.error("");

    console.error("ОШИБКА УЛИТКИ");

    console.error("");

    console.error("Тип: ошибка синтаксиса");

    console.error("");

    console.error(`Строка: ${строка}`);

    console.error(`Позиция: ${позиция}`);

    console.error("");

    console.error(сообщение);

    console.error("");

    console.error(`${строка} | ${исходнаяСтрока}`);

    console.error(

        `${" ".repeat(String(строка).length)} | ` +

        `${" ".repeat(Math.max(позиция - 1, 0))}^`

    );

    console.error("");

    throw new Error("ОШИБКА УЛИТКИ");
}


// ============================================================
// 🐌 ЛЕКСИЧЕСКИЙ АНАЛИЗ
// ============================================================

export function разобрать(

    исходныйКод: string

): Лексема[] {


    const лексемы: Лексема[] = [];


    let индекс = 0;

    let строка = 1;

    let позиция = 1;


    // --------------------------------------------------------
    // Текущий символ
    // --------------------------------------------------------

    function текущийСимвол(): string {

        return исходныйКод[индекс] ?? "";
    }


    // --------------------------------------------------------
    // Следующий символ
    // --------------------------------------------------------

    function следующийСимвол(): string {

        return исходныйКод[индекс + 1] ?? "";
    }


    // --------------------------------------------------------
    // Перейти вперёд
    // --------------------------------------------------------

    function перейтиВперёд(

        количество = 1

    ): void {


        for (

            let i = 0;

            i < количество;

            i++

        ) {


            if (исходныйКод[индекс] === "\n") {

                строка++;

                позиция = 1;

            } else {

                позиция++;

            }


            индекс++;
        }
    }


    // ========================================================
    // Основной цикл
    // ========================================================

    while (индекс < исходныйКод.length) {


        const символ = текущийСимвол();


        // ----------------------------------------------------
        // Пробелы
        // ----------------------------------------------------

        if (

            символ === " " ||

            символ === "\t" ||

            символ === "\r"

        ) {

            перейтиВперёд();

            continue;
        }


        // ----------------------------------------------------
        // Перевод строки
        // ----------------------------------------------------

        if (символ === "\n") {

            перейтиВперёд();

            continue;
        }


        // ----------------------------------------------------
        // Комментарий
        // ----------------------------------------------------

        if (символ === "#") {


            while (

                индекс < исходныйКод.length &&

                текущийСимвол() !== "\n"

            ) {

                перейтиВперёд();
            }


            continue;
        }


        // ====================================================
        // 📝 ТЕКСТ
        // ====================================================

        if (символ === '"') {


            const строкаНачала = строка;

            const позицияНачала = позиция;


            перейтиВперёд();


            let текст = "";

            let закрыт = false;


            while (индекс < исходныйКод.length) {


                const текущий = текущийСимвол();


                if (текущий === '"') {

                    закрыт = true;

                    перейтиВперёд();

                    break;
                }


                текст += текущий;

                перейтиВперёд();
            }


            if (!закрыт) {

                ошибкаУлитки(

                    'Незакрытый текст.\nОжидалась закрывающая кавычка: "',

                    исходныйКод,

                    строкаНачала,

                    позицияНачала
                );
            }


            лексемы.push({

                тип: "ТЕКСТ",

                значение: текст,

                строка: строкаНачала,

                позиция: позицияНачала

            });


            continue;
        }


        // ====================================================
        // 🔢 ДВУХСИМВОЛЬНЫЕ ОПЕРАТОРЫ
        // ====================================================

        const дваСимвола =

            символ +

            следующийСимвол();


        if (

            дваСимвола === "==" ||

            дваСимвола === "!=" ||

            дваСимвола === ">=" ||

            дваСимвола === "<="

        ) {


            лексемы.push({

                тип: "ОПЕРАТОР",

                значение: дваСимвола,

                строка,

                позиция

            });


            перейтиВперёд(2);

            continue;
        }


        // ====================================================
        // ➕ ОДНОСИМВОЛЬНЫЕ ОПЕРАТОРЫ
        // ====================================================

        if (

            символ === "=" ||

            символ === "+" ||

            символ === "-" ||

            символ === "*" ||

            символ === "/" ||

            символ === "%" ||

            символ === ">" ||

            символ === "<"

        ) {


            лексемы.push({

                тип: "ОПЕРАТОР",

                значение: символ,

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // ( ЛЕВАЯ КРУГЛАЯ СКОБКА
        // ====================================================

        if (символ === "(") {


            лексемы.push({

                тип: "СКОБКА_ЛЕВАЯ",

                значение: "(",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // ) ПРАВАЯ КРУГЛАЯ СКОБКА
        // ====================================================

        if (символ === ")") {


            лексемы.push({

                тип: "СКОБКА_ПРАВАЯ",

                значение: ")",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // [ ЛЕВАЯ КВАДРАТНАЯ СКОБКА
        // ====================================================

        if (символ === "[") {


            лексемы.push({

                тип: "КВАДРАТНАЯ_СКОБКА_ЛЕВАЯ",

                значение: "[",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // ] ПРАВАЯ КВАДРАТНАЯ СКОБКА
        // ====================================================

        if (символ === "]") {


            лексемы.push({

                тип: "КВАДРАТНАЯ_СКОБКА_ПРАВАЯ",

                значение: "]",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // { ЛЕВАЯ ФИГУРНАЯ СКОБКА
        // ====================================================

        if (символ === "{") {


            лексемы.push({

                тип: "ФИГУРНАЯ_СКОБКА_ЛЕВАЯ",

                значение: "{",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // } ПРАВАЯ ФИГУРНАЯ СКОБКА
        // ====================================================

        if (символ === "}") {


            лексемы.push({

                тип: "ФИГУРНАЯ_СКОБКА_ПРАВАЯ",

                значение: "}",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // , ЗАПЯТАЯ
        // ====================================================

        if (символ === ",") {


            лексемы.push({

                тип: "ЗАПЯТАЯ",

                значение: ",",

                строка,

                позиция

            });


            перейтиВперёд();

            continue;
        }


        // ====================================================
        // 🔢 ЧИСЛО
        // ====================================================

        if (/[0-9]/.test(символ)) {


            const строкаНачала = строка;

            const позицияНачала = позиция;


            let число = "";


            while (

                индекс < исходныйКод.length &&

                /[0-9]/.test(текущийСимвол())

            ) {


                число += текущийСимвол();

                перейтиВперёд();
            }


            лексемы.push({

                тип: "ЧИСЛО",

                значение: число,

                строка: строкаНачала,

                позиция: позицияНачала

            });


            continue;
        }


        // ====================================================
        // 🔤 ИМЯ ИЛИ КЛЮЧЕВОЕ СЛОВО
        // ====================================================

        if (/[А-Яа-яЁёA-Za-z_]/.test(символ)) {


            const строкаНачала = строка;

            const позицияНачала = позиция;


            let слово = "";


            while (

                индекс < исходныйКод.length &&

                /[А-Яа-яЁёA-Za-z0-9_]/.test(текущийСимвол())

            ) {


                слово += текущийСимвол();

                перейтиВперёд();
            }


            // ------------------------------------------------
            // Логические операторы
            // ------------------------------------------------

            if (

                слово === "и" ||

                слово === "или" ||

                слово === "не"

            ) {


                лексемы.push({

                    тип: "ОПЕРАТОР",

                    значение: слово,

                    строка: строкаНачала,

                    позиция: позицияНачала

                });


            // ------------------------------------------------
            // Ключевые слова
            // ------------------------------------------------

            } else if (ключевыеСлова.has(слово)) {


                лексемы.push({

                    тип: "КЛЮЧЕВОЕ_СЛОВО",

                    значение: слово,

                    строка: строкаНачала,

                    позиция: позицияНачала

                });


            // ------------------------------------------------
            // Обычное имя
            // ------------------------------------------------

            } else {


                лексемы.push({

                    тип: "ИМЯ",

                    значение: слово,

                    строка: строкаНачала,

                    позиция: позицияНачала

                });
            }


            continue;
        }


        // ====================================================
        // ❌ НЕИЗВЕСТНЫЙ СИМВОЛ
        // ====================================================

        ошибкаУлитки(

            `Неизвестный символ "${символ}".`,

            исходныйКод,

            строка,

            позиция
        );
    }


    // ========================================================
    // 🏁 КОНЕЦ ФАЙЛА
    // ========================================================

    лексемы.push({

        тип: "КОНЕЦ_ФАЙЛА",

        значение: "",

        строка,

        позиция

    });


    return лексемы;
}