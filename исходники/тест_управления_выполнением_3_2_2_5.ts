// ============================================================
// 🐌 УЛИТКА
// Тест 3.2.2.5 — управление выполнением
// ============================================================

import {
    Исполнитель
} from "./исполнитель.js";

import type {
    Узел
} from "./дерево/узлы.js";

// ============================================================
// ВСПОМОГАТЕЛЬНЫЕ ПРОВЕРКИ
// ============================================================

let номерПроверки = 0;
let успешно = 0;

function проверить(
    условие: boolean,
    сообщение: string
): void {
    номерПроверки++;

    if (!условие) {
        console.error(
            `❌ ПРОВЕРКА ${номерПроверки}: ${сообщение}`
        );

        throw new Error(
            `Проверка не пройдена: ${сообщение}`
        );
    }

    успешно++;

    console.log(
        `✅ ПРОВЕРКА ${номерПроверки}: ${сообщение}`
    );
}

// ============================================================
// ТЕСТОВАЯ ПРОГРАММА
// ============================================================

const дерево: Узел[] = [
    {
        вид: "ПРОГРАММА",
        имя: "тест_управления",
        тело: {
            вид: "БЛОК",
            команды: [
                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
                    имя: "число",
                    значение: {
                        вид: "ЧИСЛО",
                        значение: 10
                    }
                },
                {
                    вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
                    имя: "результат",
                    значение: {
                        вид: "ОПЕРАЦИЯ",
                        оператор: "+",
                        левое: {
                            вид: "ИМЯ",
                            значение: "число"
                        },
                        правое: {
                            вид: "ЧИСЛО",
                            значение: 5
                        }
                    }
                },
                {
                    вид: "ПОКАЗАТЬ",
                    значения: [
                        {
                            вид: "ИМЯ",
                            значение: "результат"
                        }
                    ]
                }
            ]
        }
    }
];

// ============================================================
// ИСПОЛНИТЕЛЬ
// ============================================================

const исполнитель =
    new Исполнитель();

// ============================================================
// 1. НАЧАЛЬНОЕ СОСТОЯНИЕ
// ============================================================

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "ожидание",
    "до запуска состояние равно «ожидание»"
);

проверить(
    исполнитель.получитьТекущийШаг() === 0,
    "до запуска текущий шаг равен 0"
);

проверить(
    исполнитель.получитьТекущийУзел() === null,
    "до запуска текущий узел отсутствует"
);

// ============================================================
// 2. ЗАПУСК
// ============================================================

исполнитель.начатьПошаговоеВыполнение(
    дерево
);

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "выполнение",
    "после запуска состояние равно «выполнение»"
);

проверить(
    исполнитель.получитьТекущийШаг() === 0,
    "после запуска текущий шаг равен 0"
);

проверить(
    исполнитель.получитьКоличествоШагов() === 3,
    "определено 3 шага"
);

проверить(
    исполнитель.получитьТекущийУзел() === null,
    "до первого шага текущий узел отсутствует"
);

// ============================================================
// 3. ПЕРВЫЙ ШАГ
// ============================================================

исполнитель.выполнитьШаг();

проверить(
    исполнитель.получитьТекущийШаг() === 1,
    "после первого шага текущий шаг равен 1"
);

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "приостановлено",
    "после одного шага выполнение приостановлено"
);

проверить(
    исполнитель.получитьПеременные().число === 10,
    "после первого шага переменная «число» равна 10"
);

проверить(
    исполнитель.получитьТекущийУзел()?.вид ===
        "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
    "текущий узел является объявлением переменной"
);

// ============================================================
// 4. ЯВНАЯ ПАУЗА
// ============================================================

исполнитель.приостановитьПошаговоеВыполнение();

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "приостановлено",
    "явная пауза сохраняет состояние «приостановлено»"
);

проверить(
    исполнитель.получитьТекущийШаг() === 1,
    "при паузе текущий шаг не изменился"
);

проверить(
    исполнитель.получитьПеременные().число === 10,
    "при паузе переменная «число» сохранена"
);

проверить(
    исполнитель.получитьВывод().length === 0,
    "при паузе вывод остаётся пустым"
);

// ============================================================
// 5. ПРОДОЛЖЕНИЕ
// ============================================================

исполнитель.продолжитьПошаговоеВыполнение();

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "завершено",
    "после продолжения программа завершена"
);

проверить(
    исполнитель.получитьТекущийШаг() === 3,
    "после продолжения выполнены все 3 шага"
);

проверить(
    исполнитель.получитьПеременные().результат === 15,
    "результат вычисления равен 15"
);

проверить(
    исполнитель.получитьВывод()[0] === "15",
    "вывод программы равен 15"
);

проверить(
    исполнитель.получитьТекущийУзел()?.вид ===
        "ПОКАЗАТЬ",
    "после завершения сохранён последний узел «ПОКАЗАТЬ»"
);

// ============================================================
// 6. ПОПЫТКА ПРОДОЛЖИТЬ ЗАВЕРШЁННУЮ ПРОГРАММУ
// ============================================================

исполнитель.продолжитьПошаговоеВыполнение();

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "завершено",
    "завершённая программа не запускается повторно через продолжение"
);

проверить(
    исполнитель.получитьТекущийШаг() === 3,
    "после повторного продолжения шаг не изменился"
);

// ============================================================
// 7. НОВЫЙ ЗАПУСК
// ============================================================

исполнитель.начатьПошаговоеВыполнение(
    дерево
);

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "выполнение",
    "новый запуск возвращает состояние «выполнение»"
);

проверить(
    исполнитель.получитьТекущийШаг() === 0,
    "новый запуск сбрасывает текущий шаг"
);

проверить(
    исполнитель.получитьТекущийУзел() === null,
    "новый запуск сбрасывает текущий узел"
);

проверить(
    исполнитель.получитьПеременные().число ===
        undefined,
    "новый запуск очищает старые переменные"
);

проверить(
    исполнитель.получитьВывод().length === 0,
    "новый запуск очищает старый вывод"
);

// ============================================================
// 8. ПРОВЕРКА ОСТАНОВКИ
// ============================================================

исполнитель.выполнитьШаг();

проверить(
    исполнитель.получитьТекущийШаг() === 1,
    "перед остановкой выполнен первый шаг"
);

исполнитель.остановитьПошаговоеВыполнение();

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "остановлено",
    "после остановки состояние равно «остановлено»"
);

проверить(
    исполнитель.получитьТекущийШаг() === 1,
    "остановка сохраняет текущий шаг"
);

проверить(
    исполнитель.получитьПеременные().число === 10,
    "остановка сохраняет переменные"
);

// ============================================================
// 9. ПОСЛЕ ОСТАНОВКИ ПРОДОЛЖЕНИЕ НЕ РАБОТАЕТ
// ============================================================

исполнитель.продолжитьПошаговоеВыполнение();

проверить(
    исполнитель.получитьСостояниеПошаговогоВыполнения() ===
        "остановлено",
    "остановленную программу нельзя продолжить"
);

проверить(
    исполнитель.получитьТекущийШаг() === 1,
    "после попытки продолжения шаг остаётся 1"
);

проверить(
    исполнитель.получитьВывод().length === 0,
    "после остановки вывод не изменился"
);

// ============================================================
// 10. ФИНАЛ
// ============================================================

console.log("");
console.log(
    "============================================================"
);
console.log(
    "🐌 ТЕСТ 3.2.2.5 — УПРАВЛЕНИЕ ВЫПОЛНЕНИЕМ"
);
console.log(
    "============================================================"
);
console.log(
    `ПРОЙДЕНО: ${успешно} из ${номерПроверки}`
);
console.log(
    "============================================================"
);

if (успешно !== номерПроверки) {
    throw new Error(
        "🐌 Тест управления выполнением завершился с ошибками."
    );
}

console.log(
    "🐌 ТЕСТ 3.2.2.5 УСПЕШНО ЗАВЕРШЁН."
);