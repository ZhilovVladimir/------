type РезультатПроверки = {
    успешно: boolean;
    сообщение: string;
};

// ============================================================
// СЧЁТЧИКИ ПРОВЕРОК
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибокПроверки = 0;

// ============================================================
// ФУНКЦИЯ ПРОВЕРКИ
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {
    всегоПроверок++;

    if (условие) {
        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибокПроверки++;

    console.log(
        `❌ ОШИБКА: ${сообщение}`
    );
}

