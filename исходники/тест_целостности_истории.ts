// ============================================================
// ФУНКЦИЯ ПОЛУЧЕНИЯ ИМЕНИ ПЕРЕМЕННОЙ
// ============================================================

function получитьИмяПеременной(
    данные: unknown
): string | null {
    if (
        typeof данные !== "object" ||
        данные === null
    ) {
        return null;
    }

    const объект =
        данные as {
            имя?: unknown;
        };

    if (
        typeof объект.имя !== "string"
    ) {
        return null;
    }

    return объект.имя;
}

// ============================================================
// ФУНКЦИЯ ПОЛУЧЕНИЯ ЗНАЧЕНИЯ ПЕРЕМЕННОЙ
// ============================================================

function получитьЗначениеПеременной(
    данные: unknown
): unknown {
    if (
        typeof данные !== "object" ||
        данные === null
    ) {
        return undefined;
    }

    const объект =
        данные as {
            значение?: unknown;
        };

    return объект.значение;
}

// ============================================================
// ФУНКЦИЯ ПОЛУЧЕНИЯ ПАРАМЕТРОВ ФУНКЦИИ
// ============================================================

function получитьПараметрыФункции(
    данные: unknown
): unknown[] | null {
    if (
        typeof данные !== "object" ||
        данные === null
    ) {
        return null;
    }

    const объект =
        данные as {
            параметры?: unknown;
        };

    if (
        !Array.isArray(объект.параметры)
    ) {
        return null;
    }

    return объект.параметры;
}

// ============================================================
// ФУНКЦИЯ ПОЛУЧЕНИЯ ВНУТРЕННИХ ДАННЫХ СОЗДАНИЯ УЗЛА
// ============================================================
//
// В истории структура события:
//
// событие.данные
//     ├── идентификатор
//     ├── тип
//     ├── имя
//     └── данные
//          └── исходный снимок переменной/функции
//
// Поэтому для проверки снимка нужно получить именно
// внутреннее поле "данные".
//
// ============================================================

function получитьСнимокСозданияУзла(
    данные: unknown
): unknown {
    if (
        typeof данные !== "object" ||
        данные === null
    ) {
        return undefined;
    }

    const оболочка =
        данные as {
            данные?: unknown;
        };

    return оболочка.данные;
}

