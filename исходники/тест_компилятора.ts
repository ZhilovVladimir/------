// ============================================================
// 🐌 УЛИТКА
// Самотест единого компиляционного конвейера
// ============================================================

import {
    Компилятор
} from "./компилятор.js";

// ============================================================
// СЧЁТЧИКИ
// ============================================================

let всегоПроверок = 0;
let успешныхПроверок = 0;
let ошибок = 0;

// ============================================================
// ПРОВЕРКА
// ============================================================

function проверить(
    условие: boolean,
    сообщение: string
): void {

    всегоПроверок++;

    if (условие) {

        успешныхПроверок++;

        console.log(
            `✅ ${сообщение}`
        );

        return;
    }

    ошибок++;

    console.log(
        `❌ ${сообщение}`
    );
}

// ============================================================
// ЗАГОЛОВОК
// ============================================================

function заголовок(
    номер: number,
    название: string
): void {

    console.log("");
    console.log("================================");
    console.log(`[${номер}] ${название}`);
    console.log("================================");
}

// ============================================================
// [1] ПРОСТАЯ ПРОГРАММА
// ============================================================

заголовок(
    1,
    "ПОЛНЫЙ КОНВЕЙЕР"
);

{
    const компилятор =
        new Компилятор();

    const результат =
        компилятор.выполнить(`
            пусть число = 10

            пусть другое = 20

            пусть сумма = число + другое

            показать сумма
        `);

    проверить(
        результат.успешно,
        "Корректная программа проходит весь конвейер"
    );

    проверить(
        результат.выполнение !== null,
        "После семантики программа передаётся исполнителю"
    );

    проверить(
        результат.выполнение?.вывод.length === 1,
        "Исполнитель создаёт один результат вывода"
    );

    проверить(
        результат.выполнение?.вывод[0] === "30",
        "Результат выполнения равен 30"
    );

    проверить(
        результат.выполнение?.переменные.сумма === 30,
        "Переменная «сумма» получает значение 30"
    );
}

// ============================================================
// [2] СЕМАНТИЧЕСКАЯ ОШИБКА БЛОКИРУЕТ ВЫПОЛНЕНИЕ
// ============================================================

заголовок(
    2,
    "СЕМАНТИЧЕСКАЯ ЗАЩИТА"
);

{
    const компилятор =
        new Компилятор();

    const результат =
        компилятор.выполнить(`
            пусть число = 10

            пусть число = 20

            показать число
        `);

    проверить(
        !результат.успешно,
        "Программа с семантической ошибкой отклоняется"
    );

    проверить(
        результат.семантика.ошибки.length > 0,
        "Семантическая ошибка возвращается пользователю"
    );

    проверить(
        результат.выполнение === null,
        "Исполнитель не запускается после семантической ошибки"
    );

    проверить(
        результат.семантика.ошибки.some(
            ошибка =>
                ошибка.код === "ПОВТОРНОЕ_ИМЯ"
        ),
        "Возвращается правильный код семантической ошибки"
    );
}

// ============================================================
// [3] ФУНКЦИИ
// ============================================================

заголовок(
    3,
    "КОНВЕЙЕР С ФУНКЦИЕЙ"
);

{
    const компилятор =
        new Компилятор();

    const результат =
        компилятор.выполнить(`
            функция сложить(первое, второе)

                вернуть первое + второе

            конец

            пусть результат = сложить(10, 25)

            показать результат
        `);

    проверить(
        результат.успешно,
        "Функция проходит все этапы конвейера"
    );

    проверить(
        результат.семантика.ошибки.length === 0,
        "Функция не создаёт семантических ошибок"
    );

    проверить(
        результат.выполнение?.вывод[0] === "35",
        "Функция возвращает правильный результат"
    );

    проверить(
        результат.выполнение?.события.some(
            событие =>
                событие.тип ===
                "вызов_функции"
        ) === true,
        "Выполнение создаёт событие вызова функции"
    );

    проверить(
        результат.выполнение?.события.some(
            событие =>
                событие.тип ===
                "возврат"
        ) === true,
        "Выполнение создаёт событие возврата"
    );
}

// ============================================================
// [4] УСЛОВИЕ
// ============================================================

заголовок(
    4,
    "КОНВЕЙЕР С УСЛОВИЕМ"
);

{
    const компилятор =
        new Компилятор();

    const результат =
        компилятор.выполнить(`
            пусть возраст = 30

            если возраст >= 18 тогда

                показать "взрослый"

            иначе

                показать "ребёнок"

            конец
        `);

    проверить(
        результат.успешно,
        "Условная программа проходит конвейер"
    );

    проверить(
        результат.выполнение?.вывод[0] ===
            "взрослый",
        "Выбрана правильная ветка"
    );

    проверить(
        результат.выполнение?.события.some(
            событие =>
                событие.тип ===
                "проверка_условия"
        ) === true,
        "Создаётся событие проверки условия"
    );

    проверить(
        результат.выполнение?.события.some(
            событие =>
                событие.тип ===
                "ветка_тогда"
        ) === true,
        "Создаётся событие ветки «тогда»"
    );
}

// ============================================================
// [5] СОБЫТИЯ
// ============================================================

заголовок(
    5,
    "ЕДИНЫЙ ПОТОК СОБЫТИЙ"
);

{
    const компилятор =
        new Компилятор();

    const события: string[] = [];

    компилятор.установитьОбработчикСобытий(
        событие => {
            события.push(
                событие.тип
            );
        }
    );

    const результат =
        компилятор.выполнить(`
            пусть число = 100

            показать число
        `);

    проверить(
        результат.успешно,
        "Программа успешно выполняется с обработчиком событий"
    );

    проверить(
        события.includes("начало_программы"),
        "Обработчик получает начало программы"
    );

    проверить(
        события.includes("объявление_переменной"),
        "Обработчик получает объявление переменной"
    );

    проверить(
        события.includes("показ"),
        "Обработчик получает событие показа"
    );

    проверить(
        события.includes("завершение_программы"),
        "Обработчик получает завершение программы"
    );
}

// ============================================================
// ИТОГ
// ============================================================

console.log("");

console.log("================================");
console.log("🐌 ИТОГ");
console.log("================================");

console.log(
    `Всего проверок: ${всегоПроверок}`
);

console.log(
    `Успешных: ${успешныхПроверок}`
);

console.log(
    `Ошибок теста: ${ошибок}`
);

console.log("");

if (ошибок === 0) {

    console.log(
        "🐌 ✅ ЕДИНЫЙ КОМПИЛЯЦИОННЫЙ КОНВЕЙЕР ПРОШЁЛ ВСЕ ПРОВЕРКИ"
    );

} else {

    console.log(
        "🐌 ❌ ЕДИНЫЙ КОМПИЛЯЦИОННЫЙ КОНВЕЙЕР НЕ ПРОШЁЛ ВСЕ ПРОВЕРКИ"
    );
}

console.log("");

console.log(
    "🐌 ТЕСТ КОМПИЛЯТОРА ЗАВЕРШЁН"
);
