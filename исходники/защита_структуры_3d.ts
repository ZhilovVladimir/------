import type {
    Объект3D
} from "./объект_3d";

import {
    проверитьОбъект3D
} from "./объект_3d";

export type ТипПроблемыСтруктуры3D =
    | "некорректный_объект"
    | "отсутствует_родитель"
    | "отсутствует_ребёнок"
    | "самоссылка"
    | "дублированный_ребёнок"
    | "несовпадение_родителя"
    | "цикл";

export interface ПроблемаСтруктуры3D {
    тип: ТипПроблемыСтруктуры3D;
    объект: string;
    связанныйОбъект: string | null;
    сообщение: string;
}

export interface РезультатПроверкиСтруктуры3D {
    корректно: boolean;
    проблемы: ПроблемаСтруктуры3D[];
    количествоОбъектов: number;
    количествоКорневыхОбъектов: number;
}

export function проверитьСтруктуру3D(
    объекты: Объект3D[]
): РезультатПроверкиСтруктуры3D {

    const проблемы:
        ПроблемаСтруктуры3D[] = [];

    const карта =
        new Map<string, Объект3D>();

    // ========================================================
    // ПРОВЕРКА ИДЕНТИФИКАТОРОВ
    // ========================================================

    for (
        const объект
        of объекты
    ) {

        if (
            !проверитьОбъект3D(
                объект
            )
        ) {

            проблемы.push({
                тип: "некорректный_объект",
                объект:
                    объект?.идентификатор ??
                    "<неизвестный>",
                связанныйОбъект: null,
                сообщение:
                    "Объект 3D имеет некорректную структуру."
            });

            continue;
        }

        if (
            карта.has(
                объект.идентификатор
            )
        ) {

            проблемы.push({
                тип: "некорректный_объект",
                объект:
                    объект.идентификатор,
                связанныйОбъект: null,
                сообщение:
                    `Обнаружен повторный идентификатор ` +
                    `"${объект.идентификатор}".`
            });

            continue;
        }

        карта.set(
            объект.идентификатор,
            объект
        );
    }

    // ========================================================
    // ПРОВЕРКА СТРУКТУРЫ КАЖДОГО ОБЪЕКТА
    // ========================================================

    for (
        const объект
        of карта.values()
    ) {

        // ----------------------------------------------------
        // ПРОВЕРКА РОДИТЕЛЯ
        // ----------------------------------------------------

        if (
            объект.родитель !== null
        ) {

            if (
                объект.родитель ===
                объект.идентификатор
            ) {

                проблемы.push({
                    тип: "самоссылка",
                    объект:
                        объект.идентификатор,
                    связанныйОбъект:
                        объект.родитель,
                    сообщение:
                        `Объект "${объект.идентификатор}" ` +
                        "не может быть собственным родителем."
                });

            } else if (
                !карта.has(
                    объект.родитель
                )
            ) {

                проблемы.push({
                    тип: "отсутствует_родитель",
                    объект:
                        объект.идентификатор,
                    связанныйОбъект:
                        объект.родитель,
                    сообщение:
                        `Родитель "${объект.родитель}" ` +
                        `объекта "${объект.идентификатор}" ` +
                        "не найден."
                });

            } else {

                const родитель =
                    карта.get(
                        объект.родитель
                    )!;

                if (
                    !родитель.дети.includes(
                        объект.идентификатор
                    )
                ) {

                    проблемы.push({
                        тип:
                            "несовпадение_родителя",
                        объект:
                            объект.идентификатор,
                        связанныйОбъект:
                            родитель.идентификатор,
                        сообщение:
                            `Объект "${объект.идентификатор}" ` +
                            `считает "${родитель.идентификатор}" ` +
                            "своим родителем, но родитель " +
                            "не содержит его в списке детей."
                    });
                }
            }
        }

        // ----------------------------------------------------
        // ПРОВЕРКА СПИСКА ДЕТЕЙ
        // ----------------------------------------------------

        const уникальныеДети =
            new Set(
                объект.дети
            );

        if (
            уникальныеДети.size !==
            объект.дети.length
        ) {

            проблемы.push({
                тип:
                    "дублированный_ребёнок",
                объект:
                    объект.идентификатор,
                связанныйОбъект: null,
                сообщение:
                    `В списке детей объекта ` +
                    `"${объект.идентификатор}" ` +
                    "обнаружен дубликат."
            });
        }

        for (
            const идентификаторРебёнка
            of объект.дети
        ) {

            if (
                идентификаторРебёнка ===
                объект.идентификатор
            ) {

                проблемы.push({
                    тип: "самоссылка",
                    объект:
                        объект.идентификатор,
                    связанныйОбъект:
                        идентификаторРебёнка,
                    сообщение:
                        `Объект "${объект.идентификатор}" ` +
                        "не может быть собственным ребёнком."
                });

                continue;
            }

            const ребёнок =
                карта.get(
                    идентификаторРебёнка
                );

            if (!ребёнок) {

                проблемы.push({
                    тип:
                        "отсутствует_ребёнок",
                    объект:
                        объект.идентификатор,
                    связанныйОбъект:
                        идентификаторРебёнка,
                    сообщение:
                        `Ребёнок "${идентификаторРебёнка}" ` +
                        `объекта "${объект.идентификатор}" ` +
                        "не найден."
                });

                continue;
            }

            if (
                ребёнок.родитель !==
                объект.идентификатор
            ) {

                проблемы.push({
                    тип:
                        "несовпадение_родителя",
                    объект:
                        объект.идентификатор,
                    связанныйОбъект:
                        ребёнок.идентификатор,
                    сообщение:
                        `Объект "${объект.идентификатор}" ` +
                        `содержит "${ребёнок.идентификатор}" ` +
                        "в списке детей, но ребёнок " +
                        "не указывает этого объекта как родителя."
                });
            }
        }

        // ====================================================
        // ПРОВЕРКА ЦИКЛА
        // ====================================================

        const посещённые =
            new Set<string>();

        const путь =
            new Set<string>();

        let текущий:
            Объект3D | undefined =
            объект;

        while (
            текущий &&
            текущий.родитель !== null
        ) {

            if (
                путь.has(
                    текущий.идентификатор
                )
            ) {

                проблемы.push({
                    тип: "цикл",
                    объект:
                        объект.идентификатор,
                    связанныйОбъект:
                        текущий.идентификатор,
                    сообщение:
                        `Обнаружен циклический путь ` +
                        `в иерархии объекта "${объект.идентификатор}".`
                });

                break;
            }

            if (
                посещённые.has(
                    текущий.идентификатор
                )
            ) {
                break;
            }

            путь.add(
                текущий.идентификатор
            );

            посещённые.add(
                текущий.идентификатор
            );

            текущий =
                карта.get(
                    текущий.родитель
                );
        }
    }

    // ========================================================
    // КОРНЕВЫЕ ОБЪЕКТЫ
    // ========================================================

    let количествоКорневыхОбъектов = 0;

    for (
        const объект
        of карта.values()
    ) {

        if (
            объект.родитель === null
        ) {
            количествоКорневыхОбъектов++;
        }
    }

    return {
        корректно:
            проблемы.length === 0,
        проблемы,
        количествоОбъектов:
            объекты.length,
        количествоКорневыхОбъектов
    };
}

// ============================================================
// БЕЗОПАСНАЯ ПРОВЕРКА
// ============================================================

export function структура3DКорректна(
    объекты: Объект3D[]
): boolean {

    return проверитьСтруктуру3D(
        объекты
    ).корректно;
}

// ============================================================
// ПОЛУЧЕНИЕ ТОЛЬКО ПРОБЛЕМ
// ============================================================

export function получитьПроблемыСтруктуры3D(
    объекты: Объект3D[]
): ПроблемаСтруктуры3D[] {

    return проверитьСтруктуру3D(
        объекты
    ).проблемы;
}