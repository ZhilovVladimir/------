import type {
    IncomingMessage,
    ServerResponse,
} from "node:http";

import {
    разобратьКоманду,
} from "../терминал/исходники/разборщик_команд.js";

import {
    выполнитьБезопаснуюGitКоманду,
} from "../терминал/исходники/связка_команды_git.js";

import {
    СистемаУлитки3D,
} from "./система_улитки_3d.js";

import {
    обработчикФайловПроекта,
} from "./мост_файлов_проекта.js";

/** Подпись HTTP-обработчика — как у connect, который использует Vite. */
export type ОбработчикМоста = (
    запрос: IncomingMessage,
    ответ: ServerResponse,
    следующий: (ошибка?: unknown) => void,
) => void;

/**
 * Git-команды терминала: POST /api/git.
 * Разбирает русскую команду и выполняет только безопасные операции.
 */
export const мостGit: ОбработчикМоста = (
    запрос,
    ответ,
    следующий,
) => {
    const путь =
        decodeURIComponent(
            new URL(
                запрос.url ?? "/",
                "http://localhost",
            ).pathname,
        );

    if (путь !== "/api/git") {
        следующий();
        return;
    }

    if (запрос.method !== "POST") {
        ответ.statusCode = 405;

        ответ.setHeader(
            "Content-Type",
            "application/json; charset=utf-8",
        );

        ответ.end(
            JSON.stringify({
                успешно: false,
                сообщение:
                    "Разрешена только команда POST.",
            }),
        );

        return;
    }

    const части: Buffer[] = [];

    запрос.on(
        "data",
        (часть: Buffer) => {
            части.push(часть);
        },
    );

    запрос.on(
        "end",
        () => {
            try {
                const тело =
                    Buffer.concat(части)
                        .toString("utf8");

                const данные =
                    JSON.parse(тело) as {
                        команда?: unknown;
                    };

                if (
                    typeof данные.команда !==
                    "string"
                ) {
                    ответ.statusCode = 400;

                    ответ.setHeader(
                        "Content-Type",
                        "application/json; charset=utf-8",
                    );

                    ответ.end(
                        JSON.stringify({
                            успешно: false,
                            сообщение:
                                "Не указана команда терминала.",
                        }),
                    );

                    return;
                }

                const разобраннаяКоманда =
                    разобратьКоманду(
                        данные.команда,
                    );

                if (
                    разобраннаяКоманда ===
                    undefined
                ) {
                    ответ.statusCode = 400;

                    ответ.setHeader(
                        "Content-Type",
                        "application/json; charset=utf-8",
                    );

                    ответ.end(
                        JSON.stringify({
                            успешно: false,
                            сообщение:
                                "Не удалось разобрать команду «" +
                                данные.команда +
                                "».",
                        }),
                    );

                    return;
                }

                const результат =
                    выполнитьБезопаснуюGitКоманду(
                        разобраннаяКоманда,
                    );

                ответ.statusCode =
                    результат.выполнено
                        ? 200
                        : 400;

                ответ.setHeader(
                    "Content-Type",
                    "application/json; charset=utf-8",
                );

                ответ.end(
                    JSON.stringify({
                        успешно:
                            результат.выполнено,
                        сообщение:
                            результат.сообщение,
                        вывод:
                            результат.вывод,
                    }),
                );
            } catch (ошибка) {
                ответ.statusCode = 500;

                ответ.setHeader(
                    "Content-Type",
                    "application/json; charset=utf-8",
                );

                const сообщение =
                    ошибка instanceof Error
                        ? ошибка.message
                        : String(ошибка);

                ответ.end(
                    JSON.stringify({
                        успешно: false,
                        сообщение:
                            "Ошибка серверного моста Git: " +
                            сообщение,
                    }),
                );
            }
        },
    );
};

/**
 * Одна система 3D-ядра на процесс — как раньше в vite.config.ts.
 */
const система = new СистемаУлитки3D();

/**
 * Выполнение программ: POST /api/выполнение.
 * Компилирует код «Улитки» и возвращает результат со снимком 3D-ядра.
 */
export const мостВыполнения: ОбработчикМоста = (
    запрос,
    ответ,
    следующий,
) => {
    const путь =
        decodeURIComponent(
            new URL(
                запрос.url ?? "/",
                "http://localhost",
            ).pathname,
        );

    if (путь !== "/api/выполнение") {
        следующий();
        return;
    }

    if (запрос.method !== "POST") {
        ответ.statusCode = 405;

        ответ.setHeader(
            "Content-Type",
            "application/json; charset=utf-8",
        );

        ответ.end(
            JSON.stringify({
                успешно: false,
                сообщение:
                    "Разрешена только команда POST.",
            }),
        );

        return;
    }

    const части: Buffer[] = [];

    запрос.on(
        "data",
        (часть: Buffer) => {
            части.push(часть);
        },
    );

    запрос.on(
        "end",
        () => {
            try {
                const тело =
                    Buffer.concat(части)
                        .toString("utf8");

                const данные =
                    JSON.parse(тело) as {
                        код?: unknown;
                    };

                if (
                    typeof данные.код !== "string"
                ) {
                    ответ.statusCode = 400;

                    ответ.setHeader(
                        "Content-Type",
                        "application/json; charset=utf-8",
                    );

                    ответ.end(
                        JSON.stringify({
                            успешно: false,
                            сообщение:
                                "Не указан исходный код программы.",
                        }),
                    );

                    return;
                }

                const компилятор =
                    система.получитьКомпилятор();

                const результат =
                    компилятор
                        .выполнить(данные.код);

                const интегратор =
                    система
                        .получитьИнтегратор();

                const ядро =
                    система
                        .получитьЯдро();

                const сообщениеОбОшибке =
                    результат.успешно
                        ? "Программа выполнена успешно."
                        : (
                            результат.семантика?.ошибки?.[0]?.сообщение ??
                            результат.контекст?.диагностика?.at(-1)?.сообщение ??
                            "Программа завершилась с ошибкой."
                        );

                const функции =
                    результат
                        .семантика
                        .глобальныеСимволы
                        .filter(
                            символ =>
                                символ.вид ===
                                "функция",
                        )
                        .map(
                            символ => ({
                                имя:
                                    символ.имя,
                                параметры:
                                    символ.параметры
                                        ? [
                                            ...символ.параметры,
                                        ]
                                        : [],
                            }),
                        );

                const функцииДля3D =
                    результат
                        .семантика
                        .глобальныеСимволы
                        .filter(
                            символ =>
                                символ.вид ===
                                "функция",
                        )
                        .map(
                            символ => ({
                                вид:
                                    "функция" as const,
                                имя:
                                    символ.имя,
                            }),
                        );

                интегратор
                    .синхронизироватьОбъявленныеФункции(
                        функцииДля3D,
                    );

                const снимок3D =
                    ядро.получитьСнимок3D();

                const ответТело = {
                    успешно: результат.успешно,
                    сообщение: сообщениеОбОшибке,
                    вывод: результат.контекст.вывод,
                    переменные:
                        результат.контекст.переменные,
                    события:
                        результат.контекст.события,
                    диагностика:
                        результат.контекст.диагностика,
                    состояние:
                        результат.контекст.фаза,
                    дерево:
                        результат.контекст.дерево,
                    функции,

                    трехмернаяСистема: {
                        узлов:
                            снимок3D.узлы.length,
                        связей:
                            снимок3D.связи.length,
                        событий:
                            снимок3D.количествоСобытий,
                    },

                    снимок3D,
                };

                ответ.statusCode = 200;

                ответ.setHeader(
                    "Content-Type",
                    "application/json; charset=utf-8",
                );

                ответ.end(
                    JSON.stringify(
                        ответТело,
                    ),
                );
            } catch (ошибка) {
                ответ.statusCode = 500;

                ответ.setHeader(
                    "Content-Type",
                    "application/json; charset=utf-8",
                );

                const сообщение =
                    ошибка instanceof Error
                        ? ошибка.message
                        : String(ошибка);

                ответ.end(
                    JSON.stringify({
                        успешно: false,
                        сообщение:
                            "Ошибка серверной части выполнения: " +
                            сообщение,
                    }),
                );
            }
        },
    );
};

/**
 * Единый роутер для прод-сервера: git → выполнение → файлы.
 * Порядок не важен: маршруты не пересекаются,
 * несвойственные пути уходят в следующий обработчик.
 */
export const мостAPI: ОбработчикМоста = (
    запрос,
    ответ,
    следующий,
) => {
    мостGit(запрос, ответ, () => {
        мостВыполнения(запрос, ответ, () => {
            обработчикФайловПроекта(
                запрос,
                ответ,
                следующий,
            );
        });
    });
};
