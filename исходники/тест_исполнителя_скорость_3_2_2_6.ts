function проверить(
    условие: boolean,
    сообщение: string
): void {

    if (!условие) {
        throw new Error(
            `❌ ПРОВЕРКА НЕ ПРОЙДЕНА: ${сообщение}`
        );
    }

    console.log(
        `   ✅ ${сообщение}`
    );
}


function пауза(
    миллисекунды: number
): Promise<void> {

    return new Promise(
        разрешить => {
            setTimeout(
                разрешить,
                миллисекунды
            );
        }
    );
}


// ============================================================
// ТЕСТ
// ============================================================

async function выполнитьТест(): Promise<void> {

    console.log("");
    console.log(
        "============================================================"
    );
    console.log(
        "🐌 ТЕСТ 3.2.2.6 — УПРАВЛЕНИЕ СКОРОСТЬЮ"
    );
    console.log(
        "============================================================"
    );
    console.log("");


    // ========================================================
    // ТЕСТОВАЯ ПРОГРАММА
    // ========================================================

    const программа = [
        {
            вид: "ПРОГРАММА",
            имя: "тест_скорости",

            тело: {
                вид: "БЛОК",

                команды: [

                    {
                        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
                        имя: "число",

                        значение: {
                            вид: "ЧИСЛО",
                            значение: 1
                        }
                    },

                    {
                        вид: "ОБЪЯВЛЕНИЕ_ПЕРЕМЕННОЙ",
                        имя: "второе_число",

                        значение: {
                            вид: "ЧИСЛО",
                            значение: 2
                        }
                    },

                    {
                        вид: "ПОКАЗАТЬ",

                        значения: [
                            {
                                вид: "ИМЯ",
                                значение: "число"
                            }
                        ]
                    }

                ]
            }
        }
    ] as any;


    // ========================================================
    // СОЗДАНИЕ ИСПОЛНИТЕЛЯ
    // ========================================================

    const исполнитель =
        new Исполнитель();


    // ========================================================
    // ПРОВЕРКА 1 — МГНОВЕННО
    // ========================================================

    console.log(
        "⚡ ПРОВЕРКА СКОРОСТИ: МГНОВЕННО"
    );

    исполнитель.установитьСкоростьВыполнения(
        "мгновенно"
    );

    проверить(
        исполнитель.получитьСкоростьВыполнения() ===
            "мгновенно",
        "скорость «мгновенно» установлена"
    );


    // ========================================================
    // ПРОВЕРКА 2 — БЫСТРО
    // ========================================================

    console.log(
        "🟢 ПРОВЕРКА СКОРОСТИ: БЫСТРО"
    );

    исполнитель.установитьСкоростьВыполнения(
        "быстро"
    );

    проверить(
        исполнитель.получитьСкоростьВыполнения() ===
            "быстро",
        "скорость «быстро» установлена"
    );


    // ========================================================
    // ПРОВЕРКА 3 — ОБЫЧНО
    // ========================================================

    console.log(
        "🟡 ПРОВЕРКА СКОРОСТИ: ОБЫЧНО"
    );

    исполнитель.установитьСкоростьВыполнения(
        "обычно"
    );

    проверить(
        исполнитель.получитьСкоростьВыполнения() ===
            "обычно",
        "скорость «обычно» установлена"
    );


    // ========================================================
    // ПРОВЕРКА 4 — МЕДЛЕННО
    // ========================================================

    console.log(
        "🐢 ПРОВЕРКА СКОРОСТИ: МЕДЛЕННО"
    );

    исполнитель.установитьСкоростьВыполнения(
        "медленно"
    );

    проверить(
        исполнитель.получитьСкоростьВыполнения() ===
            "медленно",
        "скорость «медленно» установлена"
    );


    // ========================================================
    // ПРОВЕРКА 5 — АВТОМАТИЧЕСКОЕ ВЫПОЛНЕНИЕ
    // ========================================================

    console.log("");
    console.log(
        "▶ ПРОВЕРКА АВТОМАТИЧЕСКОГО ВЫПОЛНЕНИЯ"
    );


    исполнитель.установитьСкоростьВыполнения(
        "мгновенно"
    );


    исполнитель.начатьПошаговоеВыполнение(
        программа
    );


    проверить(
        исполнитель.получитьСостояниеПошаговогоВыполнения() ===
            "выполнение",
        "пошаговое выполнение начато"
    );


    const результат =
        await исполнитель
            .запуститьАвтоматическоеВыполнение();


    проверить(
        результат !== null,
        "результат автоматического выполнения получен"
    );


    проверить(
        исполнитель.получитьСостояниеПошаговогоВыполнения() ===
            "завершено",
        "автоматическое выполнение завершено"
    );


    // ========================================================
    // ПРОВЕРКА 6 — ПАУЗА И ПРОДОЛЖЕНИЕ
    // ========================================================

    console.log("");
    console.log(
        "⏸️ ПРОВЕРКА ПАУЗЫ И ПРОДОЛЖЕНИЯ"
    );


    исполнитель.установитьСкоростьВыполнения(
        "медленно"
    );


    исполнитель.начатьПошаговоеВыполнение(
        программа
    );


    const выполнение =
        исполнитель
            .запуститьАвтоматическоеВыполнение();


    // Даём автоматическому выполнению начать работу.
    await пауза(50);


    исполнитель.приостановитьПошаговоеВыполнение();


    await пауза(50);


    проверить(
        исполнитель.получитьСостояниеПошаговогоВыполнения() ===
            "приостановлено",
        "автоматическое выполнение действительно приостановлено"
    );


    исполнитель.продолжитьПошаговоеВыполнение();


    проверить(
        исполнитель.получитьСостояниеПошаговогоВыполнения() ===
            "выполнение",
        "автоматическое выполнение продолжено"
    );


    await выполнение;


    проверить(
        исполнитель.получитьСостояниеПошаговогоВыполнения() ===
            "завершено",
        "после продолжения программа завершена"
    );


    // ========================================================
    // ПРОВЕРКА 7 — ОСТАНОВКА
    // ========================================================

    console.log("");
    console.log(
        "⏹️ ПРОВЕРКА ОСТАНОВКИ"
    );


    исполнитель.установитьСкоростьВыполнения(
        "медленно"
    );


    исполнитель.начатьПошаговоеВыполнение(
        программа
    );


    const выполнениеОстановки =
        исполнитель
            .запуститьАвтоматическоеВыполнение();


    await пауза(50);


    исполнитель.остановитьПошаговоеВыполнение();


    await выполнениеОстановки;


    проверить(
        исполнитель.получитьСостояниеПошаговогоВыполнения() ===
            "остановлено",
        "автоматическое выполнение остановлено"
    );


    // ========================================================
    // ИТОГ
    // ========================================================

    console.log("");
    console.log(
        "============================================================"
    );
    console.log(
        "🐌 ТЕСТ 3.2.2.6 ЗАВЕРШЁН УСПЕШНО"
    );
    console.log(
        "============================================================"
    );
    console.log("");
}


