/**
 * Состояние жизненного цикла 3D-объекта.
 *
 * Это состояние относится именно к объекту 3D-мира,
 * а не к состоянию всей программы.
 */
export type СостояниеОбъекта3D =
    | "создан"
    | "ожидание"
    | "активен"
    | "изменяется"
    | "выполняется"
    | "завершён"
    | "ошибка"
    | "восстанавливается";

/**
 * Позиция объекта в пространстве.
 */
export interface Позиция3D {
    x: number;
    y: number;
    z: number;
}

/**
 * Поворот объекта в пространстве.
 *
 * Значения задаются в градусах.
 */
export interface Поворот3D {
    x: number;
    y: number;
    z: number;
}

/**
 * Масштаб объекта.
 */
export interface Масштаб3D {
    x: number;
    y: number;
    z: number;
}

/**
 * Полная пространственная трансформация объекта.
 */
export interface Трансформация3D {
    позиция: Позиция3D;
    поворот: Поворот3D;
    масштаб: Масштаб3D;
}

/**
 * Тип объекта 3D-мира.
 *
 * На этом уровне тип намеренно общий.
 * Связь с ТипУзла будет выполнена позже.
 */
export type ТипОбъекта3D =
    | "программа"
    | "переменная"
    | "функция"
    | "выполнение"
    | "ошибка"
    | "группа"
    | "система";

/**
 * Базовый объект 3D-мира.
 *
 * Это НЕ графический объект.
 *
 * Здесь нет Three.js, WebGL, Canvas или DOM.
 *
 * Объект3D описывает только состояние и структуру
 * объекта внутри логического 3D-мира.
 */
export interface Объект3D {

    /**
     * Уникальный идентификатор объекта.
     */
    идентификатор: string;

    /**
     * Человекочитаемое имя объекта.
     */
    имя: string;

    /**
     * Тип объекта.
     */
    тип: ТипОбъекта3D;

    /**
     * Жизненный цикл объекта.
     */
    состояние: СостояниеОбъекта3D;

    /**
     * Пространственная трансформация.
     */
    трансформация: Трансформация3D;

    /**
     * Видимость объекта в 3D-мире.
     *
     * Это логическая видимость.
     * Графический движок позже сам решит,
     * как именно её отображать.
     */
    видим: boolean;

    /**
     * Активен ли объект.
     */
    активен: boolean;

    /**
     * Интенсивность объекта.
     *
     * Например:
     * 0   — полностью неактивен;
     * 1   — обычная активность;
     * >1  — повышенная активность.
     */
    интенсивность: number;

    /**
     * Идентификатор родительского объекта.
     *
     * null означает отсутствие родителя.
     */
    родитель: string | null;

    /**
     * Идентификаторы дочерних объектов.
     */
    дети: string[];

    /**
     * Дополнительные данные объекта.
     *
     * Здесь ядро может хранить произвольную информацию,
     * не разрушая основную модель.
     */
    метаданные: Record<string, unknown>;
}

/**
 * Создание стандартной позиции.
 */
export function создатьПозицию3D(
    x: number = 0,
    y: number = 0,
    z: number = 0
): Позиция3D {
    return {
        x,
        y,
        z
    };
}

/**
 * Создание стандартного поворота.
 */
export function создатьПоворот3D(
    x: number = 0,
    y: number = 0,
    z: number = 0
): Поворот3D {
    return {
        x,
        y,
        z
    };
}

/**
 * Создание стандартного масштаба.
 */
export function создатьМасштаб3D(
    x: number = 1,
    y: number = 1,
    z: number = 1
): Масштаб3D {
    return {
        x,
        y,
        z
    };
}

/**
 * Создание полной трансформации.
 */
export function создатьТрансформацию3D(
    позиция: Позиция3D = создатьПозицию3D(),
    поворот: Поворот3D = создатьПоворот3D(),
    масштаб: Масштаб3D = создатьМасштаб3D()
): Трансформация3D {
    return {
        позиция: structuredClone(позиция),
        поворот: structuredClone(поворот),
        масштаб: structuredClone(масштаб)
    };
}

/**
 * Создание нового объекта 3D-мира.
 */
export function создатьОбъект3D(
    идентификатор: string,
    имя: string,
    тип: ТипОбъекта3D
): Объект3D {
    return {
        идентификатор,
        имя,
        тип,
        состояние: "создан",

        трансформация:
            создатьТрансформацию3D(),

        видим: true,

        активен: false,

        интенсивность: 0,

        родитель: null,

        дети: [],

        метаданные: {}
    };
}

/**
 * Глубокое копирование объекта 3D.
 */
export function клонироватьОбъект3D(
    объект: Объект3D
): Объект3D {
    return structuredClone(объект);
}

/**
 * Устанавливает позицию объекта.
 */
export function установитьПозицию3D(
    объект: Объект3D,
    x: number,
    y: number,
    z: number
): void {
    объект.трансформация.позиция = {
        x,
        y,
        z
    };
}

/**
 * Устанавливает поворот объекта.
 */
export function установитьПоворот3D(
    объект: Объект3D,
    x: number,
    y: number,
    z: number
): void {
    объект.трансформация.поворот = {
        x,
        y,
        z
    };
}

/**
 * Устанавливает масштаб объекта.
 */
export function установитьМасштаб3D(
    объект: Объект3D,
    x: number,
    y: number,
    z: number
): void {
    объект.трансформация.масштаб = {
        x,
        y,
        z
    };
}

/**
 * Устанавливает состояние жизненного цикла.
 */
export function установитьСостояниеОбъекта3D(
    объект: Объект3D,
    состояние: СостояниеОбъекта3D
): void {
    объект.состояние = состояние;
}

/**
 * Активирует объект.
 */
export function активироватьОбъект3D(
    объект: Объект3D,
    интенсивность: number = 1
): void {
    объект.активен = true;
    объект.интенсивность = интенсивность;
    объект.состояние = "активен";
}

/**
 * Деактивирует объект.
 */
export function деактивироватьОбъект3D(
    объект: Объект3D
): void {
    объект.активен = false;
    объект.интенсивность = 0;
    объект.состояние = "ожидание";
}

/**
 * Устанавливает родителя.
 */
export function установитьРодителя3D(
    объект: Объект3D,
    родитель: string | null
): void {
    объект.родитель = родитель;
}

/**
 * Добавляет дочерний объект.
 */
export function добавитьРебёнка3D(
    объект: Объект3D,
    идентификаторРебёнка: string
): void {
    if (
        объект.дети.includes(
            идентификаторРебёнка
        )
    ) {
        return;
    }

    объект.дети.push(
        идентификаторРебёнка
    );
}

/**
 * Удаляет дочерний объект.
 */
export function удалитьРебёнка3D(
    объект: Объект3D,
    идентификаторРебёнка: string
): void {
    объект.дети =
        объект.дети.filter(
            идентификатор =>
                идентификатор !==
                идентификаторРебёнка
        );
}

/**
 * Добавляет или изменяет метаданные.
 */
export function установитьМетаданные3D(
    объект: Объект3D,
    ключ: string,
    значение: unknown
): void {
    объект.метаданные[ключ] = значение;
}

/**
 * Получает метаданные.
 */
export function получитьМетаданные3D(
    объект: Объект3D,
    ключ: string
): unknown {
    return объект.метаданные[ключ];
}

/**
 * Проверяет корректность объекта 3D.
 */
export function проверитьОбъект3D(
    объект: Объект3D
): boolean {

    if (!объект) {
        return false;
    }

    if (
        typeof объект.идентификатор !==
        "string"
    ) {
        return false;
    }

    if (
        typeof объект.имя !==
        "string"
    ) {
        return false;
    }

    if (
        typeof объект.тип !==
        "string"
    ) {
        return false;
    }

    if (
        typeof объект.состояние !==
        "string"
    ) {
        return false;
    }

    if (!объект.трансформация) {
        return false;
    }

    if (
        !объект.трансформация.позиция ||
        !объект.трансформация.поворот ||
        !объект.трансформация.масштаб
    ) {
        return false;
    }

    if (
        typeof объект.видим !==
        "boolean"
    ) {
        return false;
    }

    if (
        typeof объект.активен !==
        "boolean"
    ) {
        return false;
    }

    if (
        typeof объект.интенсивность !==
        "number"
    ) {
        return false;
    }

    if (
        объект.родитель !== null &&
        typeof объект.родитель !==
        "string"
    ) {
        return false;
    }

    if (!Array.isArray(объект.дети)) {
        return false;
    }

    if (
        !объект.метаданные ||
        typeof объект.метаданные !==
            "object"
    ) {
        return false;
    }

    return true;
}