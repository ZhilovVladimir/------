import { СистемаУлитки3D } from "./система_улитки_3d.js";

function проверить(
    условие: boolean,
    сообщение: string
): void {

    if (!условие) {
        throw new Error(`❌ ${сообщение}`);
    }
}

console.log("🐌 ТЕСТ ПОЛНОГО КОНВЕЙЕРА УЛИТКИ 3D");
console.log("");

const код = `
программа проверка

начало

    пусть а = 10
    пусть б = 20
    пусть сумма = а + б

    показать сумма

конец
`;

console.log("📜 Исходный код:");
console.log(код);

console.log("");
console.log("🏗️ Создание центральной системы...");

const система = new СистемаУлитки3D();

проверить(
    система.получитьКомпилятор() !== undefined,
    "Компилятор не создан"
);

проверить(
    система.получитьИнтегратор() !== undefined,
    "Интегратор не создан"
);

проверить(
    система.получитьЯдро() !== undefined,
    "3D-ядро не создано"
);

console.log("✅ Центральная система создана");

console.log("");
console.log("⚙️ Запуск Компилятора...");

const компилятор = система.получитьКомпилятор();

const результат = компилятор.выполнить(код);

проверить(
    результат !== undefined,
    "Компилятор не вернул результат"
);

проверить(
    результат.успешно === true,
    "Компиляция или выполнение завершились ошибкой"
);

проверить(
    результат.выполнение !== null,
    "Результат выполнения отсутствует"
);

console.log("✅ Компилятор успешно выполнил программу");

console.log("");
console.log("📊 Проверка результата:");

console.dir(
    результат.выполнение,
    { depth: null }
);

console.log("");
console.log("🌐 Проверка 3D-системы:");

const ядро = система.получитьЯдро();

const узлы = ядро.получитьУзлы();
const связи = ядро.получитьСвязи();
const события = ядро.получитьСобытия();

проверить(
    узлы.length > 0,
    "3D-ядро не получило узлы"
);

проверить(
    события.length > 0,
    "3D-ядро не получило события"
);

console.log(`✅ 3D-узлов: ${узлы.length}`);
console.log(`✅ 3D-связей: ${связи.length}`);
console.log(`✅ Событий: ${события.length}`);

console.log("");
console.log("🎉 ПОЛНЫЙ КОНВЕЙЕР УЛИТКИ 3D ПРОЙДЕН");
console.log("");
console.log(
    "Код → Компилятор → Исполнитель → Интегратор → Ядро3D"
);