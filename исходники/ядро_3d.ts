// ============================================================
// 🐌 УЛИТКА — 3D-ЯДРО
// Центральное ядро визуальной системы
// ============================================================

import type {
    СостояниеПрограммы,
    ПеременнаяПрограммы,
    ФункцияПрограммы,
    ОшибкаПрограммы,
    СостояниеВыполнения
} from "./состояние_программы";

import type {
    УзелСистемы,
    ТипУзла
} from "./узел_системы";

import type {
    СвязьСистемы,
    ТипСвязи
} from "./связь_системы";

import type {
    СобытиеСистемы,
    ТипСобытия
} from "./события_системы";

// ============================================================
// ТИП РЕЖИМА ВОСПРОИЗВЕДЕНИЯ
// ============================================================

export type РежимВоспроизведения =
    | "остановлено"
    | "воспроизведение";

// ============================================================
// 🐌 КЛАСС 3D-ЯДРА
// ============================================================

export class Ядро3D {

    // ========================================================
    // ОСНОВНОЕ СОСТОЯНИЕ ПРОГРАММЫ
    // ========================================================

    private состояние: СостояниеПрограммы;

    // ========================================================
    // 3D-ОБЪЕКТЫ
    // ========================================================

    private узлы: УзелСистемы[] = [];
    private связи: СвязьСистемы[] = [];

    // ========================================================
    // ИСТОРИЯ СОБЫТИЙ
    // ========================================================

    private события: СобытиеСистемы[] = [];

    // ========================================================
    // КУРСОР ИСТОРИИ
    //
    // -1 означает, что ни одно событие не выбрано.
    // ========================================================

    private текущаяПозицияИстории: number = -1;

    // ========================================================
    // РЕЖИМ ВОСПРОИЗВЕДЕНИЯ
    // ========================================================

    private режимВоспроизведения: РежимВоспроизведения =
        "остановлено";

    // ========================================================
    // ЗАЩИТА ОТ СОЗДАНИЯ СОБЫТИЙ ПРИ ВОСПРОИЗВЕДЕНИИ
    // ========================================================

    private воспроизведениеАктивно: boolean = false;

    // ========================================================
    // КОНСТРУКТОР
    // ========================================================

    constructor() {
        this.состояние = {
            состояние: "ожидание",
            текущаяСтрока: 0,
            переменные: [],
            функции: [],
            ошибки: []
        };
    }

    // ========================================================
    // ПОЛУЧЕНИЕ СОСТОЯНИЯ
    // ========================================================

    получитьСостояние(): СостояниеПрограммы {
        return this.состояние;
    }

    получитьУзлы(): УзелСистемы[] {
        return this.узлы;
    }

    получитьСвязи(): СвязьСистемы[] {
        return this.связи;
    }

    получитьСобытия(): СобытиеСистемы[] {
        return this.события;
    }

    // ========================================================
    // ПОЛУЧЕНИЕ СОСТОЯНИЯ ИСТОРИИ
    // ========================================================

    получитьТекущуюПозициюИстории(): number {
        return this.текущаяПозицияИстории;
    }

    получитьКоличествоСобытий(): number {
        return this.события.length;
    }

    получитьРежимВоспроизведения(): РежимВоспроизведения {
        return this.режимВоспроизведения;
    }

    получитьТекущееСобытие(): СобытиеСистемы | null {
        if (
            this.текущаяПозицияИстории < 0 ||
            this.текущаяПозицияИстории >=
                this.события.length
        ) {
            return null;
        }

        return this.события[
            this.текущаяПозицияИстории
        ];
    }

    // ========================================================
    // СОСТОЯНИЕ ВЫПОЛНЕНИЯ
    // ========================================================

    установитьСостояние(
        состояние: СостояниеВыполнения
    ): void {

        this.состояние.состояние =
            состояние;

        // Во время воспроизведения историю
        // записывать нельзя.
        if (this.воспроизведениеАктивно) {
            return;
        }

        if (состояние === "выполнение") {
            this.добавитьСобытие(
                "начало_выполнения",
                "ядро_3d",
                {
                    состояние
                }
            );
        }

        if (состояние === "завершено") {
            this.добавитьСобытие(
                "завершение_выполнения",
                "ядро_3d",
                {
                    состояние
                }
            );
        }
    }

    // ========================================================
    // ТЕКУЩАЯ СТРОКА
    // ========================================================

    установитьТекущуюСтроку(
        строка: number
    ): void {

        this.состояние.текущаяСтрока =
            строка;

        // При воспроизведении новые события
        // создавать нельзя.
        if (this.воспроизведениеАктивно) {
            return;
        }

        // Каждое изменение строки становится
        // отдельным событием истории.
        this.добавитьСобытие(
            "изменение_строки",
            "ядро_3d",
            {
                строка
            }
        );
    }

    // ========================================================
    // ПЕРЕМЕННЫЕ
    // ========================================================

    добавитьПеременную(
        переменная: ПеременнаяПрограммы
    ): void {

        this.состояние.переменные.push(
            this.создатьСнимок(переменная)
        );

        const идентификаторУзла =
            this.добавитьУзел(
                "переменная",
                переменная.имя
            );

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "создание_узла",
                идентификаторУзла,
                переменная
            );
        }
    }

    // ========================================================
    // ФУНКЦИИ
    // ========================================================

    добавитьФункцию(
        функция: ФункцияПрограммы
    ): void {

        this.состояние.функции.push(
            this.создатьСнимок(функция)
        );

        const идентификаторУзла =
            this.добавитьУзел(
                "функция",
                функция.имя
            );

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "создание_узла",
                идентификаторУзла,
                функция
            );
        }
    }

    // ========================================================
    // ОШИБКИ
    // ========================================================

    добавитьОшибку(
        ошибка: ОшибкаПрограммы
    ): void {

        this.состояние.ошибки.push(
            this.создатьСнимок(ошибка)
        );

        const идентификаторУзла =
            this.добавитьУзел(
                "ошибка",
                `ошибка_${ошибка.строка}`
            );

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "ошибка",
                идентификаторУзла,
                ошибка
            );

            this.установитьСостояние("ошибка");
        }
    }

    // ========================================================
    // УЗЛЫ
    // ========================================================

    добавитьУзел(
        тип: ТипУзла,
        имя: string
    ): string {

        const идентификатор =
            `узел_${this.узлы.length + 1}`;

        const узел: УзелСистемы = {
            идентификатор,
            тип,
            имя,
            позиция: {
                x: 0,
                y: 0,
                z: 0
            },
            активен: false,
            интенсивность: 0
        };

        this.узлы.push(узел);

        return идентификатор;
    }

    активироватьУзел(
        идентификатор: string,
        интенсивность: number = 1
    ): boolean {

        const узел = this.узлы.find(
            элемент =>
                элемент.идентификатор ===
                идентификатор
        );

        if (!узел) {
            return false;
        }

        узел.активен = true;
        узел.интенсивность =
            интенсивность;

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "изменение_узла",
                идентификатор,
                {
                    активен: true,
                    интенсивность
                }
            );
        }

        return true;
    }

    деактивироватьУзел(
        идентификатор: string
    ): boolean {

        const узел = this.узлы.find(
            элемент =>
                элемент.идентификатор ===
                идентификатор
        );

        if (!узел) {
            return false;
        }

        узел.активен = false;
        узел.интенсивность = 0;

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "изменение_узла",
                идентификатор,
                {
                    активен: false,
                    интенсивность: 0
                }
            );
        }

        return true;
    }

    изменитьИнтенсивностьУзла(
        идентификатор: string,
        интенсивность: number
    ): boolean {

        const узел = this.узлы.find(
            элемент =>
                элемент.идентификатор ===
                идентификатор
        );

        if (!узел) {
            return false;
        }

        узел.интенсивность =
            интенсивность;

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "изменение_узла",
                идентификатор,
                {
                    активен: узел.активен,
                    интенсивность
                }
            );
        }

        return true;
    }

    // ========================================================
    // СВЯЗИ
    // ========================================================

    добавитьСвязь(
        откуда: string,
        куда: string,
        тип: ТипСвязи
    ): string {

        const идентификатор =
            `связь_${this.связи.length + 1}`;

        const связь: СвязьСистемы = {
            идентификатор,
            откуда,
            куда,
            тип,
            активна: false,
            интенсивность: 0
        };

        this.связи.push(связь);

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "создание_связи",
                идентификатор,
                {
                    идентификатор:
                        связь.идентификатор,
                    откуда:
                        связь.откуда,
                    куда:
                        связь.куда,
                    тип:
                        связь.тип,
                    активна:
                        связь.активна,
                    интенсивность:
                        связь.интенсивность
                }
            );
        }

        return идентификатор;
    }

    активироватьСвязь(
        идентификатор: string,
        интенсивность: number = 1
    ): boolean {

        const связь = this.связи.find(
            элемент =>
                элемент.идентификатор ===
                идентификатор
        );

        if (!связь) {
            return false;
        }

        связь.активна = true;
        связь.интенсивность =
            интенсивность;

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "изменение_связи",
                идентификатор,
                {
                    активна: true,
                    интенсивность
                }
            );
        }

        return true;
    }

    деактивироватьСвязь(
        идентификатор: string
    ): boolean {

        const связь = this.связи.find(
            элемент =>
                элемент.идентификатор ===
                идентификатор
        );

        if (!связь) {
            return false;
        }

        связь.активна = false;
        связь.интенсивность = 0;

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "изменение_связи",
                идентификатор,
                {
                    активна: false,
                    интенсивность: 0
                }
            );
        }

        return true;
    }

    изменитьИнтенсивностьСвязи(
        идентификатор: string,
        интенсивность: number
    ): boolean {

        const связь = this.связи.find(
            элемент =>
                элемент.идентификатор ===
                идентификатор
        );

        if (!связь) {
            return false;
        }

        связь.интенсивность =
            интенсивность;

        if (!this.воспроизведениеАктивно) {
            this.добавитьСобытие(
                "изменение_связи",
                идентификатор,
                {
                    активна: связь.активна,
                    интенсивность
                }
            );
        }

        return true;
    }

    // ========================================================
    // ДОБАВЛЕНИЕ СОБЫТИЯ
    // ========================================================

    добавитьСобытие(
        тип: ТипСобытия,
        источник: string,
        данные: unknown
    ): void {

        if (this.воспроизведениеАктивно) {
            return;
        }

        const событие: СобытиеСистемы = {
            идентификатор:
                `событие_${this.события.length + 1}`,

            тип,

            время:
                Date.now(),

            источник,

            данные:
                this.создатьСнимок(данные)
        };

        this.события.push(событие);

        this.текущаяПозицияИстории =
            this.события.length - 1;
    }

    // ========================================================
    // СОЗДАНИЕ СНИМКА ДАННЫХ
    // ========================================================

    private создатьСнимок(
        данные: unknown
    ): any {

        if (данные === null) {
            return null;
        }

        if (typeof данные !== "object") {
            return данные;
        }

        return structuredClone(данные);
    }

    // ========================================================
    // 🐌 ВОСПРОИЗВЕДЕНИЕ ИСТОРИИ
    // ========================================================

    // ========================================================
    // НАЧАТЬ ВОСПРОИЗВЕДЕНИЕ
    // ========================================================

    начатьВоспроизведение(): void {

        if (this.события.length === 0) {
            this.текущаяПозицияИстории =
                -1;

            this.режимВоспроизведения =
                "остановлено";

            this.воспроизведениеАктивно =
                false;

            return;
        }

        this.режимВоспроизведения =
            "воспроизведение";

        this.воспроизведениеАктивно =
            true;

        this.восстановитьСостояниеДо(-1);

        this.текущаяПозицияИстории =
            -1;

        // Остаёмся в режиме воспроизведения.
        this.воспроизведениеАктивно =
            true;
    }

    // ========================================================
    // СЛЕДУЮЩЕЕ СОБЫТИЕ
    // ========================================================

    следующееСобытие():
        СобытиеСистемы | null {

        if (this.события.length === 0) {
            return null;
        }

        const следующаяПозиция =
            this.текущаяПозицияИстории + 1;

        if (
            следующаяПозиция >=
            this.события.length
        ) {
            return null;
        }

        this.воспроизведениеАктивно =
            true;

        this.применитьСобытие(
            this.события[следующаяПозиция]
        );

        this.текущаяПозицияИстории =
            следующаяПозиция;

        this.воспроизведениеАктивно =
            false;

        return this.события[
            следующаяПозиция
        ];
    }

    // ========================================================
    // ПРЕДЫДУЩЕЕ СОБЫТИЕ
    // ========================================================

    предыдущееСобытие():
        СобытиеСистемы | null {

        if (
            this.текущаяПозицияИстории <= 0
        ) {

            this.воспроизведениеАктивно =
                true;

            this.восстановитьСостояниеДо(-1);

            this.текущаяПозицияИстории =
                -1;

            this.воспроизведениеАктивно =
                true;

            return null;
        }

        const предыдущаяПозиция =
            this.текущаяПозицияИстории - 1;

        this.восстановитьСостояниеДо(
            предыдущаяПозиция
        );

        this.текущаяПозицияИстории =
            предыдущаяПозиция;

        return this.события[
            предыдущаяПозиция
        ];
    }

    // ========================================================
    // ПЕРЕЙТИ К КОНКРЕТНОМУ СОБЫТИЮ
    // ========================================================

    перейтиКСобытию(
        позиция: number
    ): СобытиеСистемы | null {

        if (this.события.length === 0) {
            return null;
        }

        if (позиция < -1) {
            позиция = -1;
        }

        if (
            позиция >=
            this.события.length
        ) {
            позиция =
                this.события.length - 1;
        }

        this.восстановитьСостояниеДо(
            позиция
        );

        this.текущаяПозицияИстории =
            позиция;

        if (позиция === -1) {
            return null;
        }

        return this.события[позиция];
    }

    // ========================================================
    // ОСТАНОВИТЬ ВОСПРОИЗВЕДЕНИЕ
    // ========================================================

    остановитьВоспроизведение(): void {

        this.режимВоспроизведения =
            "остановлено";

        this.воспроизведениеАктивно =
            false;
    }

    // ========================================================
    // ВОСПРОИЗВЕСТИ ВСЮ ИСТОРИЮ
    // ========================================================

    воспроизвестиИсторию(): void {

        this.начатьВоспроизведение();

        while (
            this.текущаяПозицияИстории <
            this.события.length - 1
        ) {

            const событие =
                this.следующееСобытие();

            if (!событие) {
                break;
            }
        }

        this.остановитьВоспроизведение();
    }

    // ========================================================
    // ВОССТАНОВИТЬ СОСТОЯНИЕ ДО СОБЫТИЯ
    // ========================================================

    private восстановитьСостояниеДо(
        позиция: number
    ): void {

        this.воспроизведениеАктивно =
            true;

        // Очищаем визуальное состояние.
        this.узлы = [];
        this.связи = [];

        // Сбрасываем состояние программы.
        this.состояние = {
            состояние: "ожидание",
            текущаяСтрока: 0,
            переменные: [],
            функции: [],
            ошибки: []
        };

        // Применяем события от начала
        // до указанной позиции.
        for (
            let индекс = 0;
            индекс <= позиция;
            индекс++
        ) {

            const событие =
                this.события[индекс];

            if (событие) {
                this.применитьСобытие(
                    событие
                );
            }
        }
    }

    // ========================================================
    // ПРИМЕНИТЬ ОДНО СОБЫТИЕ
    // ========================================================

    private применитьСобытие(
        событие: СобытиеСистемы
    ): void {

        switch (событие.тип) {

            // ==================================================
            // СОЗДАНИЕ УЗЛА
            // ==================================================

            case "создание_узла": {

                this.применитьСозданиеУзла(
                    событие
                );

                break;
            }

            // ==================================================
            // ИЗМЕНЕНИЕ УЗЛА
            // ==================================================

            case "изменение_узла": {

                this.применитьИзменениеУзла(
                    событие
                );

                break;
            }

            // ==================================================
            // СОЗДАНИЕ СВЯЗИ
            // ==================================================

            case "создание_связи": {

                this.применитьСозданиеСвязи(
                    событие
                );

                break;
            }

            // ==================================================
            // ИЗМЕНЕНИЕ СВЯЗИ
            // ==================================================

            case "изменение_связи": {

                this.применитьИзменениеСвязи(
                    событие
                );

                break;
            }

            // ==================================================
            // НАЧАЛО ВЫПОЛНЕНИЯ
            // ==================================================

            case "начало_выполнения": {

                const данные =
                    this.получитьОбъект(
                        событие.данные
                    );

                if (
                    this.являетсяСостояниемВыполнения(
                        данные?.состояние
                    )
                ) {

                    this.состояние.состояние =
                        данные.состояние;
                }

                break;
            }

            // ==================================================
            // ЗАВЕРШЕНИЕ ВЫПОЛНЕНИЯ
            // ==================================================

            case "завершение_выполнения": {

                const данные =
                    this.получитьОбъект(
                        событие.данные
                    );

                if (
                    this.являетсяСостояниемВыполнения(
                        данные?.состояние
                    )
                ) {

                    this.состояние.состояние =
                        данные.состояние;
                }

                break;
            }

            // ==================================================
            // ИЗМЕНЕНИЕ ТЕКУЩЕЙ СТРОКИ
            // ==================================================

            case "изменение_строки": {

                const данные =
                    this.получитьОбъект(
                        событие.данные
                    );

                if (
                    typeof данные?.строка ===
                    "number"
                ) {

                    this.состояние.текущаяСтрока =
                        данные.строка;
                }

                break;
            }

            // ==================================================
            // ОШИБКА
            // ==================================================

            case "ошибка": {

                const ошибка =
                    this.создатьСнимок(
                        событие.данные
                    ) as ОшибкаПрограммы;

                this.состояние.ошибки.push(
                    ошибка
                );

                this.состояние.состояние =
                    "ошибка";

                break;
            }
        }
    }

    // ========================================================
    // ПРИМЕНИТЬ СОЗДАНИЕ УЗЛА
    // ========================================================

    private применитьСозданиеУзла(
        событие: СобытиеСистемы
    ): void {

        const существующий =
            this.узлы.find(
                узел =>
                    узел.идентификатор ===
                    событие.источник
            );

        if (существующий) {
            return;
        }

        const данные =
            this.получитьОбъект(
                событие.данные
            );

        let тип: ТипУзла =
            "переменная";

        let имя =
            событие.источник;

        // ----------------------------------------------------
        // Сначала функция.
        // ----------------------------------------------------

        if (
            this.являетсяФункцией(
                данные
            )
        ) {

            тип = "функция";
            имя = данные.имя;

            this.состояние.функции.push(
                this.создатьСнимок(
                    данные
                )
            );
        }

        // ----------------------------------------------------
        // Затем переменная.
        // ----------------------------------------------------

        else if (
            this.являетсяПеременной(
                данные
            )
        ) {

            тип = "переменная";
            имя = данные.имя;

            this.состояние.переменные.push(
                this.создатьСнимок(
                    данные
                )
            );
        }

        // ----------------------------------------------------
        // Создание восстановленного узла.
        // ----------------------------------------------------

        this.узлы.push({

            идентификатор:
                событие.источник,

            тип,

            имя,

            позиция: {
                x: 0,
                y: 0,
                z: 0
            },

            активен: false,

            интенсивность: 0
        });
    }

    // ========================================================
    // ПРИМЕНИТЬ ИЗМЕНЕНИЕ УЗЛА
    // ========================================================

    private применитьИзменениеУзла(
        событие: СобытиеСистемы
    ): void {

        const узел =
            this.узлы.find(
                элемент =>
                    элемент.идентификатор ===
                    событие.источник
            );

        if (!узел) {
            return;
        }

        const данные =
            this.получитьОбъект(
                событие.данные
            );

        if (
            typeof данные?.активен ===
            "boolean"
        ) {

            узел.активен =
                данные.активен;
        }

        if (
            typeof данные?.интенсивность ===
            "number"
        ) {

            узел.интенсивность =
                данные.интенсивность;
        }
    }

    // ========================================================
    // ПРИМЕНИТЬ СОЗДАНИЕ СВЯЗИ
    // ========================================================

    private применитьСозданиеСвязи(
        событие: СобытиеСистемы
    ): void {

        const данные =
            this.получитьОбъект(
                событие.данные
            );

        if (!данные) {
            return;
        }

        const существующая =
            this.связи.find(
                связь =>
                    связь.идентификатор ===
                    данные.идентификатор
            );

        if (существующая) {
            return;
        }

        if (
            typeof данные.идентификатор !==
            "string"
        ) {
            return;
        }

        if (
            typeof данные.откуда !==
            "string"
        ) {
            return;
        }

        if (
            typeof данные.куда !==
            "string"
        ) {
            return;
        }

        if (
            !this.являетсяТипомСвязи(
                данные.тип
            )
        ) {
            return;
        }

        this.связи.push({

            идентификатор:
                данные.идентификатор,

            откуда:
                данные.откуда,

            куда:
                данные.куда,

            тип:
                данные.тип,

            активна:
                данные.активна === true,

            интенсивность:
                typeof данные.интенсивность ===
                "number"
                    ? данные.интенсивность
                    : 0
        });
    }

    // ========================================================
    // ПРИМЕНИТЬ ИЗМЕНЕНИЕ СВЯЗИ
    // ========================================================

    private применитьИзменениеСвязи(
        событие: СобытиеСистемы
    ): void {

        const связь =
            this.связи.find(
                элемент =>
                    элемент.идентификатор ===
                    событие.источник
            );

        if (!связь) {
            return;
        }

        const данные =
            this.получитьОбъект(
                событие.данные
            );

        if (
            typeof данные?.активна ===
            "boolean"
        ) {

            связь.активна =
                данные.активна;
        }

        if (
            typeof данные?.интенсивность ===
            "number"
        ) {

            связь.интенсивность =
                данные.интенсивность;
        }
    }

    // ========================================================
    // ПОЛУЧИТЬ ОБЪЕКТ ИЗ UNKNOWN
    // ========================================================

    private получитьОбъект(
        данные: unknown
    ): Record<string, any> | null {

        if (
            typeof данные !== "object" ||
            данные === null
        ) {
            return null;
        }

        return данные as Record<string, any>;
    }

    // ========================================================
    // ПРОВЕРКА ПЕРЕМЕННОЙ
    // ========================================================

    private являетсяПеременной(
        данные: Record<string, any> | null
    ): данные is ПеременнаяПрограммы {

        return (
            данные !== null &&
            typeof данные.имя === "string" &&
            "значение" in данные &&
            "тип" in данные
        );
    }

    // ========================================================
    // ПРОВЕРКА ФУНКЦИИ
    // ========================================================

    private являетсяФункцией(
        данные: Record<string, any> | null
    ): данные is ФункцияПрограммы {

        return (
            данные !== null &&
            typeof данные.имя === "string" &&
            Array.isArray(
                данные.параметры
            )
        );
    }

    // ========================================================
    // ПРОВЕРКА СОСТОЯНИЯ ВЫПОЛНЕНИЯ
    // ========================================================

    private являетсяСостояниемВыполнения(
        значение: unknown
    ): значение is СостояниеВыполнения {

        return (
            значение === "ожидание" ||
            значение === "выполнение" ||
            значение === "завершено" ||
            значение === "ошибка"
        );
    }

    // ========================================================
    // ПРОВЕРКА ТИПА СВЯЗИ
    // ========================================================

    private являетсяТипомСвязи(
        значение: unknown
    ): значение is ТипСвязи {

        return typeof значение === "string";
    }
}