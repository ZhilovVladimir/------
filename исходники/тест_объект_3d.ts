// ============================================================
// 🐌 УЛИТКА — 3D-ЯДРО
// Тест базовой модели объекта 3D-мира
// ============================================================

import {
    создатьОбъект3D,
    клонироватьОбъект3D,
    установитьПозицию3D,
    установитьПоворот3D,
    установитьМасштаб3D,
    активироватьОбъект3D,
    деактивироватьОбъект3D,
    установитьРодителя3D,
    добавитьРебёнка3D,
    удалитьРебёнка3D,
    установитьМетаданные3D,
    получитьМетаданные3D,
    проверитьОбъект3D
} from "./объект_3d";

console.log(
    "============================================================"
);

console.log(
    "🐌 ТЕСТ БАЗОВОГО 3D-ОБЪЕКТА"
);

console.log(
    "============================================================"
);

console.log("");
console.log("1. Создание объекта");

const объект = создатьОбъект3D(
    "объект_1",
    "Главная программа",
    "программа"
);

console.log(объект);

if (!проверитьОбъект3D(объект)) {
    throw new Error(
        "❌ Проверка нового объекта не пройдена."
    );
}

console.log(
    "✅ Объект создан и успешно проверен."
);

console.log("");
console.log("2. Изменение позиции");

установитьПозицию3D(
    объект,
    10,
    20,
    30
);

console.log(
    "Позиция:",
    объект.трансформация.позиция
);

if (
    объект.трансформация.позиция.x !== 10 ||
    объект.трансформация.позиция.y !== 20 ||
    объект.трансформация.позиция.z !== 30
) {
    throw new Error(
        "❌ Позиция объекта установлена неправильно."
    );
}

console.log(
    "✅ Позиция установлена."
);

console.log("");
console.log("3. Изменение поворота");

установитьПоворот3D(
    объект,
    15,
    30,
    45
);

console.log(
    "Поворот:",
    объект.трансформация.поворот
);

if (
    объект.трансформация.поворот.x !== 15 ||
    объект.трансформация.поворот.y !== 30 ||
    объект.трансформация.поворот.z !== 45
) {
    throw new Error(
        "❌ Поворот объекта установлен неправильно."
    );
}

console.log(
    "✅ Поворот установлен."
);

console.log("");
console.log("4. Изменение масштаба");

установитьМасштаб3D(
    объект,
    2,
    3,
    4
);

console.log(
    "Масштаб:",
    объект.трансформация.масштаб
);

if (
    объект.трансформация.масштаб.x !== 2 ||
    объект.трансформация.масштаб.y !== 3 ||
    объект.трансформация.масштаб.z !== 4
) {
    throw new Error(
        "❌ Масштаб объекта установлен неправильно."
    );
}

console.log(
    "✅ Масштаб установлен."
);

console.log("");
console.log("5. Активация объекта");

активироватьОбъект3D(
    объект,
    0.8
);

console.log(
    "Состояние:",
    объект.состояние
);

console.log(
    "Активен:",
    объект.активен
);

console.log(
    "Интенсивность:",
    объект.интенсивность
);

if (
    объект.активен !== true ||
    объект.интенсивность !== 0.8 ||
    объект.состояние !== "активен"
) {
    throw new Error(
        "❌ Активация объекта работает неправильно."
    );
}

console.log(
    "✅ Объект активирован."
);

console.log("");
console.log("6. Родитель и дочерний объект");

const ребёнок = создатьОбъект3D(
    "объект_2",
    "Переменная имя",
    "переменная"
);

установитьРодителя3D(
    ребёнок,
    объект.идентификатор
);

добавитьРебёнка3D(
    объект,
    ребёнок.идентификатор
);

console.log(
    "Родитель ребёнка:",
    ребёнок.родитель
);

console.log(
    "Дети родителя:",
    объект.дети
);

if (
    ребёнок.родитель !==
        объект.идентификатор
) {
    throw new Error(
        "❌ Родитель объекта установлен неправильно."
    );
}

if (
    !объект.дети.includes(
        ребёнок.идентификатор
    )
) {
    throw new Error(
        "❌ Ребёнок не добавлен к родителю."
    );
}

console.log(
    "✅ Иерархия объектов работает."
);

console.log("");
console.log("7. Метаданные");

установитьМетаданные3D(
    объект,
    "роль",
    "корневой объект программы"
);

установитьМетаданные3D(
    объект,
    "уровень",
    1
);

const роль =
    получитьМетаданные3D(
        объект,
        "роль"
    );

const уровень =
    получитьМетаданные3D(
        объект,
        "уровень"
    );

console.log(
    "Роль:",
    роль
);

console.log(
    "Уровень:",
    уровень
);

if (
    роль !==
        "корневой объект программы"
) {
    throw new Error(
        "❌ Метаданные роли работают неправильно."
    );
}

if (уровень !== 1) {
    throw new Error(
        "❌ Метаданные уровня работают неправильно."
    );
}

console.log(
    "✅ Метаданные работают."
);

console.log("");
console.log("8. Клонирование объекта");

const копия =
    клонироватьОбъект3D(
        объект
    );

console.log(
    "Копия:",
    копия
);

if (
    копия === объект
) {
    throw new Error(
        "❌ Клон является той же ссылкой."
    );
}

if (
    копия.идентификатор !==
        объект.идентификатор
) {
    throw new Error(
        "❌ Идентификатор копии отличается."
    );
}

if (
    копия.трансформация.позиция.x !==
        объект.трансформация.позиция.x
) {
    throw new Error(
        "❌ Позиция не скопирована."
    );
}

console.log(
    "✅ Глубокое клонирование работает."
);

console.log("");
console.log("9. Удаление ребёнка");

удалитьРебёнка3D(
    объект,
    ребёнок.идентификатор
);

console.log(
    "Дети после удаления:",
    объект.дети
);

if (
    объект.дети.includes(
        ребёнок.идентификатор
    )
) {
    throw new Error(
        "❌ Ребёнок не был удалён."
    );
}

console.log(
    "✅ Удаление ребёнка работает."
);

console.log("");
console.log("10. Деактивация объекта");

деактивироватьОбъект3D(
    объект
);

console.log(
    "Состояние:",
    объект.состояние
);

console.log(
    "Активен:",
    объект.активен
);

console.log(
    "Интенсивность:",
    объект.интенсивность
);

/*
 * После вызова функции TypeScript может сохранить
 * предыдущее сужение типов объекта.
 *
 * Поэтому здесь явно расширяем значения до базовых
 * типов JavaScript.
 */

const активенПослеДеактивации: boolean =
    Boolean(объект.активен);

const интенсивностьПослеДеактивации: number =
    Number(объект.интенсивность);

const состояниеПослеДеактивации: string =
    String(объект.состояние);

if (
    активенПослеДеактивации === true ||
    интенсивностьПослеДеактивации !== 0 ||
    состояниеПослеДеактивации !== "ожидание"
) {
    throw new Error(
        "❌ Деактивация объекта работает неправильно."
    );
}

console.log(
    "✅ Деактивация работает."
);

console.log("");
console.log("11. Финальная проверка");

if (!проверитьОбъект3D(объект)) {
    throw new Error(
        "❌ Финальная проверка объекта не пройдена."
    );
}

if (!проверитьОбъект3D(копия)) {
    throw new Error(
        "❌ Проверка копии не пройдена."
    );
}

if (!проверитьОбъект3D(ребёнок)) {
    throw new Error(
        "❌ Проверка дочернего объекта не пройдена."
    );
}

console.log(
    "✅ Все объекты корректны."
);

console.log("");

console.log(
    "============================================================"
);

console.log(
    "🐌 ТЕСТ ОБЪЕКТА 3D ЗАВЕРШЁН УСПЕШНО"
);

console.log(
    "============================================================"
);
