/**
 * Поворот точки вокруг начала координат.
 *
 * Повороты задаются в градусах.
 *
 * Порядок:
 * 1. X
 * 2. Y
 * 3. Z
 */
function повернутьТочку3D(точка, поворот) {
    проверитьТочку3D(точка);
    проверитьПоворот3D(поворот);
    let x = точка.x;
    let y = точка.y;
    let z = точка.z;
    /* Поворот вокруг X */
    const радианыX = градусыВРадианы(поворот.x);
    const cosX = Math.cos(радианыX);
    const sinX = Math.sin(радианыX);
    const yПослеX = y * cosX - z * sinX;
    const zПослеX = y * sinX + z * cosX;
    y = yПослеX;
    z = zПослеX;
    /* Поворот вокруг Y */
    const радианыY = градусыВРадианы(поворот.y);
    const cosY = Math.cos(радианыY);
    const sinY = Math.sin(радианыY);
    const xПослеY = x * cosY + z * sinY;
    const zПослеY = -x * sinY + z * cosY;
    x = xПослеY;
    z = zПослеY;
    /* Поворот вокруг Z */
    const радианыZ = градусыВРадианы(поворот.z);
    const cosZ = Math.cos(радианыZ);
    const sinZ = Math.sin(радианыZ);
    const xПослеZ = x * cosZ - y * sinZ;
    const yПослеZ = x * sinZ + y * cosZ;
    x = xПослеZ;
    y = yПослеZ;
    return {
        x,
        y,
        z
    };
}
