let состояниеТерминала = "готов";
let таймерЗавершения = null;
// ============================================================
// ВСПОМОГАТЕЛЬНЫЕ ФУНКЦИИ
// ============================================================
function добавитьВывод(сообщение) {
    if (!элементы.вывод) {
        return;
    }
    const строка = document.createElement("div");
    строка.textContent = сообщение;
    элементы.вывод.appendChild(строка);
    элементы.вывод.scrollTop =
        элементы.вывод.scrollHeight;
}
function установитьСостояние(новоеСостояние) {
    состояниеТерминала =
        новоеСостояние;
    if (элементы.состояние) {
        switch (новоеСостояние) {
            case "готов":
                элементы.состояние.textContent =
                    "● Готово";
                break;
            case "выполнение":
                элементы.состояние.textContent =
                    "● Выполнение";
                break;
            case "остановлено":
                элементы.состояние.textContent =
                    "● Остановлено";
                break;
            case "завершено":
                элементы.состояние.textContent =
                    "● Завершено";
                break;
        }
    }
    if (элементы.состояниеСистемы) {
        switch (новоеСостояние) {
            case "готов":
                элементы.состояниеСистемы.textContent =
                    "● Система готова";
                break;
            case "выполнение":
                элементы.состояниеСистемы.textContent =
                    "● Программа выполняется";
                break;
            case "остановлено":
                элементы.состояниеСистемы.textContent =
                    "● Выполнение остановлено";
                break;
            case "завершено":
                элементы.состояниеСистемы.textContent =
                    "● Программа завершена";
                break;
        }
    }
    if (элементы.состояниеРедактора) {
        switch (новоеСостояние) {
            case "готов":
                элементы.состояниеРедактора.textContent =
                    "готов";
                break;
            case "выполнение":
                элементы.состояниеРедактора.textContent =
                    "выполнение";
                break;
            case "остановлено":
                элементы.состояниеРедактора.textContent =
                    "остановлено";
                break;
            case "завершено":
                элементы.состояниеРедактора.textContent =
                    "завершено";
                break;
        }
    }
}
// ============================================================
// ОЧИСТКА ПРЕДЫДУЩЕГО ВЫПОЛНЕНИЯ
// ============================================================
function очиститьТаймер() {
    if (таймерЗавершения !== null) {
        clearTimeout(таймерЗавершения);
        таймерЗавершения = null;
    }
}
// ============================================================
// ЗАПУСК ПРОГРАММЫ
// ============================================================
function запуститьПрограмму() {
    if (состояниеТерминала ===
        "выполнение") {
        добавитьВывод("⚠ Программа уже выполняется.");
        return;
    }
    очиститьТаймер();
    установитьСостояние("выполнение");
    добавитьВывод("▶ Запуск программы...");
    добавитьВывод("🐌 Терминал передал управление системе выполнения.");
    таймерЗавершения =
        setTimeout(() => {
            таймерЗавершения = null;
            if (состояниеТерминала !==
                "выполнение") {
                return;
            }
            установитьСостояние("завершено");
            добавитьВывод("✓ Выполнение завершено.");
            добавитьВывод("● Ошибок интерфейса не обнаружено.");
        }, 700);
}
// ============================================================
// ОСТАНОВКА ПРОГРАММЫ
// ============================================================
function остановитьПрограмму() {
    if (состояниеТерминала !==
        "выполнение") {
        добавитьВывод("⚠ Сейчас нет выполняемой программы.");
        установитьСостояние("остановлено");
        return;
    }
    очиститьТаймер();
    установитьСостояние("остановлено");
    добавитьВывод("■ Выполнение остановлено пользователем.");
}
// ============================================================
// НАЧАЛЬНАЯ ПРОВЕРКА ИНТЕРФЕЙСА
// ============================================================
function проверитьИнтерфейс() {
    const отсутствующие = [];
    if (!элементы.кнопкаЗапуск) {
        отсутствующие.push("кнопка-запуск");
    }
    if (!элементы.кнопкаОстановка) {
        отсутствующие.push("кнопка-остановка");
    }
    if (!элементы.вывод) {
        отсутствующие.push("вывод");
    }
    if (!элементы.состояние) {
        отсутствующие.push("состояние");
    }
    if (!элементы.состояниеСистемы) {
        отсутствующие.push("состояние-системы");
    }
    if (!элементы.состояниеРедактора) {
        отсутствующие.push("состояние-редактора");
    }
    if (отсутствующие.length > 0) {
        console.error("🐌 Ошибка интерфейса. Отсутствуют элементы:", отсутствующие);
        return;
    }
    console.log("🐌 Интерфейс терминала «Улитки» проверен.");
}
