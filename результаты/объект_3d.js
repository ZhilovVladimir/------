function проверитьОбъект3D(объект) {
    if (!объект) {
        return false;
    }
    if (typeof объект.идентификатор !==
        "string") {
        return false;
    }
    if (typeof объект.имя !==
        "string") {
        return false;
    }
    if (typeof объект.тип !==
        "string") {
        return false;
    }
    if (typeof объект.состояние !==
        "string") {
        return false;
    }
    if (!объект.трансформация) {
        return false;
    }
    if (!объект.трансформация.позиция ||
        !объект.трансформация.поворот ||
        !объект.трансформация.масштаб) {
        return false;
    }
    if (typeof объект.видим !==
        "boolean") {
        return false;
    }
    if (typeof объект.активен !==
        "boolean") {
        return false;
    }
    if (typeof объект.интенсивность !==
        "number") {
        return false;
    }
    if (объект.родитель !== null &&
        typeof объект.родитель !==
            "string") {
        return false;
    }
    if (!Array.isArray(объект.дети)) {
        return false;
    }
    if (!объект.метаданные ||
        typeof объект.метаданные !==
            "object") {
        return false;
    }
    return true;
}
