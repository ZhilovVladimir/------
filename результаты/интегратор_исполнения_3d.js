class ИнтеграторИсполнения3D {
    ядро;
    узлыПоИсточнику = new Map();
    связиПоКлючу = new Map();
    constructor(ядро) {
        this.ядро = ядро;
    }
    // ========================================================
    // ПОЛУЧИТЬ ЯДРО
    // ========================================================
    получитьЯдро() {
        return this.ядро;
    }
    // ========================================================
    // ОБРАБОТАТЬ СОБЫТИЕ
    // ========================================================
    обработатьСобытие(событие) {
        const данные = this.получитьДанные(событие.данные);
        switch (событие.тип) {
            // ------------------------------------------------
            // НАЧАЛО ПРОГРАММЫ
            // ------------------------------------------------
            case "начало_программы": {
                this.ядро.установитьСостояние("выполнение");
                break;
            }
            // ------------------------------------------------
            // ЗАВЕРШЕНИЕ ПРОГРАММЫ
            // ------------------------------------------------
            case "завершение_программы": {
                this.ядро.установитьСостояние("завершено");
                break;
            }
            // ------------------------------------------------
            // ОБЪЯВЛЕНИЕ / ИЗМЕНЕНИЕ ПЕРЕМЕННОЙ
            // ------------------------------------------------
            case "объявление_переменной":
            case "изменение_переменной": {
                this.обработатьИзменениеПеременной(событие, данные);
                break;
            }
            // ------------------------------------------------
            // ВЫЗОВ ФУНКЦИИ
            // ------------------------------------------------
            case "вызов_функции": {
                this.обработатьВызовФункции(событие, данные);
                break;
            }
            // ------------------------------------------------
            // ВОЗВРАТ ИЗ ФУНКЦИИ
            // ------------------------------------------------
            case "возврат": {
                const имя = this.получитьСтроку(данные?.имя);
                if (имя === null) {
                    break;
                }
                const идентификатор = this.узлыПоИсточнику.get(`функция:${имя}`);
                if (идентификатор ===
                    undefined) {
                    break;
                }
                this.ядро.деактивироватьУзел(идентификатор);
                break;
            }
            // ------------------------------------------------
            // ПРОВЕРКА УСЛОВИЯ
            // ------------------------------------------------
            case "проверка_условия": {
                this.обработатьУсловие(событие, данные);
                break;
            }
            // ------------------------------------------------
            // ОШИБКА
            // ------------------------------------------------
            case "ошибка": {
                const идентификатор = this.ядро.добавитьУзел("ошибка", событие.источник);
                this.ядро.активироватьУзел(идентификатор, 1);
                break;
            }
            // ------------------------------------------------
            // ПОКА НЕ СОЗДАЮТ ОТДЕЛЬНЫЙ УЗЕЛ
            // ------------------------------------------------
            case "показ":
            case "ветка_тогда":
            case "ветка_иначе":
                break;
            default:
                break;
        }
    }
    // ========================================================
    // ПОДКЛЮЧИТЬСЯ К ПОТОКУ СОБЫТИЙ
    // ========================================================
    создатьОбработчик() {
        return (событие) => {
            this.обработатьСобытие(событие);
        };
    }
    // ========================================================
    // ОБРАБОТАТЬ ИЗМЕНЕНИЕ ПЕРЕМЕННОЙ
    // ========================================================
    обработатьИзменениеПеременной(событие, данные) {
        const имя = this.получитьСтроку(данные?.имя);
        if (имя === null) {
            return;
        }
        const идентификаторПеременной = this.получитьИлиСоздатьУзел(`переменная:${имя}`, "переменная", имя);
        this.ядро.активироватьУзел(идентификаторПеременной, 1);
        const источники = this.получитьМассивСтрок(данные?.источники);
        const оператор = this.получитьСтроку(данные?.оператор);
        // ----------------------------------------------------
        // Простое присваивание:
        //
        // пусть число = 10
        //
        // Для сохранения старого поведения здесь не создаём
        // отдельный узел "выполнение".
        // ----------------------------------------------------
        if (источники.length === 0 &&
            оператор === null) {
            return;
        }
        // ----------------------------------------------------
        // Причинное вычисление:
        //
        // а → выполнение → б
        // ----------------------------------------------------
        const идентификаторВыполнения = this.создатьУзелВыполнения(событие, `вычисление:${имя}`);
        for (const источник of источники) {
            const идентификаторИсточника = this.получитьИлиСоздатьИсточник(источник);
            if (идентификаторИсточника === null) {
                continue;
            }
            const типСвязи = источник.startsWith("функция:")
                ? "вызов"
                : "зависимость";
            this.создатьИлиАктивироватьСвязь(идентификаторИсточника, идентификаторВыполнения, типСвязи);
        }
        this.создатьИлиАктивироватьСвязь(идентификаторВыполнения, идентификаторПеременной, "передача");
        this.ядро.активироватьУзел(идентификаторВыполнения, 1);
    }
    // ========================================================
    // ОБРАБОТАТЬ ВЫЗОВ ФУНКЦИИ
    // ========================================================
    обработатьВызовФункции(событие, данные) {
        const имя = this.получитьСтроку(данные?.имя);
        if (имя === null) {
            return;
        }
        const идентификаторФункции = this.получитьИлиСоздатьУзел(`функция:${имя}`, "функция", имя);
        this.ядро.активироватьУзел(идентификаторФункции, 1);
        const идентификаторВыполнения = this.создатьУзелВыполнения(событие, `вызов:${имя}`);
        this.создатьИлиАктивироватьСвязь(идентификаторФункции, идентификаторВыполнения, "вызов");
        const источники = this.получитьМассивСтрок(данные?.источники);
        for (const источник of источники) {
            if (источник ===
                `функция:${имя}`) {
                continue;
            }
            const идентификаторИсточника = this.получитьИлиСоздатьИсточник(источник);
            if (идентификаторИсточника === null) {
                continue;
            }
            this.создатьИлиАктивироватьСвязь(идентификаторИсточника, идентификаторФункции, "передача");
        }
        this.ядро.активироватьУзел(идентификаторВыполнения, 1);
    }
    // ========================================================
    // ОБРАБОТАТЬ УСЛОВИЕ
    // ========================================================
    обработатьУсловие(событие, данные) {
        const идентификаторВыполнения = this.создатьУзелВыполнения(событие, "условие");
        const источники = this.получитьМассивСтрок(данные?.источники);
        for (const источник of источники) {
            const идентификаторИсточника = this.получитьИлиСоздатьИсточник(источник);
            if (идентификаторИсточника === null) {
                continue;
            }
            this.создатьИлиАктивироватьСвязь(идентификаторИсточника, идентификаторВыполнения, "зависимость");
        }
        const результат = данные?.результат;
        const интенсивность = результат === true
            ? 1
            : 0.4;
        this.ядро.активироватьУзел(идентификаторВыполнения, интенсивность);
    }
    // ========================================================
    // СОЗДАТЬ УЗЕЛ ВЫПОЛНЕНИЯ
    // ========================================================
    создатьУзелВыполнения(событие, имя) {
        const источник = `выполнение:${событие.идентификатор}`;
        const существующий = this.узлыПоИсточнику.get(источник);
        if (существующий !== undefined) {
            return существующий;
        }
        const идентификатор = this.ядро.добавитьУзел("выполнение", имя);
        this.узлыПоИсточнику.set(источник, идентификатор);
        return идентификатор;
    }
    // ========================================================
    // ПОЛУЧИТЬ ИЛИ СОЗДАТЬ УЗЕЛ ИСТОЧНИКА
    // ========================================================
    получитьИлиСоздатьИсточник(источник) {
        if (источник.startsWith("переменная:")) {
            const имя = источник.slice("переменная:".length);
            if (имя.length === 0) {
                return null;
            }
            return this.получитьИлиСоздатьУзел(источник, "переменная", имя);
        }
        if (источник.startsWith("функция:")) {
            const имя = источник.slice("функция:".length);
            if (имя.length === 0) {
                return null;
            }
            return this.получитьИлиСоздатьУзел(источник, "функция", имя);
        }
        return null;
    }
    // ========================================================
    // ПОЛУЧИТЬ ИЛИ СОЗДАТЬ УЗЕЛ
    // ========================================================
    получитьИлиСоздатьУзел(источник, тип, имя) {
        const существующий = this.узлыПоИсточнику.get(источник);
        if (существующий !== undefined) {
            return существующий;
        }
        const идентификатор = this.ядро.добавитьУзел(тип, имя);
        this.узлыПоИсточнику.set(источник, идентификатор);
        return идентификатор;
    }
    // ========================================================
    // СОЗДАТЬ ИЛИ АКТИВИРОВАТЬ СВЯЗЬ
    // ========================================================
    создатьИлиАктивироватьСвязь(откуда, куда, тип) {
        const ключ = `${откуда}->${куда}:${тип}`;
        const существующий = this.связиПоКлючу.get(ключ);
        if (существующий !== undefined) {
            this.ядро.активироватьСвязь(существующий, 1);
            return существующий;
        }
        const идентификатор = this.ядро.добавитьСвязь(откуда, куда, тип);
        this.связиПоКлючу.set(ключ, идентификатор);
        this.ядро.активироватьСвязь(идентификатор, 1);
        return идентификатор;
    }
    // ========================================================
    // ПОЛУЧИТЬ ДАННЫЕ
    // ========================================================
    получитьДанные(данные) {
        if (typeof данные !== "object" ||
            данные === null) {
            return null;
        }
        return данные;
    }
    // ========================================================
    // ПОЛУЧИТЬ СТРОКУ
    // ========================================================
    получитьСтроку(значение) {
        return typeof значение === "string"
            ? значение
            : null;
    }
    // ========================================================
    // ПОЛУЧИТЬ МАССИВ СТРОК
    // ========================================================
    получитьМассивСтрок(значение) {
        if (!Array.isArray(значение)) {
            return [];
        }
        return значение.filter(элемент => typeof элемент === "string");
    }
    // ========================================================
    // СБРОС СОПРОВОЖДЕНИЯ
    // ========================================================
    очиститьПривязки() {
        this.узлыПоИсточнику.clear();
        this.связиПоКлючу.clear();
    }
}
exports.ИнтеграторИсполнения3D = ИнтеграторИсполнения3D;
