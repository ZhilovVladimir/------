// ============================================================
// 🐌 СИНХРОНИЗАТОР МОДЕЛИ С 3D
// ============================================================
class СинхронизаторМодели3D {
    ядро;
    идентификаторПрограммы = null;
    идентификаторыПеременных = new Map();
    идентификаторыФункций = new Map();
    идентификаторыОшибок = [];
    // ========================================================
    // КОНСТРУКТОР
    // ========================================================
    constructor(ядро) {
        this.ядро = ядро;
    }
    // ========================================================
    // ПОЛУЧИТЬ ЯДРО
    // ========================================================
    получитьЯдро() {
        return this.ядро;
    }
    // ========================================================
    // СИНХРОНИЗИРОВАТЬ МОДЕЛЬ
    // ========================================================
    синхронизировать(модель) {
        this.очиститьПривязки();
        let созданоУзлов = 0;
        // ----------------------------------------------------
        // ПРОГРАММА
        //
        // Имя программы подтверждено внутренней моделью.
        // ----------------------------------------------------
        this.идентификаторПрограммы =
            this.ядро.добавитьУзел("программа", модель.получитьИмяПрограммы(), {
                источник: "единая_внутренняя_модель",
                тип: "программа"
            });
        созданоУзлов++;
        // ----------------------------------------------------
        // ГЛОБАЛЬНЫЕ СИМВОЛЫ
        // ----------------------------------------------------
        const символы = модель.получитьГлобальныеСимволы();
        for (const символ of символы) {
            // ------------------------------------------------
            // ПЕРЕМЕННАЯ
            // ------------------------------------------------
            if (символ.вид ===
                "переменная") {
                const идентификатор = this.ядро.добавитьУзел("переменная", символ.имя, {
                    источник: "единая_внутренняя_модель",
                    вид: символ.вид,
                    тип: символ.тип,
                    инициализирована: символ.инициализирован
                });
                this.идентификаторыПеременных.set(символ.имя, идентификатор);
                созданоУзлов++;
                continue;
            }
            // ------------------------------------------------
            // ФУНКЦИЯ
            // ------------------------------------------------
            if (символ.вид ===
                "функция") {
                const идентификатор = this.ядро.добавитьУзел("функция", символ.имя, {
                    источник: "единая_внутренняя_модель",
                    вид: символ.вид,
                    тип: символ.тип,
                    параметры: символ.параметры ??
                        [],
                    типВозврата: символ.типВозврата ??
                        "неизвестно"
                });
                this.идентификаторыФункций.set(символ.имя, идентификатор);
                созданоУзлов++;
            }
            // ------------------------------------------------
            // ПАРАМЕТР
            //
            // Параметры находятся внутри функций.
            // На этом этапе они не являются глобальными узлами.
            // ------------------------------------------------
        }
        // ----------------------------------------------------
        // СЕМАНТИЧЕСКИЕ ОШИБКИ
        //
        // Ошибки уже подтверждены семантическим анализатором.
        // ----------------------------------------------------
        const ошибки = модель.получитьОшибки();
        for (const ошибка of ошибки) {
            const идентификатор = this.ядро.добавитьУзел("ошибка", `ошибка_${ошибка.код}`, {
                источник: "единая_внутренняя_модель",
                код: ошибка.код,
                сообщение: ошибка.сообщение,
                имя: ошибка.имя,
                ожидаемыйТип: ошибка.ожидаемыйТип,
                полученныйТип: ошибка.полученныйТип
            });
            this.идентификаторыОшибок.push(идентификатор);
            созданоУзлов++;
        }
        return {
            успешно: модель.успешна(),
            идентификаторПрограммы: this.идентификаторПрограммы,
            идентификаторыПеременных: new Map(this.идентификаторыПеременных),
            идентификаторыФункций: new Map(this.идентификаторыФункций),
            идентификаторыОшибок: [
                ...this.идентификаторыОшибок
            ],
            созданоУзлов
        };
    }
    // ========================================================
    // ОЧИСТИТЬ ПРИВЯЗКИ
    // ========================================================
    очиститьПривязки() {
        this.идентификаторПрограммы =
            null;
        this.идентификаторыПеременных.clear();
        this.идентификаторыФункций.clear();
        this.идентификаторыОшибок = [];
    }
    // ========================================================
    // ПОЛУЧИТЬ УЗЕЛ ПРОГРАММЫ
    // ========================================================
    получитьИдентификаторПрограммы() {
        return this.идентификаторПрограммы;
    }
    // ========================================================
    // ПОЛУЧИТЬ УЗЕЛ ПЕРЕМЕННОЙ
    // ========================================================
    получитьИдентификаторПеременной(имя) {
        return (this.идентификаторыПеременных
            .get(имя)
            ?? null);
    }
    // ========================================================
    // ПОЛУЧИТЬ УЗЕЛ ФУНКЦИИ
    // ========================================================
    получитьИдентификаторФункции(имя) {
        return (this.идентификаторыФункций
            .get(имя)
            ?? null);
    }
    // ========================================================
    // ПОЛУЧИТЬ УЗЛЫ ОШИБОК
    // ========================================================
    получитьИдентификаторыОшибок() {
        return [
            ...this.идентификаторыОшибок
        ];
    }
}
exports.СинхронизаторМодели3D = СинхронизаторМодели3D;
// ============================================================
// ФАБРИКА
// ============================================================
function создатьСинхронизаторМодели3D(ядро) {
    return new СинхронизаторМодели3D(ядро);
}
